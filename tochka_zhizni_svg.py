"""
ЗНАЧОК ТОЧКИ ЖИЗНИ ДЛЯ КОЛЕСА — жёлтое солнышко со спицами.

Его выбор 05.09: «сделай как на рендере дня, жёлтым».
Вставляется в колесо на своём градусе, как обычная точка.
"""

ЦВЕТ = "#E8B23A"

# ⚠️ Его выбор 05.09: вариант «в размере колеса, с градусом».
# Радиус 9, толщина 1.6, подпись градусом под значком — этот вид
# и ставим по умолчанию.
РАЗМЕР_НА_КОЛЕСЕ = 5      # 06.09: было 9 — его слово «сильно большое», уменьшил почти вдвое
ТОЛЩИНА = 1.2             # 06.09: было 1.6

ЗНАКИ_СИМВОЛ = {"Овен": "♈", "Телец": "♉", "Близнецы": "♊", "Рак": "♋",
                "Лев": "♌", "Дева": "♍", "Весы": "♎", "Скорпион": "♏",
                "Стрелец": "♐", "Козерог": "♑", "Водолей": "♒", "Рыбы": "♓"}


def подпись_градуса(абс_градус):
    """'11°07′ ♑' — как на его выбранном образце."""
    из_знаки = list(ЗНАКИ_СИМВОЛ)
    зн = из_знаки[int(абс_градус // 30) % 12]
    в = абс_градус % 30
    г = int(в)
    м = int(round((в - г) * 60))
    if м == 60:
        г, м = г + 1, 0
    return f"{г}°{м:02d}′ {ЗНАКИ_СИМВОЛ[зн]}"


def значок_тж(x, y, размер=9, цвет=ЦВЕТ, подпись=None, толщина=1.6):
    """SVG-группа: круг, ядро и восемь лучей.

    x, y     — где рисовать (уже посчитанная позиция на колесе)
    размер   — радиус круга; лучи выходят чуть дальше
    подпись  — например '11°07′ ♑', рисуется под значком
    """
    r = размер
    луч_от, луч_до = r + 3, r + 7
    д = луч_от * 0.707            # для косых лучей
    д2 = луч_до * 0.707
    лучи = "".join(
        f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}"/>'
        for x1, y1, x2, y2 in (
            (0, -луч_до, 0, -луч_от), (0, луч_от, 0, луч_до),
            (-луч_до, 0, -луч_от, 0), (луч_от, 0, луч_до, 0),
            (-д2, -д2, -д, -д), (д, д, д2, д2),
            (д2, -д2, д, -д), (-д2, д2, -д, д),
        ))
    текст = ""
    if подпись:
        текст = (f'<text x="0" y="{r + 16:.0f}" fill="{цвет}" '
                 f'font-size="8" text-anchor="middle">{подпись}</text>')
    return (
        f'<g class="tochka-zhizni" transform="translate({x:.1f},{y:.1f})">'
        f'<circle r="{r}" fill="none" stroke="{цвет}" stroke-width="{толщина}"/>'
        f'<circle r="{r/3:.1f}" fill="{цвет}"/>'
        f'<g stroke="{цвет}" stroke-width="{толщина}" stroke-linecap="round">{лучи}</g>'
        f'{текст}</g>'
    )


def позиция_на_колесе(градус, радиус, центр_x, центр_y, поворот_ас=0.0):
    """Где рисовать точку: градус зодиака → координаты на колесе.
    поворот_ас — градус асцендента, колесо Кериkeion развёрнуто от него.

    06.09: формула — ровно та, которой сам Кериkeion ставит планеты
    (draw_planets: offset = градус − десцендент; x = R·cos, y = −R·sin).
    Раньше стояло зеркало по вертикали и без поворота — значок уезжал в чужой знак."""
    import math
    угол = math.radians(градус - (поворот_ас + 180.0))
    return центр_x + радиус * math.cos(угол), центр_y - радиус * math.sin(угол)


def вставить_в_колесо(градус, радиус, центр_x, центр_y,
                      поворот_ас=0.0, подпись=None,
                      размер=РАЗМЕР_НА_КОЛЕСЕ):
    """Готовый SVG для вставки — одной строкой."""
    x, y = позиция_на_колесе(градус, радиус, центр_x, центр_y, поворот_ас)
    if подпись is None:
        подпись = подпись_градуса(градус)      # ставится сама
    return значок_тж(x, y, размер=размер, подпись=подпись, толщина=ТОЛЩИНА)


# ═══════════════════════════════════════════════════════════════════
#  ВСТАВКА В ГОТОВЫЙ SVG КОЛЕСА
# ═══════════════════════════════════════════════════════════════════
#  Колесо рисует kerykeion и отдаёт готовым SVG. Значок Точки Жизни
#  дорисовывается поверх — до закрывающего </svg>.

import re


def дорисовать_на_колесе(svg, градус_тж, доля_радиуса=0.74, асцендент=None):
    """Ставит жёлтое солнышко ТЖ на готовое колесо.

    svg           — разметка от kerykeion
    градус_тж     — абсолютный градус 0..360
    доля_радиуса  — где по радиусу ставить (0.74 — между кругами)
    асцендент     — градус АС внутренней карты; без него значок ставить нельзя

    06.09: центр и радиус берём из самого колеса (группа Full_Wheel
    translate(x,y) + круг r=240), а не из viewBox — раньше центр
    считался от размеров холста без учёта его смещения (75,25) и
    значок уезжал на 75 px вбок и 25 px вверх.
    """
    if not svg or градус_тж is None or асцендент is None:
        return svg
    г = re.search(r"kr:node=['\"]Full_Wheel['\"][^>]*translate\(([\d.\-]+),\s*([\d.\-]+)\)", svg)
    к = re.search(r"<circle cx=['\"]([\d.]+)['\"] cy=['\"]([\d.]+)['\"] r=['\"]([\d.]+)['\"]", svg)
    if not г or not к:
        return svg
    tx, ty = float(г.group(1)), float(г.group(2))
    cx, cy, R = tx + float(к.group(1)), ty + float(к.group(2)), float(к.group(3))
    радиус = R * доля_радиуса
    сдвиг = float(асцендент)

    значок = вставить_в_колесо(градус_тж, радиус, cx, cy, поворот_ас=сдвиг)
    подпись = (f'<title>Точка Жизни · {подпись_градуса(градус_тж)}</title>')
    вставка = f'<g class="tochka-zhizni-layer">{подпись}{значок}</g>'
    и = svg.rfind("</svg>")
    if и < 0:
        return svg
    return svg[:и] + вставка + svg[и:]
