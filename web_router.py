def _есть(текст: str, слова) -> bool:
    return any(с in текст for с in слова)


def найти_сайт(текст: str) -> Optional[List[str]]:
    """Не назвал ли человек сайт, по которому искать.

    Три способа: прямой адрес, «на сайте такой-то», знакомое имя издания.
    """
    # 1. прямая ссылка
    м = _АДРЕС.search(текст)
    if м:
        адрес = м.group(0).rstrip(".,!?)")
        дом = адрес.split("//")[-1].split("/")[0]
        return [дом] if дом else None

    # 2. голый домен без протокола
    м = _ДОМЕН.search(текст)
    if м:
        return [м.group(1).lower()]

    # 3. «на сайте ...»
    м = _НА_САЙТЕ.search(текст)
    if м:
        имя = м.group(1).lower().strip(".,")
        # если назвали знакомое имя — берём его домен
        for ключ, дом in _САЙТЕ_ключи():
            if ключ in имя:
                return [дом]
        # иначе считаем доменом как есть, если похоже на домен
        if "." in имя:
            return [имя]
        return None

    # 4. знакомое имя издания где угодно в реплике
    for ключ, дом in _САЙТЕ_ключи():
        if ключ in текст:
            return [дом]
    return None



def _САЙТЕ_ключи():
    # длинные ключи первыми: «википеди» раньше «вики»
    return sorted(_САЙТЫ.items(), key=lambda п: -len(п[0]))




# 🔤 ПАДЕЖИ ГОРОДОВ. Справочник Open-Meteo не склоняет: «Самаре» он читает
# как чужое имя и отдаёт Самар на Филиппинах, «Ижевске» не находит вовсе.
# Морфологический анализатор приводит слово к именительному падежу и помечает
# географические названия — так «Гори» остаётся городом, а не глаголом.
# Поднимаем ЛЕНИВО: словарь весит 16 МБ, грузить его при старте незачем.
_морф = None
_морф_нет = False


def _фраза_в_именительный(фраза: str) -> str:
    """«нижнем новгороде» → «нижний новгород»: склоняем КАЖДОЕ слово.

    Для составных названий одного вызова мало: анализатор работает по слову,
    и «Нижний Новгород» иначе рассыпается на «Нижний».
    """
    части = re.split(r"(\s+)", фраза or "")
    return "".join(ч if ч.isspace() else _в_именительный(ч) for ч in части)


def _в_именительный(слово: str) -> str:
    """«Самаре» → «самара». Не вышло — возвращаем как было."""
    global _морф, _морф_нет
    if _морф_нет or not слово:
        return слово
    if _морф is None:
        try:
            import pymorphy3
            _морф = pymorphy3.MorphAnalyzer()
        except Exception as e:
            _морф_нет = True
            logger.warning(f"падежи городов недоступны, работаем без них: {e}")
            return слово
    try:
        разборы = _морф.parse(слово)
        # берём разбор, помеченный как ГЕОГРАФИЧЕСКОЕ НАЗВАНИЕ, иначе
        # существительное. Без этого «Гори» превращается в «гореть».
        гео = [р for р in разборы if "Geox" in р.tag]
        сущ = [р for р in разборы if "NOUN" in р.tag]
        выбор = (гео or сущ or разборы)[0]
        return выбор.normal_form
    except Exception:
        return слово


