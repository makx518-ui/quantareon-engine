async def _новостная_очередь(запрос: str, lang: str = "ru") -> str:
    """Запасные новостные источники, по очереди.

    Порядок: Tavily (новостной режим) → Serper (новостной) → DuckDuckGo
    News. Следующий берётся, только если предыдущий вернул пусто. Каждый
    отдаёт заголовки с источниками — это ближе к ленте, чем общий поиск.
    """
    try:
        import web_tools as WT
    except ImportError:
        return ""

    текст = (запрос or "").strip()
    if not текст:
        текст = "главные новости" if lang == "ru" else "top news"

    попытки = [
        ("Tavily новости",
         lambda: WT.tavily_search(текст, max_results=4, topic="news",
                                  time_range="day",
                                  country="georgia" if lang == "ru" else None)),
        ("Serper новости",
         lambda: WT.serper_search(текст, max_results=4, search_type="news")),
        # ⏱️ DuckDuckGo — последний и самый ненадёжный: у него нет ключа,
        # библиотека просто изображает браузер. Замер 07.08 на восьми
        # запросах: срабатывает 6 из 8, медиана 3.1 с, худшее 5.4 с, и
        # новости приносит несвежие (2 материала из 14 за текущий месяц).
        # Поэтому короткий поводок: не уложился — не судьба, лучше
        # промолчать, чем заставлять человека ждать впустую.
        ("DuckDuckGo новости",
         lambda: asyncio.wait_for(WT.ddg_news(текст, max_results=4),
                                  timeout=float(os.getenv("DDG_TIMEOUT", "2.5")))),
    ]

    for имя, вызов in попытки:
        try:
            r = await вызов()
        except Exception as e:
            logger.warning(f"📰 {имя}: {type(e).__name__}")
            continue
        if r and r.get("success") and r.get("results"):
            logger.info(f"📰 новости: {имя}")
            подпись = "[NEWS FEED]" if lang == "en" else "[НОВОСТИ ИЗ ЛЕНТЫ]"
            return WT.format_for_prompt(r, label=подпись, max_chars=1800)
        logger.info(f"📰 {имя}: пусто, пробую следующий")

    return ""


async def выполнить(запрос: str = "", тема: str = "поиск",
                    город: str = "", lang: str = "ru") -> str:
    """Сходить за данными по параметрам, которые дала модель."""
    запрос = (запрос or "").strip()
    тема = (тема or "поиск").strip().lower()
    город = (город or "").strip()
    logger.info(f"🌐 поиск: тема={тема} запрос={запрос!r} город={город!r}")

    if тема == "погода":
        return await _погода(город or запрос, lang)

    if тема == "валюта":
        цифра = await _курс(запрос, lang)
        if цифра:
            return цифра

    if тема == "крипта":
        цифра = await _крипта(запрос, lang)
        if цифра:
            return цифра

    if тема == "новости":
        # ⚠️ Ленте NewsData слово «новости» в запросе МЕШАЕТ: она ищет
        # статьи, где это слово просто встречается. Замер: q=«новости» →
        # 6544 мусорных, q=«Грузия» → 160 по делу. Подготовка запроса под
        # конкретный источник — наша работа, не модели.
        суть = _суть_новостей(запрос)
        лента = await _новости(суть, None, lang)
        if лента:
            logger.info("📰 новости: лента NewsData")
            return лента

        # 🔁 ЛЕНТА МОЛЧИТ — ИДЁМ ПО НОВОСТНОЙ ОЧЕРЕДИ, а не в общий поиск.
        # Проверено 07.08: у NewsData кончились дневные кредиты (429), и
        # без этой очереди новости уходили в обычный поиск и приходили
        # безликим «ФАКТ:» вместо заголовков с датами и источниками.
        новостные = await _новостная_очередь(запрос, lang)
        if новостные:
            return новостные

    if not запрос:
        return ""

    try:
        import web_tools as WT
    except ImportError:
        return ""

    страна = "georgia" if lang == "ru" else None
    текст_запроса = запрос + (". Ответь на русском языке." if lang == "ru" else "")
    тема_поиска = "news" if тема == "новости" else (
        "finance" if тема in ("валюта", "крипта", "финансы", "экономика") else "general")
    try:
        r = await WT.tavily_search(текст_запроса, max_results=3, topic=тема_поиска,
                                   include_answer=True,
                                   include_domains=найти_сайт(запрос.lower()),
                                   country=страна,
                                   time_range="day" if тема in ("новости", "валюта", "крипта") else None)
        if not r.get("success") or not r.get("results"):
            r = await WT.serper_search(текст_запроса, max_results=3)
        if not r.get("success") or not r.get("results"):
            r = await WT.ddg_search(текст_запроса, max_results=3)
        if not r.get("success"):
            return ""
        подпись = "🌐 CURRENT INFORMATION" if lang == "en" else "🌐 АКТУАЛЬНАЯ ИНФОРМАЦИЯ"
        return WT.format_for_prompt(r, label=подпись, max_chars=1800)
    except Exception as e:
        logger.warning(f"поиск не вышел: {e}")
        return ""


