async def _погода(реплика: str, lang: str = "ru") -> str:
    """Open-Meteo — без ключа. Город ищем в реплике, иначе Тбилиси."""
    import aiohttp
    город, коорд = "Тбилиси", _ГОРОДА["тбилиси"]
    for имя, к in _ГОРОДА.items():
        if имя in реплика.lower():
            город, коорд = имя.capitalize(), к
            break
    try:
        url = (f"https://api.open-meteo.com/v1/forecast?latitude={коорд[0]}"
               f"&longitude={коорд[1]}&current=temperature_2m,wind_speed_10m,"
               f"relative_humidity_2m&timezone=auto")
        async with aiohttp.ClientSession() as s:
            async with s.get(url, timeout=aiohttp.ClientTimeout(total=8)) as r:
                d = await r.json()
        c = d.get("current", {})
        if lang == "en":
            return (f"[CURRENT WEATHER]\nCity: {город}\n"
                    f"Temperature: {c.get('temperature_2m')} °C\n"
                    f"Wind: {c.get('wind_speed_10m')} km/h\n"
                    f"Humidity: {c.get('relative_humidity_2m')} %")
        return (f"[ПОГОДА СЕЙЧАС]\nГород: {город}\n"
                f"Температура: {c.get('temperature_2m')} °C\n"
                f"Ветер: {c.get('wind_speed_10m')} км/ч\n"
                f"Влажность: {c.get('relative_humidity_2m')} %")
    except Exception as e:
        logger.warning(f"погода не вышла: {e}")
        return ""


async def _новости(запрос: str, сайты=None, lang: str = "ru") -> str:
    """NewsData — живая лента с датой и источником. Точнее поиска."""
    import aiohttp
    # ключ берём из переменной, а если её нет — из web_tools
    # (репозиторий закрытый, ключи лежат там; см. пояснение в web_tools.py)
    ключ = os.getenv("NEWSDATA_API_KEY", "")
    if not ключ:
        try:
            import web_tools as _WT
            ключ = _WT._ключ("NEWSDATA_API_KEY")
        except Exception:
            ключ = ""
    if not ключ:
        return ""
    try:
        язык = "en" if lang == "en" else "ru"
        url = f"https://newsdata.io/api/1/latest?apikey={ключ}&language={язык}&size=5"
        # ⚠️ ГЛАВНАЯ ЛОВУШКА: на слово «Georgia» лента приносит ШТАТ ДЖОРДЖИЯ
        # (Олбани, Панама-Сити, Гранд-Айленд) вместо страны — и указание
        # страны не спасает, потому что поиск по слову сильнее. Поэтому для
        # Грузии слово из запроса УБИРАЕМ и берём ленту страны целиком.
        _з = (запрос or "").lower()
        про_грузию = any(сл in _з for сл in
                         ("georgia", "груз", "тбилиси", "tbilisi", "батуми", "batumi"))
        if про_грузию:
            url += "&country=ge"
        elif запрос and len(запрос) > 2:
            from urllib.parse import quote
            url += f"&q={quote(запрос[:100])}"
        if сайты:
            url += f"&domain={','.join(d.split('.')[0] for d in сайты)}"
        async with aiohttp.ClientSession() as s:
            async with s.get(url, timeout=aiohttp.ClientTimeout(total=10)) as r:
                d = await r.json()
        # ⚠️ ПРОВЕРКА НА ОСМЫСЛЕННОСТЬ. Лента любит вернуть что попало:
        # на «Georgia» — новости штата Джорджия, на «artificial intelligence» —
        # биржевые сводки. Если в заголовках нет того, о чём спросили,
        # лента бесполезна: отдаём пусто и падаем в обычный поиск.
        новости = (d.get("results") or [])

        if про_грузию:
            # Слово «Georgia» стоит и в новостях ШТАТА, поэтому по тексту
            # различить нельзя — смотрим ТОЛЬКО страну, которую проставила
            # сама лента. У штата будет «united states of america».
            новости = [н for н in новости
                       if "georgia" in " ".join(н.get("country") or []).lower()]
        else:
            # служебные слова выкидываем: по ним совпадёт что угодно
            СЛУЖЕБНЫЕ = {"news", "about", "search", "latest", "today", "please",
                         "новости", "новость", "найди", "поищи", "посмотри", "интернете"}
            ключевые = [w for w in re.split(r"[^\wа-яёА-ЯЁ]+", _з)
                        if len(w) > 3 and w not in СЛУЖЕБНЫЕ][:4]
            if ключевые:
                новости = [н for н in новости
                           if any(к in ((н.get("title") or "") + " " +
                                        (н.get("description") or "")).lower()
                                  for к in ключевые)]

        строки = []
        for н in новости[:4]:
            дата = (н.get("pubDate") or "")[:16]
            строки.append(f"• {н.get('title','')} ({н.get('source_name','')}, {дата})")
        if not строки:
            return ""
        подпись = "[NEWS FEED]" if lang == "en" else "[НОВОСТИ ИЗ ЛЕНТЫ]"
        return подпись + "\n" + "\n".join(строки)
    except Exception as e:
        logger.warning(f"новости не вышли: {e}")
        return ""


async def собрать(реплика: str, lang: str = "ru") -> str:
    """Главный вход. Реплика → блок для промпта (или пустая строка).

    Ничего не решает за модель: только приносит факты. Что с ними
    делать, сказано в промпте.
    """
    р = разобрать(реплика)
    if not р["идём"]:
        return ""

    тема, сайты = р["тема"], р["сайты"]
    запрос = очистить_запрос(реплика) or реплика

    # время считаем на месте, без сети
    if тема == "время":
        return ""      # филлер и так называет дату и время

    if тема == "погода":
        return await _погода(реплика, lang)

    if тема == "новости":
        # ⚠️ ЛЕНТА НЕ РАЗЛИЧАЕТ Грузию и штат Джорджия: обеим ставит
        # country=['georgia'], поэтому на английский вопрос про Грузию она
        # приносит Атланту и Олбани. Проверено живьём. Обходим её и идём
        # в поиск — он с указанием страны различает верно.
        _про_гру = any(сл in (запрос or "").lower()
                       for сл in ("georgia", "tbilisi", "batumi"))
        лента = "" if (lang == "en" and _про_гру) else await _новости(запрос, сайты, lang)
        if лента:
            return лента
        # лента пуста — падаем в обычный поиск

    # ── остальное: поиск ──
    try:
        import web_tools as WT
    except ImportError:
        return ""

    # ⚠️ ДВЕ ХИТРОСТИ, найдены опытом:
    # 1) без страны Tavily путает Грузию-страну со штатом Джорджия и приносит
    #    новости Атланты вместо Тбилиси;
    # 2) на русский вопрос он всё равно отвечает по-английски — лечится
    #    прямой просьбой прямо в тексте запроса.
    # Страна: на русской версии сайта человек чаще в Грузии — без этого
    # Tavily путал страну Грузию со штатом Джорджия и нёс новости Атланты.
    # На английской версии страну не задаём: аудитория со всего мира.
    страна = "georgia" if lang == "ru" else None
    _з = (запрос or "").lower()
    if any(сл in _з for сл in ("georgia", "груз", "тбилиси", "tbilisi", "батуми", "batumi")):
        страна = "georgia"          # страна, а не штат — даже на английской версии
        # ⚠️ По-английски одного указания страны мало: «Georgia» для поиска
        # прежде всего штат США. Уточняем прямо в запросе — проверено живьём.
        if lang == "en" and "tbilisi" not in _з and "batumi" not in _з:
            запрос = запрос.replace("Georgia", "Georgia (the country, Tbilisi, Caucasus)")
            if "Georgia (the country" not in запрос:
                запрос += " (the country Georgia in the Caucasus, not the US state)"
    # Язык ответа: Tavily по русскому вопросу всё равно отвечает по-английски,
    # лечится прямой просьбой в тексте запроса. Английской версии это не нужно.
    if lang == "ru":
        запрос = запрос + ". Ответь на русском языке."
    тема_поиска = "news" if тема == "новости" else (
        "finance" if тема in ("валюта", "крипта", "финансы", "экономика") else "general")

    try:
        r = await WT.tavily_search(
            запрос, max_results=3, topic=тема_поиска,
            include_answer=True,
            include_domains=сайты,
            country=страна,
            time_range="day" if тема in ("новости", "валюта", "крипта") else None,
        )
        if not r.get("success") or not r.get("results"):
            r = await WT.serper_search(запрос, max_results=3)
        if not r.get("success") or not r.get("results"):
            r = await WT.ddg_search(запрос, max_results=3)
        if not r.get("success"):
            return ""
        подпись = "🌐 CURRENT INFORMATION" if lang == "en" else "🌐 АКТУАЛЬНАЯ ИНФОРМАЦИЯ"
        if сайты:
            подпись += (f" (searched on {', '.join(сайты)})" if lang == "en"
                        else f" (искали на {', '.join(сайты)})")
        return WT.format_for_prompt(r, label=подпись, max_chars=1800)
    except Exception as e:
        logger.warning(f"поиск не вышел: {e}")
        return ""
