async def _найти_город(реплика: str, lang: str = "ru"):
    """Незнакомый город — спросить справочник Open-Meteo (без ключа).

    БЫЛО ОПАСНО: если города не было в жёстком списке из 15 штук, молча
    подставлялся Тбилиси. Проверено 07.08 — «погода в Мадриде», «в Гори»,
    «в Риме» все три возвращали тбилисские 24,7 °C. Тихая ложь хуже отказа.
    """
    import aiohttp
    from urllib.parse import quote
    т = (реплика or "").lower()
    # вырезаем служебное, чтобы осталось имя города
    # ⚠️ ГЛАГОЛЫ ПОИСКА ТОЖЕ СЛУЖЕБНЫЕ. Без этого «Найди погоду в Ижевске»
    # уходило в справочник как «найди ижевске», город не находился и молча
    # подставлялся Тбилиси. Проверено 07.08 на его живой фразе.
    т = re.sub(r"\b(найди|найти|найдёшь|найдешь|поищи|посмотри|посмотреть|"
               r"глянь|глянуть|узнай|узнать|скажи|подскажи|проверь|покажи|"
               r"какая|какой|каково|погода|погоду|погоде|температура|температуру|"
               r"сейчас|сегодня|завтра|там|на|улице|в|во|weather|what|is|the|"
               r"temperature|now|today|in|at|find|show|tell)\b",
               " ", т, flags=re.IGNORECASE)
    имя = re.sub(r"[^\wА-Яа-яёЁ\- ]", " ", т)
    имя = re.sub(r"\s+", " ", имя).strip()
    if not имя or len(имя) < 3:
        return None
    # ПАДЕЖИ. Справочник не склоняет: «в Риме» он не знает, «в Мадриде»
    # понимает как Мадридехос. Поэтому пробуем имя целиком, потом без
    # одной и без двух последних букв — и берём САМОЕ КОРОТКОЕ совпадение,
    # начинающееся с той же основы (Мадрид выигрывает у Мадридехоса).
    # ПАДЕЖИ. Справочник знает города всего мира, но не склоняет: он ждёт
    # «Оахака», а человек говорит «в Оахаке». Поэтому пробуем имя целиком,
    # потом без хвостовых букв, потом с восстановленной гласной
    # («флоренци» + я = Флоренция). Идём по порядку и встаём на первом
    # подходящем — обычно это первый же вариант, лишних запросов нет.
    язык = "en" if lang == "en" else "ru"
    # ⚠️ ЛИШНЕЕ СЛОВО РЯДОМ ЛОМАЛО ПОИСК. «Найди погоду в Ижевске, Удмуртия»
    # уходило в справочник целой строкой «ижевске удмуртия», не находилось
    # и молча подставлялся Тбилиси. Поэтому кроме строки целиком пробуем
    # КАЖДОЕ СЛОВО отдельно — длинные первыми, они обычно и есть город.
    # ⚡ ГОРОД ПРИХОДИТ ОТ МОДЕЛИ УЖЕ ЧИСТЫМ, в именительном падеже
    # («в Ижевске, Удмуртия» → Ижевск). Поэтому длинный перебор вариантов
    # больше не нужен — он раньше стоил до девяти секунд на неизвестных
    # городах. Оставлены два запасных варианта на случай, если падеж всё
    # же просочился.
    варианты = [имя]
    if len(имя) > 3:
        варианты += [имя[:-1], имя[:-1] + "а", имя[:-1] + "я"]
    видели = set()
    варианты = [в for в in варианты if not (в in видели or видели.add(в))]
    # ОТБОР ПО БАЛЛАМ, а не «первый похожий».
    # 0 — имя в точности равно спрошенному (Анкара);
    # 1 — имя начинается со спрошенного (Оахака-де-Хуарес для «оахака»);
    # 2 — имя начинается с основы (запасной случай).
    # При равном балле выигрывает вариант с меньшей обрезкой, затем более
    # короткое имя. Так «Мадриде» доходит до Мадрида, а не до Мадридехоса,
    # и «Анкаре» до Анкары, а не до шведского Анкареде.
    лучшие = []
    try:
        async with aiohttp.ClientSession() as s:
            for i, вар in enumerate(варианты[:4]):
                основа = вар[:max(3, len(вар) - 1)].lower()
                url = (f"https://geocoding-api.open-meteo.com/v1/search?"
                       f"name={quote(вар[:60])}&count=5&language={язык}")
                try:
                    async with s.get(url, timeout=aiohttp.ClientTimeout(total=8)) as r:
                        d = await r.json()
                except Exception:
                    continue
                точное = None
                for м in (d.get("results") or []):
                    имя_м = (м.get("name") or "").lower()
                    if имя_м == вар:
                        балл = 0
                    elif имя_м.startswith(вар):
                        балл = 1
                    elif имя_м.startswith(основа):
                        балл = 2
                    else:
                        continue
                    лучшие.append((балл, i, len(имя_м), м))
                    if балл == 0 and точное is None:
                        точное = м
                # точное попадание — дальше искать незачем
                if точное is not None:
                    return _имя_города(точное), (точное["latitude"], точное["longitude"])
        if not лучшие:
            return None
        лучшие.sort(key=lambda п: (п[0], п[1], п[2]))
        м = лучшие[0][3]
        return _имя_города(м), (м["latitude"], м["longitude"])
    except Exception as e:
        logger.warning(f"справочник городов не ответил: {e}")
        return None
    except Exception as e:
        logger.warning(f"справочник городов не ответил: {e}")
        return None



def _имя_города(м) -> str:
    страна = м.get("country") or ""
    return f"{м.get('name','')}" + (f" ({страна})" if страна else "")



async def _погода(реплика: str, lang: str = "ru") -> str:
    """Open-Meteo — без ключа. Город из реплики; незнакомый ищем в справочнике."""
    import aiohttp
    город, коорд = None, None
    # длинные имена первыми: «санкт-петербург» раньше «питер»
    for имя, к in sorted(_ГОРОДА.items(), key=lambda п: -len(п[0])):
        if имя in реплика.lower():
            город, коорд = имя.title(), к
            break
    if коорд is None:
        найдено = await _найти_город(реплика, lang)
        if найдено:
            город, коорд = найдено
    if коорд is None:
        # города не назвали вовсе — тогда честно берём город по умолчанию
        город, коорд = "Тбилиси", _ГОРОДА["тбилиси"]
    # ДВЕ ПОПЫТКИ: одиночный запрос иногда не доходит (замечено и на Render,
    # и здесь — «Оахака» молчала именно из-за этого, а не из-за логики)
    d = None
    for попытка in (1, 2):
        try:
            url = (f"https://api.open-meteo.com/v1/forecast?latitude={коорд[0]}"
                   f"&longitude={коорд[1]}&current=temperature_2m,wind_speed_10m,"
                   f"relative_humidity_2m&timezone=auto")
            async with aiohttp.ClientSession() as s:
                async with s.get(url, timeout=aiohttp.ClientTimeout(total=8)) as r:
                    d = await r.json()
            if d:
                break
        except Exception as e:
            logger.warning(f"погода, попытка {попытка} не вышла: {e}")
            if попытка == 2:
                return ""
            await asyncio.sleep(0.4)
    if not d:
        return ""
    c = d.get("current", {})
    if lang == "en":
        return (f"[CURRENT WEATHER]\nCity: {город}\n"
                f"Temperature: {c.get('temperature_2m')} °C\n"
                f"Wind: {c.get('wind_speed_10m')} km/h\n"
                f"Humidity: {c.get('relative_humidity_2m')} %")
    return (f"[ПОГОДА СЕЙЧАС]\nГород: {город}\n"
            f"Температура: {c.get('temperature_2m')} °C\n"
            f"Ветер: {c.get('wind_speed_10m')} км/ч\n"
            f"Влажность: {c.get('relative_humidity_2m')} %")


def _суть_новостей(запрос: str) -> str:
    """Убрать из запроса само слово «новости» и служебную обвязку.

    ЗАМЕРЕНО 07.08 на живом ключе NewsData: запрос «новости» находит 6544
    статьи, где это слово просто встречается в тексте (Ижевск, Выборг,
    шоу-бизнес) — чистый мусор. Запрос «Грузия» находит 160 и все по делу.
    Слово «новости» — это НАЗВАНИЕ ТЕМЫ, а не то, что надо искать.
    """
    т = запрос or ""
    # ⚠️ ВЕЖЛИВАЯ ОБЁРТКА — ОТДЕЛЬНАЯ БЕДА. Живая фраза «Я бы хотел, чтобы
    # ты нашёл в интернете новости Москва» после обычной очистки оставляла
    # запрос «Я бы хотел чтобы ты нашел интернете Москва» — лента по такому
    # пуста, и ответ зависел от того, успеет ли судья переформулировать.
    # Успел — новости есть, не успел — «нет актуальных новостей». Убираем
    # обёртку сразу, чтобы не зависеть от везения.
    for об in ("я бы хотел чтобы ты", "я бы хотела чтобы ты", "я хотел бы чтобы ты",
               "я бы хотел", "я хотел бы", "я хочу чтобы ты", "хочу чтобы ты",
               "мне нужно чтобы ты", "можешь ли ты", "ты можешь", "можешь",
               "будь добр", "пожалуйста", "давай ка", "давай-ка", "давай",
               "мне нужно", "мне надо", "надо бы", "хотелось бы",
               "чтобы ты", "если можно", "будь любезен"):
        т = re.sub(re.escape(об) + r"\w*", " ", т, flags=re.IGNORECASE)

    for сл in ("новостями", "новостей", "новости", "новостях", "новость",
               "новостное", "news", "headlines", "последние события",
               "что нового в мире", "что нового", "что случилось",
               "что происходит",
               # формы глаголов поиска в вежливой речи
               "нашёл", "нашел", "найдёшь", "найдешь", "поискал", "посмотрел",
               "поищешь", "посмотришь", "глянешь", "узнаешь", "поглядел",
               "посмотреть", "поискать", "поглядеть", "глянуть", "узнать",
               "найти", "разузнать", "выяснить",
               # место поиска — тоже служебное
               "в интернете", "в интернет", "интернете", "интернет",
               "в сети", "в инете", "в гугле", "онлайн"):
        т = re.sub(re.escape(сл), " ", т, flags=re.IGNORECASE)
    # предлоги и вопросительные слова, оставшиеся сиротами
    т = re.sub(r"\b(в|во|о|об|про|на|из|по|мире|какие|какая|какой|расскажи|"
               r"latest|breaking|in|about|the)\b", " ", т, flags=re.IGNORECASE)
    return re.sub(r"\s+", " ", т).strip(" ,.!?-")


def _лента_по_сути(строки: List[str], суть: str) -> List[str]:
    """Оставить в ленте только то, что правда про спрошенное.

    Лента страны тупая: на «новости Тбилиси» она способна принести Рим и
    Ливан. Сверяем заголовок с корнями значимых слов запроса (первые пять
    букв — чтобы «Грузии» совпало с «Грузия», «грузинской»).
    """
    корни = [с[:5].lower() for с in re.findall(r"[\wА-Яа-яёЁ]{4,}", суть)]
    if not корни:
        return строки          # спросили вообще без уточнения — отдаём как есть
    годные = [с for с in строки if any(к in с.lower() for к in корни)]
    return годные or []


