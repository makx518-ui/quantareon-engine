def найти_сайт(текст: str) -> Optional[List[str]]:
    """Не назвал ли человек сайт, по которому искать.

    Три способа: прямой адрес, «на сайте такой-то», знакомое имя издания.
    """
    # 1. прямая ссылка
    м = _АДРЕС.search(текст)
    if м:
        адрес = м.group(0).rstrip(".,!?)")
        дом = адрес.split("//")[-1].split("/")[0]
        return [дом] if дом else None

    # 2. голый домен без протокола
    м = _ДОМЕН.search(текст)
    if м:
        return [м.group(1).lower()]

    # 3. «на сайте ...»
    м = _НА_САЙТЕ.search(текст)
    if м:
        имя = м.group(1).lower().strip(".,")
        # если назвали знакомое имя — берём его домен
        for ключ, дом in _САЙТЕ_ключи():
            if ключ in имя:
                return [дом]
        # иначе считаем доменом как есть, если похоже на домен
        if "." in имя:
            return [имя]
        return None

    # 4. знакомое имя издания где угодно в реплике
    for ключ, дом in _САЙТЕ_ключи():
        if ключ in текст:
            return [дом]
    return None



def _САЙТЕ_ключи():
    # длинные ключи первыми: «википеди» раньше «вики»
    return sorted(_САЙТЫ.items(), key=lambda п: -len(п[0]))




