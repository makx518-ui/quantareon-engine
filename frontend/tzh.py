# -*- coding: utf-8 -*-
"""
ТОЧКА ЖИЗНИ (ТЖ) — отдельный движок для прогноза дня.

Его решение 14.08:
  · ГРАДУС ТЖ отсчитывается по КОСМОГРАММЕ — от 0° Овна в момент рождения,
    скорость 30° (один знак) за 7 лет, полный круг 84 года. Время рождения
    для этого не нужно: ТЖ зависит только от прожитых суток.
  · ДОМ, в котором стоит ТЖ, берётся НЕ из натала (домов рождения у нас нет),
    а ИЗ ДИНАМИКИ ДНЯ — от бегущего асцендента. За сутки куспиды обходят круг,
    поэтому ТЖ последовательно оказывается во всех двенадцати домах:
    стержень стоит, а сцена вокруг него меняется.

Формула ТЖ взята из engine/natal.compute_point_of_life (П. Глоба), чтобы
прогноз дня и натал считали одну и ту же точку одинаково.
"""
from datetime import datetime, timedelta, timezone
import swisseph as swe

ЗНАКИ = ['Овен', 'Телец', 'Близнецы', 'Рак', 'Лев', 'Дева',
         'Весы', 'Скорпион', 'Стрелец', 'Козерог', 'Водолей', 'Рыбы']
УПРАВИТЕЛЬ = ['Марс', 'Венера', 'Меркурий', 'Луна', 'Солнце', 'Меркурий',
              'Венера', 'Плутон', 'Юпитер', 'Сатурн', 'Уран', 'Нептун']
ГОД = 365.25          # как в натальной методике — его решение
ЦИКЛ_ЛЕТ = 84.0


def jd_из(дата: datetime) -> float:
    """datetime в UTC → юлианский день."""
    д = дата.astimezone(timezone.utc)
    return swe.julday(д.year, д.month, д.day,
                      д.hour + д.minute / 60.0 + д.second / 3600.0)


def градус_тж(рождение_utc: datetime, момент_utc: datetime) -> dict:
    """Градус Точки Жизни на заданный момент. Время рождения не требуется —
    при неизвестном часе берётся полдень, ошибка ТЖ от этого < 0.006°."""
    прожито_суток = jd_из(момент_utc) - jd_из(рождение_utc)
    лет = прожито_суток / ГОД
    гр = (лет * 360.0 / ЦИКЛ_ЛЕТ) % 360.0
    знак = int(гр // 30)
    return {
        "градус": round(гр, 6),
        "знак": ЗНАКИ[знак],
        "в_знаке": round(гр % 30, 4),
        "управитель_знака": УПРАВИТЕЛЬ[знак],
        "возраст_лет": round(лет, 3),
        "скорость_в_сутки": round(360.0 / ЦИКЛ_ЛЕТ / ГОД, 6),   # ≈0.0117°
        "эпоха_номер": знак + 1,
        "годы_эпохи": (знак * 7, (знак + 1) * 7),
    }


def дата_входа_в_знак(рождение_utc: datetime, номер_знака: int) -> datetime:
    """Когда ТЖ вошла (или войдёт) в знак номер 1..12 — по той же формуле."""
    лет = (номер_знака - 1) * 7.0
    return рождение_utc + timedelta(days=лет * ГОД)


def дом_тж(градус: float, куспиды: list) -> int:
    """В каком доме стоит ТЖ при данных куспидах (12 значений, от асцендента)."""
    г = ((градус % 360) + 360) % 360
    for i in range(12):
        a, b = куспиды[i], куспиды[(i + 1) % 12]
        охват = (b - a) % 360
        if охват <= 0:
            охват += 360
        if ((г - a) % 360) < охват:
            return i + 1
    return 12


def дома_тж_за_сутки(градус: float, начало_utc: datetime, широта: float,
                     долгота: float, шаг_минут: int = 1) -> list:
    """Как ТЖ переходит из дома в дом за сутки — куспиды бегут, ТЖ стоит.

    Возвращает список отрезков: дом, начало, конец (моменты в UTC).
    Момент перехода уточняется до секунды делением пополам.
    """
    hs = b'P' if abs(широта) <= 66.5 else b'R'

    def дом_в(момент: datetime) -> int:
        куспиды, _ = swe.houses(jd_из(момент), широта, долгота, hs)
        return дом_тж(градус, list(куспиды[:12]))

    отрезки = []
    т = начало_utc
    конец = начало_utc + timedelta(days=1)
    текущий = дом_в(т)
    начало_отрезка = т
    шаг = timedelta(minutes=шаг_минут)
    while т < конец:
        следующий_момент = т + шаг
        д = дом_в(следующий_момент)
        if д != текущий:
            # уточняем момент перехода до секунды
            низ, верх = т, следующий_момент
            while (верх - низ).total_seconds() > 1:
                середина = низ + (верх - низ) / 2
                if дом_в(середина) == текущий:
                    низ = середина
                else:
                    верх = середина
            отрезки.append({"дом": текущий, "начало": начало_отрезка, "конец": верх})
            текущий, начало_отрезка = д, верх
        т = следующий_момент
    отрезки.append({"дом": текущий, "начало": начало_отрезка, "конец": конец})
    return отрезки
