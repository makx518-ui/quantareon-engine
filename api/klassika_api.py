def ключ_из_номера(номер):
    """QN-XXXX-XXXX-XXXX-XXXX — свой префикс, не пересекается с QS/QK/QD/QF."""
    return "QN-" + "-".join(номер[i:i + 4] for i in range(0, 16, 4)).upper()


