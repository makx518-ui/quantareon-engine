def _по_русски(гео, как_назвал):
    """28.09 · его находка: в шапке файла «Petropavl Kazakhstan» — метка чата пишет место латиницей
    (для поиска). Показываем адрес, который нашёл геокодер по-русски: «Петропавловск, Северо-
    Казахстанская область». Нет адреса — как назвал клиент."""
    адрес = str((гео or {}).get("address") or "").strip()
    if not адрес or not __import__("re").search(r"[А-Яа-яЁё]", адрес):
        return как_назвал
    ч = [x.strip() for x in адрес.split("·") if x.strip()]
    return (ч[0] + (", " + ч[-1] if len(ч) > 1 else ""))[:120]


async def _собрать_dannye(метка):
    """Метка из чата → структурные данные с геокодингом. Формат — как ждёт фронт
    (razbor-ru.html, показатьСводку) плюс скрытые поля _shirota/_dolgota/_gmt для расчёта."""
    тип = метка["тип"]
    if тип in ("натал", "соляр"):
        место = (метка.get("место") or "").strip()
        if not место:
            raise _ОшибкаМеста("Не назвал(а) город рождения — уточни, пожалуйста, где ты родился(-ась).")
        гео = await _геокод(место, on_date=_дата_в_iso(метка["дата"]))
        итог = {"тип": тип, "дата": метка["дата"], "время": метка.get("время"),
                "место": _по_русски(гео, место), "пол": (метка.get("пол") or ""),
                "_shirota": гео["latitude"], "_dolgota": гео["longitude"], "_gmt": гео["utc_offset"]}
        if тип == "соляр":
            текущее = (метка.get("текущее_место") or место).strip()
            гео2 = await _геокод(текущее, on_date=None)
            итог.update({"текущее_место": _по_русски(гео2, текущее),
                        "_shirota_seychas": гео2["latitude"], "_dolgota_seychas": гео2["longitude"],
                        "_gmt_seychas": гео2["utc_offset"]})
            if метка.get("год"):
                итог["_god_solyara"] = метка["год"]
        return итог
    # синастрия
    люди = []
    for ключ in ("первый", "второй"):
        ч = метка.get(ключ) or {}
        if not _ДАТА.fullmatch(ч.get("дата") or ""):
            чей = "первого" if ключ == "первый" else "второго"
            raise _ОшибкаМеста(f"Не хватает даты рождения {чей} человека — уточни, пожалуйста.")
        место = (ч.get("место") or "").strip()
        if not место:
            чей = "первого" if ключ == "первый" else "второго"
            raise _ОшибкаМеста(f"Не хватает города рождения {чей} человека — уточни, пожалуйста.")
        гео = await _геокод(место, on_date=_дата_в_iso(ч["дата"]))
        люди.append({"дата": ч["дата"], "время": ч.get("время"), "место": _по_русски(гео, место),
                    "пол": (ч.get("пол") or ""),
                    "_shirota": гео["latitude"], "_dolgota": гео["longitude"], "_gmt": гео["utc_offset"]})
    return {"тип": "синастрия", "первый": люди[0], "второй": люди[1]}


@роутер.post("/api/klassika/chat")
async def klassika_chat(request: Request):
    try:
        т = await request.json()
    except Exception:
        return JSONResponse({"ok": False, "reason": "bad_request"}, status_code=400)
    тариф = str(т.get("tarif") or "")
    if тариф not in ТИП_ПО_ТАРИФУ:
        return JSONResponse({"ok": False, "reason": "bad_tarif"}, status_code=400)
    текст = str(т.get("text") or "").strip()[:2000]
