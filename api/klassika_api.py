class _ОшибкаМеста(Exception):
    """Геокодер не нашёл место — просим клиента уточнить, диалог не прерываем."""


def _дата_в_iso(дд_мм_гггг):
    д, м, г = str(дд_мм_гггг).strip().split(".")
    return f"{int(г):04d}-{int(м):02d}-{int(д):02d}"


def _разобрать_место(место_текст):
    """28.09 · «Советское / район Магжана Жумабаева / Северо-Казахстанская область / Казахстан» →
    ("Советское, район Магжана Жумабаева, Северо-Казахстанская область", "Казахстан") — ровно как
    окно ввода voice.quantareon.com (geoFind): город с районом и областью, страна отдельно.
    Старый вид без косой черты («Moscow Russia») идёт как раньше, целиком."""
    части = [ч.strip() for ч in str(место_текст or "").split("/") if ч.strip()]
    if len(части) >= 2:
        return ", ".join(части[:-1]), части[-1]
    return (части[0] if части else ""), ""


async def _геокод(место_текст, on_date=None):
    import main as _main
    город, страна = _разобрать_место(место_текст)
    гео = await run_in_threadpool(_main.geocode, город, страна, on_date)
    if not гео or гео.get("error"):
        raise _ОшибкаМеста(
            f"Не нахожу на карте «{место_текст.replace(' / ', ', ')}» — уточни, пожалуйста, город, "
            f"район, область и страну (например: Советское, район Магжана Жумабаева, "
            f"Северо-Казахстанская область, Казахстан).")
    return гео


