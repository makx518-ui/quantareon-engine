# -*- coding: utf-8 -*-
"""
sverka.py — СВЕРКА ЧИСЕЛ · 10.09.2026.

Его случай: строка «Хирон — Телец 14°» лежала в блоке перед глазами читателя,
а он написал «Хирон стоит в 25° Тельца». Строку видел — число взял чужое.
Просьбами это не лечится: нужна проверка после.

Правило узкое, чтобы не навредить, как прошлый сторож:
  • источник истины — ПОЛОЧКА, та самая, что получил читатель (не наш расчёт:
    теги Азбуки у нас и у их модуля разные);
  • сверяется только то, что В ТЕКСТЕ НАПИСАНО. Написано число и не совпало —
    ставим машинное. Числа нет вовсе — НЕ ТРОГАЕМ и ничего не подставляем;
  • код и ядро правим, только если назван код ДРУГОЙ точки — то есть явная
    путаница соседних строк. Иначе не трогаем;
  • правка идёт только внутри раздела своей точки.

Так сверка либо исправит, либо пройдёт мимо. Выдумать своё она не может.
"""
import re

ЗНАКИ = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева", "Весы", "Скорпион",
         "Стрелец", "Козерог", "Водолей", "Рыбы"]
ЗН = "|".join(ЗНАКИ)

# 10.09 · знаки в тексте стоят в падежах: «25° Тельца», «7° Девы», «6° Козерога».
# Ловим по основе, иначе сверка проходит мимо. Основа → именительный падеж.
ОСНОВЫ = {
    "Овн": "Овен", "Овен": "Овен",
    "Тельц": "Телец", "Телец": "Телец",
    "Близнец": "Близнецы",
    "Рак": "Рак",
    "Льв": "Лев", "Лев": "Лев",
    "Дев": "Дева",
    "Весо": "Весы", "Вес": "Весы",
    "Скорпион": "Скорпион",
    "Стрельц": "Стрелец", "Стрелец": "Стрелец",
    "Козерог": "Козерог",
    "Водоле": "Водолей", "Водолей": "Водолей",
    "Рыб": "Рыбы",
}
ЗНАК_ЛЮБОЙ = "|".join(sorted(ОСНОВЫ, key=len, reverse=True))


def _имен(слово):
    """«Тельца» → «Телец»; «Девы» → «Дева»."""
    for о in sorted(ОСНОВЫ, key=len, reverse=True):
        if слово.startswith(о):
            return ОСНОВЫ[о]
    return слово

# как точка зовётся в тексте → как она зовётся на полочке
ИМЕНА = {
    "Солнце": "Солнце", "Луна": "Луна", "Меркурий": "Меркурий", "Венера": "Венера",
    "Марс": "Марс", "Юпитер": "Юпитер", "Сатурн": "Сатурн", "Уран": "Уран",
    "Нептун": "Нептун", "Плутон": "Плутон", "Хирон": "Хирон",
    "Северный Узел": "Сев.Узел", "Северный узел": "Сев.Узел", "Сев.Узел": "Сев.Узел",
    "Южный Узел": "Юж.Узел", "Южный узел": "Юж.Узел", "Юж.Узел": "Юж.Узел",
    "Чёрная Луна": "Чёрная Луна", "Белая Луна": "Белая Луна",
    "Асцендент": "ASC", "асцендент": "ASC", "ASC": "ASC", "MC": "MC", "МС": "MC",
    # образы из глоссария Книги: «Градус духа — Водолей 27°»
    "Градус духа": "Солнце", "Градус души": "Луна", "Градус мысли": "Меркурий",
    "Градус любви": "Венера", "Градус воли": "Марс", "Градус тени": "Чёрная Луна",
    "Градус благодати": "Белая Луна", "Градус раны": "Хирон",
}
ПОРЯДОК = sorted(ИМЕНА, key=len, reverse=True)


def из_полочки(полка):
    """Разбирает строки полочки: точка → знак, градус, дом, код, ядро."""
    итог = {}
    if not полка:
        return итог
    шаблон = re.compile(
        r"^\s*([А-ЯЁA-Z][\w.\u0400-\u04FF ]{1,14}?)\s+—\s+[^\n]*?"
        r"Натал:\s*(" + ЗН + r")\s+(\d{1,2})°,\s*дом\s*(\d{1,2})"
        r"[^\n]*?Код жизни\s*\[([^\]]+)\]"
        r"(?:[^\n]*?·\s*ядро\s+(" + ЗН + r")\s+(\d{1,2})°\s*\[([^\]]+)\])?",
        re.M)
    for м in шаблон.finditer(полка):
        итог[м.group(1).strip()] = {
            "знак": м.group(2), "градус": int(м.group(3)), "дом": int(м.group(4)),
            "код": (м.group(5) or "").strip(),
            "ядро": {"знак": м.group(6) or "", "градус": int(м.group(7)) if м.group(7) else None,
                     "тег": (м.group(8) or "").strip()},
        }
    return итог


def _разделы(текст):
    """Режет текст на разделы по заголовкам — правим только внутри своего."""
    куски = re.split(r"(?m)^(#{1,3} [^\n]*)$", текст)
    итог, заг = [], ""
    for ч in куски:
        if ч.startswith("#"):
            заг = ч
            итог.append((заг, ""))
        elif итог:
            итог[-1] = (итог[-1][0], итог[-1][1] + ч)
        else:
            итог.append(("", ч))
    return итог


def сверить(текст, полка):
    """Возвращает (текст, список правок). Ничего не подставляет — только правит
    то, что написано и не совпало."""
    данные = из_полочки(полка)
    if not данные:
        return текст, []
    правки = []

    # чьи коды и ядра — чтобы отличить чужое от иначе названного
    хозяева_кодов, хозяева_ядер = {}, {}
    for и, д in данные.items():
        if д["код"]:
            хозяева_кодов.setdefault(д["код"], set()).add(и)
        if д["ядро"]["тег"]:
            хозяева_ядер.setdefault(д["ядро"]["тег"], set()).add(и)

    собрано = []
    for заг, тело in _разделы(текст):
        # чей это раздел
        чей = None
        нз = заг.lower()
        for имя_т in ПОРЯДОК:            # длинные имена первыми
            на_полке = ИМЕНА[имя_т]
            if на_полке not in данные:
                continue
            # имя должно стоять в заголовке словом, а не куском другого слова
            for вар in (имя_т.lower(), на_полке.lower()):
                if re.search(r"(?<![а-яёa-z])" + re.escape(вар) + r"(?![а-яёa-z])", нз):
                    чей = (имя_т, на_полке)
                    break
            if чей:
                break

        # 1 · градус — ТОЛЬКО в разделе своей точки. Иначе короткое имя лезет
        #     внутрь длинного: «Белая Луна» ловится как «Луна» и получает чужое
        #     число. Проверено на карте Грахово — так и вышло.
        # берём ВСЕ имена, какими эта точка может зваться в тексте:
        # раздел мог опознаться по образу («Градус раны»), а в теле стоит «Хирон»
        имена_раздела = []
        if чей:
            на_полке_чей = чей[1]
            имена_раздела = sorted(
                [и for и, п_ in ИМЕНА.items() if п_ == на_полке_чей],
                key=len, reverse=True)
        for имя_т in имена_раздела:
            на_полке = ИМЕНА[имя_т]
            д = данные.get(на_полке)
            if not д:
                continue
            ш = re.compile(re.escape(имя_т) + r"([^.\n]{0,60}?)(" + ЗНАК_ЛЮБОЙ +
                           r")([а-яё]{0,3})(\s*,?\s*)(\d{1,2})(\s*°)")
            ш2 = re.compile(re.escape(имя_т) + r"([^.\n]{0,40}?в\s+)(\d{1,2})(\s*°\s*)(" +
                            ЗНАК_ЛЮБОЙ + r")([а-яё]{0,3})")

            def пг(м, д=д, наше=на_полке, имя_т=имя_т):
                был_знак = _имен(м.group(2) + м.group(3))
                if был_знак == д["знак"] and int(м.group(5)) == д["градус"]:
                    return м.group(0)
                правки.append(f"{наше}: {был_знак} {м.group(5)}° → {д['знак']} {д['градус']}°")
                return (имя_т + м.group(1) + д["знак"] + м.group(4)
                        + str(д["градус"]) + м.group(6))

            def пг2(м, д=д, наше=на_полке, имя_т=имя_т):
                # форма «Хирон стоит в 25° Тельца» — знак в падеже
                был_знак = _имен(м.group(4) + м.group(5))
                хвост = м.group(5)
                if int(м.group(2)) == д["градус"] and был_знак == д["знак"]:
                    return м.group(0)
                правки.append(f"{наше}: {м.group(2)}° {был_знак} → {д['градус']}° {д['знак']}")
                # знак ставим в том же падеже: меняем только основу
                новый_знак = д["знак"]
                for о, им in ОСНОВЫ.items():
                    if им == д["знак"] and len(о) < len(д["знак"]) + 1:
                        новый_знак = о + хвост if хвост else д["знак"]
                        break
                return (имя_т + м.group(1) + str(д["градус"]) + м.group(3) + новый_знак)

            тело = ш.sub(пг, тело)
            тело = ш2.sub(пг2, тело)

        # 2 · код и ядро — только в своём разделе и только если чужие
        if чей:
            имя_т, на_полке = чей
            д = данные[на_полке]
            if д["код"]:
                шк = re.compile(r"\[([^\]]{4,90})\]")

                def пк(м, д=д, наше=на_полке):
                    тег = м.group(1).strip()
                    if тег == д["код"] or тег == д["ядро"]["тег"]:
                        return м.group(0)
                    хоз = хозяева_кодов.get(тег, set())
                    if хоз and наше not in хоз:
                        правки.append(f"{наше}: код [{тег[:34]}] → [{д['код'][:34]}]")
                        return "[" + д["код"] + "]"
                    хоз2 = хозяева_ядер.get(тег, set())
                    if хоз2 and наше not in хоз2 and д["ядро"]["тег"]:
                        правки.append(f"{наше}: ядро [{тег[:34]}] → [{д['ядро']['тег'][:34]}]")
                        return "[" + д["ядро"]["тег"] + "]"
                    return м.group(0)
                тело = шк.sub(пк, тело)

        собрано.append(заг + тело if заг else тело)

    return "".join(собрано), правки
