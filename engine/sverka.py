# -*- coding: utf-8 -*-
"""
sverka.py — СВЕРКА ЧИСЕЛ · 10.09.2026.

Его случай: строка «Хирон — Телец 14°» лежала в блоке перед глазами читателя,
а он написал «Хирон стоит в 25° Тельца». Строку видел — число взял чужое.
Просьбами это не лечится: нужна проверка после.

Правило узкое, чтобы не навредить, как прошлый сторож:
  • источник истины — ПОЛОЧКА, та самая, что получил читатель (не наш расчёт:
    теги Азбуки у нас и у их модуля разные);
  • сверяется только то, что В ТЕКСТЕ НАПИСАНО. Написано число и не совпало —
    ставим машинное. Числа нет вовсе — НЕ ТРОГАЕМ и ничего не подставляем;
  • код и ядро правим, только если назван код ДРУГОЙ точки — то есть явная
    путаница соседних строк. Иначе не трогаем;
  • правка идёт только внутри раздела своей точки.

Так сверка либо исправит, либо пройдёт мимо. Выдумать своё она не может.
"""
import re

ЗНАКИ = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева", "Весы", "Скорпион",
         "Стрелец", "Козерог", "Водолей", "Рыбы"]
ЗН = "|".join(ЗНАКИ)

# 10.09 · знаки в тексте стоят в падежах: «25° Тельца», «7° Девы», «6° Козерога».
# Ловим по основе, иначе сверка проходит мимо. Основа → именительный падеж.
ОСНОВЫ = {
    "Овн": "Овен", "Овен": "Овен",
    "Тельц": "Телец", "Телец": "Телец",
    "Близнец": "Близнецы",
    "Рак": "Рак",
    "Льв": "Лев", "Лев": "Лев",
    "Дев": "Дева",
    "Весо": "Весы", "Вес": "Весы",
    "Скорпион": "Скорпион",
    "Стрельц": "Стрелец", "Стрелец": "Стрелец",
    "Козерог": "Козерог",
    "Водоле": "Водолей", "Водолей": "Водолей",
    "Рыб": "Рыбы",
}
ЗНАК_ЛЮБОЙ = "|".join(sorted(ОСНОВЫ, key=len, reverse=True))


def _имен(слово):
    """«Тельца» → «Телец»; «Девы» → «Дева»."""
    for о in sorted(ОСНОВЫ, key=len, reverse=True):
        if слово.startswith(о):
            return ОСНОВЫ[о]
    return слово

# как точка зовётся в тексте → как она зовётся на полочке
ИМЕНА = {
    "Солнце": "Солнце", "Луна": "Луна", "Меркурий": "Меркурий", "Венера": "Венера",
    "Марс": "Марс", "Юпитер": "Юпитер", "Сатурн": "Сатурн", "Уран": "Уран",
    "Нептун": "Нептун", "Плутон": "Плутон", "Хирон": "Хирон",
    "Северный Узел": "Сев.Узел", "Северный узел": "Сев.Узел", "Сев.Узел": "Сев.Узел",
    "Южный Узел": "Юж.Узел", "Южный узел": "Юж.Узел", "Юж.Узел": "Юж.Узел",
    "Чёрная Луна": "Чёрная Луна", "Белая Луна": "Белая Луна",
    "Асцендент": "ASC", "асцендент": "ASC", "ASC": "ASC", "MC": "MC", "МС": "MC",
    # образы из глоссария Книги: «Градус духа — Водолей 27°»
    "Градус духа": "Солнце", "Градус души": "Луна", "Градус мысли": "Меркурий",
    "Градус любви": "Венера", "Градус воли": "Марс", "Градус тени": "Чёрная Луна",
    "Градус благодати": "Белая Луна", "Градус раны": "Хирон",
}
ПОРЯДОК = sorted(ИМЕНА, key=len, reverse=True)


def из_полочки(полка):
    """Разбирает строки полочки: точка → знак, градус, дом, код, ядро."""
    итог = {}
    if not полка:
        return итог
    шаблон = re.compile(
        r"^\s*([А-ЯЁA-Z][\w.\u0400-\u04FF ]{1,14}?)\s+—\s+[^\n]*?"
        r"Натал:\s*(" + ЗН + r")\s+(\d{1,2})°,\s*дом\s*(\d{1,2})"
        r"[^\n]*?Код жизни\s*\[([^\]]+)\]"
        r"(?:[^\n]*?·\s*ядро\s+(" + ЗН + r")\s+(\d{1,2})°\s*\[([^\]]+)\])?",
        re.M)
    for м in шаблон.finditer(полка):
        итог[м.group(1).strip()] = {
            "знак": м.group(2), "градус": int(м.group(3)), "дом": int(м.group(4)),
            "минут": None,
            "код": (м.group(5) or "").strip(),
            "ядро": {"знак": м.group(6) or "", "градус": int(м.group(7)) if м.group(7) else None,
                     "тег": (м.group(8) or "").strip()},
        }
    return итог


def минуты_из_тегов(полка, данные):
    """Минуты берём из блока <точные_данные>: в прозе их нет."""
    for м in re.finditer(r'<точка имя="([^"]+)" градус="(\d+)" минут="(\d+)"', полка or ""):
        имя = м.group(1)
        if имя in данные and данные[имя]["градус"] == int(м.group(2)):
            данные[имя]["минут"] = int(м.group(3))
    return данные


def _разделы(текст):
    """Режет текст на разделы по заголовкам — правим только внутри своего."""
    куски = re.split(r"(?m)^(#{1,3} [^\n]*)$", текст)
    итог, заг = [], ""
    for ч in куски:
        if ч.startswith("#"):
            заг = ч
            итог.append((заг, ""))
        elif итог:
            итог[-1] = (итог[-1][0], итог[-1][1] + ч)
        else:
            итог.append(("", ч))
    return итог


def сверить(текст, полка):
    """Правит только НЕВЕРНЫЕ числа, ничего не переставляя.

    10.09 · урок: попытка пересобрать фразу («знак в падеже», «минуты») ломала
    верные записи — «9°28′ Рыб» превращалось в «9° Дева», Хирон в «14°Тельц′».
    Теперь так: находим в разделе точки пару «градус + знак» в любом виде,
    сверяем; если не совпало — заменяем ТОЛЬКО цифры градуса и минут, слово
    знака не трогаем вовсе. Хуже сделать нельзя.
    """
    данные = из_полочки(полка)
    if not данные:
        return текст, []
    данные = минуты_из_тегов(полка, данные)
    правки = []

    собрано = []
    for заг, тело in _разделы(текст):
        чей = None
        нз = заг.lower()
        for имя_т in ПОРЯДОК:
            на_полке = ИМЕНА[имя_т]
            if на_полке not in данные:
                continue
            for вар in (имя_т.lower(), на_полке.lower()):
                if re.search(r"(?<![а-яёa-z])" + re.escape(вар) + r"(?![а-яёa-z])", нз):
                    чей = (имя_т, на_полке)
                    break
            if чей:
                break

        if чей:
            имена_точки = sorted([и for и, п_ in ИМЕНА.items() if п_ == чей[1]],
                                 key=len, reverse=True)
            д = данные[чей[1]]
            for имя_т in имена_точки:
                # «Хирон стоит в 18°32′ Тельца» и «Хирон — Телец 18°32′»
                # штрих после минут обязателен к учёту: «18°32′ Тельца»
                ш = re.compile(
                    re.escape(имя_т) + r"[^.\n]{0,60}?"
                    r"(?:(" + ЗНАК_ЛЮБОЙ + r")[а-яё]{0,3}[\s,]*(\d{1,2})\s*°(\d{1,2})?[′'\u2032]?"
                    r"|(\d{1,2})\s*°(\d{1,2})?[′'\u2032]?\s*(" + ЗНАК_ЛЮБОЙ + r")[а-яё]{0,3})")

                def правка(м, д=д, наше=чей[1]):
                    цел = м.group(0)
                    if м.group(1):           # знак впереди
                        знак_т, град_т, мин_т = м.group(1), м.group(2), м.group(3)
                    else:                     # число впереди
                        знак_т, град_т, мин_т = м.group(6), м.group(4), м.group(5)
                    if _имен(знак_т) == д["знак"] and int(град_т) == д["градус"]:
                        return цел
                    правки.append(f"{наше}: {град_т}° {_имен(знак_т)} → "
                                  f"{д['градус']}° {д['знак']}")
                    # меняем ТОЛЬКО цифры: градус и, если стоят, минуты
                    новый = re.sub(r"(?<![\d])" + re.escape(град_т) + r"(?=\s*°)",
                                   str(д["градус"]), цел, count=1)
                    if мин_т is not None and д.get("минут") is not None:
                        новый = re.sub(r"°" + re.escape(мин_т),
                                       "°" + f"{д['минут']:02d}", новый, count=1)
                    return новый

                тело = ш.sub(правка, тело)

            # код и ядро — только явно чужие
            if д["код"]:
                хоз_к, хоз_я = {}, {}
                for и, дд in данные.items():
                    if дд["код"]:
                        хоз_к.setdefault(дд["код"], set()).add(и)
                    if дд["ядро"]["тег"]:
                        хоз_я.setdefault(дд["ядро"]["тег"], set()).add(и)

                def пк(м, д=д, наше=чей[1], хоз_к=хоз_к, хоз_я=хоз_я):
                    тег = м.group(1).strip()
                    if тег in (д["код"], д["ядро"]["тег"]):
                        return м.group(0)
                    if хоз_к.get(тег) and наше not in хоз_к[тег]:
                        правки.append(f"{наше}: код [{тег[:30]}] → [{д['код'][:30]}]")
                        return "[" + д["код"] + "]"
                    if хоз_я.get(тег) and наше not in хоз_я[тег] and д["ядро"]["тег"]:
                        правки.append(f"{наше}: ядро [{тег[:30]}] → [{д['ядро']['тег'][:30]}]")
                        return "[" + д["ядро"]["тег"] + "]"
                    return м.group(0)
                тело = re.sub(r"\[([^\]]{4,90})\]", пк, тело)

        собрано.append(заг + тело if заг else тело)
    return "".join(собрано), правки
