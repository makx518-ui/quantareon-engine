def _связей(n, какая):
    """«одна напряжённая связь», «две гармоничные связи», «пять связей»"""
    слова = {1: "одна", 2: "две", 3: "три", 4: "четыре", 5: "пять", 6: "шесть", 7: "семь", 8: "восемь"}
    ч = слова.get(n, str(n))
    if n == 1:
        return f"{ч} {какая} связь"
    if 2 <= n <= 4:
        оконч = какая[:-2] + "ые" if какая.endswith("ая") else какая
        return f"{ч} {оконч} связи"
    оконч = какая[:-2] + "ых" if какая.endswith("ая") else какая
    return f"{ч} {оконч} связей"


