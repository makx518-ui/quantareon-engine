def скопления(точки, куспиды=None, орбис=5.0):
    """Связки — точки, стоящие вместе. Собираются ЦЕПОЧКОЙ (его правило 08.09):
    если узел соединён с Плутоном, а Плутон в орбисе с асцендентом, то все трое —
    один стеллиум, даже когда крайние далеки друг от друга: они взаимодействуют
    через среднее звено, на внутреннем плане.

    Углы участвуют наравне с планетами; у асцендента орбис широкий.
    """
    все = {и: т["градус"] for и, т in точки.items() if и != "ТЖ"}
    if куспиды and len(куспиды) >= 12:
        все["Асцендент"] = куспиды[0]
        все["Вершина"] = куспиды[9]
        все["Десцендент"] = куспиды[6]
        все["Дно"] = куспиды[3]

    имена = list(все)
    # кто с кем в орбисе
    рядом = {и: set() for и in имена}
    for i, а in enumerate(имена):
        for б in имена[i + 1:]:
            if {а, б} == {"Сев.Узел", "Юж.Узел"}:
                continue
            if K.дуга(все[а], все[б]) <= орбис:
                рядом[а].add(б)
                рядом[б].add(а)
    # цепочки: связное множество
    группы, пройдено = [], set()
    for и in имена:
        if и in пройдено or not рядом[и]:
            continue
        цепь, очередь = set(), [и]
        while очередь:
            х = очередь.pop()
            if х in цепь:
                continue
            цепь.add(х)
            очередь.extend(рядом[х] - цепь)
        пройдено |= цепь
        if len(цепь) >= 2:
            группы.append(sorted(цепь, key=lambda x: все[x]))
    # самая большая — первой
    группы.sort(key=len, reverse=True)
    return группы


def узор_скопления(группа, точки, куспиды=None, аспекты=None, самая_большая=False):
    """Цельная картина связки по классическому алгоритму, восемь слоёв подряд:
       1 что за место — дом и знак; 2 кто в ней, у каждого градус, владение, сила;
       3 управитель знака связки; 4 управитель самого дома; 5 обратные кольца;
       6 соединения внутри; 7 аспекты извне; 8 итог.
    Ни один слой не пропускается."""
    все = dict(точки)
    if куспиды and len(куспиды) >= 12:
        for имя, i in (("Асцендент", 0), ("Вершина", 9), ("Десцендент", 6), ("Дно", 3)):
            т_ = K.точка("Асцендент" if "сцендент" in имя else "MC", куспиды[i])
