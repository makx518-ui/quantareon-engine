# предлог «во» перед стечением согласных
ПРЕДЛОГ_ВО = {"Лев", "Львы"}


def _в(з):
    """«в Деве», но «во Льве»"""
    return ("во " if з in ПРЕДЛОГ_ВО else "в ") + ЗНАК_ПРЕДЛ.get(з, з)


def _знак_род(з):
    """«в роли Скорпиона»"""
    род = {"Овен": "Овна", "Телец": "Тельца", "Близнецы": "Близнецов", "Рак": "Рака",
           "Лев": "Льва", "Дева": "Девы", "Весы": "Весов", "Скорпион": "Скорпиона",
           "Стрелец": "Стрельца", "Козерог": "Козерога", "Водолей": "Водолея", "Рыбы": "Рыб"}
    return род.get(з, з)


def _знак_предл(з):
    return ЗНАК_ПРЕДЛ.get(з, з)


def _дом_предл(н):
    """«в пятом доме творчества» — предложный падеж, читаемо."""
    числ = {1: "первом", 2: "втором", 3: "третьем", 4: "четвёртом", 5: "пятом", 6: "шестом",
            7: "седьмом", 8: "восьмом", 9: "девятом", 10: "десятом", 11: "одиннадцатом", 12: "двенадцатом"}
    д = S.ДОМА.get(н)
    имя = (д["имя"] if д else "доме").replace("дом ", "доме ")
    return f"{числ.get(н, str(н))} {имя}"


