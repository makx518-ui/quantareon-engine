    гр = скопления(точки, куспиды)
    if гр:
        л += ["─" * 74, "  СВЯЗКИ — силы, стоящие в одном месте", "─" * 74]
        for н_, г in enumerate(гр):
            т_ = узор_скопления(г, точки, куспиды, аспекты, самая_большая=(н_ == 0))
            if т_:
                л += ["", т_]
        л.append("")
