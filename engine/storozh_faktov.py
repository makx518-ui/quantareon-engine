# -*- coding: utf-8 -*-
"""28.09 · СТОРОЖ ФАКТОВ натала классики — его решение: «если ИИ глючит, пусть машина поправляет».

ИИ пишет прозу, но три вещи раз за разом выдумывает, хотя в задании правило стоит:
  1. «Марс на самой вершине» — а Марс просто в десятом доме, с MC не соединён;
  2. «Солнце в чертоге Водолея» — а Солнце в Водолее в изгнании (чертог — только свой знак);
  3. «Хирон рядом с Южным узлом» — а между ними 5,7°, соединения по его орбисам нет.

Машина знает карту: дома, достоинства, аспекты с его орбисами и связками. После ИИ сторож
проходит текст по предложениям, находит точку, к которой относится фраза (последняя названная
перед ней в том же предложении), и сверяет с машиной. Не совпало — фраза правится или убирается.
Совпало — не трогается. Числа, коды и остальной текст сторож не меняет.
"""
import re

# имена точек в любых падежах; составные — раньше простых (Чёрная Луна раньше Луны)
_ТОЧКИ = [
    ("Чёрная Луна", r"Ч[её]рн\w{0,3}\s+Лун\w{0,2}"),
    ("Белая Луна", r"Бел\w{0,3}\s+Лун\w{0,2}"),
    ("Сев.Узел", r"Северн\w{0,3}\s+[Уу]з(?:ел|л\w{0,2})"),
    ("Юж.Узел", r"Южн\w{0,3}\s+[Уу]з(?:ел|л\w{0,2})"),
    ("Солнце", r"Солнц(?:е|а|у|ем)"),
    ("Луна", r"Лун(?:а|ы|е|у|ой)(?![а-яё])"),
    ("Меркурий", r"Меркури(?:й|я|ю|ем|и)"),
    ("Венера", r"Венер(?:а|ы|е|у|ой)"),
    ("Марс", r"Марс(?:а|у|ом|е)?(?![а-яё])"),
    ("Юпитер", r"Юпитер(?:а|у|ом|е)?(?![а-яё])"),
    ("Сатурн", r"Сатурн(?:а|у|ом|е)?(?![а-яё])"),
    ("Уран", r"Уран(?:а|у|ом|е)?(?![а-яё])"),
    ("Нептун", r"Нептун(?:а|у|ом|е)?(?![а-яё])"),
    ("Плутон", r"Плутон(?:а|у|ом|е)?(?![а-яё])"),
    ("Хирон", r"Хирон(?:а|у|ом|е)?(?![а-яё])"),
    ("ASC", r"ASC|Асцендент(?:а|у|ом|е)?"),
    ("MC", r"(?<![A-Za-z])MC(?![A-Za-z])"),
]
_ПЛАНЕТЫ = ("Солнце", "Луна", "Меркурий", "Венера", "Марс", "Юпитер", "Сатурн", "Уран", "Нептун", "Плутон")
_ЗНАКИ = ["Овна", "Тельца", "Близнецов", "Рака", "Льва", "Девы", "Весов", "Скорпиона", "Стрельца",
          "Козерога", "Водолея", "Рыб"]
_ЗНАКИ_ИМ = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева", "Весы", "Скорпион", "Стрелец",
             "Козерог", "Водолей", "Рыбы"]


def _упоминания(предл):
    """[(начало, конец, точка)] в предложении, без наложений."""
    занято, итог = [], []
    for имя, выр in _ТОЧКИ:
        for м in re.finditer(выр, предл):
            if any(м.start() < к and н < м.end() for н, к in занято):
                continue
            занято.append((м.start(), м.end()))
            итог.append((м.start(), м.end(), имя))
    return sorted(итог)


def _предложения(текст):
    """Куски текста: предложения и разделители — склеиваются обратно без потерь."""
    return re.split(r"((?<=[.!?…])\s+|\n)", текст)


class Сторож:
    def __init__(self, мост, аспекты):
        self.м = мост
        self.соед, self.вид, self.орб = set(), {}, {}
        for в, _о, a, b, *_ in аспекты:
            self.вид.setdefault(frozenset((a, b)), в)
            self.орб.setdefault(frozenset((a, b)), _о)
            if в == "соединение":
                self.соед.add(frozenset((a, b)))
        from engine import kosmogramma as K
        self.дост = {}
        for п in _ПЛАНЕТЫ:
            if п in мост.flat:
                з = _ЗНАКИ_ИМ[int(мост.flat[п] // 30) % 12]
                try:
                    д = K.достоинство(п, з)
                    self.дост[п] = (д[0] if isinstance(д, (tuple, list)) else (д or "")).upper()
                except Exception:
                    self.дост[п] = ""
        self.правки = []

    def _дом(self, точка):
        try:
            return self.м.house_of(self.м.flat[точка])
        except Exception:
            return None

    def _знак(self, точка):
        return _ЗНАКИ[int(self.м.flat[точка] // 30) % 12] if точка in self.м.flat else ""

    def _кто(self, предл, поз):
        """Последняя точка, названная в предложении до позиции поз."""
        до = [у for у in _упоминания(предл) if у[1] <= поз]
        return до[-1][2] if до else None

    # ── 1. «на самой вершине» без соединения с MC
    _ВЕРШИНА = re.compile(r"(?:,\s*)?(?:который\s+|которая\s+)?(?:стоит\s+|находится\s+)?"
                          r"(?:прямо\s+)?[Нн]а\s+(?:самой\s+)?вершине(?:\s+(?:судьбы|дела|призвания|карты|неба))?")

    def вершина(self, предл):
        def зам(м):
            кто = self._кто(предл, м.start())
            заглавная = м.group(0)[:1] == "Н"
            if not кто and заглавная:                     # «На самой вершине дела стоит Марс»
                после = [у for у in _упоминания(предл) if у[0] >= м.end() and у[0] - м.end() <= 30]
                кто = после[0][2] if после else None
                if кто and кто != "MC" and frozenset((кто, "MC")) not in self.соед and self._дом(кто) == 10:
                    self.правки.append(f"{кто}: «{м.group(0)}» → «В десятом доме» (с MC не соединён)")
                    return "В десятом доме"
                return м.group(0)
            if not кто or кто == "MC" or frozenset((кто, "MC")) in self.соед:
                return м.group(0)
            хвост = предл[м.end():м.end() + 25]
            if re.match(r"\s*,?\s*в\s+десятом\s+доме", хвост) or self._дом(кто) != 10:
                нов = ""                                  # дом уже назван рядом (или планета не в 10-м)
            else:
                нов = (", " if м.group(0).startswith(",") else " ") + "в десятом доме"
            self.правки.append(f"{кто}: «{м.group(0).strip(' ,')}» → «{нов.strip(' ,') or '—'}» (с MC не соединён)")
            return нов
        return self._ВЕРШИНА.sub(зам, предл)

    # ── 2. достоинство, которого у точки нет («чертог» при изгнании и т. п.)
    _ДОСТ = re.compile(r"(?:в\s+)?(?:(?:своём|своем|собственном|родном|свободном|глубоком|и)\s+){0,4}"
                       r"(чертог[еау]?|обители)(\s+(?:" + "|".join(_ЗНАКИ) + r"))?")

    def достоинство(self, предл):
        def зам(м):
            кто = self._кто(предл, м.start())
            if кто not in self.дост or "ЧЕРТОГ" in self.дост[кто]:
                return м.group(0)
            знак = (м.group(2) or "").strip()
            нов = f"в знаке {знак}" if знак else ""
            self.правки.append(f"{кто}: «{м.group(0).strip()}» → «{нов or '—'}» "
                               f"(у машины: {self.дост[кто].lower() or 'без достоинства'})")
            return нов
        нов = self._ДОСТ.sub(зам, предл)
        return re.sub(r"\s+,", ",", re.sub(r" {2,}", " ", нов)) if нов != предл else нов

    # ── 3. «рядом / вплотную / в соединении» без соединения у машины
    _РЯДОМ = re.compile(r"(?:,\s*)?(?:прямо\s+)?(?:рядом\s+с|вплотную\s+(?:к|с)|"
                        r"в\s+(?:тесном\s+|плотном\s+|точном\s+)?соединении\s+с)\s+")

    def рядом(self, предл):
        итог, поз = [], 0
        for м in self._РЯДОМ.finditer(предл):
            после = предл[м.end():]
            с_кем = next((у for у in _упоминания(после) if у[0] <= 25), None)
            кто = self._кто(предл, м.start())
            if not с_кем or not кто or кто == с_кем[2] or frozenset((кто, с_кем[2])) in self.соед:
                continue
            # соединения нет: «рядом с X» → «в одном доме с X» (дом общий) или убрать упоминание
            к_концу = м.end() + с_кем[1]
            рядом_дом = re.search(r"дом\w*\s*$", предл[max(0, м.start() - 30):м.start()])
            нач = ", " if м.group(0).startswith(",") else " "
            имя_с = после[:с_кем[1]]
            дательный = bool(re.search(r"\sк\s+$", м.group(0)))   # «вплотную к Южному узлу»
            if self.вид.get(frozenset((кто, с_кем[2]))) == "оппозиция":
                нов = нач + ("в оппозиции к " if дательный else "в оппозиции с ") + имя_с   # у машины ось
            elif (not дательный and self._дом(кто) and self._дом(кто) == self._дом(с_кем[2])
                  and not рядом_дом):
                нов = нач + "в одном доме с " + имя_с
            else:
                нов = ""
            итог.append((м.start(), к_концу, нов))
            self.правки.append(f"{кто}–{с_кем[2]}: «{предл[м.start():к_концу].strip(' ,')}» → "
                               f"«{нов.strip(' ,') or '—'}» (соединения нет)")
        for н, к, нов in reversed(итог):
            предл = предл[:н] + нов + предл[к:]
        return предл

    # ── 4. «точное соединение» — только до 1° (его правка 28.09: Плутон–Сев.узел 1,17°, Юпитер–Сатурн 2,13°)
    _ТОЧНОЕ = re.compile(r"\b(?:в\s+)?(точн(?:ое|ом|ым|ого|ая|ой)\s+)(соединени[еяию]|соединени[ея]м)\b")

    def точное(self, предл):
        def зам(м):
            кто = self._кто(предл, м.start())
            после = предл[м.end():]
            с_кем = next((у for у in _упоминания(после) if у[0] <= 25), None)
            if not с_кем:     # «Юпитер … в точном соединении в том же доме» — вторая точка раньше
                до = [у for у in _упоминания(предл) if у[1] <= м.start()]
                пары = [(до[i][2], до[-1][2]) for i in range(len(до) - 1)] if len(до) >= 2 else []
                if not пары:
                    return м.group(0)
                кто, второй = пары[-1]
            else:
                второй = с_кем[2]
            о = self.орб.get(frozenset((кто or "", второй)))
            if о is None or о <= 1.0:
                return м.group(0)
            self.правки.append(f"{кто}–{второй}: «{м.group(1).strip()}» убрано (орб {о:.2f}° > 1°)")
            return м.group(0).replace(м.group(1), "")
        return self._ТОЧНОЕ.sub(зам, предл)

    def проверить(self, текст):
        куски = _предложения(текст)
        for i in range(0, len(куски), 2):
            п = куски[i]
            if not п or not п.strip():
                continue
            п = self.вершина(п)
            п = self.достоинство(п)
            п = self.рядом(п)
            п = self.точное(п)
            if п != куски[i]:
                п = re.sub(r"\s+([,.;:!?])", r"\1", re.sub(r"(?<=\S) {2,}", " ", п))
            куски[i] = п
        return "".join(к for к in куски if к is not None)


def сторожить(текст, точки, куспиды, углы=None):
    """(текст, правки). При любой ошибке — текст как есть."""
    try:
        from engine import most as М, klassika_natal as KN
        м = М.Мост(точки, куспиды, углы)
        с = Сторож(м, KN.аспекты_классики(м.flat))
        return с.проверить(текст), с.правки
    except Exception as e:
        print(f"сторож фактов: {type(e).__name__}: {e}")
        return текст, []
