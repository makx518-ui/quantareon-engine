"""
НАТАЛЬНЫЙ ПОРТРЕТ ПЛАНЕТЫ (фон «кто она по жизни») — дополнение машины по его правилу:
трактовка каждого аспекта — через натальную суть планеты: кто она (управитель какого дома),
где жила всю жизнь (натальный дом), её задача (код градуса) — и лишь потом что даёт в аспекте.
Эталон: Уран — управитель 6-го, жил в тени 12-го, бурит на MC к живой воде.
Машина готовит портрет как фон; событийный вектор из него выводит ИИ.
"""
import kod360, micro_cascade

SIGN=["Овен","Телец","Близнецы","Рак","Лев","Дева","Весы","Скорпион","Стрелец","Козерог","Водолей","Рыбы"]
RULER=["Марс","Венера","Меркурий","Луна","Солнце","Меркурий","Венера","Плутон","Юпитер","Сатурн","Уран","Нептун"]
CHAR={"Солнце":"дух, ядро «Я»","Луна":"душа, чувства, корни","Меркурий":"ум, речь","Венера":"любовь, ценности",
 "Марс":"воля, действие","Юпитер":"рост, вера","Сатурн":"структура, форма","Уран":"прорыв, высшее Я",
 "Нептун":"туман, тонкий канал","Плутон":"чистка, глубина","Сев.Узел":"кармическая цель","Юж.Узел":"кармический багаж",
 "Хирон":"рана-целитель","Чёрная Луна":"тень, искушение","Белая Луна":"благодать свыше",
 "ASC":"личность","MC":"цель, вершина","IC":"основа, итог","DSC":"партнёр"}

def natal_portrait(machine, name):
    """Портрет точки по наталу: знак·дом, какими домами владеет, диспозитор, код, ядро."""
    if name not in machine.flat: return None
    ap = machine.flat[name]
    sn = int(ap//30); pis = ap % 30
    dom = machine.house_of(ap)
    # какими домами планета владеет (по знакам на куспидах)
    vladeet = [i+1 for i in range(12) if RULER[int(machine.cusps[i]//30)] == name]
    code = kod360.code_by_abs(ap)
    core = micro_cascade.cascade_from_absolute(ap,1)['cascade'][0]
    core_code = kod360.load()[(core.get('sign_num', core.get('sign_index',0))+1, core['sabian'])]
    return {
        "имя": name, "характер": CHAR.get(name,name),
        "знак": SIGN[sn], "градус_н": int(pis)+1, "дом": dom,
        "владеет_домами": vladeet,
        "диспозитор": RULER[sn],
        "код": code['tag'], "суть": code.get('sut','')[:90],
        "ядро": f"{core['sign_name']} {core['sabian']}° [{core_code['tag']}]",
    }

def portrait_line(p):
    vl = ("управитель "+"/".join(f"{h}-го" for h in p["владеет_домами"])+" дома") if p["владеет_домами"] else "домами не управляет"
    return (f"{p['имя']} — {p['характер']}. Натал: {p['знак']} {p['градус_н']}°, дом {p['дом']}, {vl}; "
            f"диспозитор {p['диспозитор']}. Код жизни [{p['код']}] · ядро {p['ядро']}")

def all_portraits(machine):
    order=["Солнце","Луна","Меркурий","Венера","Марс","Юпитер","Сатурн","Уран","Нептун","Плутон",
           "Хирон","Сев.Узел","Юж.Узел","Чёрная Луна","Белая Луна","ASC","MC"]
    return {n: natal_portrait(machine,n) for n in order if n in machine.flat}
