def ядро_абзацем(юж_дом: int, сев_дом: int, сев_знак: str,
                 оттенок: str = "", второй_оборот: bool = False,
                 движение: str = "отрыв") -> str:
    """Ядро дня живыми словами.

    Форма первой строки выбирается ПО СМЫСЛУ карты: куда ведёт день (дом
    приходящего узла) и как идти (напряжён ли уходящий узел).
    """
    от_чего, раскрытие_от = ЮЖНЫЙ_ДОМ.get(юж_дом, ("", ""))
    к_чему, раскрытие_к = СЕВЕРНЫЙ_ДОМ.get(сев_дом, ("", ""))
    дальше = СЕВЕРНЫЙ_ЗНАК_ДАЛЬШЕ.get(сев_знак, "")

    вид = ХАРАКТЕР_ДНЯ.get(сев_дом, "действие")
    форма = ЗАЧИН[вид].get(движение) or ЗАЧИН[вид]["отрыв"]

    строка = форма.format(
        откуда=от_чего,
        откуда_род=ОТКУДА_РОД.get(юж_дом, от_чего),
        откуда_деепр=ОТКУДА_ДЕЕПР.get(юж_дом, от_чего),
        где=ГДЕ.get(юж_дом, от_чего),
        куда=к_чему,
        куда_дел=КУДА_ДЕЛ.get(сев_дом, к_чему),
    )
    if оттенок:
        строка += " " + оттенок
    абзац = " ".join(х for х in (раскрытие_от, раскрытие_к, дальше) if х)
    return f"**{строка}**\n{абзац}"


def расстановка_абзацем(опора_дом: int, цена_дом: int, тень_дом: int,
                        тень_на_векторе: bool = False,
                        бьёт_по: tuple = ()) -> str:
    """Опора, цена, тень — тремя фразами."""
    строки = [ОПОРА_ДОМ.get(опора_дом, ""), ЦЕНА_ДОМ.get(цена_дом, "")]

    тень = ТЕНЬ_ДОМ.get(тень_дом, "")
    if тень_на_векторе:
        тень = f"{тень} {ТЕНЬ_НА_ВЕКТОРЕ}"
    if бьёт_по:
        сферы = ", ".join(СФЕРА_КОРОТКО[д] for д in sorted(set(бьёт_по))
                          if д in СФЕРА_КОРОТКО)
        if сферы:
            тень = f"{тень} {ТЕНЬ_БЬЁТ.format(сферы=сферы)}"
    строки.append(тень)
    return "\n".join(с for с in строки if с)


