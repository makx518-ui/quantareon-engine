def данные_прочтения(мост, полка="", имена=None, с_аспектами=True):
    """Each degree meaning is bound to its own name and coordinate, not a neighbour.

    Uses the same AF dictionary as most.полочка_натала. Never substitutes a
    different dictionary's label or infers houses when cusps are absent.
    """
    коды_полки = KN._коды_полки(полка)
    управление = KN._дома_управления(мост)
    точки = []
    for имя, градус in мост.flat.items():
        if имена is not None and имя not in имена:
            continue
        запись = {
            "имя": имя, "функция": ФУНКЦИИ.get(имя, ""),
            "положение": KN._реал(градус), "символ_градуса": KN._градус(градус),
            "непосредственный_диспозитор": KN.УПРАВИТЕЛЬ[KN._знак(градус)],
        }
        if len(мост.cusps) >= 12:
            запись["дом"] = мост.house_of(градус)
            запись["управляет_домами"] = управление.get(имя, [])
        код = kod360.code_by_abs(градус)
        из_полки = коды_полки.get(имя)
        # A contradictory shelf is not repaired by inventing a preferred source.
        if из_полки and из_полки[0] != код["tag"]:
            запись["противоречие_кода"] = "код строки не совпал со словарём; не выводить смысл догадкой"
        else:
            запись["код_градуса"] = {ключ: код[ключ] for ключ in ("tag", "суть", "действие", "риск")}
        точки.append(запись)
    аспекты = []
    for вид, орб, a, b, пометка in (KN.аспекты_классики(мост.flat) if с_аспектами else []):
        аспекты.append({
            "A": a, "B": b, "вид": вид,
            "номинальный_угол": KN.УГЛЫ_АСПЕКТОВ[вид],
            "реальный_угол": round(KN._разн(мост.flat[a], мост.flat[b]), 4),
            "орб": орб, "пометка": пометка,
        })
    данные = {
        "источник": "текущий машинный расчёт; значения не из учебного примера",
        "система_управителей": "современная; традиционные не подменяют главных",
        "баланс_считается_по": "10 планет и присутствующие ASC, MC; не только планеты",
        "точки": точки, "аспекты": аспекты,
    }
    return "[ДАННЫЕ СМЫСЛОВОГО ПРОЧТЕНИЯ — каждому имени только его запись]\n" + json.dumps(
        данные, ensure_ascii=False, separators=(",", ":"))
