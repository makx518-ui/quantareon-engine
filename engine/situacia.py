def средняя_скорость(код, момент):
    """Средний ход планеты — считается по эфемеридам за полный оборот,
    а не берётся из таблицы. ⚠️ Его правило 03.09: не выдумывать
    коэффициенты — движок считает всё сам, ему только дай данные."""
    j = юлиан(момент)
    ОБОРОТ = {swe.SUN: 365.25, swe.MOON: 27.32, swe.MERCURY: 87.97,
              swe.VENUS: 224.7, swe.MARS: 686.98, swe.JUPITER: 4332.6,
              swe.SATURN: 10759.2, swe.URANUS: 30685.4, swe.NEPTUNE: 60189.0,
              swe.PLUTO: 90560.0, swe.CHIRON: 18516.0}
    период = ОБОРОТ.get(код)
    if not период:
        return None
    # берём реальное смещение за половину оборота и делим — чистая эфемерида
    шаг = период / 2
    а = swe.calc_ut(j - шаг / 2, код)[0][0]
    б = swe.calc_ut(j + шаг / 2, код)[0][0]
    пройдено = (б - а) % 360
    if период > 400:                       # медленные за полоборота < 360°
        return пройдено / шаг
    return 360.0 / период


def юлиан(момент):
    return swe.julday(момент.year, момент.month, момент.day,
                      момент.hour + момент.minute/60 + момент.second/3600)


