def таблица_медленных(космо, рождение, момент, куспиды_натал=None):
    """Все медленные величины одной таблицей: Колесо, дирекции,
    прогрессии, профекция. То, что не видно на колесе."""
    кол = колесо(рождение, момент)
    дир = дирекции(космо, рождение, момент)
    прог = прогрессии(None, рождение, момент, 0, 0)
    проф = профекция(рождение, момент)
    ск = сроки_колеса(кол["градус"], момент)
    строки = []

    # Колесо жизни
    строки.append({
        "раздел": "КОЛЕСО ЖИЗНИ", "точка": "Точка Жизни",
        "позиция": кол["словами"], "код": кол["код"]["тег"],
        "дом": (K.дом_точки(кол["градус"], куспиды_натал)
                if куспиды_натал else None),
        "срок": (f"{ск['градус']['начался'].strftime('%m.%Y')}–"
                 f"{ск['градус']['кончится'].strftime('%m.%Y')}"),
        "примечание": (f"эпоха {кол['эпоха']['знак']}, "
                       f"годы {кол['эпоха']['годы'][0]}–{кол['эпоха']['годы'][1]}"),
    })
    п = (кол.get("подградусы") or [{}])[0]
    if п.get("тег"):
        строки.append({
            "раздел": "КОЛЕСО ЖИЗНИ", "точка": "подградус",
            "позиция": п.get("словами", ""), "код": п["тег"], "дом": None,
            "срок": (f"{ск['подградус']['начался'].strftime('%d.%m')}–"
                     f"{ск['подградус']['кончится'].strftime('%d.%m')}"),
            "примечание": f"долька {ск['подградус']['номер']} из 12",
        })

    # Дирекции
    for имя, т in дир["точки"].items():
        строки.append({
            "раздел": "ДИРЕКЦИИ", "точка": имя,
            "позиция": т.get("словами", ""), "код": т["код"]["тег"],
            "дом": (K.дом_точки(т["градус"], куспиды_натал)
                    if куспиды_натал else None),
            "срок": "", "примечание": f"дуга {дир['дуга']}°",
        })
    # связи дирекций
    for с in связи_медленных(дир["точки"], космо, "дирекция"):
        ср = сроки_дирекции(с["т"]["градус"], с["н"]["градус"], с["угол"], момент)
        строки.append({
            "раздел": "ДИРЕКЦИИ · связи",
            "точка": f"дир.{K.имя_точки(с['точка'])} {с['аспект']} "
                     f"косм.{K.имя_точки(с['натал'])}",
            "позиция": f"орб {с['орбис']:.2f}°", "код": с["н"]["код"]["тег"],
            "дом": None, "срок": ср["дата"].strftime("%m.%Y"),
            "примечание": "точная" if с["точный"] else "в орбисе",
        })

    # Прогрессии
    for имя, т in прог["точки"].items():
        строки.append({
            "раздел": "ПРОГРЕССИИ", "точка": имя,
            "позиция": т.get("словами", ""), "код": т["код"]["тег"],
            "дом": (K.дом_точки(т["градус"], куспиды_натал)
                    if куспиды_натал else None),
            "срок": "", "примечание": "день за год",
        })
    строки.append({
        "раздел": "ПРОГРЕССИИ", "точка": "фаза прогр. Луны",
        "позиция": прог["фаза"]["имя"], "код": "",
        "дом": None, "срок": "", "примечание": прог["фаза"]["смысл"],
    })

    # Профекция
    строки.append({
        "раздел": "ПРОФЕКЦИЯ", "точка": "тема года",
        "позиция": f"сектор {проф['сектор']}", "код": "",
        "дом": проф["сектор"], "срок": f"{проф['возраст']} лет",
        "примечание": проф["тема"],
    })
    return строки


def таблица_медленных_текстом(строки):
    """Та же таблица словами — для полочки."""
    л = ["", "╔══ МЕДЛЕННЫЕ · ТАБЛИЦА ПОД КАРТУ ══",
         "  Колесо, дирекции, прогрессии, профекция — то, чего не видно",
         "  на колесе, но что задаёт весь фон периода.", ""]
    текущий = None
    for с in строки:
        if с["раздел"] != текущий:
            текущий = с["раздел"]
            л.append(f"  ── {текущий}")
        дом = f" · дом {с['дом']}" if с.get("дом") else ""
        код = f" [{с['код']}]" if с.get("код") else ""
        срок = f" · {с['срок']}" if с.get("срок") else ""
        л.append(f"     {с['точка']:34} {с['позиция']:30}{код}{дом}{срок}")
        if с.get("примечание"):
            л.append(f"        {с['примечание']}")
    return л
