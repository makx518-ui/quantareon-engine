# ═══════════════════════════════════════════════════════════════════
#  СОЛЯР — ветка второго слоя, а не отдельный продукт
# ═══════════════════════════════════════════════════════════════════
#  Его решение 04.09: «соляр это тот же транзит, просто считается
#  от дня рождения». Механика одна, разница только в моменте.

def момент_соляра(рождение, год, широта=None, долгота=None):
    """Когда Солнце вернётся в свой натальный градус в заданном году.
    Ищем движком, не приближением."""
    j0 = юлиан(рождение)
    сол0 = swe.calc_ut(j0, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]

    def солнце(т):
        j = юлиан(т)
        return swe.calc_ut(j, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]

    # старт — день рождения этого года, минус пять суток
    низ = datetime(год, рождение.month, рождение.day,
                   tzinfo=timezone.utc) - timedelta(days=5)
    верх = низ + timedelta(days=10)
    for _ in range(60):
        с = низ + (верх - низ) / 2
        d = (солнце(с) - сол0) % 360
        if d > 180:
            d -= 360
        if d < 0:
            низ = с
        else:
            верх = с
    м = низ + (верх - низ) / 2
    return {"момент": м, "натальное_солнце": сол0,
            "солнце_соляра": солнце(м),
            "расхождение_сек": round(K.дуга(солнце(м), сол0) * 3600, 1)}


def соляр(космо, рождение, год, широта, долгота, куспиды_натал=None,
          имя_человека="человек", место=""):
    """Полный расклад года — тем же кодом, что и обычная ситуация.

    Единственная разница: момент расчёта не «сейчас», а возвращение
    Солнца. Всё прочее считается одинаково — Колесо, дирекции,
    прогрессии, накладка, семь звеньев классики.
    """
    св = момент_соляра(рождение, год, широта, долгота)
    м = св["момент"]
    текст = полочка_ситуации(космо, рождение, м, место=место,
                             имя_человека=имя_человека,
                             широта=широта, долгота=долгота,
                             куспиды_натал=куспиды_натал,
                             подпись_слоя="СОЛЯР")
    # шапка соляра — поверх обычной
    ч = "═" * 74
    шапка = [ч, f"СОЛЯР {год}–{год+1} · КАРТА ГОДА",
             f"{имя_человека}{' · ' + место if место else ''}", ч,
             f"  возвращение Солнца: {м.strftime('%d.%m.%Y %H:%M')} UTC",
             f"  расхождение с натальным градусом: {св['расхождение_сек']}″"]
    if св["расхождение_сек"] < 60:
        шапка.append("  ⚑ СОВЕРШЕННЫЙ СОЛЯР — Солнце вернулось точно: "
                     "год идёт на полной мощности природы, без разбавления")
    шапка += ["  Считается тем же кодом, что и ситуация: разница только в моменте.",
              "  Всё, что ниже, относится к году от дня рождения до дня рождения.", ""]
    return "\n".join(шапка) + "\n" + текст


def дома_момента_и_натала(космо, тр, куспиды_момента, куспиды_натал):
    """Накладка дом на дом: где точка стоит в одной сетке и в другой.

    Его требование 04.09: для соляра надо видеть не только знак,
    но и как натальный дом ложится в дом года. Это и есть перевод
    темы жизни в тему периода.
    """
    итог = {"натальные_в_домах_момента": [], "точки_момента_в_домах": [],
            "хозяева_домов_момента": []}
    if not куспиды_момента:
        return итог

    for имя, т in космо.items():
        д_мом = K.дом_точки(т["градус"], куспиды_момента)
        д_нат = K.дом_точки(т["градус"], куспиды_натал) if куспиды_натал else None
        итог["натальные_в_домах_момента"].append({
            "точка": имя, "дом_момента": д_мом, "дом_натальный": д_нат,
            "сфера_момента": K.СФЕРА_ДОМА.get(д_мом),
            "сфера_натальная": K.СФЕРА_ДОМА.get(д_нат) if д_нат else None,
            "сместился": (д_мом != д_нат) if д_нат else None,
            "код": т["код"]["тег"], "словами": т.get("словами"),
        })
    for имя, т in тр.items():
        if имя in ("Юж.Узел",):
            continue
        итог["точки_момента_в_домах"].append({
            "точка": имя,
            "дом_момента": K.дом_точки(т["градус"], куспиды_момента),
            "дом_натальный": (K.дом_точки(т["градус"], куспиды_натал)
                              if куспиды_натал else None),
            "код": т["код"]["тег"], "словами": т.get("словами"),
            "ретро": т.get("ретро", False),
        })
    # хозяева домов момента и где они стоят
    for н in range(1, 13):
        зн = K.знак(куспиды_момента[н - 1])
        хоз = K.УПРАВИТЕЛЬ[зн][0]
        где_мом = тр.get(хоз)
        итог["хозяева_домов_момента"].append({
            "дом": н, "сфера": K.СФЕРА_ДОМА[н], "знак_куспида": зн,
            "хозяин": хоз,
            "стоит_в_доме_момента": (K.дом_точки(где_мом["градус"], куспиды_момента)
                                     if где_мом else None),
            "стоит_в_доме_натал": (K.дом_точки(где_мом["градус"], куспиды_натал)
                                   if где_мом and куспиды_натал else None),
            "словами": где_мом.get("словами") if где_мом else None,
            "код": где_мом["код"]["тег"] if где_мом else None,
        })
    return итог


