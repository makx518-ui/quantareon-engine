# ═══════════════════════════════════════════════════════════════════
#  СРОКИ · когда точно, сколько прохождений, какой коридор
# ═══════════════════════════════════════════════════════════════════
#  Его требование: машина должна давать не снимок, а коридор с датами.
#  Ретроградные планеты проходят точку по три раза — это надо видеть.

def сроки_транзита(планета_код, цель, угол, момент, вперёд_лет=3, назад_лет=2):
    """Все точные прохождения транзита через аспект: назад и вперёд.
    Учитывает ретроградные петли — их бывает до трёх подряд."""
    def где(т):
        j = swe.julday(т.year, т.month, т.day, 12)
        return swe.calc_ut(j, планета_код)[0][0]

    цели = [(цель + угол) % 360, (цель - угол) % 360]
    точные = []
    т = момент - timedelta(days=назад_лет * 365)
    конец = момент + timedelta(days=вперёд_лет * 365)
    шаг = timedelta(days=2)
    пред = min(K.дуга(где(т), ц) for ц in цели)
    while т < конец:
        т2 = т + шаг
        d = min(K.дуга(где(т2), ц) for ц in цели)
        if d > пред and пред < 1.0:
            низ, верх = т - шаг, т2
            for _ in range(35):
                a = низ + (верх - низ) / 3
                b = верх - (верх - низ) / 3
                da = min(K.дуга(где(a), ц) for ц in цели)
                db = min(K.дуга(где(b), ц) for ц in цели)
                if da < db:
                    верх = b
                else:
                    низ = a
            м = низ + (верх - низ) / 2
            если_точно = min(K.дуга(где(м), ц) for ц in цели)
            if если_точно < 0.15:
                точные.append(м)
        пред = d
        т = т2
    # коридор рабочего орбиса вокруг текущего момента
    орб = ОРБИС_ВЫСШЕЙ if планета_код in (swe.URANUS, swe.NEPTUNE, swe.PLUTO) else ОРБИС_ТРАНЗИТА
    вход = выход = None
    т = момент - timedelta(days=назад_лет * 365)
    внутри = False
    while т < конец:
        d = min(K.дуга(где(т), ц) for ц in цели)
        if d <= орб and not внутри:
            вход, внутри = т, True
        elif d > орб and внутри:
            выход, внутри = т, False
            if выход > момент:
                break
        т += шаг
    return {"точные": точные, "вход": вход, "выход": выход,
            "прохождений": len(точные)}


def сроки_дирекции(градус_дир, цель, угол, момент, скорость_дуги=None):
    """Дирекция идёт ~1°/год: дата точности и коридор орбиса 1°."""
    # скорость берём из движка: сколько Солнце проходит за год около этой даты
    if скорость_дуги is None:
        j = юлиан(момент)
        с0 = swe.calc_ut(j, swe.SUN)[0][0]
        с1 = swe.calc_ut(j + 1, swe.SUN)[0][0]
        скорость_дуги = (с1 - с0) % 360        # °/год (день за год)
    лучшее = None
    for знак_ in (угол, -угол):
        точка_ = (цель + знак_) % 360
        сдвиг = (точка_ - градус_дир) % 360
        if сдвиг > 180:
            сдвиг -= 360
        лет = сдвиг / скорость_дуги
        if лучшее is None or abs(лет) < abs(лучшее[0]):
            лучшее = (лет, момент + timedelta(days=лет * 365.25))
    лет, дата = лучшее
    коридор = ОРБИС_МЕДЛЕННЫХ / скорость_дуги * 365.25
    return {"лет": round(лет, 3), "дата": дата,
            "вход": дата - timedelta(days=коридор),
            "выход": дата + timedelta(days=коридор),
            "прошло": лет < 0}


# ═══════════════════════════════════════════════════════════════════
#  СОЛНЦЕ ПО НЕСУЩИМ ТОЧКАМ — узловые дни
# ═══════════════════════════════════════════════════════════════════
#  Находка 03.09: события завязались, когда транзитное Солнце шло
#  по связке узел–Плутон, то есть по точке сборки карты.
#  Мы считаем ОТ СОЛНЦА — значит его проход по несущим точкам
#  подсвечивает саму дорогу судьбы. Машина обязана это отмечать.

def солнце_по_несущим(космо, момент, ядро=None, окно_дней=45):
    """Когда транзитное Солнце проходит точку сборки, хозяина узора
    и точки, ведущие цепи. Даёт узловые дни: прошедшие и ближайшие."""
    ядро = ядро or K.ядро_узора(космо)
    несущие = set()
    х = ядро.get("хозяин") or {}
    несущие.update(х.get("кто", []))
    for с_ in K.судьбоносные(космо):
        несущие.add(с_["узел"])
        несущие.add(с_["планета"])
    for и, н in list((ядро.get("связность") or {}).items())[:3]:
        несущие.add(и)

    def солнце(т):
        return swe.calc_ut(swe.julday(т.year, т.month, т.day, 12), swe.SUN)[0][0]

    найдено = []
    for имя in несущие:
        if имя not in космо:
            continue
        цель = космо[имя]["градус"]
        т = момент - timedelta(days=окно_дней)
        пред = K.дуга(солнце(т), цель)
        while т < момент + timedelta(days=окно_дней):
            т2 = т + timedelta(days=1)
            d = K.дуга(солнце(т2), цель)
            if d > пред and пред < 1.0:
                найдено.append({"точка": имя, "дата": т, "орбис": round(пред, 2),
                                "прошло": т < момент,
                                "код": космо[имя]["код"]})
            пред = d
            т = т2
    найдено.sort(key=lambda x: x["дата"])
    return найдено


