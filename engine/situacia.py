def контекст_связи(транзит, натал, все_связи, космо):
    """Никогда не трактовать связь без её окружения: какие ещё
    транзиты приходят к тому же натальному концу."""
    мягче, жёстче = [], []
    for с_ in все_связи:
        if с_["натал"] != натал or с_["транзит"] == транзит:
            continue
        строка = (f"тр.{K.имя_точки(с_['транзит'])} {с_['аспект']} "
                  f"({с_['орбис']:.1f}°)")
        (мягче if с_["аспект"] in ("трин", "секстиль") else жёстче).append(строка)
    # и что говорит сама космограмма про эту точку
    свои = [а for а in K.аспекты_космограммы(космо)
            if натал in (а["а"], а["б"]) and а.get("вес") != "ФОНОВЫЙ"]
    родное = [f"{а['аспект']} с {K.имя_точки(а['б'] if а['а'] == натал else а['а'])}"
              for а in свои[:3]]
    return {"смягчает": мягче, "усугубляет": жёстче, "своё_в_карте": родное}


