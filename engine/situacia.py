#  ДОРОЖКА КОЛЕСА — коридор с датами, а не снимок
# ═══════════════════════════════════════════════════════════════════
#  Его правило 03.09: «прописать, что аспект Колеса давал точной тогда-то,
#  а даст тогда-то. У Колеса орбис 1°, и получается коридор — с августа
#  до декабря он работает сразу на несколько точек. Надо смотреть, кто
#  ещё в него попадает».

СКОРОСТЬ_КОЛЕСА = ХОД_КОЛЕСА


def когда_точный(градус_колеса, цель, угол_аспекта, момент, предел_лет=6):
    """Дата, когда Колесо встанет точно в аспект. Трин и прочие аспекты
    бывают с двух сторон — берём ближайшую по ходу движения."""
    лучшее = None
    for знак_ in (угол_аспекта, -угол_аспекта):
        точка_ = (цель + знак_) % 360
        сдвиг = (точка_ - градус_колеса) % 360
        if сдвиг > 180:
            сдвиг -= 360
        лет = сдвиг / СКОРОСТЬ_КОЛЕСА
        if abs(лет) > предел_лет:
            continue
        if лучшее is None or abs(лет) < abs(лучшее[0]):
            лучшее = (лет, момент + timedelta(days=лет * 365.25))
    return лучшее


ОБЗОР_ДОРОЖКИ = 3.0   # шире рабочего орбиса: чтобы видеть, кто на подходе


def дорожка_колеса(кол, космо, углы=None, орб=ОБЗОР_ДОРОЖКИ, момент=None):
    """Все точки в коридоре Колеса: что прошло, что впереди, когда точно.

    Колесо идёт 4.29°/год, орбис 1° — значит одна связь держится
    почти полгода, а несколько подряд складываются в единый период.
    """
    момент = момент or datetime.now(timezone.utc)
    цели = dict(космо)
    if углы:
        цели.update(углы)
    найдено = []
    for имя, т in цели.items():
        г = т["градус"] if isinstance(т, dict) else т
        d = K.дуга(кол["градус"], г)
        for ан, угол in АСПЕКТЫ:
            о = abs(d - угол)
            if о <= орб:
                срок = когда_точный(кол["градус"], г, угол, момент)
                вошло = когда_точный(кол["градус"],
                                     (г + орб) % 360, угол, момент)
                найдено.append({
                    "точка": имя, "аспект": ан, "угол": угол,
                    "орбис": round(о, 3), "градус_цели": г,
                    "лет_до_точного": round(срок[0], 3) if срок else None,
                    "дата_точного": срок[1] if срок else None,
                    "прошёл": (срок[0] < 0) if срок else None,
                    "код_цели": kod360.code_by_abs(г),
                })
                break
    найдено.sort(key=lambda x: x["дата_точного"] or момент)
    return найдено


