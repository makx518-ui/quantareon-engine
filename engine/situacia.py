def сходится(транзитная, натальная_градус, скорость, аспект_угол):
    """Сходящийся аспект ещё работает, расходящийся уже отработал."""
    d0 = K.дуга(транзитная, натальная_градус)
    d1 = K.дуга(транзитная + скорость * 0.5, натальная_градус)
    было = abs(d0 - аспект_угол)
    стало = abs(d1 - аспект_угол)
    return стало < было


def накладка(космо, тр, орбис_особый=None):
    """Все связи транзитного неба с картой рождения."""
    найдено = []
    for ти, тт in тр.items():
        for ки, кт in космо.items():
            d = K.дуга(тт["градус"], кт["градус"])
            предел = орбис_особый or орбис_пары(ти, ки)
            for ан, угол in АСПЕКТЫ:
                о = abs(d - угол)
                if о <= предел:
                    в, поясн = вес(о, предел)
                    сх = сходится(тт["градус"], кт["градус"],
                                  тт.get("скорость", 0) or 0, угол)
                    найдено.append({
                        "транзит": ти, "натал": ки, "аспект": ан, "угол": угол,
                        "орбис": round(о, 3), "вес": в, "поясн_веса": поясн,
                        "сходится": сх, "т": тт, "н": кт})
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


def связи_медленных(медленные_точки, космо, подпись, орб=ОРБИС_МЕДЛЕННЫХ):
    """Дирекции или прогрессии к космограмме, орбис жёстко 1°."""
    найдено = []
    for ди, дт in медленные_точки.items():
        for ки, кт in космо.items():
            d = K.дуга(дт["градус"], кт["градус"])
            for ан, угол in АСПЕКТЫ:
                о = abs(d - угол)
                if о <= орб:
                    найдено.append({"слой": подпись, "точка": ди, "натал": ки,
                                    "аспект": ан, "угол": угол, "орбис": round(о, 3),
                                    "точный": о <= ТОЧНЫЙ, "т": дт, "н": кт})
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


