# ⚠️ Его решение 04.09: у Колеса считаем ТРИ уровня и не глубже.
# Четвёртый дал бы час с небольшим, пятый — минуты, а стержень слишком
# медленный, чтобы отвечать за часы. Часы — территория третьего слоя.
УРОВНЕЙ_КОЛЕСА = 2      # градус и подградус — глубже путаница, проверено 04.09


def сроки_колеса(градус, момент):
    """Точные границы градуса и подградуса — считаются прямо от положения.

    ⚠️ 04.09: раньше я путал НОМЕР дольки с её ИМЕНЕМ по кругу зодиака
    и называл вторую дольку одиннадцатой. Теперь номер считается явно:
    доля градуса × 12, и границы берутся от начала градуса.
    """
    ход = ХОД_КОЛЕСА
    низ_гр = int(градус)
    доля = градус % 1
    номер = int(доля * 12)          # 0..11
    низ_п = низ_гр + номер / 12
    верх_п = низ_гр + (номер + 1) / 12

    def когда(цель):
        return момент + timedelta(days=(цель - градус) / ход * 365.25)

    return {
        "градус": {"номер": низ_гр % 30 + 1,
                   "начался": когда(низ_гр), "кончится": когда(низ_гр + 1),
                   "длится_дней": round(365.25 / ход),
                   "прошло_процентов": round(доля * 100)},
        "подградус": {"номер": номер + 1, "из": 12,
                      "начался": когда(низ_п), "кончится": когда(верх_п),
                      "длится_дней": round(365.25 / ход / 12, 1)},
    }


def колесо(рождение, момент):
    """Точка Жизни: 360° за 84 года от 0° Овна. Стержень, на который
    нанизывается всё остальное."""
    лет = (момент - рождение).total_seconds() / (365.25 * 86400)
    градус = (лет * ХОД_КОЛЕСА) % 360
    номер_эпохи = int(градус // 30) + 1
    т = K.точка("Колесо жизни", градус)
    т["подградусы"] = (т.get("подградусы") or [])[:УРОВНЕЙ_КОЛЕСА]
    т["лет"] = round(лет, 3)
    т["эпоха"] = {"номер": номер_эпохи, "знак": K.знак(градус),
                  "годы": (int((номер_эпохи - 1) * 7), int(номер_эпохи * 7))}
    # когда войдёт в следующий градус и когда сменится эпоха
    в_год = ХОД_КОЛЕСА
    до_градуса = (1 - (градус % 1)) / в_год * 365.25
    до_эпохи = (30 - (градус % 30)) / в_год * 365.25
    # ⚠️ его правило 04.09: у Колеса важен не только градус, но и подградус —
    # он даёт точку реализации внутри медленного сезона.
    доля = кол_градус = градус % 1
    до_под1 = (1/12 - (доля % (1/12))) / в_год * 365.25
    доля2 = (доля % (1/12)) * 12
    до_под2 = (1/12 - (доля2 % (1/12))) / 12 / в_год * 365.25
    т["сроки"] = {"следующий_градус": момент + timedelta(days=до_градуса),
                  "смена_эпохи": момент + timedelta(days=до_эпохи),
                  "скорость": f"{в_год:.4f}°/год",
                  "смена_подградуса": момент + timedelta(days=до_под1),
                  "смена_подградуса_2": момент + timedelta(days=до_под2),
                  "держится": {"знак": f"{30/в_год:.0f} лет",
                               "градус": f"{1/в_год*12:.1f} мес",
                               "подградус": f"{1/12/в_год*365.25:.1f} дней",
                               "подградус_2": f"{1/144/в_год*365.25*24:.1f} часов"}}
    т["фаза"] = K.фазы_эпох().get(K.знак(градус), {})
    return т


def аспекты_колеса(кол, космо, тр):
    """Колесо ко всему: к космограмме и к небу. Орбис жёстко 1°."""
    найдено = []
    for подпись, набор in (("космограмма", космо), ("транзит", тр)):
        for имя, т in набор.items():
            d = K.дуга(кол["градус"], т["градус"])
            for ан, угол in АСПЕКТЫ:
                о = abs(d - угол)
                if о <= ОРБИС_МЕДЛЕННЫХ:
                    найдено.append({"аспект": ан, "слой": подпись, "точка": имя,
                                    "орбис": round(о, 3), "точный": о <= ТОЧНЫЙ,
                                    "цель": т})
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


