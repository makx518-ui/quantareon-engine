def конец_связи(имя, т, чей, космо=None, ядро=None, куспиды=None, все_точки=None):
    """Один конец во всех слоях: планета · знак · владение · градус · ход."""
    з = т["знак"]
    роль, поясн = K.РОЛЬ.get(имя, ("", ""))
    л = [f"     ── {чей}: {K.имя_точки(имя).upper()} · {т.get('словами', т['текст'])}"]
    if роль:
        л.append(f"        сила: {роль} — {поясн}")
    ст = statyi.В_ЗНАКЕ.get((имя, з))
    if ст:
        л.append(f"        в знаке {з}: {ст[0]}")
    else:
        л.append(f"        в знаке {з}")
    д = K.достоинство(имя, з)[0]
    if д:
        л.append(f"        достоинство: {д}")
    свои = K.владеет(имя)[0]
    if свои:
        обл = statyi.ЗНАК_КАК_ОБЛАСТЬ.get(свои[0], "")
        л.append(f"        владеет {', '.join(свои)} → тянет дела {обл}")
    # ⚠️ 04.09: во втором слое связь читается так же полно, как в первом —
    # хозяин знака и где он стоит, дом точки, владение домами, переход градуса
    упр = K.УПРАВИТЕЛЬ.get(з, [None])[0]
    if упр and космо and упр in космо:
        гх = космо[упр]
        хвост = ""
        if куспиды:
            дх = K.дом_точки(гх["градус"], куспиды)
            if дх:
                хвост = f", в {дх}-м доме"
        л.append(f"        хозяин знака {упр} стоит {гх.get('словами','')} "
                 f"[{гх['код']['тег']}]{хвост}")
    if куспиды:
        мой = K.дом_точки(т["градус"], куспиды)
        if мой:
            л.append(f"        стоит в {мой}-м доме — {K.СФЕРА_ДОМА[мой]}")
        точки_для = все_точки or космо or {}
        свои_дома = K.чем_владеет_в_домах(имя, куспиды, точки_для)
        if свои_дома:
            л.append("        владеет домами: " +
                     ", ".join(f"{н}-м ({K.СФЕРА_ДОМА[н].split(',')[0]})" for н in свои_дома))
    к = т["код"]
    л.append(f"        градус [{к['тег']}]" +
             (f" · ФЛАГ: {к['флаг']}" if к.get("флаг") not in ("НЕТ", "", None) else ""))
    л.append(f"           {к['суть']}")
    if к.get("переход"):
        л.append(f"           {к['переход']}")
    п = (т.get("подградусы") or [{}])[0]
    if п.get("тег"):
        л.append(f"        подградус {п.get('словами','')} [{п['тег']}] — {п.get('суть','')[:90]}")
    if т.get("ретро"):
        л.append("        РЕТРОГРАДНА — сила работает внутрь, на переосмысление")
    if т.get("ход") and т["ход"] != "обычным ходом":
        л.append(f"        ход: {т['ход']}")
    # место натальной точки в узоре
    if чей == "В КАРТЕ" and ядро:
        хозяева = (ядро.get("хозяин") or {}).get("кто", [])
        if имя in хозяева:
            л.append("        ⚑ ЭТО ХОЗЯИН УЗОРА — связь бьёт в несущую ось карты")
        ц = K.цепь_диспозиторов(имя, космо) if космо else None
        if ц and len(ц["путь"]) > 1:
            л.append(f"        цепь: {' → '.join(K.имя_точки(x) for x in ц['путь'])}")
    return л


def трактовка_связи(св, космо, ядро=None, куспиды=None):
    """Полная выкладка одной связи транзит→натал с машинным резюме."""
    ти, ки, ан = св["транзит"], св["натал"], св["аспект"]
    л = ["", f"  ▪ ТРАНЗИТ {K.имя_точки(ти).upper()} {ан.upper()} {св['угол']}° "
         f"НАТАЛЬНОГО {K.имя_точки(ки).upper()}",
         f"    орбис {св['орбис']:.2f}° · {св['вес']} — {св['поясн_веса']} · "
         + ("сходится, ещё работает" if св["сходится"] else "расходится, уже отработал")]
    л += конец_связи(ти, св["т"], "В НЕБЕ", космо, куспиды=куспиды, все_точки=космо)
    л += конец_связи(ки, св["н"], "В КАРТЕ", космо, ядро, куспиды, космо)

    гл, вывод = ЧТО_ДЕЛАЕТ_АСПЕКТ.get(ан, ("связан с", ""))
    роль_т = K.РОЛЬ.get(ти, ("", ""))[0] or ти
    роль_н = K.РОЛЬ.get(ки, ("", ""))[0] or ки
    if куспиды:
        дт = K.дом_точки(св["т"]["градус"], куспиды)
        дн = K.дом_точки(св["н"]["градус"], куспиды)
        if дт and дн:
            л += ["     ── ЧТО СВЯЗЫВАЕТ ЭТА СВЯЗЬ ПО ДОМАМ",
                  f"        небо приходит в {дт}-й дом ({K.СФЕРА_ДОМА[дт]})",
                  f"        и задевает точку в {дн}-м ({K.СФЕРА_ДОМА[дн]})",
                  f"        ▸ " + ("обе в одной сфере — весь напор туда"
                                    if дт == дн else
                                    f"внешнее из сферы {K.СФЕРА_ДОМА[дт].split(',')[0]} "
                                    f"входит в сферу {K.СФЕРА_ДОМА[дн].split(',')[0]}")]
    л += ["     ── ЧТО ЭТО ДАЁТ КАРТЕ",
          f"        природа связи: {ПРИРОДА_СВЯЗИ.get(ан, '')}",
          f"        внешнее ({роль_т}) {гл} внутреннему ({роль_н})",
          f"        {вывод}",
          f"        тема встречи: [{св['т']['код']['тег']}] приходит к [{св['н']['код']['тег']}]",
          f"        область: дела {statyi.ЗНАК_КАК_ОБЛАСТЬ.get(св['н']['знак'], '')}"]
    if св["вес"] == "ТОЧНЫЙ":
        л.append("        орбис меньше получаса — звучит громче прочего сейчас")
    # сроки: когда точный и сколько прохождений будет
    if св.get("сроки"):
        ср = св["сроки"]
        if ср["точные"]:
            даты = " · ".join(д.strftime("%m.%Y") for д in ср["точные"][:4])
            л.append(f"     СРОКИ: точных прохождений {ср['прохождений']} — {даты}")
        if ср.get("вход") and ср.get("выход"):
            л.append(f"     коридор орбиса: {ср['вход'].strftime('%m.%Y')} – "
                     f"{ср['выход'].strftime('%m.%Y')}")
    # контекст: что смягчает и что усугубляет
    if св.get("контекст"):
        к_ = св["контекст"]
        if к_["смягчает"]:
            л.append("     СМЯГЧАЕТ: " + " · ".join(к_["смягчает"]))
        if к_["усугубляет"]:
            л.append("     УСУГУБЛЯЕТ: " + " · ".join(к_["усугубляет"]))
        if к_["своё_в_карте"]:
            л.append("     эта точка в карте: " + " · ".join(к_["своё_в_карте"]))
    return л


