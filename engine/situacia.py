def углы_карты(рождение, широта, долгота):
    """Асцендент, вершина и их противоположности — только если известно время.
    ⚠️ Его находка 03.09: Колесо аспектирует и к углам, а машина их не видела,
    потому что космограмма считается без домов."""
    j = юлиан(рождение)
    ку, у = swe.houses(j, широта, долгота, b'P')
    итог = {}
    for имя, г in (("Асцендент", у[0]), ("MC", у[1]),
                   ("Десцендент", (у[0]+180) % 360), ("IC", (у[1]+180) % 360)):
        итог[имя] = K.точка(имя, г)
    return итог


