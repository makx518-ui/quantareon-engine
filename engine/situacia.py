def дирекции(космо, рождение, момент):
    """Солнечная дуга. Причина, вызревающая внутри.

    ⚠️ ИСПРАВЛЕНО 03.09 (он поймал): дуга считается НЕ приближением
    0.9856°/год, а по эфемеридам — где реально стояло Солнце через
    столько дней после рождения, сколько прожито лет (день за год).
    Разница на 65 годах — больше градуса, и она сдвигает даты
    точности на год с лишним.
    """
    лет = (момент - рождение).total_seconds() / (365.2422 * 86400)
    j0 = юлиан(рождение)
    сол0 = swe.calc_ut(j0, swe.SUN)[0][0]
    солN = swe.calc_ut(j0 + лет, swe.SUN)[0][0]
    дуга_ = (солN - сол0) % 360
    итог = {}
    for имя, т in космо.items():
        д = (т["градус"] + дуга_) % 360
        итог[имя] = K.точка(имя, д, т.get("ретро", False))
    return {"дуга": round(дуга_, 4), "лет": round(лет, 3), "точки": итог}


