# -*- coding: utf-8 -*-
"""
ДИСПЕТЧЕР — одна точка входа для всех заказов.

Его правило 04.09: пользователь вводит данные в окно, а машина сама
решает, что считать. Время рождения есть — натальная карта с домами.
Времени нет — космограмма от Солнца, без домов. Ни шагу вручную.

    разобрать(дата, место, время=None, заказ="натал")

    заказ:  "натал"  — только первый слой
            "ситуация" — первый плюс второй на текущий момент
            "соляр"  — первый плюс второй на возвращение Солнца
            "день"   — всё три слоя
"""
from datetime import datetime, timedelta, timezone

import swisseph as swe

from engine import kod360
from engine import kosmogramma as K
from engine import situacia as S
from engine.natal import calculate_natal


def солнечный_час(год, месяц, день, пояс, широта, долгота):
    """Когда асцендент равен Солнцу — момент расчёта, если времени нет."""
    низ, верх = 0.0, 24.0
    for _ in range(40):
        с = (низ + верх) / 2
        j = swe.julday(год, месяц, день, с - пояс)
        солнце = swe.calc_ut(j, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]
        ас = swe.houses(j, широта, долгота, b'P')[1][0]
        d = (ас - солнце) % 360
        if d > 180:
            d -= 360
        if d < 0:
            низ = с
        else:
            верх = с
    ч = (низ + верх) / 2
    j = swe.julday(год, месяц, день, ч - пояс)
    солнце = swe.calc_ut(j, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]
    ас = swe.houses(j, широта, долгота, b'P')[1][0]
    return {"час": ч, "расхождение_сек": round(K.дуга(ас, солнце) * 3600, 1),
            "словами": f"{int(ч):02d}:{int(ч%1*60):02d}:{int((ч*60)%1*60):02d}"}


def разобрать(год, месяц, день, широта, долгота, пояс,
              час=None, минута=None, секунда=0,
              заказ="натал", имя="человек", место="",
              момент_запроса=None, широта_сейчас=None, долгота_сейчас=None,
              пояс_сейчас=None, год_соляра=None):
    """Одна точка входа. Машина сама решает, что считать."""
    kod360.load()
    время_известно = час is not None

    # ── момент рождения ──
    if время_известно:
        ч = час + (минута or 0) / 60 + секунда / 3600
        подпись_времени = f"{час:02d}:{(минута or 0):02d}:{секунда:02d}"
        сч = None
    else:
        сч = солнечный_час(год, месяц, день, пояс, широта, долгота)
        ч = сч["час"]
        подпись_времени = сч["словами"]

    рождение = (datetime(год, месяц, день) + timedelta(hours=ч - пояс)
                ).replace(tzinfo=timezone.utc)
    н = calculate_natal(year=год, month=месяц, day=день,
                        hour=int(ч), minute=int(ч % 1 * 60),
                        second=int((ч * 60) % 1 * 60),
                        timezone=пояс, latitude=широта, longitude=долгота)
    точки = {и: K.точка(и, п["abs_degree"], п.get("retrograde", False),
                        п.get("стоянка", False))
             for и, п in н["planets"].items()}
    for и, п in н["planets"].items():
        точки[и]["скорость"] = п.get("speed")

    # ── дома только при известном времени ──
    куспиды = углы = None
    if время_известно:
        j = swe.julday(год, месяц, день, ч - пояс)
        ку, у = swe.houses(j, широта, долгота, b'P')
        куспиды, углы = list(ку), у

    паспорт = {
        "дата_р": f"{день:02d}.{месяц:02d}.{год}",
        "место_р": место or f"{широта:.4f} {долгота:.4f}",
        "пояс_р": f"GMT{пояс:+g}",
        "солнечный_час": подпись_времени,
        "расхождение_сек": сч["расхождение_сек"] if сч else 0.0,
        "всего_шагов_кода": len(kod360._KOD),
        "момент": datetime.now(timezone.utc).strftime("%d.%m.%Y"),
        "время_известно": время_известно,
        "время_рождения": подпись_времени if время_известно else None,
    }
    угол_фазы = (точки["Луна"]["градус"] - точки["Солнце"]["градус"]) % 360
    # ⚠️ 04.09: лунный день рождения — его требование, сверено с ZET (14-й)
    from engine import lunacii as Л
    try:
        лд = Л.лунный_день(рождение)
        лунный_день_р = лд["день"] if лд else None
    except Exception:
        лунный_день_р = None

    итог = {"время_известно": время_известно, "точки": точки,
            "куспиды": куспиды, "углы": углы, "рождение": рождение,
            "заказ": заказ}

    # ── СЛОЙ 1 · всегда ──
    # 08.09: Колесо жизни на сегодня — для строки «где человек сейчас» в конце натала
    try:
        _кол = S.колесо(рождение, datetime.now(timezone.utc))
    except Exception:
        _кол = None
    итог["слой1"] = K.полочка(
        точки, тж=_кол, имя_человека=имя,
        дата=datetime.now(timezone.utc).strftime("%d.%m.%Y"),
        паспорт_данные=паспорт,
        лунные_данные={"угол_фазы": угол_фазы, "лунный_день": лунный_день_р, "момент": рождение},
        куспиды=куспиды, углы=углы)

    if заказ == "натал":
        return итог

    # ── СЛОЙ 2 · ситуация или соляр ──
    ш2 = широта_сейчас if широта_сейчас is not None else широта
    д2 = долгота_сейчас if долгота_сейчас is not None else долгота
    углы_карты = S.углы_карты(рождение, широта, долгота) if время_известно else None

    if заказ == "соляр":
        # ⚠️ 04.09: год пустой — берём ДЕЙСТВУЮЩИЙ соляр, а не календарный год.
        # Если день рождения в этом году ещё не наступил, действует прошлогодний.
        if год_соляра:
            год_с = год_соляра
        else:
            сейчас_ = datetime.now(timezone.utc)
            др_в_этом = datetime(сейчас_.year, месяц, день, tzinfo=timezone.utc)
            год_с = сейчас_.year if сейчас_ >= др_в_этом else сейчас_.year - 1
        # 07.09 · слой 2 по скрипту машины: карта года натальной машиной + накладка
        # + Колесо по году + кармика + медленные + планетарный + развёртка + свод
        from engine import sloy2 as L2
        итог["слой2"] = L2.собрать_соляр(точки, рождение, год_с, ш2, д2,
                                         куспиды_натал=куспиды, углы_натал=углы,
                                         имя_человека=имя, место=место,
                                         время_известно=время_известно, заказ="соляр")
        итог["полочка_ии"] = L2.полочка_для_ии(итог["слой2"])
    else:
        момент = момент_запроса or datetime.now(timezone.utc)
        итог["момент"] = момент
        if заказ in ("транзиты", "ситуация"):
            from engine import sloy2 as L2
            итог["слой2"] = L2.собрать_соляр(точки, рождение, None, ш2, д2,
                                             куспиды_натал=куспиды, углы_натал=углы,
                                             имя_человека=имя, место=место,
                                             время_известно=время_известно, заказ="транзиты", момент=момент)
            итог["полочка_ии"] = L2.полочка_для_ии(итог["слой2"])
        else:
            итог["слой2"] = S.полочка_ситуации(
                точки, рождение, момент, место=место, имя_человека=имя,
                широта=ш2, долгота=д2, углы=углы_карты, куспиды_натал=куспиды)

    if заказ in ("натал", "ситуация", "соляр", "транзиты"):
        return итог

    # ── СЛОЙ 3 · сутки ──
    from engine import sutki as U
    момент = момент_запроса or datetime.now(timezone.utc)
    ядро = K.ядро_узора(точки)
    тр = S.небо(момент)
    кол = S.колесо(рождение, момент)
    слой2 = {"аспекты_колеса": S.аспекты_колеса(кол, точки, тр),
             "дирекции": S.связи_медленных(
                 S.дирекции(точки, рождение, момент)["точки"], точки, "дир"),
             "транзиты": S.накладка(точки, тр)}
    пояс_ч = пояс_сейчас if пояс_сейчас is not None else пояс
    д = U.сутки(момент, ш2, д2, н, точки, ядро, слой2, пояс_часов=пояс_ч)
    итог["слой3"] = U.полочка_суток(
        д, имя_человека=имя, пояс=место or "местное",
        ночь=U.ночная_полочка(д, ш2, д2, пояс_часов=пояс_ч))
    return итог


def синастрия(данные_а, данные_б, имя_а="первый", имя_б="второй"):
    """Две карты одна на другую. Каждая считается своим правилом:
    есть время — с домами, нет — от Солнца."""
    from engine import sinastria as СН
    а = разобрать(заказ="натал", имя=имя_а, **данные_а)
    б = разобрать(заказ="натал", имя=имя_б, **данные_б)
    текст = СН.полочка_синастрии(
        а["точки"], б["точки"], имя_а, имя_б,
        куспиды_а=а["куспиды"], куспиды_б=б["куспиды"],
        ядро_а=K.ядро_узора(а["точки"]), ядро_б=K.ядро_узора(б["точки"]),
        время_а=а["время_известно"], время_б=б["время_известно"])
    return {"первый": а, "второй": б, "встреча": текст,
            "время_известно_а": а["время_известно"],
            "время_известно_б": б["время_известно"]}
