# -*- coding: utf-8 -*-
"""
АРХИВ КАРТ — каждый расчёт ложится в astro_memory/archive/karty/<Имя>/<момент>.json

Его решение 04.09: делаем как в аудите — папка на клиента, файл на заход,
всё в репозитории. Внутри файла четыре части:
    данные · раскладка машины · трактовка ИИ · отклик по факту

Четвёртая часть пустая до поры — она и есть самое ценное:
по ней потом видно, сбылось или нет, и растёт азбука перевода.
"""
import json
import os
import re
from datetime import datetime, timezone, timedelta

КОРЕНЬ = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                      "astro_memory")
АРХИВ = os.path.join(КОРЕНЬ, "archive", "karty")
ДНЕВНИК = os.path.join(КОРЕНЬ, "dnevnik_astro.json")

ВЕРСИЯ = {
    "методика": "2026-09-05",
    "азбука": "360 шагов, приземлённая редакция",
    "орбисы_космограммы": "светила 5° · септенер и Юпитер/Сатурн 4° · высшие 3.5° · Хирон, Лилит, Селена, узлы 3°",
    "орбисы_транзитов": "планеты 3° · высшие 2°",
    "орбисы_медленных": "дирекции, прогрессии, Колесо — 1°",
    "уровней_колеса": 2,
}


def _слаг(имя):
    """Имя клиента в имя папки: пробелы в подчёркивания, лишнее убрать."""
    ч = re.sub(r"[^\w\s-]", "", имя, flags=re.UNICODE).strip()
    return re.sub(r"[\s]+", "_", ч) or "без_имени"


def положить_кухню(имя_клиента, заказ, итог, данные_рождения,
                   момент=None, пояс_часов=0):
    """КУХНЯ — для ученика. Три слоя целиком, вся механика.
    Лежит отдельно от карты клиента (его правило 05.09)."""
    момент = момент or datetime.now(timezone.utc)
    местное = момент + timedelta(hours=пояс_часов)
    папка = os.path.join(АРХИВ, _слаг(имя_клиента), "кухня")
    os.makedirs(папка, exist_ok=True)
    файл = os.path.join(папка, местное.strftime("%Y-%m-%d_%H-%M") + ".json")
    with open(файл, "w", encoding="utf-8") as ф:
        json.dump({
            "клиент": имя_клиента, "заказ": заказ,
            "момент_расчёта": местное.strftime("%Y-%m-%d %H:%M:%S"),
            "версия": ВЕРСИЯ,
            "данные_рождения": данные_рождения,
            "время_известно": итог.get("время_известно"),
            "слой1_данность": итог.get("слой1", ""),
            "слой2_ситуация": итог.get("слой2", ""),
            "слой3_сутки": итог.get("слой3", ""),
        }, ф, ensure_ascii=False, indent=2)
    return файл


def положить_карту(имя_клиента, заказ, html, момент=None, пояс_часов=0):
    """КАРТА — для клиента. Готовый HTML, без единого термина.
    Отдаётся файлом, лежит отдельно от кухни."""
    момент = момент or datetime.now(timezone.utc)
    местное = момент + timedelta(hours=пояс_часов)
    папка = os.path.join(АРХИВ, _слаг(имя_клиента), "карты")
    os.makedirs(папка, exist_ok=True)
    файл = os.path.join(папка,
                        f"{местное.strftime('%Y-%m-%d_%H-%M')}_{заказ}.html")
    with open(файл, "w", encoding="utf-8") as ф:
        ф.write(html)
    return файл


def сохранить_расчёт(имя_клиента, заказ, итог, данные_рождения,
                     трактовка="", момент=None, пояс_часов=0, заметки=None):
    """Кладёт готовый расчёт из диспетчера прямо в архив.

    ⚠️ Его правило 05.09: карта ложится в архив под именем того, кто
    заказал; внутри — ВСЯ кухня расклада для ученика.
    """
    раскладка = {
        "заказ": заказ,
        "время_известно": итог.get("время_известно"),
        "слой1_данность": итог.get("слой1", ""),
        "слой2_ситуация": итог.get("слой2", ""),
        "слой3_сутки": итог.get("слой3", ""),
    }
    return сохранить(имя_клиента, данные_рождения, раскладка, трактовка,
                     момент, пояс_часов, заметки)


def сохранить_синастрию(имя_а, имя_б, итог, данные_а, данные_б,
                        трактовка="", момент=None, пояс_часов=0):
    """Встреча двух карт — в папку первого, с пометкой о втором."""
    раскладка = {
        "заказ": "синастрия",
        "первый": имя_а, "второй": имя_б,
        "карта_первого": итог["первый"].get("слой1", ""),
        "карта_второго": итог["второй"].get("слой1", ""),
        "встреча": итог.get("встреча", ""),
    }
    данные = {"первый": данные_а, "второй": данные_б}
    return сохранить(f"{имя_а} и {имя_б}", данные, раскладка, трактовка,
                     момент, пояс_часов)


def сохранить(имя_клиента, данные_рождения, раскладка, трактовка="",
              момент=None, пояс_часов=0, заметки=None):
    """Кладёт один заход в архив и возвращает путь к файлу."""
    момент = момент or datetime.now(timezone.utc)
    местное = момент + timedelta(hours=пояс_часов)
    папка = os.path.join(АРХИВ, _слаг(имя_клиента))
    os.makedirs(папка, exist_ok=True)
    файл = os.path.join(папка, местное.strftime("%Y-%m-%d_%H-%M") + ".json")

    запись = {
        "клиент": имя_клиента,
        "момент_расчёта": местное.strftime("%Y-%m-%d %H:%M:%S"),
        "момент_utc": момент.strftime("%Y-%m-%d %H:%M:%S"),
        "версия": ВЕРСИЯ,
        "данные_рождения": данные_рождения,
        "раскладка": раскладка,          # что посчитала машина, по слоям
        "трактовка": трактовка,          # что написал читатель
        "отклик": {                      # дописывается позже
            "что_было": "",
            "сбылось": None,
            "промахи": "",
            "дата_отклика": "",
        },
        "заметки": заметки or "",
    }
    with open(файл, "w", encoding="utf-8") as ф:
        json.dump(запись, ф, ensure_ascii=False, indent=2)
    _в_дневник(имя_клиента, файл, местное)
    return файл


def _в_дневник(имя, путь, когда):
    """Короткая строка в общий дневник — как dnevnik_auditor в аудите."""
    дн = {"заходы": []}
    if os.path.exists(ДНЕВНИК):
        try:
            with open(ДНЕВНИК, encoding="utf-8") as ф:
                дн = json.load(ф)
        except Exception:
            pass
    дн.setdefault("заходы", []).append({
        "номер": len(дн.get("заходы", [])) + 1,
        "клиент": имя,
        "когда": когда.strftime("%Y-%m-%d %H:%M"),
        "файл": os.path.relpath(путь, КОРЕНЬ),
    })
    os.makedirs(КОРЕНЬ, exist_ok=True)
    with open(ДНЕВНИК, "w", encoding="utf-8") as ф:
        json.dump(дн, ф, ensure_ascii=False, indent=2)


def дописать_отклик(путь_файла, что_было, сбылось=None, промахи=""):
    """Возвращаемся к старой записи и добавляем, что случилось на самом деле.
    Это и есть материал для азбуки перевода."""
    with open(путь_файла, encoding="utf-8") as ф:
        запись = json.load(ф)
    запись["отклик"] = {
        "что_было": что_было,
        "сбылось": сбылось,
        "промахи": промахи,
        "дата_отклика": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
    }
    with open(путь_файла, "w", encoding="utf-8") as ф:
        json.dump(запись, ф, ensure_ascii=False, indent=2)
    return путь_файла


def карты_клиента(имя):
    """Все заходы по человеку, от старых к новым."""
    папка = os.path.join(АРХИВ, _слаг(имя))
    if not os.path.isdir(папка):
        return []
    return sorted(os.path.join(папка, ф) for ф in os.listdir(папка)
                  if ф.endswith(".json"))


def найти_по_градусу(тег):
    """Все записи, где встречается этот код градуса — для азбуки."""
    найдено = []
    if not os.path.isdir(АРХИВ):
        return найдено
    for клиент in os.listdir(АРХИВ):
        п = os.path.join(АРХИВ, клиент)
        if not os.path.isdir(п):
            continue
        for ф in os.listdir(п):
            путь = os.path.join(п, ф)
            try:
                with open(путь, encoding="utf-8") as файл:
                    текст = файл.read()
                if тег in текст:
                    найдено.append(путь)
            except Exception:
                continue
    return найдено
