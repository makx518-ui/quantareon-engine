"""Расчёт точек космограммы — восстановлено после сброса контейнера."""
import swisseph as swe

ТОЧКИ = [(swe.SUN,"Солнце"),(swe.MOON,"Луна"),(swe.MERCURY,"Меркурий"),(swe.VENUS,"Венера"),
         (swe.MARS,"Марс"),(swe.JUPITER,"Юпитер"),(swe.SATURN,"Сатурн"),(swe.URANUS,"Уран"),
         (swe.NEPTUNE,"Нептун"),(swe.PLUTO,"Плутон"),(swe.CHIRON,"Хирон"),
         (swe.MEAN_APOG,"Лилит"),(swe.TRUE_NODE,"Сев.Узел")]

def _селена(jd):
    """Белая Луна. Опора и ход выверены 05.09 по двум сверкам:
    ZET на дату рождения (10°43'00" Тельца) и его сайт на 05.09.2026
    (24°11'39" Девы). Обе сошлись до нуля секунд."""
    return (87.9580 + (jd - 2447892.5) * 0.1408056) % 360

def calculate_natal(year, month, day, hour, minute, second=0, timezone=0.0,
                    latitude=0.0, longitude=0.0):
    ч = hour + minute/60 + second/3600 - timezone
    jd = swe.julday(year, month, day, ч)
    итог = {}
    for pid, имя in ТОЧКИ:
        # ⚠️ 04.09: без FLG_SPEED движок возвращает скорость нулём —
        # и все точки выглядели стоянками. Скорость надо запрашивать явно.
        флаги = swe.FLG_SWIEPH | swe.FLG_SPEED
        try:
            поз = swe.calc_ut(jd, pid, флаги)[0]
        except Exception:
            try:
                поз = swe.calc_ut(jd, pid, swe.FLG_MOSEPH | swe.FLG_SPEED)[0]
            except Exception:
                continue
        # ⚠️ стоянка определяется НЕ порогом (для Нептуна 0.007°/сут это
        # обычный ход), а фактом разворота: движок сам покажет смену знака.
        # ⚠️ узлы и Лилит — точки вычисляемые, у них знак скорости пляшет
        # по природе. Разворотом это не считается.
        стоянка = False
        if имя in ("Сев.Узел", "Юж.Узел", "Лилит", "Селена"):
            итог[имя] = {"abs_degree": поз[0] % 360, "speed": поз[3],
                         "retrograde": поз[3] < 0, "стоянка": False}
            continue
        try:
            до = swe.calc_ut(jd - 7, pid, флаги)[0][3]
            после = swe.calc_ut(jd + 7, pid, флаги)[0][3]
            стоянка = (до * после < 0) or (до * поз[3] < 0) or (поз[3] * после < 0)
        except Exception:
            pass
        итог[имя] = {"abs_degree": поз[0] % 360, "speed": поз[3],
                     "retrograde": поз[3] < 0, "стоянка": стоянка}
    итог["Юж.Узел"] = {"abs_degree": (итог["Сев.Узел"]["abs_degree"] + 180) % 360,
                       "speed": итог["Сев.Узел"]["speed"],
                       "retrograde": итог["Сев.Узел"]["retrograde"]}
    итог["Селена"] = {"abs_degree": _селена(jd), "speed": 0.1408056, "retrograde": False}

    # ⚠️ 05.09: страница ждёт от каждой точки sign/formatted/symbol/house.
    # При переписывании этих полей не стало, и таблица падала
    # с «Cannot read properties of undefined (reading 'formatted')».
    for имя, п in итог.items():
        _обогатить(п, имя)

    ответ = {"planets": итог, "jd": jd}

    # углы и дома — только если известно место
    if latitude or longitude:
        try:
            ку, у = swe.houses(jd, latitude, longitude, b'P')
            углы = {}
            for имя_у, г in (("ASC", у[0]), ("MC", у[1]),
                             ("DSC", (у[0] + 180) % 360), ("IC", (у[1] + 180) % 360)):
                углы[имя_у] = _обогатить({"abs_degree": г % 360}, имя_у)
            ответ["angles"] = углы
            ответ["houses"] = {str(i + 1): _обогатить({"abs_degree": к % 360}, f"дом {i+1}")
                               for i, к in enumerate(ку)}
            # дом каждой точки
            for имя, п in итог.items():
                п["house"] = _дом(п["abs_degree"], list(ку))
                п["house_part"] = _треть(п["abs_degree"], list(ку), п["house"])
        except Exception:
            pass
    return ответ


ЗНАКИ_ИМЕНА = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева",
               "Весы", "Скорпион", "Стрелец", "Козерог", "Водолей", "Рыбы"]
ЗНАКИ_ЗНАКИ = ["♈", "♉", "♊", "♋", "♌", "♍", "♎", "♏", "♐", "♑", "♒", "♓"]
СИМВОЛЫ = {"Солнце": "☉", "Луна": "☽", "Меркурий": "☿", "Венера": "♀",
           "Марс": "♂", "Юпитер": "♃", "Сатурн": "♄", "Уран": "♅",
           "Нептун": "♆", "Плутон": "♇", "Сев.Узел": "☊", "Юж.Узел": "☋",
           "Лилит": "⚸", "Хирон": "⚷", "Селена": "⚜"}


def _обогатить(п, имя=""):
    """Добавляет sign, formatted, symbol, sabian — то, что ждёт страница."""
    г = п.get("abs_degree", 0) % 360
    ин = int(г // 30) % 12
    в = г % 30
    гр = int(в)
    м = int((в - гр) * 60)
    с_ = int(round(((в - гр) * 60 - м) * 60))
    if с_ >= 60:
        м, с_ = м + 1, 0
    if м >= 60:
        гр, м = гр + 1, 0
    текст = f"{гр}°{м:02d}'{с_:02d}\" {ЗНАКИ_ИМЕНА[ин]}"
    п["sign"] = {"name": ЗНАКИ_ИМЕНА[ин], "symbol": ЗНАКИ_ЗНАКИ[ин],
                 "degree_in_sign": round(в, 6), "formatted": текст}
    п["formatted"] = текст
    п["sign_name"] = ЗНАКИ_ИМЕНА[ин]
    п["sign_symbol"] = ЗНАКИ_ЗНАКИ[ин]
    п["symbol"] = СИМВОЛЫ.get(имя, "")
    п["sabian"] = гр + 1
    п.setdefault("house", None)
    п.setdefault("house_part", 1)
    return п


def _дом(градус, куспиды):
    """В каком доме точка."""
    if not куспиды:
        return None
    for i in range(12):
        а, б = куспиды[i], куспиды[(i + 1) % 12]
        ш = ((б - а) % 360) or 360
        if ((градус - а) % 360) < ш:
            return i + 1
    return 12


def _треть(градус, куспиды, дом):
    """Какая треть дома — первая, вторая или третья."""
    if not куспиды or not дом:
        return 1
    а = куспиды[дом - 1]
    б = куспиды[дом % 12]
    ш = ((б - а) % 360) or 360
    доля = ((градус - а) % 360) / ш
    return min(3, int(доля * 3) + 1)


