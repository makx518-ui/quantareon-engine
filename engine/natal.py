def _compute_selena(jd):
    """Белая Луна по юлианской дате — старое имя той же формулы."""
    return _селена(jd)


ЗНАКИ_RU = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева",
            "Весы", "Скорпион", "Стрелец", "Козерог", "Водолей", "Рыбы"]


def format_natal(данные, заголовок="НАТАЛЬНАЯ КАРТА"):
    """Позиции карты человеческим текстом — как было до правок."""
    if not данные:
        return ""
    л = [f"═══ {заголовок} ═══", ""]
    точки = данные.get("planets") or данные.get("точки") or {}
    for имя, п in точки.items():
        г = п.get("abs_degree", 0) % 360
        зн = ЗНАКИ_RU[int(г // 30) % 12]
        в = г % 30
        гр = int(в)
        м = int((в - гр) * 60)
        с = int(round(((в - гр) * 60 - м) * 60))
        if с == 60:
            м, с = м + 1, 0
        ретро = " R" if п.get("retrograde") else ""
        л.append(f"  {имя:12} {гр:2}°{м:02d}'{с:02d}\" {зн}{ретро}")
    углы = данные.get("angles") or {}
    if углы:
        л.append("")
        for имя, у in углы.items():
            г = (у.get("abs_degree", 0) if isinstance(у, dict) else у) % 360
            зн = ЗНАКИ_RU[int(г // 30) % 12]
            в = г % 30
            гр = int(в)
            м = int((в - гр) * 60)
            л.append(f"  {имя:12} {гр:2}°{м:02d}' {зн}")
    дома = данные.get("houses") or {}
    if дома:
        л.append("")
        for н, к in (дома.items() if isinstance(дома, dict) else enumerate(дома, 1)):
            г = (к.get("abs_degree", 0) if isinstance(к, dict) else к) % 360
            зн = ЗНАКИ_RU[int(г // 30) % 12]
            в = г % 30
            л.append(f"  дом {н:2}      {int(в):2}°{int((в % 1) * 60):02d}' {зн}")
    return "\n".join(л)
