"""
КНИГА ДНЕЙ — ключи покупателей, страницы, сшивание (16.09.2026).

Его методика: первый день — основа книги, его асцендент — КОРЕНЬ (название книги).
Каждые сутки в то же время суток машина считает новую карту: асцендент чуть впереди —
новая СТРАНИЦА (градус), реже новая ГЛАВА (знак), ядро градуса — СТРОКА дня.
Читатель пишет продолжение, а не новый гороскоп. Разовый тариф — один день, снимок.

Хранение — в архиве (R2, engine/arhiv): один JSON на ключ:
  archive/karty/kniga/<КЛЮЧ>.json
    ключ, почта, тариф ("den" | "shiv"), дней, lang, создан, корень {момент, lat, lon, tz, асц…},
    страницы [{n, дата, момент, fayl, резюме, асц_знак, асц_градус, ядро}]
Сам HTML страницы — рядом, положить_карту(имя=ключ, заказ="kniga_N").

Ключи выдаёт хозяин (пока) или оплата (потом) — выдать(); формат QD-XXXX-XXXX (день),
QK-XXXX-XXXX-XXXX (книга).
"""
import json
import re
import secrets
from datetime import datetime, timedelta, timezone

from engine import arhiv as A

АЛФАВИТ = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
ВИД_КЛЮЧА = re.compile(r"^Q[DK](-[A-Z2-9]{4}){2,3}$")


def _кусок(n=4):
    return "".join(secrets.choice(АЛФАВИТ) for _ in range(n))


def _путь(ключ):
    return f"{A.АРХИВ}/kniga/{ключ}.json"


def _читать(ключ):
    т = A._взять(_путь(ключ))
    return json.loads(т) if т else None


def _писать(з):
    A._положить(_путь(з["ключ"]), json.dumps(з, ensure_ascii=False, indent=1))
    return з


def выдать(почта, тариф="den", дней=1, lang="ru"):
    """Новый ключ. den → один день; shiv → книга на N дней."""
    тариф = "shiv" if str(тариф).lower().startswith(("shiv", "сшив", "kniga", "книг")) else "den"
    дней = 1 if тариф == "den" else max(1, int(дней or 1))
    ключ = ("QD-" + _кусок() + "-" + _кусок()) if тариф == "den" else ("QK-" + _кусок() + "-" + _кусок() + "-" + _кусок())
    з = {"ключ": ключ, "почта": str(почта or "").strip()[:200], "тариф": тариф, "дней": дней,
         "lang": "en" if str(lang).lower().startswith("en") else "ru",
         "создан": datetime.now(timezone.utc).isoformat(), "корень": None, "страницы": []}
    return _писать(з)


def _местная_дата(iso, пояс):
    м = datetime.fromisoformat(iso.replace("Z", "+00:00"))
    return (м + timedelta(hours=пояс)).date()


def статус(ключ):
    """Что с ключом: есть ли, жив ли, сколько дней, какие страницы уже есть."""
    ключ = str(ключ or "").strip().upper()
    if not ВИД_КЛЮЧА.match(ключ):
        return {"ok": False, "reason": "bad_key"}
    з = _читать(ключ)
    if not з:
        return {"ok": False, "reason": "no_key"}
    к = з.get("корень")
    сегодня_n = None
    жив = True
    if к:
        сегодня = _местная_дата(datetime.now(timezone.utc).isoformat(), к["tz"])
        сегодня_n = (сегодня - _местная_дата(к["момент"], к["tz"])).days + 1
        жив = 1 <= сегодня_n <= з["дней"]
    return {"ok": True, "klyuch": ключ, "tarif": з["тариф"], "dney": з["дней"], "lang": з["lang"],
            "nachata": bool(к), "segodnya_n": сегодня_n, "zhiva": жив,
            "stranicy": [{"n": с["n"], "data": с["дата"], "fayl": с["fayl"]} for с in з["страницы"]]}


def номер_сегодня(з, сейчас_iso):
    к = з["корень"]
    return (_местная_дата(сейчас_iso, к["tz"]) - _местная_дата(к["момент"], к["tz"])).days + 1


def момент_страницы(з, n):
    """Момент страницы n — корневая секунда плюс (n−1) суток: то же время суток, как в эссе."""
    к = з["корень"]
    м = datetime.fromisoformat(к["момент"].replace("Z", "+00:00"))
    return м + timedelta(days=n - 1)


def взять_страницу(з, n):
    for с in з["страницы"]:
        if с["n"] == n:
            return с
    return None


def открыть_корень(з, iso, lat, lon, tz):
    """Первый день: секунда входа становится корнем книги."""
    if з.get("корень"):
        return з
    з["корень"] = {"момент": iso, "lat": float(lat), "lon": float(lon), "tz": float(tz)}
    return _писать(з)


def записать_страницу(з, n, момент, fayl, резюме, асц):
    з["страницы"] = [с for с in з["страницы"] if с["n"] != n]
    з["страницы"].append({"n": n, "дата": (момент + timedelta(hours=з["корень"]["tz"])).strftime("%Y-%m-%d"),
                          "момент": момент.isoformat(), "fayl": fayl, "резюме": (резюме or "")[:4000],
                          "асц_знак": асц.get("знак"), "асц_градус": асц.get("градус"),
                          "асц_код": асц.get("код"), "ядро": асц.get("ядро")})
    з["страницы"].sort(key=lambda с: с["n"])
    if n == 1:
        з["корень"].update({"асц_знак": асц.get("знак"), "асц_градус": асц.get("градус"),
                            "асц_код": асц.get("код"), "ядро": асц.get("ядро")})
    return _писать(з)


def контекст_продолжения(з, n, асц_сегодня):
    """Что читатель получает сверх полочки на странице n>1: корень, статус страницы/главы,
    вчерашнее резюме. Числа — от машины, слова — от читателя."""
    к = з["корень"]
    вчера = взять_страницу(з, n - 1) or (з["страницы"][-1] if з["страницы"] else None)
    та_же_глава = (асц_сегодня.get("знак") == (вчера or {}).get("асц_знак"))
    та_же_страница = та_же_глава and (асц_сегодня.get("градус") == (вчера or {}).get("асц_градус"))
    return {
        "n": n,
        "корень": {"знак": к.get("асц_знак"), "градус": к.get("асц_градус"), "код": к.get("асц_код"), "ядро": к.get("ядро")},
        "вчера": {"n": вчера["n"], "знак": вчера.get("асц_знак"), "градус": вчера.get("асц_градус"),
                  "код": вчера.get("асц_код"), "ядро": вчера.get("ядро"), "резюме": вчера.get("резюме", "")} if вчера else None,
        "сегодня": асц_сегодня,
        "новая_глава": (not та_же_глава) if вчера else False,
        "новая_страница": (not та_же_страница) if вчера else False,
    }


# ── СЕКУНДА ВИТРИНЫ ──────────────────────────────────────────────────────────
# 16.09 · его правка: раньше секунда карты жила только в браузере, и в другом браузере книга
# начиналась «с нуля». Теперь витрина кладёт её сюда под коротким номером, браузер держит номер,
# а книга берёт корень отсюда — открывается с любого устройства.

def _путь_витрины(номер):
    return f"{A.АРХИВ}/vitrina/{номер}.json"


def запомнить_витрину(момент_iso, широта, долгота, пояс, lang="ru"):
    """Короткий номер секунды витрины. Живёт двое суток — дольше не нужно."""
    номер = "V" + _кусок(5) + _кусок(5)
    A._положить(_путь_витрины(номер), json.dumps({
        "номер": номер, "момент": момент_iso, "lat": float(широта), "lon": float(долгота),
        "tz": float(пояс), "lang": "en" if str(lang).startswith("en") else "ru",
        "создан": datetime.now(timezone.utc).isoformat()}, ensure_ascii=False))
    return номер


def взять_витрину(номер):
    """Секунда витрины по номеру; None — если номера нет или он старше двух суток."""
    номер = str(номер or "").strip().upper()
    if not re.match(r"^V[A-Z2-9]{10}$", номер):
        return None
    т = A._взять(_путь_витрины(номер))
    if not т:
        return None
    в = json.loads(т)
    м = datetime.fromisoformat(в["момент"].replace("Z", "+00:00"))
    if (datetime.now(timezone.utc) - м).total_seconds() > 86400 * 2:
        return None
    return в
