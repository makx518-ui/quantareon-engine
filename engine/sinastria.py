"""
СИНАСТРИЯ — две карты одна на другую.

Его слова 04.09: «там всё проще. Накладка машина уже делает, просто
вместо неба вторая карта. Прописать механику трактовки полную.
Трактоваться будет в психологическом формате — это уже промпт».

Механика одна с накладкой второго слоя:
    его точки → её карта,  её точки → его карта, оба конца полностью.
Отличие: обе карты неподвижны, сроков и коридоров нет.
"""
from engine import kod360
from engine import kosmogramma as K
from engine import situacia as S

ОРБИС_СИНАСТРИИ = 3.0        # обе карты статичны — орбис как у транзитов
ОРБИС_СВЕТИЛ = 5.0           # к Солнцу и Луне шире: они несут больше


def орбис_пары(а, б):
    if "Солнце" in (а, б) or "Луна" in (а, б):
        return ОРБИС_СВЕТИЛ
    return ОРБИС_СИНАСТРИИ


def встреча(карта_а, карта_б, имя_а="первый", имя_б="второй"):
    """Все связи между двумя картами, с весом и направлением."""
    найдено = []
    for иа, та in карта_а.items():
        for иб, тб in карта_б.items():
            d = K.дуга(та["градус"], тб["градус"])
            предел = орбис_пары(иа, иб)
            for ан, угол in S.АСПЕКТЫ:
                о = abs(d - угол)
                if о <= предел:
                    вес = ("ТОЧНЫЙ" if о <= 1.0 else
                           "РАБОЧИЙ" if о <= предел * 0.6 else "ФОНОВЫЙ")
                    найдено.append({
                        "чья_точка": имя_а, "а": иа, "чья_цель": имя_б, "б": иб,
                        "аспект": ан, "угол": угол, "орбис": round(о, 2),
                        "вес": вес, "та": та, "тб": тб})
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


def дома_друг_друга(карта_а, куспиды_б, имя_а="первый", имя_б="второй"):
    """В какие дома одного попадают точки другого — где он его задевает."""
    если = []
    if not куспиды_б:
        return если
    for иа, та in карта_а.items():
        д = K.дом_точки(та["градус"], куспиды_б)
        если.append({"точка": иа, "дом": д, "сфера": K.СФЕРА_ДОМА.get(д),
                     "словами": та.get("словами"), "код": та["код"]["тег"]})
    если.sort(key=lambda x: x["дом"] or 13)
    return если


def узлы_встречи(карта_а, карта_б, имя_а, имя_б):
    """Особые касания, которые в синастрии значат больше прочего."""
    особые = []
    пары = [
        ("Солнце", "Луна", "дух одного и душа другого — основа притяжения"),
        ("Венера", "Марс", "притяжение как таковое: желание и то, что дорого"),
        ("Солнце", "Солнце", "две воли: совпадают или спорят"),
        ("Луна", "Луна", "две души: один быт или разный"),
        ("Сатурн", "Солнце", "один держит другого рамкой — опора или гнёт"),
        ("Сатурн", "Луна", "холод к чувству: долг вместо тепла"),
        ("Плутон", "Венера", "переплавка через любовь, власть в чувстве"),
        ("Уран", "Луна", "покой рушится: живо, но без опоры"),
        ("Нептун", "Венера", "любовь сквозь туман: очарование и обман"),
        ("Хирон", "Солнце", "один задевает рану другого — и может её лечить"),
        ("Сев.Узел", "Солнце", "встреча на дороге судьбы"),
        ("Сев.Узел", "Луна", "судьба входит через чувство"),
        ("Лилит", "Венера", "тень в любви: искушение и его цена"),
    ]
    for па, пб, смысл in пары:
        for (к1, и1), (к2, и2) in (((карта_а, имя_а), (карта_б, имя_б)),
                                   ((карта_б, имя_б), (карта_а, имя_а))):
            if па not in к1 or пб not in к2:
                continue
            d = K.дуга(к1[па]["градус"], к2[пб]["градус"])
            for ан, угол in S.АСПЕКТЫ:
                о = abs(d - угол)
                if о <= орбис_пары(па, пб):
                    особые.append({
                        "что": f"{па} ({и1}) {ан} {пб} ({и2})",
                        "орбис": round(о, 2), "аспект": ан,
                        "смысл": смысл,
                        "код_а": к1[па]["код"]["тег"], "код_б": к2[пб]["код"]["тег"],
                    })
                    break
    особые.sort(key=lambda x: x["орбис"])
    return особые


def полочка_синастрии(карта_а, карта_б, имя_а="первый", имя_б="второй",
                      куспиды_а=None, куспиды_б=None,
                      ядро_а=None, ядро_б=None,
                      время_а=None, время_б=None):
    """Раскладка встречи двух карт — механика та же, что в накладке."""
    ч = "═" * 74
    л = [ч, f"СИНАСТРИЯ · {имя_а} ↔ {имя_б}", ч,
         "Две карты одна на другую. Механика та же, что у транзитов:",
         "оба конца читаются целиком. Отличие — обе карты неподвижны,",
         "сроков и коридоров нет: это устройство пары, а не событие.", "",
         f"  орбисы: обычные точки {ОРБИС_СИНАСТРИИ}° · светила {ОРБИС_СВЕТИЛ}°"]
    # ⚠️ 04.09: сказать честно, по каким картам считано
    без = [и for и, вр in ((имя_а, время_а), (имя_б, время_б)) if вр is False]
    if без:
        кто = " и ".join(без)
        л.append(f"  ВРЕМЯ РОЖДЕНИЯ НЕ УКАЗАНО ({кто}) — эта карта прочитана от Солнца, "
                 f"без домов")
    л.append("")

    # ── УЗЛЫ ВСТРЕЧИ ──
    уз = узлы_встречи(карта_а, карта_б, имя_а, имя_б)
    л += ["╔══ 1 · УЗЛЫ ВСТРЕЧИ — что связывает по существу ══"]
    if уз:
        for у in уз:
            метка = "  ⚑" if у["орбис"] <= 1.0 else "   "
            л += [f"{метка} {у['что']} · орб {у['орбис']}°",
                  f"        {у['смысл']}",
                  f"        [{у['код_а']}] ↔ [{у['код_б']}]"]
    else:
        л.append("     особых касаний нет — пара держится не притяжением, а другим")
    л += ["", "  ▸ РЕЗЮМЕ: на чём стоит связь.", ""]

    # ── ВСЕ СВЯЗИ ──
    св = встреча(карта_а, карта_б, имя_а, имя_б)
    точн = [с for с in св if с["вес"] == "ТОЧНЫЙ"]
    раб = [с for с in св if с["вес"] == "РАБОЧИЙ"]
    фон = [с for с in св if с["вес"] == "ФОНОВЫЙ"]
    л += [f"╔══ 2 · СВЯЗИ МЕЖДУ КАРТАМИ · всего {len(св)} ══",
          f"  точных {len(точн)} · рабочих {len(раб)} · фоновых {len(фон)}", ""]
    for подпись, набор, полно in (("ТОЧНЫЕ (≤1°)", точн, True),
                                  ("РАБОЧИЕ", раб, False)):
        if not набор:
            continue
        л.append(f"  ── {подпись} ──")
        for с in набор:
            л += [f"", f"  ▪ {K.имя_точки(с['а']).upper()} ({с['чья_точка']}) "
                  f"{с['аспект'].upper()} {K.имя_точки(с['б']).upper()} ({с['чья_цель']}) "
                  f"· орб {с['орбис']}°"]
            л += _конец(с["а"], с["та"], с["чья_точка"], карта_а, куспиды_а, полно)
            л += _конец(с["б"], с["тб"], с["чья_цель"], карта_б, куспиды_б, полно)
            гл, вывод = S.ЧТО_ДЕЛАЕТ_АСПЕКТ.get(с["аспект"], ("", ""))
            л += [f"     ── ЧТО ЭТО ДАЁТ ПАРЕ",
                  f"        природа связи: {S.ПРИРОДА_СВЯЗИ.get(с['аспект'],'')}",
                  f"        {K.имя_точки(с['а'])} одного {гл} {K.имя_точки(с['б'])} другого",
                  f"        {вывод}"]
            # в чей дом попадает
            if куспиды_б:
                д = K.дом_точки(с["та"]["градус"], куспиды_б)
                if д:
                    л.append(f"        точка {с['чья_точка']} падает в {д}-й дом "
                             f"{с['чья_цель']} — {K.СФЕРА_ДОМА[д]}")
    if фон:
        л += ["", "  ── ФОНОВЫЕ — окраска, не основа ──"]
        for с in фон[:12]:
            л.append(f"     {K.имя_точки(с['а'])} ({с['чья_точка']}) {с['аспект']} "
                     f"{K.имя_точки(с['б'])} ({с['чья_цель']}) · {с['орбис']}°")
    л += ["", "  ▸ РЕЗЮМЕ: чем эти двое цепляют друг друга.", ""]

    # ── ДОМА ДРУГ ДРУГА ──
    if куспиды_б or куспиды_а:
        л += ["╔══ 3 · В КАКИЕ СФЕРЫ ДРУГ ДРУГА ПОПАДАЮТ ══",
              "  Точка одного в доме другого — та сфера его жизни, которую этот", 
              "  человек задевает самим своим присутствием.", ""]
        for карта, куспиды, кто, чей in ((карта_а, куспиды_б, имя_а, имя_б),
                                          (карта_б, куспиды_а, имя_б, имя_а)):
            если = дома_друг_друга(карта, куспиды, кто, чей)
            if если:
                л.append(f"  ── точки {кто} в домах {чей}:")
                по_домам = {}
                for x in если:
                    по_домам.setdefault(x["дом"], []).append(K.имя_точки(x["точка"]))
                for д in sorted(k for k in по_домам if k):
                    л.append(f"     {д:2}-й ({K.СФЕРА_ДОМА[д]}): {', '.join(по_домам[д])}")
                л.append("")
    л += ["  ▸ РЕЗЮМЕ: где один входит в жизнь другого.", "", ч]
    return "\n".join(л)


def _конец(имя, т, чей, карта, куспиды, полно=True):
    """Одна сторона связи — как в накладке, но без сроков."""
    з = т["знак"]
    роль, поясн = K.РОЛЬ.get(имя, ("", ""))
    л = [f"     ── {K.имя_точки(имя).upper()} ({чей}) · {т.get('словами','')}"]
    if роль:
        л.append(f"        сила: {роль} — {поясн}")
    ст = None
    try:
        from engine import statyi
        ст = statyi.В_ЗНАКЕ.get((имя, з))
    except Exception:
        pass
    л.append(f"        в знаке {з}" + (f": {ст[0]}" if ст else ""))
    д = K.достоинство(имя, з)[0]
    if д:
        л.append(f"        достоинство: {д}")
    # ⚠️ 04.09: владение знаками нужно всегда — и без домов тоже
    свои_знаки = K.владеет(имя)[0]
    if свои_знаки:
        обл = ", ".join(свои_знаки)
        л.append(f"        владеет {обл} → тянет за собой эти дела")
    упр = K.УПРАВИТЕЛЬ.get(з, [None])[0]
    if упр and упр in карта:
        гх = карта[упр]
        л.append(f"        хозяин знака {упр} стоит {гх.get('словами','')} "
                 f"[{гх['код']['тег']}]")
    if куспиды:
        мой = K.дом_точки(т["градус"], куспиды)
        if мой:
            л.append(f"        в своей карте — {мой}-й дом ({K.СФЕРА_ДОМА[мой]})")
        свои = K.чем_владеет_в_домах(имя, куспиды, карта)
        if свои:
            л.append("        владеет домами: " +
                     ", ".join(f"{н}-м" for н in свои))
    к = т["код"]
    л.append(f"        градус [{к['тег']}]" +
             (f" · ФЛАГ: {к['флаг']}" if к.get("флаг") not in ("НЕТ", "", None) else ""))
    if полно:
        л.append(f"           {к['суть']}")
        if к.get("переход"):
            л.append(f"           {к['переход']}")
        for у in (т.get("подградусы") or [])[:2]:
            л.append(f"        подградус {у['уровень']} (кухня): "
                     f"{у.get('словами','')} [{у['тег']}]")
    if т.get("ретро"):
        л.append("        РЕТРОГРАДНА — сила работает внутрь")
    return л
