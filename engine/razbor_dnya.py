def выбрать_оттенок(я: dict) -> tuple:
    """Оттенок первой строки — только из ЛИЧНЫХ признаков карты.

    Признаки, одинаковые на сутки, сюда не годятся: они у всех одни и те же.
    Возвращает саму фразу и признак «взять второй оборот зачина».
    """
    # какой из оборотов взять — решает дом, а он у каждого свой
    def оборот(ключ, дом):
        обороты = С.ОТТЕНОК[ключ]
        return обороты[(дом or 1) % len(обороты)]

    оп = я.get("опора")
    if оп and оп.get("на_угле"):
        return оборот("опора_на_угле", оп.get("дом")), False
    if я.get("схождение_целей"):
        дом = ((я.get("схождение_целей") or {}).get("где_хозяин_пути") or {}).get("дом")
        return оборот("цели_сошлись", дом), True
    р = я.get("реализация") or {}
    дом_вектора = (я["вектор"]["куда"] or {}).get("дом")
    if not р.get("канал_открыт", True):
        return оборот("канал_зажат", дом_вектора), True
    почему = " ".join(р.get("почему_канал") or [])
    if "угловом доме" in почему:
        return оборот("канал_свободен", дом_вектора), False
    return "", False


def смысл_движения(я: dict) -> str:
    """Не всегда «уйти»: решает, напряжён ли уходящий узел связями.

    Напряжён — прошлое держит, нужен отрыв.
    Спокоен — прошлое не держит, а питает: на него можно опереться.
    И то, и другое — сохранить и повернуть.
    """
    о = я["вектор"]["откуда"]
    if not о:
        return "отрыв"
    жёсткие = [с for с in о.get("связи", [])
               if с["аспект"] in ("квадрат", "оппозиция") and с["орбис"] <= 3.0]
    мягкие = [с for с in о.get("связи", [])
              if с["аспект"] in ("трин", "секстиль") and с["орбис"] <= 3.0]
    if жёсткие and мягкие:
        return "поворот"
    if жёсткие:
        return "отрыв"
    if мягкие:
        return "опора"
    return "отрыв"


def ядро_полностью(я: dict) -> list:
    строки = []

    о, к = я["вектор"]["откуда"], я["вектор"]["куда"]
    if о and к:
        оттенок, второй = выбрать_оттенок(я)
        строки.append(С.ядро_абзацем(о["дом"], к["дом"], к["знак"],
                                     оттенок=оттенок, второй_оборот=второй,
                                     движение=смысл_движения(я)))

    боль = я.get("боль")
    if боль:
        т = С.ХИРОН_ДОМ.get(боль["дом"], "")
        if т:
            строки.append(т + " " + С.ХИРОН_ДАЁТ)

    оп = я.get("опора")
    if оп:
        т = С.ОПОРА_ДОМ.get(оп["дом"], "")
        if оп.get("на_угле"):
            т = (т + " " + С.СЕЛЕНА_НА_УГЛЕ).strip()
        if т:
            строки.append(т)

    сб = я.get("соблазн")
    if сб:
        т = С.ТЕНЬ_ДОМ.get(сб["дом"], "")
        if я.get("тень_на_векторе"):
            т = (т + " " + С.ЛИЛИТ_НА_ВЕКТОРЕ).strip()
        if т:
            строки.append(т)

    return [с for с in строки if с]


