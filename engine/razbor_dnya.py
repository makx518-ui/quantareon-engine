def резюме(я: dict) -> str:
    части = []

    исход = (я.get("реализация") or {}).get("исход") or "с задержкой"

    о, к = я["вектор"]["откуда"], я["вектор"]["куда"]
    if о and к:
        откуда = С.ЮЖНЫЙ_ДОМ.get(о["дом"], ("", ""))[0]
        куда = С.СЕВЕРНЫЙ_ДОМ.get(к["дом"], ("", ""))[0]
        зачин = С.ЗАЧИН_РЕЗЮМЕ.get(исход, "Коротко: ")
        главное = С.ГЛАВНОЕ.get(исход).format(откуда=откуда, куда=куда)
        части.append(зачин + главное)

    оп = я.get("опора")
    if оп:
        части.append("Опереться есть на что: " +
                     ОПОРА_КОРОТКО.get(оп["дом"], "на уже сделанное") + ".")

    сб = я.get("соблазн")
    if сб:
        части.append("Беречься стоит одного: " +
                     ТЕНЬ_КОРОТКО.get(сб["дом"], "подмены дела видимостью") + ".")

    if исход == "сразу":
        части.append("Начатое сегодня сегодня и сложится.")
    elif исход == "с задержкой":
        части.append("Начинать нужно сегодня, а завершится это позже "
                     "и не без чужого участия.")
    elif исход == "не сейчас":
        части.append("Решающий шаг лучше отложить: сегодня он не пройдёт.")

    return " ".join(части)
