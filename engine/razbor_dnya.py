def сферы_дня(точки: dict, куспиды: list, аспекты: list, ядро: dict) -> list:
    """Есть планеты — читаются они и сила каждой.
    Планет нет — сфера читается по управителю: где стоит, в какой силе,
    куда ведут его связи, и лежит ли сфера на линии дня."""
    if not куспиды:
        return []

    по_домам = {}
    for имя, т in точки.items():
        if имя in ПРОПУСТИТЬ:
            continue
        д = K.дом_точки(т["градус"], куспиды)
        if д:
            по_домам.setdefault(д, []).append(имя)

    линия = set()
    for сторона in (ядро.get("вектор") or {}).values():
        if сторона and сторона.get("дом"):
            линия.add(сторона["дом"])

    абзацы = []
    сказано_ранее = set()

    def выбрать(пара):
        """Из двух оборотов берётся тот, который ещё не звучал."""
        if not пара:
            return ""
        if isinstance(пара, str):
            return пара
        for ф in пара:
            if ф not in сказано_ранее:
                return ф
        return пара[0]

    for дом in range(1, 13):
        куски = []

        def добавить(ф):
            if ф and ф not in сказано_ранее:
                куски.append(ф)
                сказано_ранее.add(ф)

        стоят = [и for и in по_домам.get(дом, []) if и in СФ.ТОЧКА_В_СФЕРЕ]
        управитель = K.УПРАВИТЕЛЬ[K.знак(куспиды[дом - 1])][0]
        ту = точки.get(управитель)
        дом_упр = K.дом_точки(ту["градус"], куспиды) if ту else None

        def сила(имя, т):
            дост = K.достоинство(имя, т["знак"])[0]
            if дост in ("В ПАДЕНИИ", "В ИЗГНАНИИ"):
                добавить(СФ.ТРУДНО)
            elif дост in ("В СВОЁМ ЧЕРТОГЕ", "В ВОЗВЫШЕНИИ"):
                добавить(СФ.СВОБОДНО)
            if т.get("ретро") and имя not in ("Юж.Узел", "Сев.Узел", "Лилит"):
                добавить(СФ.РЕТРО)

        if стоят:
            for имя in стоят[:2]:
                куски.append(СФ.ТОЧКА_В_СФЕРЕ[имя])
                сила(имя, точки[имя])
            if дом_упр:
                добавить(выбрать(СФ.ЧЕРЕЗ_ДОМ.get(дом_упр)))
        else:
            ф = СФ.НА_ЛИНИИ_ДНЯ if дом in линия else выбрать(СФ.БЕЗ_СОБЫТИЙ)
            куски.append(ф)
            сказано_ранее.add(ф)
            ф = выбрать(СФ.ЧЕРЕЗ_ДОМ.get(дом_упр)) if дом_упр else ""
            if ф:
                куски.append(ф)
                сказано_ранее.add(ф)
            if ту:
                сила(управитель, ту)

        свои = set(стоят) | ({управитель} if управитель else set())
        задевают = sorted([а for а in аспекты if а["а"] in свои or а["б"] in свои],
                          key=lambda а: а["орбис"])
        if задевают and задевают[0]["орбис"] <= 2.0:
            добавить(СФ.СВЯЗЬ.get(задевают[0]["аспект"]))

        # чем обернётся: итог сферы в обе стороны. Зависит от того, где стоит
        # её управитель — оттуда и приходит всё, что в ней случится.
        if дом_упр:
            ф = выбрать(СФ.ЧЕМ_ОБЕРНЁТСЯ.get(дом_упр))
            if ф:
                куски.append(ф)
                сказано_ранее.add(ф)

        абзацы.append((СФ.СФЕРА[дом], " ".join(к for к in куски if к)))

    return абзацы


