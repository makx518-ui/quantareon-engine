def _jd(t):
    return swe.julday(t.year, t.month, t.day, t.hour + t.minute / 60 + t.second / 3600)


def _дуга(a, b):
    d = abs((a - b) % 360)
    return min(d, 360 - d)


def _дмс(x):
    x %= 360
    d = x % 30
    return f"{int(d)}°{int((d % 1) * 60):02d}′ {ЗНАКИ_РОД[int(x // 30)]}"


def _код(x):
    try:
        k = kod360.code_by_abs(x) or {}
        return k.get("tag") or k.get("тег") or ""
    except Exception:
        return ""


def _дата(d):
    return f"{d.day} {МЕСЯЦЫ[d.month - 1]}"


def _дата_г(d):
    return f"{d.day} {МЕСЯЦЫ[d.month - 1]} {d.year}"


# ── эфемерида ─────────────────────────────────────────────────────────
def _лента(старт, конец):
    """Дневная лента позиций транзитных планет (UTC 12:00)."""
    л = []
    d = старт
    while d <= конец:
        t = datetime(d.year, d.month, d.day, 12, 0, 0)
        jd = _jd(t)
        поз = {}
        for имя, pl in ТРАНЗИТНЫЕ:
            try:
                r = swe.calc_ut(jd, pl)[0]
                поз[имя] = (r[0] % 360, r[3])
            except Exception:
                pass
        л.append((d, поз))
        d += timedelta(days=1)
    return л


# ── аспекты к точкам ─────────────────────────────────────────────────
def _аспекты(лента, цели, метка):
    """Локальные минимумы орбиса — точные дни; окно — пока орбис ≤ порога."""
    события = []
    for тр, _ in ТРАНЗИТНЫЕ:
        for цель, гц in цели.items():
            if тр == цель and метка == "натал" and тр != "Сев.Узел":
                pass  # возврат планеты на себя — тоже событие (Сатурн на Сатурн и т.п.)
            for асп, угол in АСПЕКТЫ:
                порог = ОРБИС[асп]
                ряд = []
                for d, поз in лента:
                    if тр not in поз:
                        ряд.append(None); continue
                    о = abs(_дуга(поз[тр][0], гц) - угол)
                    ряд.append((о, поз[тр][1] < 0, поз[тр][0]))
                n = len(ряд)
                i = 1
                while i < n - 1:
                    a, b, c = ряд[i - 1], ряд[i], ряд[i + 1]
                    if a and b and c and b[0] <= порог and b[0] <= a[0] and b[0] <= c[0] and (b[0] < a[0] or b[0] < c[0]):
                        # окно
                        j = i
                        while j > 0 and ряд[j - 1] and ряд[j - 1][0] <= порог: j -= 1
                        k = i
                        while k < n - 1 and ряд[k + 1] and ряд[k + 1][0] <= порог: k += 1
                        события.append({"тр": тр, "цель": цель, "асп": асп, "метка": метка,
                                        "дата": лента[i][0], "орб": round(b[0], 2),
                                        "ретро": b[1], "где_тр": b[2], "где_цель": гц,
                                        "окно": (лента[j][0], лента[k][0])})
                        i = k + 1
                        continue
                    i += 1
    # номер прохода в серии (одна пара тр+цель+асп, несколько дат)
    группы = {}
    for е in события:
        группы.setdefault((е["тр"], е["цель"], е["асп"], е["метка"]), []).append(е)
    for ключ, сп in группы.items():
        сп.sort(key=lambda е: е["дата"])
        for i, е in enumerate(сп):
            е["проход"] = i + 1
            е["из"] = len(сп)
    события.sort(key=lambda е: е["дата"])
    return события


def _смены_знака(лента):
    из = []
    prev = {}
    for d, поз in лента:
        for имя, (lon, скор) in поз.items():
            if имя not in МЕДЛЕННЫЕ and имя != "Марс":
                continue
            z = int(lon // 30)
            if имя in prev and prev[имя] != z:
                из.append({"дата": d, "тр": имя, "из": ЗНАКИ[prev[имя]], "в": ЗНАКИ[z], "ретро": скор < 0})
            prev[имя] = z
    return из


def _стоянки(лента):
    из = []
    prev = {}
    for d, поз in лента:
        for имя, (lon, скор) in поз.items():
            if имя not in МЕДЛЕННЫЕ or имя == "Сев.Узел":
                continue
            s = скор < 0
            if имя in prev and prev[имя] != s:
                из.append({"дата": d, "тр": имя, "стал": "ретроградным (внутрь)" if s else "прямым (наружу)", "где": lon})
            prev[имя] = s
    return из


def _входы_в_дома(лента, куспиды, метка):
    из = []
    if not куспиды or len(куспиды) < 12:
        return из
    def дом(lon):
        for h in range(12):
            a, b = куспиды[h], куспиды[(h + 1) % 12]
            if (lon - a) % 360 < (b - a) % 360:
                return h + 1
        return 12
    prev = {}
    for d, поз in лента:
        for имя, (lon, скор) in поз.items():
            if имя not in МЕДЛЕННЫЕ and имя != "Марс":
                continue
            h = дом(lon)
            if имя in prev and prev[имя] != h:
                из.append({"дата": d, "тр": имя, "из": prev[имя], "в": h, "ретро": скор < 0, "метка": метка})
            prev[имя] = h
    return из


# ── вес события ───────────────────────────────────────────────────────
def _вес(е, хозяин, углы_имена):
    в = 0
    if е["тр"] in ("Уран", "Нептун", "Плутон", "Сатурн"): в += 3
    elif е["тр"] in ("Юпитер", "Хирон", "Сев.Узел"): в += 2
    else: в += 1
    if е["цель"] in углы_имена: в += 3
    if е["цель"] in ("Солнце", "Луна"): в += 2
    if е["цель"] == хозяин: в += 3
    if е["асп"] in ("соединение", "оппозиция"): в += 2
    elif е["асп"] == "квадрат": в += 1
    if е["орб"] <= 0.5: в += 1
    # высшая или Сатурн напряжённо/соединением на личную планету — всегда тема года
    if е["тр"] in ("Сатурн", "Уран", "Нептун", "Плутон") and е["цель"] in СЕПТЕНЕР and е["асп"] in ("соединение", "оппозиция", "квадрат"):
        в += 2
    return в


# ── главная функция ───────────────────────────────────────────────────
def год_помесячно(точки, момент_соляра, широта, долгота, куспиды_натал=None,
                  углы_натал=None, хозяин=None, горизонт_дней=395):
    """Текстовый раздел «ГОД ПОМЕСЯЧНО» для слоя соляра.

    точки          — натальные точки (dict имя → {"градус": ...})
    момент_соляра  — datetime UTC возвращения Солнца
    широта/долгота — место, где человек живёт (дома соляра)
    куспиды_натал  — 12 натальных куспидов (если время есть)
    углы_натал     — {"ASC": градус, "MC": градус} (если время есть)
    хозяин         — хозяин натального узора (имя точки)
    """
    м = момент_соляра.replace(tzinfo=None) if момент_соляра.tzinfo else момент_соляра
    старт = (м - timedelta(days=30)).date()
    конец = (м + timedelta(days=горизонт_дней)).date()
    лента = _лента(старт, конец)

    # цели: натальные точки + углы натала; углы соляра
    цели_н = {}
    for имя in ЦЕЛИ_ИЗ_КАРТЫ:
        if имя in точки and точки[имя].get("градус") is not None:
            цели_н[имя] = точки[имя]["градус"] % 360
    углы_имена = set()
    if углы_натал:
        for k, v in (("Асцендент", углы_натал.get("ASC")), ("Вершина (MC)", углы_натал.get("MC"))):
            if v is not None:
                цели_н[k] = v % 360; углы_имена.add(k)
    цели_с = {}
    try:
        куспиды_с = swe.houses(_jd(м), широта, долгота, b'P')[0]
        цели_с["Асцендент года"] = куспиды_с[0] % 360
        цели_с["Вершина года"] = куспиды_с[9] % 360
        углы_имена |= {"Асцендент года", "Вершина года"}
    except Exception:
        куспиды_с = None

    асп_н = _аспекты(лента, цели_н, "натал")
    асп_с = _аспекты(лента, цели_с, "соляр")
    смены = _смены_знака(лента)
    стоянки = _стоянки(лента)
    входы = _входы_в_дома(лента, куспиды_натал, "натал")

    все = асп_н + асп_с
    for е in все:
        е["вес"] = _вес(е, хозяин, углы_имена)
    ключевые = sorted([е for е in все if е["вес"] >= 8], key=lambda е: е["дата"])

    ч = "═" * 74
    л = [ч, "ГОД ПОМЕСЯЧНО · ДИНАМИКА СОЛЯРНОГО ГОДА", ч,
         "  Машина прошла эфемериду день за днём от месяца до соляра до месяца после.",
         "  Каждое событие — астрономический факт с датой точности и окном (пока держится орбис).",
         "  Орбисы: соединение, оппозиция, квадрат — 2°; трин, секстиль — 1.5°.",
         "  Порядок чтения: сперва вехи и ключевые события (⭐), потом лента по месяцам.",
         f"  событий: к натальным точкам {len(асп_н)} · к углам года {len(асп_с)} · "
         f"смен знака {len(смены)} · стоянок {len(стоянки)} · входов в дома {len(входы)}", ""]

    # ── ключевые события года
    л.append("  ── КЛЮЧЕВЫЕ СОБЫТИЯ ГОДА (⭐ — раскрывать обязательно, каждое — тема) ──")
    if not ключевые:
        л.append("     (нет событий с высоким весом)")
    for е in ключевые:
        сер = f" · проход {е['проход']} из {е['из']}" if е["из"] > 1 else ""
        р = " ℞" if е["ретро"] else ""
        л.append(f"  ⭐ {_дата_г(е['дата'])}: транзитный {е['тр']}{р} {е['асп']} {е['цель']}"
                 f" ({_дмс(е['где_цель'])}) · орб {е['орб']}°{сер}")
        л.append(f"       окно {_дата(е['окно'][0])} – {_дата(е['окно'][1])} · {е['тр']} {ЧТО_ДЕЛАЕТ.get(е['тр'], '')}; "
                 f"{ПРИРОДА[е['асп']]} тому, что отвечает за {е['цель']}")
        л.append(f"       градусы: транзит [{_код(е['где_тр'])}] {_дмс(е['где_тр'])} → цель [{_код(е['где_цель'])}] {_дмс(е['где_цель'])}")
        if е["цель"] == хозяин:
            л.append("       ⚑ бьёт в ХОЗЯИНА натального узора — это событие года, не фон")
        if е["цель"] in углы_имена:
            л.append("       ⚑ на угол — выходит наружу, в события")
    л.append("")

    # ── вехи
    л.append("  ── ВЕХИ: смены знака и стоянки медленных ──")
    for с in sorted(смены, key=lambda x: x["дата"]):
        if с["тр"] == "Марс": continue
        л.append(f"  ★ {_дата_г(с['дата'])}: {с['тр']} переходит из {с['из']} в {с['в']}{' (ретроградно)' if с['ретро'] else ''} — смена большого цикла")
    for с in sorted(стоянки, key=lambda x: x["дата"]):
        л.append(f"  ◆ {_дата_г(с['дата'])}: {с['тр']} становится {с['стал']} на {_дмс(с['где'])} [{_код(с['где'])}]")
    л.append("")

    # ── лента по месяцам
    л.append("  ── ЛЕНТА ПО МЕСЯЦАМ · что становится точным ──")
    по_мес = {}
    for е in все:
        по_мес.setdefault((е["дата"].year, е["дата"].month), []).append(е)
    for в in входы:
        по_мес.setdefault((в["дата"].year, в["дата"].month), []).append(в)
    for с in смены:
        if с["тр"] == "Марс":
            по_мес.setdefault((с["дата"].year, с["дата"].month), []).append(с)
    for (y, mo) in sorted(по_мес.keys()):
        л.append(f"\n  ▸ {МЕСЯЦЫ_ИМ[mo - 1]} {y}")
        for е in sorted(по_мес[(y, mo)], key=lambda x: x["дата"]):
            if "асп" in е:
                зв = "⭐ " if е["вес"] >= 8 else ("• " if е["вес"] >= 5 else "· ")
                р = " ℞" if е["ретро"] else ""
                сер = f" · {е['проход']}/{е['из']}" if е["из"] > 1 else ""
                л.append(f"     {зв}{_дата(е['дата'])}: {е['тр']}{р} {е['асп']} {е['цель']} · орб {е['орб']}°"
                         f" · окно {_дата(е['окно'][0])}–{_дата(е['окно'][1])}{сер}"
                         f" · [{_код(е['где_тр'])}] → [{_код(е['где_цель'])}]")
            elif "стал" in е:
                pass
            elif "в" in е and isinstance(е.get("в"), int):
                л.append(f"     ▸ {_дата(е['дата'])}: {е['тр']}{' ℞' if е['ретро'] else ''} входит в {е['в']}-й натальный дом (из {е['из']}-го)")
            elif "в" in е:
                л.append(f"     ★ {_дата(е['дата'])}: {е['тр']} переходит {е['из']} → {е['в']}")
    л.append("")
    л.append("  ▸ РЕЗЮМЕ: год читается как развитие — что нарастает, где перелом, куда сдвиг;")
    л.append("    ⭐ — стержни года, • — рабочие события, · — фон. Один и тот же аспект несколькими проходами — одна история.")
    return "\n".join(л), {"ключевые": ключевые, "аспекты": все, "смены": смены, "стоянки": стоянки, "входы": входы}
