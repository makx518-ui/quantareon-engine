# -*- coding: utf-8 -*-
"""
РАЗВЁРНУТЫЕ ГРАДУСЫ — монолит для читателя.

Его решение 04.09: машина вшивает КОРОТКИЙ код из приземлённой Азбуки,
а читатель, когда нужна глубина, берёт РАЗВЁРНУТЫЙ шаг из монолита.

Две редакции одного градуса:
    приземлённая  [ЛИДЕР/ХАРИЗМА] — «личная сила воплощает общие идеалы»
    развёрнутая   [ГОЛОС ТОЛПЫ/ХАРИЗМА] — «отточенная сила личности
                  становится голосом коллектива, преображает энергии масс»

Монолит в раскладку НЕ вшивается — иначе каждый слой раздуется втрое.
Он подаётся отдельно, по запросу читателя.
"""
import os
import re

_ШАГИ = None
ЗНАКИ = ["ОВЕН", "ТЕЛЕЦ", "БЛИЗНЕЦЫ", "РАК", "ЛЕВ", "ДЕВА",
         "ВЕСЫ", "СКОРПИОН", "СТРЕЛЕЦ", "КОЗЕРОГ", "ВОДОЛЕЙ", "РЫБЫ"]


def _путь():
    return os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "data", "kod_processa_360_polny.md")


def загрузить(path=None):
    """Разбирает монолит на 360 развёрнутых шагов.
    Ключ — (номер блока 1..12, шаг 1..30)."""
    global _ШАГИ
    if _ШАГИ is not None:
        return _ШАГИ
    путь = path or _путь()
    if not os.path.exists(путь):
        _ШАГИ = {}
        return _ШАГИ
    текст = open(путь, encoding="utf-8").read()
    _ШАГИ = {}
    блок = 0
    # блоки идут по знакам; шаги внутри блока нумерованы 1..30
    куски = re.split(r"\*\*Шаг (\d+) \[", текст)
    заголовок = куски[0]
    for i in range(1, len(куски), 2):
        номер = int(куски[i])
        тело = куски[i + 1]
        # определяем блок: перед этим шагом мог смениться знак
        before = текст[:текст.find(f"**Шаг {номер} [", 0 if номер == 1 else 0)]
        if номер == 1:
            блок += 1
        строки = тело.split("\n")
        первая = строки[0]
        тег = первая.split("]")[0] if "]" in первая else ""
        заг = "[" + первая.replace("**", "").strip()
        остаток = "\n".join(строки[1:]).strip()
        часть = остаток.split("**Шаг")[0].strip()
        _ШАГИ[(блок, номер)] = {
            "тег": тег.strip(),
            "заголовок": заг,
            "текст": часть,
        }
    return _ШАГИ


def развёрнутый(знак_или_блок, градус):
    """Развёрнутый шаг по знаку и градусу.
    знак_или_блок: имя знака ('ДЕВА') или номер 1..12."""
    шаги = загрузить()
    if isinstance(знак_или_блок, str):
        имя = знак_или_блок.upper()
        if имя not in ЗНАКИ:
            return None
        блок = ЗНАКИ.index(имя) + 1
    else:
        блок = int(знак_или_блок)
    return шаги.get((блок, int(градус)))


def развёрнутый_по_абс(абс_градус):
    """По абсолютному градусу зодиака 0..360."""
    а = абс_градус % 360
    блок = int(а // 30) + 1
    шаг = int(а % 30) + 1
    return развёрнутый(блок, шаг)


def справка(точки, только=None):
    """Развёрнутые шаги для набора точек — то, что читатель берёт,
    когда короткого кода мало.

    только: список имён точек; по умолчанию — все.
    """
    л = ["═" * 74, "  РАЗВЁРНУТЫЕ ГРАДУСЫ · для глубины чтения", "═" * 74,
         "  Машина дала короткий код. Здесь тот же градус шире —",
         "  с образами, полным действием и переходом к следующему шагу.", ""]
    for имя, т in точки.items():
        if только and имя not in только:
            continue
        р = развёрнутый_по_абс(т["градус"] if isinstance(т, dict) else т)
        if not р:
            continue
        л += [f"  ── {имя}: {т.get('словами', '') if isinstance(т, dict) else ''}",
              f"     {р['заголовок']}"]
        for строка in р["текст"].split("\n"):
            if строка.strip():
                л.append(f"     {строка.strip()}")
        л.append("")
    return "\n".join(л)
