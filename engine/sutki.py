def дом_точки(градус, куспиды):
    for i in range(12):
        а, б = куспиды[i], куспиды[(i + 1) % 12]
        ш = ((б - а) % 360) or 360
        if ((градус - а) % 360) < ш:
            return i + 1
    return 12


def что_нагружено(космо, ядро, слой2=None):
    """Готовые величины с полочек первых двух слоёв: что несущее и что горячее.
    Третий слой сам ничего не считает — только спрашивает."""
    нагрузка = {}

    def добавить(имя, метка, вес):
        """⚠️ 04.09: одна и та же метка не должна ложиться дважды.
        У него Плутон стоит на обоих узлах — и метка «ось судьбы»
        приписывалась ему два раза, удваивая вес."""
        если = нагрузка.setdefault(имя, {"метки": [], "вес": 0})
        if метка in если["метки"]:
            return
        если["метки"].append(метка)
        если["вес"] += вес

    # ── из первого слоя: что несущее в карте ──
    for х in (ядро.get("хозяин") or {}).get("кто", []):
        добавить(х, "хозяин узора", 3)
    for с_ in K.судьбоносные(космо):
        добавить(с_["узел"], "ось судьбы", 3)
        добавить(с_["планета"], "стоит на оси судьбы", 3)
    for а in ядро.get("точные", []):
        добавить(а["а"], f"точная связь с {K.имя_точки(а['б'])}", 2)
        добавить(а["б"], f"точная связь с {K.имя_точки(а['а'])}", 2)
    for и, н in list((ядро.get("связность") or {}).items())[:3]:
        добавить(и, f"узел карты, {н} связей", 1)

    # ── из второго слоя: что горячее сейчас ──
    if слой2:
        for а in слой2.get("аспекты_колеса", []):
            if а.get("слой") == "космограмма":
                добавить(а["точка"], f"Колесо {а['аспект']} ({а['орбис']:.2f}°)", 3)
        for с_ in слой2.get("дирекции", []):
            if с_.get("точный"):
                добавить(с_["натал"], f"дирекция {с_['точка']} {с_['аспект']}", 3)
        for с_ in слой2.get("транзиты", []):
            if с_.get("вес") in ("ТОЧНЫЙ", "РАБОЧИЙ"):
                вес = 2 if с_["вес"] == "ТОЧНЫЙ" else 1
                добавить(с_["натал"],
                         f"транзит {K.имя_точки(с_['транзит'])} {с_['аспект']}", вес)
    return нагрузка


def сутки(момент, широта, долгота, натал, космо, ядро, слой2=None,
          пояс_часов=0, шаг_минут=4):
    """Разметка суток: 12 глав, узлы с весом из первых слоёв, завязка и кульминация."""
    якорь = асцендент_в(момент, широта, долгота)
    начало = начало_круга(момент, якорь, широта, долгота)
    главы = главы_круга(начало, широта, долгота)
    узлы = узлы_круга(начало, натал, широта, долгота, шаг_минут=шаг_минут)
    нагрузка = что_нагружено(космо, ядро, слой2)
    мест = lambda д: (д + timedelta(hours=пояс_часов))

    # ── завязка: градус вопроса ──
    т_якоря = K.точка("Асцендент вопроса", якорь)
    завязка = {"градус": якорь, "точка": т_якоря,
               "код": kod360.code_by_abs(якорь), "когда": мест(момент)}

    # ── кульминация: когда якорный градус придёт на вершину ──
    кульминация = _когда_угол_на(якорь, момент, широта, долгота, "MC", пояс_часов=пояс_часов)
    замок = _когда_угол_на(якорь, момент, широта, долгота, "AC", пояс_часов=пояс_часов)

    # ── узлы с весом ──
    размеченные = []
    for у in узлы:
        имя = у["точка"].replace("натальный ", "").replace("транзитный ", "")
        н = нагрузка.get(имя, {})
        размеченные.append({
            **у,
            "время_местное": мест(у["время"]),
            "нагрузка": н.get("метки", []),
            "вес": н.get("вес", 0),
            "код": kod360.code_by_abs(у["градус_точки"]),
        })

    # ── главы со сферами ──
    ку = куспиды_в(момент, широта, долгота)
    вх = восход(начало, широта, долгота, пояс_часов)
    зк = закат(начало, широта, долгота, пояс_часов)
    размеченные_главы = []
    for и, г in enumerate(главы):
        свои = [у for у in размеченные if г["начало"] <= у["время"] < г["конец"]]
        свои.sort(key=lambda x: -x["вес"])
        д = г.get("длительность") or (г["конец"] - г["начало"])
        # ⚠️ 05.09: глава получает сферу жизни, код своего градуса и режим
        сер = г["начало"] + (г["конец"] - г["начало"]) / 2
        ас_сер = асцендент_в(сер - timedelta(hours=пояс_часов), широта, долгота)
        дом_главы = дом_точки(ас_сер, ку) if ку else и + 1
        размеченные_главы.append({
            "номер": и + 1, "знак": г["знак"],
            "сфера": СФЕРА.get(дом_главы, ""),
            "дом": дом_главы,
            "код_градуса": kod360.code_by_abs(ас_сер),
            "градус_середины": K.градус_словами(ас_сер),
            "режим": режим_часа(мест(сер) if hasattr(сер,'hour') else сер, вх, зк),
            "начало": мест(г["начало"]), "конец": мест(г["конец"]),
            "минут": round(д.total_seconds() / 60),
            "разорвана": г.get("разорвана", False),
            "части": [(мест(а), мест(б)) for а, б in г.get("части", [])],
            "узлы": свои,
            "вес_главы": sum(у["вес"] for у in свои),
        })
    return {"момент_utc": момент, "завязка": завязка, "кульминация": кульминация, "замок": замок,
            "начало_круга": мест(начало), "главы": размеченные_главы,
            "нагрузка": нагрузка, "узлов": len(размеченные)}


def _когда_угол_на(цель, момент, широта, долгота, какой="MC", предел_часов=26,
                   пояс_часов=0):
    """Час, когда заданный градус придёт на вершину или на асцендент."""
    def угол(т):
        ку = куспиды_в(т, широта, долгота)
        а = асцендент_в(т, широта, долгота)
        return а if какой == "AC" else ку[9]

    т = момент
    конец = момент + timedelta(hours=предел_часов)
    пред = K.дуга(угол(т), цель)
    while т < конец:
        т2 = т + timedelta(minutes=4)
        d = K.дуга(угол(т2), цель)
        if d > пред and пред < 1.0:
            низ, верх = т - timedelta(minutes=4), т2
            for _ in range(30):
                a = низ + (верх - низ) / 3
                b = верх - (верх - низ) / 3
                if K.дуга(угол(a), цель) < K.дуга(угол(b), цель):
                    верх = b
                else:
                    низ = a
            м = низ + (верх - низ) / 2
            return {"когда": м, "местное": м + timedelta(hours=пояс_часов),
                    "расхождение": round(K.дуга(угол(м), цель) * 60, 1)}
        пред = d
        т = т2
    return None


