#  обычно бодрствует — там сознание. После полуночи уже сон.
#  Ночь идёт в хвосте круга, значит это ЗАДЕЛ НА ЗАВТРА.
#
#  Мы не знаем, когда человек лёг. Потому пишем не «ты спал»,
#  а «в эти часы работает подсознание» — пусть сам сопоставит.

def восход(после_момента, широта, долгота, пояс_часов=0):
    """Первый восход ПОСЛЕ заданного момента. Считается для места и даты,
    не берётся фиксированным часом.

    ⚠️ 04.09: раньше искал восход от начала суток и попадал в прошлое —
    выходила отрицательная длительность ночи. Теперь ищу строго вперёд.
    """
    utc = после_момента - timedelta(hours=пояс_часов)
    j = swe.julday(utc.year, utc.month, utc.day,
                   utc.hour + utc.minute / 60 + utc.second / 3600)
    try:
        код, время = swe.rise_trans(j, swe.SUN, swe.CALC_RISE | swe.BIT_DISC_CENTER,
                                    (долгота, широта, 0))
        jr = время[0] if isinstance(время, (list, tuple)) else время
        if not jr:
            return None
        г, м, д, ч = swe.revjul(jr)
        в_utc = (datetime(г, м, д) + timedelta(hours=ч)).replace(tzinfo=timezone.utc)
        return в_utc + timedelta(hours=пояс_часов)
    except Exception:
        return None


def закат(после_момента, широта, долгота, пояс_часов=0):
    """Первый закат после момента — граница дня и вечера."""
    utc = после_момента - timedelta(hours=пояс_часов)
    j = swe.julday(utc.year, utc.month, utc.day,
                   utc.hour + utc.minute / 60 + utc.second / 3600)
    try:
        код, время = swe.rise_trans(j, swe.SUN, swe.CALC_SET | swe.BIT_DISC_CENTER,
                                    (долгота, широта, 0))
        jз = время[0] if isinstance(время, (list, tuple)) else время
        if not jз:
            return None
        г, м, д, ч = swe.revjul(jз)
        return ((datetime(г, м, д) + timedelta(hours=ч)).replace(tzinfo=timezone.utc)
                + timedelta(hours=пояс_часов))
    except Exception:
        return None


def режим_часа(момент, восход_, закат_):
    """Что за время суток. ⚠️ 05.09: раньше была только ночь с полуночи,
    теперь весь круг делится на четыре части."""
    полночь = момент.replace(hour=0, minute=0, second=0, microsecond=0)
    if восход_ and закат_:
        if момент < восход_:
            return ("НОЧЬ", "подсознание — работает без участия сознания")
        if момент < закат_:
            return ("ДЕНЬ", "сознание — всё происходит наяву")
        if момент < полночь + timedelta(days=1):
            return ("ВЕЧЕР", "переход — день оседает, сознание отпускает")
    return ("НОЧЬ", "подсознание — работает без участия сознания")


def ночная_полочка(данные, широта, долгота, пояс_часов=0, мухурта_минут=48):
    """Отдельный пункт: что прорабатывается во сне, с полуночи до восхода."""
    главы = данные["главы"]
    if not главы:
        return []
    # ищем ближайшую полночь ПОСЛЕ начала круга — ночь всегда в хвосте
    начало = данные["начало_круга"]
    полночь = (начало + timedelta(days=1)).replace(hour=0, minute=0, second=0, microsecond=0)
    if начало.hour == 0 and начало.minute < 5:
        полночь = начало
    в = восход(полночь, широта, долгота, пояс_часов)
    if в is None:
        в = полночь.replace(hour=6)
    # ⚠️ 04.09, сверено с его сайтом: брахма-мухурта — это ПРЕДПОСЛЕДНИЕ
    # 48 минут ночи, а не последние. Последний отрезок перед восходом
    # уже не она. Его движок считает так, и это классика.
    мух_кон = в - timedelta(minutes=мухурта_минут)
    мух_нач = мух_кон - timedelta(minutes=мухурта_минут)

    ч = "═" * 74
    л = ["", ч, "  ЧТО ПРОРАБАТЫВАЕТСЯ В ПОДСОЗНАНИИ · ЗАДЕЛ НА ЗАВТРА", ч,
         f"  ночь с {полночь.strftime('%H:%M')} до восхода в {в.strftime('%H:%M')}"
         f" ({round((в - полночь).total_seconds() / 60)} мин)",
         "  Мы не знаем, когда человек лёг. Здесь сказано, что работает в эти часы —",
         "  сопоставить со своим сном он может сам.", ""]

    ночные = []
    for г in главы:
        for у in г["узлы"]:
            т = у["время_местное"]
            if полночь <= т < в:
                ночные.append((г, у))
    if not ночные:
        л += ["  ночь тихая — угол не касается ничего значимого.",
              "  Сон идёт без проработки, назавтра ничего не заготовлено.", ч]
        return л

    # какие сферы включены ночью
    сферы = []
    for г in главы:
        если = [у for у in г["узлы"] if полночь <= у["время_местное"] < в]
        if если or (г["начало"] < в and г["конец"] > полночь):
            сферы.append(г)
    if сферы:
        л.append("  СФЕРЫ, ЧЕРЕЗ КОТОРЫЕ ИДЁТ НОЧЬ:")
        for г in сферы:
            л.append(f"     глава {г['номер']} · "
                     f"{г['начало'].strftime('%H:%M')}–{г['конец'].strftime('%H:%M')}")
        л.append("")

    сильные = [(г, у) for г, у in ночные if у["вес"] >= 3]
    прочие = [(г, у) for г, у in ночные if у["вес"] < 3]
    if сильные:
        л.append("  ⚑ ГЛАВНОЕ, ЧТО ПРОРАБАТЫВАЕТСЯ:")
        for г, у in сильные:
            л += [f"     {у['время_местное'].strftime('%H:%M')} · {у['угол'].split()[0]} "
                  f"→ {у['точка']} [{у['код']['tag']}]",
                  f"        {у['код']['суть'][:110]}",
                  f"        нагружено: {' · '.join(у['нагрузка'])}"]
        л.append("")
    if прочие:
        л.append("  прочее ночью: " + " · ".join(
            f"{у['время_местное'].strftime('%H:%M')} {у['точка'].split()[-1]} [{у['код']['tag']}]"
            for г, у in прочие[:8]))
        л.append("")

    в_мухурте = [(г, у) for г, у in ночные if мух_нач <= у["время_местное"] < мух_кон]
    л += [f"  ── МУХУРТА · {мух_нач.strftime('%H:%M')}–{мух_кон.strftime('%H:%M')} · "
          f"{мухурта_минут} минут (предпоследний отрезок ночи, восход в {в.strftime('%H:%M')})",
          "     Читается как обычная карта, только на 48 минут: какой узор сложился",
          "     в это окно, то и можно проработать в пограничном состоянии."]
    if в_мухурте:
        # какая сфера идёт в мухурте
        сфера_мух = [г for г in главы if г["начало"] <= мух_нач < г["конец"]]
        if сфера_мух:
            л.append(f"     сфера окна: глава {сфера_мух[0]['номер']}")
        сильные_мух = [(г, у) for г, у in в_мухурте if у["вес"] >= 3]
        прочие_мух = [(г, у) for г, у in в_мухурте if у["вес"] < 3]
        if сильные_мух:
            л.append("     ⚑ ЧТО СЛОЖИЛОСЬ В ОКНЕ:")
            for г, у in сильные_мух:
                л += [f"        {у['время_местное'].strftime('%H:%M')} · {у['угол'].split()[0]} "
                      f"→ {у['точка']} [{у['код']['tag']}]",
                      f"           {у['код']['суть'][:110]}",
                      f"           держат: {' · '.join(у['нагрузка'])}"]
            # лучший момент — где вес наибольший
            лучший = max(сильные_мух, key=lambda x: x[1]["вес"])[1]
            л += [f"     ▸ ЛУЧШЕЕ ВРЕМЯ: {лучший['время_местное'].strftime('%H:%M')} — "
                  f"здесь узор плотнее всего",
                  f"       прорабатывается: {лучший['код']['суть'][:90]}"]
        if прочие_мух:
            л.append("     прочее в окне: " + " · ".join(
                f"{у['время_местное'].strftime('%H:%M')} {у['точка'].split()[-1]} [{у['код']['tag']}]"
                for г, у in прочие_мух[:5]))
        if not сильные_мух and прочие_мух:
            л.append("     ▸ узор есть, но лёгкий: сон говорит, только не о главном")
    else:
        л += ["     касаний в окне нет — тихо.",
              "     Сон идёт как отдых, а не как работа; назавтра из него ничего не выйдет."]
    л += ["", "  ▸ Ночь стоит в конце круга: это не разбор прошедшего дня,",
          "    а заготовка на следующий.", ч]
    return л


