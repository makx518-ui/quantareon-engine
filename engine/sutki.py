def dlya_pravoy_kolonki(данные, космо, рождение, момент, широта, долгота,
                        пояс_часов=0, куспиды_натал=None):
    """Собирает пять блоков правой колонки одним словарём."""
    from engine import situacia as S
    from engine import lunacii as Л
    итог = {}

    # 1 · стержень дня
    з = данные["завязка"]
    итог["zavyazka"] = {"gradus": з["точка"].get("словами", ""),
                        "kod": f"[{з['код']['tag']}]"}
    if данные.get("кульминация"):
        итог["kulminaciya"] = данные["кульминация"]["местное"].strftime("%H:%M")
    if данные.get("замок"):
        итог["zamok"] = данные["замок"]["местное"].strftime("%H:%M")

    # 2 · медленные со сроками
    итог["medlennye"] = []
    try:
        for с in S.таблица_медленных(космо, рождение, момент, куспиды_натал):
            если = {"tochka": с["точка"], "poziciya": с["позиция"], "srok": с.get("срок", "")}
            if с["раздел"].startswith("ДИРЕКЦИИ · связи") or с["раздел"] == "КОЛЕСО ЖИЗНИ" \
               or с["точка"] in ("фаза прогр. Луны", "тема года"):
                итог["medlennye"].append(если)
    except Exception:
        pass

    # 3 · лунария
    try:
        лд = Л.лунный_день(момент)
        if лд:
            итог["lunnyy_den"] = f"{лд['день']}-й"
        j = swe.julday(момент.year, момент.month, момент.day,
                       момент.hour + момент.minute / 60)
        ф = Л.фаза_по_углу(Л._угол(j))
        итог["faza"] = f"{ф['имя']} — {ф['смысл']}"
        лун = Л.лунации(момент - timedelta(days=20), момент + timedelta(days=60), космо)
        итог["lunacii"] = [{
            "data": x["когда"].strftime("%d.%m"),
            "vid": x["вид"].lower(),
            "gradus": K.градус_словами(x["солнце"]),
            "kasaniya": (" · ".join(f"{K.имя_точки(к['точка'])} {к['орбис']}°"
                                    for к in x["касания"][:2]) if x["касания"] else ""),
        } for x in лун]
        зат = Л.затмения(момент - timedelta(days=20), момент + timedelta(days=90), космо)
        итог["zatmeniya"] = [{
            "data": x["когда"].strftime("%d.%m"),
            "vid": f"{x['вид'].lower()}{' полное' if x['полное'] else ''}",
            "gradus": K.градус_словами(x["солнце"]),
            "kasaniya": (" · ".join(f"{K.имя_точки(к['точка'])} {к['орбис']}°"
                                    for к in x["касания"][:2]) if x["касания"] else ""),
        } for x in зат]
    except Exception:
        pass

    # 4 · ночь и мухурта
    try:
        # ⚠️ ближайшая полночь ПОСЛЕ начала круга, а не всегда +1 день
        нк = данные["начало_круга"]
        полночь = нк.replace(hour=0, minute=0, second=0, microsecond=0)
        if полночь <= нк:
            полночь += timedelta(days=1)
        в = восход(полночь, широта, долгота, пояс_часов) or полночь.replace(hour=6)
        мух_кон = в - timedelta(minutes=48)
        мух_нач = мух_кон - timedelta(minutes=48)
        ночные = [у for г in данные["главы"] for у in г["узлы"]
                  if полночь <= у["время_местное"] < в]
        итог["noch"] = {
            "okno": f"{полночь.strftime('%H:%M')}–{в.strftime('%H:%M')}",
            "minut": round((в - полночь).total_seconds() / 60),
            "glavnoe": [{"vremya": у["время_местное"].strftime("%H:%M"),
                         "chto": f"{у['угол'].split()[0]} → {у['точка']} [{у['код']['tag']}]"}
                        for у in ночные if у["вес"] >= 3][:5],
        }
        в_мух = [у for у in ночные if мух_нач <= у["время_местное"] < мух_кон]
        итог["muhurta"] = {
            "okno": f"{мух_нач.strftime('%H:%M')}–{мух_кон.strftime('%H:%M')}",
            "luchshee": (max(в_мух, key=lambda x: x["вес"])["время_местное"].strftime("%H:%M")
                         + " — узор плотнее всего") if в_мух else "",
        }
    except Exception:
        pass

    # 5 · вес узлов
    все = [у for г in данные["главы"] for у in г["узлы"]]
    гл = [у for у in все if у["вес"] >= 3]
    итог["ves"] = {
        "glavnyh": len(гл),
        "rabochih": len([у for у in все if 1 <= у["вес"] < 3]),
        "fonovyh": len([у for у in все if у["вес"] == 0]),
        "spisok": [{"vremya": у["время_местное"].strftime("%H:%M"),
                    "chto": f"{у['угол'].split()[0]} → {у['точка']}",
                    "nagruzka": " · ".join(у["нагрузка"][:2])}
                   for у in sorted(гл, key=lambda x: -x["вес"])[:8]],
    }
    return итог
