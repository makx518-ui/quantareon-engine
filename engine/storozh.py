# -*- coding: utf-8 -*-
"""
storozh.py — СТОРОЖ · 09.09.2026.

Его случай: машина отдала «Солнце — Водолей 11°, код [УЕДИНЕНИЕ ХУДОЖНИКА]»,
а читатель написал «Солнце — Водолей 27°, [ИЕРАРХИЯ/ИСКУШЕНИЕ ВЛАСТЬЮ]» — взял
соседнюю строку Меркурия. Правило «ни одной фразы без строки-родителя» этого не
остановило: правило — не преграда.

Сторож ставит преграду. После того как текст готов, он проходит по нему,
находит у каждой названной точки градус и код, сверяет с расчётом — и правит
на верное. Числа берутся из машины, а не из чтения; ложь до клиента не доходит.

Что проверяется:
  • градус точки в знаке (число и знак);
  • код Азбуки в квадратных скобках рядом с точкой;
  • дом, если он назван числом.
Что НЕ трогается: сам разбор, образы, выводы — только числа и коды.
"""
import re

ЗНАКИ = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева", "Весы", "Скорпион",
         "Стрелец", "Козерог", "Водолей", "Рыбы"]

# как читатель зовёт точки в тексте → как они зовутся в расчёте
ИМЕНА_В_ТЕКСТЕ = {
    "Солнце": "Солнце", "Луна": "Луна", "Меркурий": "Меркурий", "Венера": "Венера",
    "Марс": "Марс", "Юпитер": "Юпитер", "Сатурн": "Сатурн", "Уран": "Уран",
    "Нептун": "Нептун", "Плутон": "Плутон", "Хирон": "Хирон",
    "Северный Узел": "Сев.Узел", "Северный узел": "Сев.Узел", "Сев.Узел": "Сев.Узел",
    "Южный Узел": "Юж.Узел", "Южный узел": "Юж.Узел", "Юж.Узел": "Юж.Узел",
    "Чёрная Луна": "Лилит", "Лилит": "Лилит",
    "Белая Луна": "Селена", "Селена": "Селена",
}
# глоссарий Книги (METODOLOGIYA_II): читатель зовёт точки образами,
# и градус может стоять рядом с образом, а не с именем — «Градус духа — Водолей 27°»
ОБРАЗЫ = {
    "дух": "Солнце", "душа": "Луна", "мысль": "Меркурий", "любовь": "Венера",
    "воля": "Марс", "рост": "Юпитер", "форма": "Сатурн", "молния": "Уран",
    "туман": "Нептун", "огонь глубин": "Плутон", "рана": "Хирон",
    "тень": "Лилит", "благодать": "Селена",
}
ИМЕНА_В_ТЕКСТЕ.update({f"Градус {о}а" if о[-1] not in "ья" else f"Градус {о}и": н
                       for о, н in ОБРАЗЫ.items()})
ИМЕНА_В_ТЕКСТЕ.update({"Градус духа": "Солнце", "Градус души": "Луна",
                       "Градус мысли": "Меркурий", "Градус любви": "Венера",
                       "Градус воли": "Марс", "Градус тени": "Лилит",
                       "Градус благодати": "Селена", "Градус раны": "Хирон"})

# длинные имена ищем первыми, чтобы «Северный Узел» не съелся «Узлом»
ПОРЯДОК_ПОИСКА = sorted(ИМЕНА_В_ТЕКСТЕ, key=len, reverse=True)


def _градус_в_знаке(абс):
    """→ (знак, номер градуса 1..30) как принято в Азбуке."""
    з = ЗНАКИ[int(абс // 30) % 12]
    н = int(абс % 30) + 1
    return з, н


def верные_данные(точки, куспиды=None):
    """Что машина знает о каждой точке: знак, градус, код, дом."""
    from engine import kosmogramma as K
    итог = {}
    for наше, т in (точки or {}).items():
        if наше == "ТЖ" or not т or т.get("градус") is None:
            continue
        з, н = _градус_в_знаке(т["градус"])
        код = ((т.get("код") or {}).get("тег") or "").strip()
        дом = K.дом_точки(т["градус"], куспиды) if куспиды else None
        итог[наше] = {"знак": з, "градус": н, "код": код, "дом": дом}
    return итог


def проверить(текст, точки, куспиды=None):
    """Ищет расхождения. Возвращает список найденного, текст не меняет."""
    верно = верные_данные(точки, куспиды)
    беды = []
    for имя_т in ПОРЯДОК_ПОИСКА:
        наше = ИМЕНА_В_ТЕКСТЕ[имя_т]
        д = верно.get(наше)
        if not д:
            continue
        # «Солнце — Водолей 27°» / «Солнце в Водолее, 27°» / «Градус духа — Водолей 27°»
        for м in re.finditer(re.escape(имя_т) + r"[^.\n]{0,80}?(" + "|".join(ЗНАКИ) +
                             r")[а-я]{0,3}\s*,?\s*(\d{1,2})\s*°", текст):
            знак, град = м.group(1), int(м.group(2))
            if знак != д["знак"] or град != д["градус"]:
                беды.append({"точка": наше, "было": f"{знак} {град}°",
                             "верно": f"{д['знак']} {д['градус']}°",
                             "где": м.start(), "кусок": м.group(0)})
    return беды


def выправить(текст, точки, куспиды=None):
    """Правит числа и коды на машинные. Возвращает (текст, список правок)."""
    верно = верные_данные(точки, куспиды)
    правки = []
    новый = текст

    for имя_т in ПОРЯДОК_ПОИСКА:
        наше = ИМЕНА_В_ТЕКСТЕ[имя_т]
        д = верно.get(наше)
        if not д:
            continue

        # 1 · градус в знаке рядом с именем точки
        шаблон = re.compile(re.escape(имя_т) + r"([^.\n]{0,80}?)(" + "|".join(ЗНАКИ) +
                            r")([а-я]{0,3})(\s*,?\s*)(\d{1,2})(\s*°)")

        def правка_градуса(м):
            знак, град = м.group(2), int(м.group(5))
            if знак == д["знак"] and град == д["градус"]:
                return м.group(0)
            правки.append(f"{наше}: {знак} {град}° → {д['знак']} {д['градус']}°")
            return (имя_т + м.group(1) + д["знак"] + м.group(3) + м.group(4)
                    + str(д["градус"]) + м.group(6))

        новый = шаблон.sub(правка_градуса, новый)

        # 2 · код Азбуки: правим только если он ЧУЖОЙ целиком — то есть
        #     совпадает с кодом другой точки. Частичные различия (тег короче
        #     полного названия) не трогаем: это одно и то же место Азбуки.
        чужие = {v["код"] for k, v in верно.items() if k != наше and v["код"]}
        if д["код"]:
            шк = re.compile(re.escape(имя_т) + r"([^\n]{0,160}?)\[([А-ЯЁ][^\]]{3,70})\]")

            def правка_кода(м):
                был = м.group(2).strip()
                if был == д["код"] or "/" not in д["код"]:
                    return м.group(0)
                # правим, только если это код ДРУГОЙ точки — значит перепутано
                if был not in чужие:
                    return м.group(0)
                # ядро/подградус не трогаем: у них свой код
                хвост = м.group(1)
                if "ядро" in хвост.lower() or "подградус" in хвост.lower():
                    return м.group(0)
                if был != д["код"]:
                    правки.append(f"{наше}: код [{был}] → [{д['код']}]")
                    return имя_т + хвост + "[" + д["код"] + "]"
                return м.group(0)

            новый = шк.sub(правка_кода, новый)

    return новый, правки
