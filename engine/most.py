def _строка_точки(текст, имя):
    """Портретная строка точки из полочки — та, что начинается её именем."""
    for л in текст.split("\n"):
        г = л.strip()
        if г.startswith(имя + " —") and "Натал:" in г:
            return л
    return ""


# к каким точкам подселять недостающие — чтобы вставали в свою группу,
# а не в конец. 10.09: Хирон вставал после MC, в разделе ОСЕЙ, и читатель
# писал «Хирон машиной не дан» — искал его среди кармических.
СОСЕДИ = {
    "Хирон": ["Юж.Узел", "Сев.Узел"],
    "Чёрная Луна": ["Хирон", "Юж.Узел", "Сев.Узел"],
    "Белая Луна": ["Чёрная Луна", "Хирон", "Юж.Узел"],
    "Сев.Узел": ["Луна", "Солнце"],
    "Юж.Узел": ["Сев.Узел", "Луна"],
}


def _дополнить_блок(к, текст, блок):
    """Кладёт в блок строки всех точек, которые задание по нему требует.
    Каждая встаёт в свою группу: кармические — к узлам, а не в конец."""
    нужны = ТОЧКИ_БЛОКА.get(блок, [])
    if not нужны:
        return к
    строки = к.split("\n")

    def найти(имя):
        for н, л in enumerate(строки):
            г = л.strip()
            if г.startswith(имя + " —") and "Натал:" in г:
                return н
        return None

    for имя in нужны:
        if any(л.strip().startswith(имя + " —") and "Натал:" in л for л in строки):
            continue
        стр = _строка_точки(текст, имя)
        if not стр:
            continue
        место = None
        for сосед in СОСЕДИ.get(имя, []):
            н = найти(сосед)
            if н is not None:
                место = н + 1
                break
        if место is None:
            # без соседа — после последней портретной строки блока
            for н, л in enumerate(строки):
                if " — " in л and "Натал:" in л:
                    место = н + 1
        if место is None:
            строки.append(стр)
        else:
            строки.insert(место, стр)
    return "\n".join(строки)


