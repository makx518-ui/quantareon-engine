def факты_тегами(точки, куспиды, полка_текстом=""):
    """Точные данные полями, как у Оракула: <point name="Солнце" degree="11" .../>.

    10.09 · его правка. Причина: наша полочка — сплошная проза, строки точек идут
    подряд, и читатель соскальзывает на соседнюю: Хирону приписал 25° вместо 14°,
    Солнцу — градус Меркурия. У Оракула такого нет, потому что он отдаёт данные
    тегами, и модель вынимает значение из поля по имени, а не читает глазом.

    Блок идёт ВМЕСТЕ с прозой, не вместо неё: проза даёт смысл, теги — числа.
    Их модуль не тронут.
    """
    from engine import kosmogramma as K
    if not точки:
        return ""
    ЗН = ["Овен", "Телец", "Близнецы", "Рак", "Лев", "Дева", "Весы", "Скорпион",
          "Стрелец", "Козерог", "Водолей", "Рыбы"]
    порядок = ["Солнце", "Луна", "Меркурий", "Венера", "Марс", "Юпитер", "Сатурн",
               "Уран", "Нептун", "Плутон", "Хирон", "Сев.Узел", "Юж.Узел",
               "Лилит", "Селена"]
    имена = {"Лилит": "Чёрная Луна", "Селена": "Белая Луна"}
    л = ['<точные_данные · ЧИСЛА БРАТЬ ТОЛЬКО ОТСЮДА, из атрибутов. '
         'Смыслы градусов и ядра — из прозы ниже.>']
    for и in порядок:
        т = точки.get(и)
        if not т or т.get("градус") is None:
            continue
        абс = float(т["градус"]) % 360.0
        зн = ЗН[int(абс // 30) % 12]
        гр = int(абс % 30) + 1
        мин = int(((абс % 30) - int(абс % 30)) * 60)
        дом = K.дом_точки(абс, куспиды) if куспиды else ""
        ход = "стоянка" if т.get("стоянка") else ("ретро" if т.get("ретро") else "прямой")
        try:
            д = K.достоинство(и, т.get("знак", ""))
            дост = (д[0] if isinstance(д, (tuple, list)) and д else (д or "")) or ""
        except Exception:
            дост = ""
        # ТОЛЬКО ЧИСЛА. Коды и ядра — в прозе полочки, из их модуля: наш kod360
        # и их дают разные теги на одно место, и два имени сбили бы читателя.
        л.append(
            f'  <точка имя="{имена.get(и, и)}" градус="{гр}" минут="{мин:02d}" знак="{зн}" '
            f'дом="{дом}" ход="{ход}" достоинство="{дост}" />')
    if куспиды and len(куспиды) >= 12:
        for имя, i in (("ASC", 0), ("MC", 9)):
            к_ = float(куспиды[i]) % 360.0
            л.append(f'  <ось имя="{имя}" градус="{int(к_ % 30) + 1}" '
                     f'минут="{int(((к_ % 30) - int(к_ % 30)) * 60):02d}" '
                     f'знак="{ЗН[int(к_ // 30) % 12]}" />')
        for н in range(1, 13):
            к_ = float(куспиды[н - 1]) % 360.0
            зк = ЗН[int(к_ // 30) % 12]
            упр = K.УПРАВИТЕЛЬ.get(зк, [None])[0] or ""
            где = ""
            if упр and упр in точки:
                где = K.дом_точки(точки[упр]["градус"], куспиды) or ""
            л.append(f'  <дом номер="{н}" градус="{int(к_ % 30)}" '
                     f'минут="{int(((к_ % 30) - int(к_ % 30)) * 60):02d}" знак="{зк}" '
                     f'управитель="{K.имя_точки(упр) if упр else ""}" управитель_в_доме="{где}" />')
    л.append('</точные_данные>')
    return "\n".join(л)


def полочка_натала(точки, куспиды, углы=None, имя="человек", рождение=None,
                   место="", пояс=None, фаза="", лунный_день=None, местное=None):
    """Полочка натала по сценарию Оракула, на наших расчётах.
    Сверху — паспорт: без него зачин выдумывает дату."""
    import os
    import sys
    путь = os.path.join(os.path.dirname(__file__), "af")
    if путь not in sys.path:
        sys.path.insert(0, путь)
    import af_natal_scenario
    # 09.09 · их сценарий требует двенадцать куспидов: af_portret обращается
    # к cusps[i] по каждому дому. Без времени рождения домов нет — тогда их
    # сценарий не применим, полочку собирает наш движок (космограмма по знакам).
    if not куспиды or len(куспиды) < 12:
        return ""
    расклад = af_natal_scenario.render_natal(Мост(точки, куспиды, углы))
    # куспиды с градусами — наш блок рядом с их раскладом (их модуль не тронут)
    # достоинства — рядом с портретами, чтобы читатель видел падения и чертоги
    дост = достоинства(точки)
    if дост:
        м = "╔══ АСПЕКТЫ"
        i = расклад.find(м)
        if i > 0:
            расклад = расклад[:i] + дост + "\n\n" + расклад[i:]
        else:
            расклад = расклад.rstrip() + "\n\n" + дост
    кусп = куспиды_с_градусами(куспиды, точки)
    if кусп:
        # ставим сразу ПОСЛЕ их блока управителей домов — там же, где читатель
        # пишет раздел о домах. В конец нельзя: попадёт в блок «каркас».
        метка = "╔══ АСПЕКТЫ"
        i = расклад.find(метка)
        if i > 0:
            расклад = расклад[:i] + кусп + "\n\n" + расклад[i:]
        else:
            расклад = расклад.rstrip() + "\n\n" + кусп
    теги = факты_тегами(точки, куспиды)
    if рождение is not None:
        шапка = паспорт(имя, рождение, место, пояс, фаза, лунный_день, местное)
        return шапка + "\n\n" + (теги + "\n\n" if теги else "") + расклад
    return (теги + "\n\n" if теги else "") + расклад


