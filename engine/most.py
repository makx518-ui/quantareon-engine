# как наши имена называются у них
ИМЕНА = {
    "Солнце": "Солнце", "Луна": "Луна", "Меркурий": "Меркурий", "Венера": "Венера",
    "Марс": "Марс", "Юпитер": "Юпитер", "Сатурн": "Сатурн", "Уран": "Уран",
    "Нептун": "Нептун", "Плутон": "Плутон", "Хирон": "Хирон",
    "Сев.Узел": "Сев.Узел", "Юж.Узел": "Юж.Узел",
    "Лилит": "Чёрная Луна",
    "Селена": "Белая Луна",
}


class Мост:
    """То, что их модули ждут от машины. Данные — наши, имена — их."""

    def __init__(self, точки, куспиды, углы=None):
        self.flat = {}
        for наше, ихнее in ИМЕНА.items():
            т = точки.get(наше)
            if т and т.get("градус") is not None:
                self.flat[ихнее] = float(т["градус"]) % 360.0
        # углы
        if куспиды and len(куспиды) >= 10:
            self.flat["ASC"] = float(куспиды[0]) % 360.0
            self.flat["MC"] = float(куспиды[9]) % 360.0
        elif углы:
            if углы.get("ASC") is not None:
                self.flat["ASC"] = float(углы["ASC"]) % 360.0
            if углы.get("MC") is not None:
                self.flat["MC"] = float(углы["MC"]) % 360.0
        self.cusps = [float(к) % 360.0 for к in (куспиды or [])[:12]]

    def house_of(self, ap):
        """Дом по абсолютному градусу — тем же способом, что у них."""
        if len(self.cusps) < 12:
            return 0
        ap = float(ap) % 360.0
        for i in range(12):
            a = self.cusps[i]
            b = self.cusps[(i + 1) % 12]
            if a < b:
                if a <= ap < b:
                    return i + 1
            else:  # переход через 0°
                if ap >= a or ap < b:
                    return i + 1
        return 0


МЕСЯЦЫ = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля",
          "августа", "сентября", "октября", "ноября", "декабря"]


def паспорт(имя, рождение, место="", пояс=None, фаза="", лунный_день=None, местное=None):
    """Шапка полочки. У Оракула она подаётся отдельной обвязкой, в самом
    af_natal_scenario её нет — поэтому зачин без неё брал дату из головы.
    Слоты канона зачина: сезон · день и год · луна и фаза · место."""
    сезоны = {12: "зимы", 1: "зимы", 2: "зимы", 3: "весны", 4: "весны", 5: "весны",
              6: "лета", 7: "лета", 8: "лета", 9: "осени", 10: "осени", 11: "осени"}
    # показываем МЕСТНОЕ время рождения, а не UTC: зачин говорит о часе,
    # когда человек родился там, где родился
    д = местное or рождение
    время_суток = ("ночь" if д.hour < 5 else "утро" if д.hour < 12
                   else "день" if д.hour < 18 else "вечер")
    л = ["╔══ ПАСПОРТ РАСЧЁТА ══",
         f"  имя: {имя}",
         f"  рождение: {д.day} {МЕСЯЦЫ[д.month - 1]} {д.year} года, "
         f"{д.hour:02d}:{д.minute:02d}" + (f":{д.second:02d}" if д.second else ""),
         f"  время суток: {время_суток} · сезон: {сезоны[д.month]}"]
    if место:
        л.append(f"  место: {место}")
    if пояс is not None:
        л.append(f"  часовой пояс: GMT{'+' if пояс >= 0 else ''}{пояс}")
    if фаза:
        л.append(f"  фаза Луны при рождении: {фаза}")
    if лунный_день:
        л.append(f"  лунный день: {лунный_день}-й")
    л.append("  ⚑ Слоты канона зачина берутся ОТСЮДА, не из головы и не из эталона.")
    return "\n".join(л)


def полочка_натала(точки, куспиды, углы=None, имя="человек", рождение=None,
                   место="", пояс=None, фаза="", лунный_день=None, местное=None):
    """Полочка натала по сценарию Оракула, на наших расчётах.
    Сверху — паспорт: без него зачин выдумывает дату."""
    import os
    import sys
    путь = os.path.join(os.path.dirname(__file__), "af")
    if путь not in sys.path:
        sys.path.insert(0, путь)
    import af_natal_scenario
    # 09.09 · их сценарий требует двенадцать куспидов: af_portret обращается
    # к cusps[i] по каждому дому. Без времени рождения домов нет — тогда их
    # сценарий не применим, полочку собирает наш движок (космограмма по знакам).
    if not куспиды or len(куспиды) < 12:
        return ""
    расклад = af_natal_scenario.render_natal(Мост(точки, куспиды, углы))
    if рождение is not None:
        шапка = паспорт(имя, рождение, место, пояс, фаза, лунный_день, местное)
        return шапка + "\n\n" + расклад
    return расклад


