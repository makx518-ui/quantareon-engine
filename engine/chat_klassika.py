# 28.09 · клиент уже выбрал тариф на странице — чат собирает данные ТОЛЬКО под него
_ВЫБОР = {
    "натал": "НАТАЛЬНУЮ КАРТУ — собирай данные только для неё и выводи только метку LAUNCH_ASTRO_NATAL.",
    "соляр": "СОЛЯР — собирай данные только для него и выводи только метку LAUNCH_ASTRO_SOLAR.",
    "синастрия": "СИНАСТРИЮ — собирай данные двух людей и выводи только метку LAUNCH_ASTRO_COMPAT.",
}


async def klassika_chat_reply(history: list, user_text: str, model: str = None, тип: str = None) -> str:
    """Один шаг диалога сбора данных.

    history — список {"role": "user"|"assistant", "content": "..."} — то, что
              уже было сказано в этом диалоге (без системного промпта).
    user_text — новая реплика клиента.

    Возвращает текст ответа ИИ — обычная реплика ИЛИ реплика, целиком состоящая
    из служебной метки (тогда parse_marker() ниже её распознает).
    """
    диалог = ""
    for м in history:
        кто = "Клиент" if м.get("role") == "user" else "Квантареон"
        диалог += f"{кто}: {м.get('content', '')}\n"
    диалог += f"Клиент: {user_text}\nКвантареон:"
    система = SYSTEM_PROMPT_KLASSIKA
    if тип in _ВЫБОР:
        система += ("\n\nВАЖНО: клиент уже выбрал на странице и оплачивает " + _ВЫБОР[тип] +
                    " Если он просит другой разбор — мягко скажи, что сейчас выбран этот, а другой"
                    " можно выбрать в списке тарифов выше.")
    # 28.09 · его слово: помощник говорит с клиентом только по-русски и грамотно
    система += ("\n\nЯЗЫК И ПРАВОПИСАНИЕ: с клиентом говори ТОЛЬКО по-русски, грамотно, без ошибок, "
                "с правильными падежами и знаками препинания. Никакой латиницы в обычных репликах: "
                "города и страны пиши по-русски (Петропавловск, Казахстан), пол спрашивай словами "
                "(«мужчина или женщина?»), без букв M/F. Латиница допустима ТОЛЬКО внутри служебной "
                "метки LAUNCH_ASTRO_… — её клиент не видит.")
    ответ = await _спросить_грок(система, диалог)
    if not ответ:
        ответ = await _спросить(
            system_prompt=система,
            user_prompt=диалог,
            model=model,
            max_tokens=400,
            temperature=0.6,
        )
    return (ответ or "").strip()


# ============================================================
# РАЗБОР МЕТОК — регулярки взяты дословно из Dream Oracle
# ============================================================

_NATAL_RE = re.compile(
    r'\[LAUNCH_ASTRO_NATAL:\s*(\d{1,2}\.\d{1,2}\.\d{4})'
    r'(?:,\s*TIME:\s*(\d{1,2}:\d{2}))?'
    r'(?:,\s*PLACE:\s*([^,\]]+))?'
    r'(?:,\s*GENDER:\s*([MFmf]))?\s*\]'
)
_SOLAR_RE = re.compile(
    r'\[LAUNCH_ASTRO_SOLAR:\s*(\d{1,2}\.\d{1,2}\.\d{4})'
    r'(?:,\s*TIME:\s*(\d{1,2}:\d{2}))?'
    r'(?:,\s*PLACE:\s*([^,\]]+))?'
    r'(?:,\s*CURRENT:\s*([^,\]]+))?'
    r'(?:,\s*GENDER:\s*([MFmf]))?'
    r'(?:,\s*YEAR:\s*(\d{4}))?\s*\]'
)
_COMPAT_RE = re.compile(r'\[LAUNCH_ASTRO_COMPAT:\s*(.+?)\s*\]', re.DOTALL)
_COMPAT_PART_RE = {
    "date": re.compile(r'(\d{1,2}\.\d{1,2}\.\d{4})'),
    "time": re.compile(r'TIME:\s*(\d{1,2}:\d{2})'),
    "place": re.compile(r'PLACE:\s*([^|,\]]+)'),
    "gender": re.compile(r'GENDER:\s*([MFmf])'),
}


def parse_marker(reply: str) -> Optional[dict]:
    """Ищет в ответе ИИ одну из трёх меток. Возвращает словарь с чистыми
    данными или None, если метки нет (значит, диалог ещё не закончен —
    нужно показать реплику клиенту и ждать следующее сообщение).

    Формат возврата:
      {"тип": "натал", "дата": "12.07.1985", "время": "14:30" | None,
       "место": "Moscow Russia", "пол": "M"}
      {"тип": "соляр", "дата": ..., "время": ..., "место": ..., "текущее_место": ...,
       "пол": ..., "год": 2030 | None}
      {"тип": "синастрия", "первый": {...}, "второй": {...}}
    """
    м = _NATAL_RE.search(reply)
    if м:
        return {
            "тип": "натал",
            "дата": м.group(1),
            "время": м.group(2),
            "место": (м.group(3) or "").strip(),
            "пол": (м.group(4) or "").upper(),
        }

    м = _SOLAR_RE.search(reply)
    if м:
        return {
            "тип": "соляр",
            "дата": м.group(1),
            "время": м.group(2),
            "место": (м.group(3) or "").strip(),
            "текущее_место": (м.group(4) or "").strip(),
            "пол": (м.group(5) or "").upper(),
            "год": int(м.group(6)) if м.group(6) else None,
        }

    м = _COMPAT_RE.search(reply)
    if м:
        части = м.group(1).split("|")
        if len(части) < 2:
            return None
        люди = []
        for часть in части[:2]:
            date_m = _COMPAT_PART_RE["date"].search(часть)
            time_m = _COMPAT_PART_RE["time"].search(часть)
            place_m = _COMPAT_PART_RE["place"].search(часть)
            gender_m = _COMPAT_PART_RE["gender"].search(часть)
            люди.append({
                "дата": date_m.group(1).strip() if date_m else "",
                "время": time_m.group(1).strip() if time_m else None,
                "место": place_m.group(1).strip() if place_m else "",
                "пол": gender_m.group(1).upper() if gender_m else "",
            })
        return {"тип": "синастрия", "первый": люди[0], "второй": люди[1]}

    return None


def есть_метка(reply: str) -> bool:
    """Быстрая проверка — есть ли в ответе служебная метка (не показывать её клиенту)."""
    return bool(_NATAL_RE.search(reply) or _SOLAR_RE.search(reply) or _COMPAT_RE.search(reply))
