# -*- coding: utf-8 -*-
"""
ЧЕТЫРЕ СТРОКИ РЕНДЕРА ДНЯ.

Наружу идёт коротко:
    1. смысл дня      — градус асцендента
    2. куда выходит   — градус вершины (MC)
    3. настроение     — лунный день   (считает страница)
    4. как действовать — знак И-Цзин  (бросает страница)

Здесь машина собирает только первые две. Берётся готовый кусок из поля
ШАГ ПУТИ базы 360 — тот, что стоит после тире. Он уже написан как короткая
мысль, поэтому ничего не сокращаем и не пересказываем: меняем только зачин.

Часы, лунный день и гексаграмму страница считает сама теми же файлами,
что стоят в приложении Luck Forecast.
"""
from __future__ import annotations

import re
from pathlib import Path

from engine.popravki_gradusov import ПОПРАВКИ

БАЗА = Path(__file__).resolve().parent.parent / "data" / "gradusy_360_baza.txt"

ЗНАКИ = ["ОВЕН", "ТЕЛЕЦ", "БЛИЗНЕЦЫ", "РАК", "ЛЕВ", "ДЕВА",
         "ВЕСЫ", "СКОРПИОН", "СТРЕЛЕЦ", "КОЗЕРОГ", "ВОДОЛЕЙ", "РЫБЫ"]

_текст_базы = None


def _база() -> str:
    global _текст_базы
    if _текст_базы is None:
        _текст_базы = БАЗА.read_text(encoding="utf-8")
    return _текст_базы


def мысль(градус: float) -> str:
    """Короткая мысль градуса: часть поля СУТЬ ПОСЛЕ тире.

    До тире стоит общая мысль, после — конкретика. Конкретика понятнее:
    вместо «доброта жизни в трагических испытаниях первых опытов возрождения»
    выходит «обязанность обеспечить здоровье и благо нового поколения».
    Тире есть у 359 градусов из 360; там, где его нет, берётся вся суть.
    """
    знак = ЗНАКИ[int(градус // 30) % 12]
    номер = int(градус % 30) + 1

    # у части градусов суть написана книжным языком — берём готовую замену
    готовая = ПОПРАВКИ.get(f"{знак} {номер}")
    if готовая:
        return готовая

    м = re.search(rf"^{знак} {номер}°\n(.*?)(?=\n[А-Я]+ \d+°|\n┌|\Z)",
                  _база(), re.S | re.M)
    if not м:
        return ""
    с = re.search(r"СУТЬ:\s*(.*?)(?=\nШАГ ПУТИ:)", м.group(1), re.S)
    if not с:
        return ""
    целиком = " ".join(с.group(1).split())
    ядро = re.split(r"\s*Свет:", целиком)[0].strip().rstrip(".")
    части = re.split(r"\s*[—–]\s*", ядро)
    # берём ВТОРУЮ часть — после тире: там конкретика, а до тире общая мысль
    кусок = части[1] if len(части) > 1 else части[0]
    # если вторая часть длинная, оставляем первое предложение
    кусок = кусок.split(". ")[0]
    return кусок.strip().rstrip(".,;")


def четыре_строки(куспиды: list) -> dict:
    """Четыре угла карты. Наружу идут только смыслы, без имён точек.

    асцендент  → смысл дня       (начало, лицо личности)
    десцендент → союзы и контакты (партнёры, встречи, договоры)
    вершина    → цель дня         (результат на виду)
    основание  → опора дня        (фундамент, откуда силы)
    """
    асц, мс = куспиды[0], куспиды[9]
    строчно = lambda т: (т[0].lower() + т[1:]) if т else т
    return {
        "смысл": строчно(мысль(асц)),
        "soyuzy": строчно(мысль((асц + 180) % 360)),
        "cel": строчно(мысль(мс)),
        "opora": строчно(мысль((мс + 180) % 360)),
    }
