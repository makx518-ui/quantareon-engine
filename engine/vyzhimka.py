def пара(а, б, точки, куспиды=None, аспекты=None):
    св = None
    for x in (аспекты or []):
        if {x["а"], x["б"]} == {а, б}:
            св = x
            break
    if not св:
        return ""
    са, сб = S.ПЛАНЕТЫ.get(а, {}), S.ПЛАНЕТЫ.get(б, {})
    ас = S.АСПЕКТЫ.get(св["аспект"], {})
    глагол = {"соединение": "слит с", "оппозиция": "против", "квадрат": "упирается в",
              "трин": "течёт к", "секстиль": "протягивает руку"}.get(св["аспект"], "связан с")
    таб = (S.ТВОР_П if св["аспект"] == "соединение" else
           S.РОД if св["аспект"] == "оппозиция" else
           S.ВИН if св["аспект"] == "квадрат" else S.ДАТ)
    да = K.дом_точки(точки[а]["градус"], куспиды) if куспиды else None
    дб = K.дом_точки(точки[б]["градус"], куспиды) if куспиды else None
    сф = (f"; {да}-й ↔ {дб}-й дом" if да and дб and да != дб else
          (f"; обе в {да}-м" if да and да == дб else ""))
    строка = (f"  {K.имя_точки(а)} {глагол} {таб.get(б, K.имя_точки(б))} ({св['орбис']:.1f}°) — "
              f"{ас.get('куда','')}{сф}.")
    # второй конец: чем отвечает вторая сила — её место, градус и что она несёт
    if св["орбис"] <= 3.0:
        тб_ = точки[б]
        кб_ = тб_.get("код") or {}
        хвост = f"\n     {K.имя_точки(б)}: {тб_.get('знак','')}"
        if дб:
            хвост += f", {дб}-й дом"
        if кб_.get("тег"):
            хвост += f" [{кб_['тег']}] — {_ф(кб_.get('суть',''))}"
        try:
            вл_б = K.чем_владеет_в_домах(б, куспиды, точки) if куспиды else []
            if вл_б:
                хвост += f"; управитель {', '.join(str(н) + '-го' for н in вл_б)}"
        except Exception:
            pass
        строка += хвост + "."
    if св["орбис"] <= 1.0:
        строка += (f"\n     Точная: без работы — {_перечень(сб.get('вниз',''), 2)}; "
                   f"через работу — {_перечень(са.get('вверх',''), 2)}.")
    return строка


