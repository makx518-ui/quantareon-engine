def связка(группа, точки, куспиды=None, аспекты=None, главная=False):
    все = dict(точки)
    if куспиды and len(куспиды) >= 12:
        for имя, i in (("Асцендент", 0), ("Вершина", 9), ("Десцендент", 6), ("Дно", 3)):
            т_ = K.точка("Асцендент" if "сцендент" in имя else "MC", куспиды[i])
            т_["знак"] = K.знак(куспиды[i])
            все.setdefault(имя, т_)
    гр = [и for и in группа if и in все]
    if len(гр) < 2:
        return ""
    первый = все[гр[0]]
    дом = K.дом_точки(первый["градус"], куспиды) if куспиды else None
    зн = первый.get("знак", "")
    имена = ", ".join(K.имя_точки(и) if и in точки else и for и in гр)
    л = [f"СВЯЗКА {имена}."]
    if дом:
        try:
            i = K.ЗНАКИ.index(зн)
            подсветка = f"знак {зн} ({K.СТИХИЯ[i%4]}, {K.КРЕСТ[i%3]}), ищет {S.ИЩЕТ_ЗНАК.get(зн,'')}"
        except Exception:
            подсветка = f"знак {зн}"
        л.append(f"Место: {U._дом_имя_коротко(дом)} — {S.ДОМА[дом]['что']}; {подсветка}.")
    # участники
    уч = []
    for и in гр:
        т_ = все[и]
        к_ = т_.get("код") or {}
        строка = f"{K.имя_точки(и) if и in точки else и} {т_.get('словами','')} [{к_.get('тег','')}] — {_ф(к_.get('суть',''))}"
        if и in точки and куспиды:
            д_ = U._дост(и, т_.get("знак", ""))
            х_ = U._ход(т_)
            доб = [x for x in ((д_.lower() if д_ else ""), ("внутрь" if х_ != "прямой" else "")) if x]
            try:
                вл = K.чем_владеет_в_домах(и, куспиды, точки)
                if вл:
                    доб.append("управляет " + " и ".join(U._дом_твор(н) for н in вл))
            except Exception:
                pass
            if доб:
                строка += f" ({'; '.join(доб)})"
        уч.append(строка)
    л.append("Участники: " + "; ".join(уч) + ".")
    # управители
    упр = K.УПРАВИТЕЛЬ.get(зн, [None])[0]
    ч = []
    if упр and упр in точки:
        д1 = K.дом_точки(точки[упр]["градус"], куспиды) if куспиды else None
        ч.append(f"знак ведёт {K.имя_точки(упр)}" + (f" из {U._дом_род(д1)}" if д1 else ""))
    if дом and куспиды:
        зк = K.знак(куспиды[дом - 1])
        хд = K.УПРАВИТЕЛЬ.get(зк, [None])[0]
        if хд and хд in точки:
            д2 = K.дом_точки(точки[хд]["градус"], куспиды)
            ч.append(f"дом начинается в {зк}е, ведёт {K.имя_точки(хд)}" + (f" из {U._дом_род(д2)}" if д2 else ""))
    if ч:
        л.append("Управители: " + "; ".join(ч) + ".")
    # кольца
    кольца = []
    if куспиды:
        for и in гр:
            if и not in точки:
                continue
            try:
                вл = set(K.чем_владеет_в_домах(и, куспиды, точки))
            except Exception:
                вл = set()
            for др, т_д in точки.items():
                if др in гр or др == "ТЖ":
                    continue
                if K.дом_точки(т_д["градус"], куспиды) in вл:
                    кольца.append(f"{K.имя_точки(и)} управляет домом, где стоит {K.имя_точки(др)}")
    if кольца:
        л.append("Кольца: " + "; ".join(кольца[:3]) + ".")
    # внутри и извне
    внутри = []
    for i, а in enumerate(гр):
        for б in гр[i + 1:]:
            d = K.дуга(все[а]["градус"], все[б]["градус"])
            if d <= 8:
                внутри.append(f"{K.имя_точки(а) if а in точки else а}—"
                              f"{K.имя_точки(б) if б in точки else б} {d:.2f}°")
    if внутри:
        л.append("Внутри: " + "; ".join(внутри) + ".")
    извне = []
    for чужой, т_ч in все.items():
        if чужой in гр or чужой == "ТЖ":
            continue
        for свой in гр:
            d = K.дуга(т_ч["градус"], все[свой]["градус"])
            for ан, у in (("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                if abs(d - у) <= 5.0:
                    извне.append(f"{K.имя_точки(чужой) if чужой in точки else чужой} {ан}")
                    break
            else:
                continue
            break
    if извне:
        л.append("Извне: " + "; ".join(sorted(set(извне))) + ".")
    if дом:
        л.append(f"ИТОГ: несколько сигнификаторов в {U._дом_предл(дом)} — эта сфера становится "
                 f"узлом судьбы; всё здесь ведёт {S.КУДА_ВЕДЁТ.get(дом,'')}"
                 + (". Самое нагруженное место карты." if главная else "."))
    return "\n".join("  " + x for x in л)


