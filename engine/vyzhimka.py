def точка(имя, точки, куспиды=None, аспекты=None):
    т = точки.get(имя)
    сл = S.ПЛАНЕТЫ.get(имя)
    if not т or not сл:
        return ""
    зн = т.get("знак", "")
    дом = K.дом_точки(т["градус"], куспиды) if куспиды else None
    к = т.get("код") or {}
    дост = U._дост(имя, зн)
    ход = U._ход(т)
    внутрь = ход != "прямой" or дост == "В ПАДЕНИИ"
    свои = []
    if куспиды:
        try:
            свои = K.чем_владеет_в_домах(имя, куспиды, точки)
        except Exception:
            свои = []

    л = []
    # кто, чем управляет, где
    строка = f"{K.имя_точки(имя)} — {сл['кто'].split(':')[-1].strip()}."
    if свои:
        строка += " Управитель " + " и ".join(U._дом_род(н) for н in свои) + "."
    if дом:
        строка += f" В {U._дом_предл(дом)}; знак {зн}, {т.get('словами','')} [{к.get('тег','')}]."
    else:
        строка += f" В {U._знак_предл(зн)}, {т.get('словами','')} [{к.get('тег','')}]."
    л.append(строка)
    # сила
    силы = []
    if дост:
        силы.append(f"{дост.lower()} — {S.ДОСТОИНСТВА.get(дост,'')}")
    if ход == "ретроградный":
        силы.append("ретроградна, сила внутрь")
    elif ход == "стоянка":
        силы.append("в стоянке, тема застыла и звучит громче")
    if силы:
        л.append("Сила: " + "; ".join(силы) + ".")
    # зачем пришёл · что даёт · что забирает
    if дом:
        л.append(f"Зачем пришёл: в {U._дом_предл(дом)} ищет {S.ИЩЕТ_ЗНАК.get(зн,'')}.")
        окр = S.в_доме(имя, дом)
        if окр:
            л.append(f"Что выходит: {окр}.")
        else:
            л.append(f"Даёт: {_перечень(сл['вверх'])}. Забирает: {S.ЗАБИРАЕТ.get(имя,'')}.")
        if окр:
            л.append(f"Забирает: {S.ЗАБИРАЕТ.get(имя,'')}.")
    # канал в мир
    if свои and дом:
        л.append("Канал в мир: рождённое здесь выходит через " +
                 ", ".join(S.ЧЕРЕЗ_ДОМ.get(н, "") for н in свои) + ".")
    # управители
    упр = K.УПРАВИТЕЛЬ.get(зн, [None])[0]
    хд = K.УПРАВИТЕЛЬ.get(K.знак(куспиды[дом - 1]), [None])[0] if (дом and куспиды) else None
    ч = []
    if упр and упр in точки and упр != имя:
        д1 = K.дом_точки(точки[упр]["градус"], куспиды) if куспиды else None
        ч.append(f"знак — {K.имя_точки(упр)}" + (f" ({д1}-й дом)" if д1 else ""))
    if хд and хд in точки and хд != имя:
        д2 = K.дом_точки(точки[хд]["градус"], куспиды)
        ч.append("он же и дом" if хд == упр else
                 f"дом — {K.имя_точки(хд)}" + (f" ({д2}-й)" if д2 else ""))
    if ч:
        л.append("Ведут: " + "; ".join(ч) + ".")
    # градус
    if к.get("суть"):
        л.append(f"Градус: {_ф(к['суть'])}."
                 + (f" Делать: {_ф(к.get('действие',''))}." if к.get("действие") else "")
                 + (f" Беречься: {_ф(к.get('риск',''))}." if к.get("риск") else ""))
    # микроградусы — только у светил
    if имя in НЕСУЩИЕ:
        for п in (т.get("подградусы") or [])[:2]:
            if isinstance(п, dict) and п.get("суть"):
                л.append(f"Микроградус {п.get('знак','')} [{п.get('тег','')}]: {_ф(п['суть'])}.")
    # что решает
    мои = [а for а in (аспекты or []) if имя in (а.get("а"), а.get("б"))]
    напр = len([а for а in мои if а["аспект"] in ("квадрат", "оппозиция")])
    гарм = len([а for а in мои if а["аспект"] in ("трин", "секстиль")])
    точн = [а for а in мои if а["орбис"] <= 1.0]
    реш = []
    if дост in ("В ЧЕРТОГЕ", "В ВОЗВЫШЕНИИ"):
        реш.append("верхний полюс включается сам")
    elif дост in ("В ИЗГНАНИИ", "В ПАДЕНИИ"):
        реш.append("верхний полюс добывается работой")
    if ход != "прямой":
        реш.append("выходит наружу позже")
    реш.append(f"напряжённых {напр}, гармоничных {гарм}")
    if точн:
        реш.append("точные: " + ", ".join(
            f"{а['аспект']} с {S.ТВОР_П.get(а['б'] if а['а']==имя else а['а'], '')}" for а in точн))
    л.append("Решает: " + "; ".join(реш) + ".")
    # куда ведёт
    if дом:
        л.append(f"КУДА ВЕДЁТ: {S.КУДА_ВЕДЁТ.get(дом,'')}"
                 + (f", через {', '.join(S.ЧЕРЕЗ_ДОМ.get(н,'') for н in свои)}" if свои else "")
                 + ("; путь внутренний." if внутрь else "; путь прямой."))
    return "\n".join("  " + x for x in л)


