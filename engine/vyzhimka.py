def выжимка_карты(точки, куспиды=None, аспекты=None):
    ч = "═" * 74
    л = [ч, "ВЫЖИМКА МАШИНЫ · всё посчитано, читателю остаётся оживить", ч, ""]
    л += ["── СВОД ──", свод(точки, куспиды, аспекты), ""]
    if куспиды and len(куспиды) >= 12:
        л.append("── УГЛЫ ──")
        for имя, i in (("Асцендент", 0), ("Вершина", 9), ("Десцендент", 6), ("Дно", 3)):
            л += [угол(имя, куспиды, точки, i), ""]
    гр = U.скопления(точки, куспиды) if куспиды else []
    if гр:
        л.append("── СВЯЗКИ ──")
        for н, г in enumerate(гр):
            т_ = связка(г, точки, куспиды, аспекты, главная=(н == 0))
            if т_:
                л += [т_, ""]
    л.append("── СИЛЫ ──")
    for имя in ПОРЯДОК:
        if имя in точки:
            т_ = точка(имя, точки, куспиды, аспекты)
            if т_:
                л += [т_, ""]
    св = sorted(аспекты or [], key=lambda x: x["орбис"])
    if св:
        л.append("── СВЯЗИ ──")
        for а in св:
            п = пара(а["а"], а["б"], точки, куспиды, аспекты)
            if п:
                л.append(п)
    return "\n".join(л)
