def _ф(текст, слов=None):
    """Первая фраза без хвоста."""
    if not текст:
        return ""
    т = текст.split("Суть:")[-1].strip() if "Суть:" in текст else текст.strip()
    т = т.split(". ")[0].rstrip(".")
    return т


def _перечень(текст, сколько=3):
    ч = [x.strip() for x in текст.replace(";", ",").split(",") if x.strip()]
    return ", ".join(ч[:сколько])


