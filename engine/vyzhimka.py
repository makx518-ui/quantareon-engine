def угол(имя, куспиды, точки, индекс):
    г = куспиды[индекс]
    сл = S.УГЛЫ[имя]
    зн = K.знак(г)
    try:
        т = K.точка("Асцендент" if "сцендент" in имя else "MC", г)
        к = т.get("код") or {}
        под = т.get("подградусы") or []
    except Exception:
        к, под = {}, []
    л = [f"{имя} — {сл['кто'].split(':')[0]}. {зн}, {K.градус_словами(г)} [{к.get('тег','')}]: "
         f"{_ф(к.get('суть',''))}."]
    упр = K.УПРАВИТЕЛЬ.get(зн, [None])[0]
    if упр and упр in точки:
        д = K.дом_точки(точки[упр]["градус"], куспиды)
        л.append(f"Управитель — {K.имя_точки(упр)} ({S.ПЛАНЕТЫ.get(упр,{}).get('кто','').split(':')[0]})"
                 + (f" из {U._дом_род(д)}: ось делается через {S.СФЕРА_ЧЕРЕЗ.get(д,'')}." if д else "."))
    if под and isinstance(под[0], dict) and под[0].get("суть"):
        л.append(f"Микроградус: {под[0].get('знак','')} [{под[0].get('тег','')}] — {_ф(под[0]['суть'])}.")
    на_оси = [и for и, т2 in точки.items() if и != "ТЖ" and K.дуга(т2["градус"], г) <= 5.0]
    if на_оси:
        л.append(f"На оси стоит: {', '.join(K.имя_точки(и) for и in на_оси)}.")
    return "\n".join("  " + x for x in л)


