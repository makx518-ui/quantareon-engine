def космограмма_текстом(натал):
    """Космограмма слоями изнутри наружу — без домов, как решено."""
    точки = {и: п["abs_degree"] for и, п in натал.get("planets", {}).items()
             if и not in ("ТЖ", "Фортуна", "Вертекс")}
    слои = []
    for имя, набор in СЛОИ_КОСМОГРАММЫ:
        строки = [{"имя": и, "градус": round(точки[и], 4), "текст": дмс(точки[и])}
                  for и in набор if и in точки]
        if строки:
            слои.append({"слой": имя, "точки": строки})

    аспекты = []
    имена = list(точки)
    for i, а in enumerate(имена):
        for б in имена[i+1:]:
            if {а, б} == {"Сев.Узел", "Юж.Узел"}:
                continue
            d = дуга(точки[а], точки[б])
            for ан, угол, орб in НАТ_АСПЕКТЫ:
                о = abs(d - угол)
                if о <= орб:
                    аспекты.append({"а": а, "б": б, "аспект": ан, "орбис": round(о, 2),
                                    "точный": о <= 1})
                    break
    аспекты.sort(key=lambda x: x["орбис"])

    стихии = {с: 0 for с in СТИХИИ}
    кресты = {к: 0 for к in КРЕСТЫ}
    for и, г in точки.items():
        if и in ("Сев.Узел", "Юж.Узел", "Лилит", "Селена"):
            continue
        зн = int(г // 30)
        стихии[СТИХИИ[зн % 4]] += 1
        кресты[КРЕСТЫ[зн % 3]] += 1
    return {"слои": слои, "аспекты": аспекты, "стихии": стихии, "кресты": кресты}


def фаза_луны(момент_utc):
    """Фаза Луна-Солнце по Радьяру: тон суток."""
    j = jd(момент_utc)
    угол = (swe.calc_ut(j, swe.MOON)[0][0] - swe.calc_ut(j, swe.SUN)[0][0]) % 360
    for от, до, имя, смысл in ФАЗЫ:
        if от <= угол < до:
            return {"угол": round(угол, 2), "имя": имя, "смысл": смысл}
    return {"угол": round(угол, 2), "имя": "—", "смысл": ""}
