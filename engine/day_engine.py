def фаза_луны(момент):
    """Фаза Луны на момент: имя, угол, смысл."""
    j = jd(момент)
    с = swe.calc_ut(j, swe.SUN, swe.FLG_SWIEPH)[0][0]
    л = swe.calc_ut(j, swe.MOON, swe.FLG_SWIEPH)[0][0]
    угол = (л - с) % 360
    фазы = [
        (0, "Новолуние", "начало круга: семя брошено, всходов ещё не видно"),
        (45, "Растущий серп", "первый прорыв: отрыв от прежнего"),
        (90, "Первая четверть", "кризис действия: строить, ломая старое"),
        (135, "Растущая выпуклая", "созревание перед полнотой: шлифовка"),
        (180, "Полнолуние", "проявление: созревшее становится видимым"),
        (225, "Убывающая выпуклая", "служение: отдать собранное"),
        (270, "Последняя четверть", "переоценка: отделить живое от исчерпанного"),
        (315, "Бальзамическая", "отпускание: подготовка нового семени"),
    ]
    имя, смысл = фазы[0][1], фазы[0][2]
    for порог, и, см in фазы:
        if угол >= порог:
            имя, смысл = и, см
    return {"имя": имя, "угол": round(угол, 2), "смысл": смысл}


def медленные(рождение_utc, момент_utc, натал):
    """Дирекции и прогрессии — причинный слой, за сутки не движется."""
    from engine import situacia as S
    точки = {}
    for имя, п in (натал.get("planets") or {}).items():
        точки[имя] = {"градус": п["abs_degree"], "ретро": p_ретро(п)}
    дир = S.дирекции({и: _как_точка(и, т["градус"]) for и, т in точки.items()},
                     рождение_utc, момент_utc)
    прог = S.прогрессии(None, рождение_utc, момент_utc, 0, 0)
    return {
        "дуга": дир.get("дуга"),
        "возраст_лет": дир.get("возраст"),
        "дирекции": {и: {"градус": т["градус"], "словами": т.get("словами", "")}
                     for и, т in dир_точки(дир).items()},
        "прогрессии": {и: {"градус": т["градус"], "словами": т.get("словами", "")}
                       for и, т in (прог.get("точки") or {}).items()},
        "фаза_прогрессивной_луны": прог.get("фаза"),
    }


def p_ретро(п):
    return bool(п.get("retrograde"))


def dир_точки(дир):
    return дир.get("точки") or {}


def _как_точка(имя, градус):
    from engine import kosmogramma as K
    return K.точка(имя, градус)


def аспекты_медленных(м, натал, точки_момента=None, орбис=1.0):
    """Связи причинного слоя с космограммой — орбис жёстко 1°."""
    from engine import kosmogramma as K
    from engine import situacia as S
    космо = {и: K.точка(и, п["abs_degree"], bool(п.get("retrograde")))
             for и, п in (натал.get("planets") or {}).items()}
    найдено = []
    for слой, ключ in (("дирекция", "дирекции"), ("прогрессия", "прогрессии")):
        for имя, т in (м.get(ключ) or {}).items():
            for кимя, кт in космо.items():
                d = K.дуга(т["градус"], кт["градус"])
                for ан, угол in S.АСПЕКТЫ:
                    о = abs(d - угол)
                    if о <= орбис:
                        найдено.append({
                            "слой": слой, "точка": имя, "натал": кимя,
                            "аспект": ан, "орбис": round(о, 3),
                            "точный": о <= 0.5,
                        })
                        break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


def космограмма_текстом(натал):
    """Космограмма по группам — изнутри наружу, без домов."""
    from engine import kosmogramma as K
    точки = {и: K.точка(и, п["abs_degree"], bool(п.get("retrograde")))
             for и, п in (натал.get("planets") or {}).items()}
    группы = [
        ("ЯДРО — кто он", ["Солнце", "Луна", "Сев.Узел", "Юж.Узел"]),
        ("КОНТУР ЛИЧНОСТИ — ум · любовь · воля", ["Меркурий", "Венера", "Марс"]),
        ("СОЦИАЛЬНЫЕ — рост · форма", ["Юпитер", "Сатурн"]),
        ("ВЫСШИЕ — прорыв · туман · глубина · рана",
         ["Уран", "Нептун", "Плутон", "Хирон"]),
        ("КАРМИЧЕСКИЕ — тень · благодать", ["Лилит", "Селена"]),
    ]
    л = []
    for имя_гр, имена in группы:
        л.append(f"  ── {имя_гр}")
        for и in имена:
            т = точки.get(и)
            if т:
                л.append(f"     {K.имя_точки(и):12} {т.get('словами','')}")
    ст = {}
    for и, т in точки.items():
        ст[K.СТИХИЯ_ЗНАКА.get(т["знак"], "?")] = \
            ст.get(K.СТИХИЯ_ЗНАКА.get(т["знак"], "?"), 0) + 1
    л.append("  стихии: " + " · ".join(f"{к} {в}" for к, в in ст.items()))
    return "\n".join(л)
