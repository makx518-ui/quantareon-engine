"""
ЯДРО ДНЯ (Э1) — машина прокручивает сутки и кладёт раскладку на полочку.

Его методика:
  · якорь круга — ГРАДУС хорарного АС на секунду вопроса; на любой день круг
    начинается там, где АС снова встал на этот градус, и длится 24 часа;
  · 12 глав — по ЗНАКАМ под бегущим АС, вперёд по зодиаку; первая и последняя
    главы неполные (круг стартует с середины знака) — так и оставляем, честно;
  · узлы быстрого слоя: АС и УГЛОВЫЕ куспиды (1/4/7/10) через точки;
    орбисы 2° септенер (Солнце, Луна, Меркурий, Венера, Марс, Юпитер, Сатурн),
    1° высшие (Уран, Нептун, Плутон), Хирон, узлы, Селена, Чёрная Луна;
  · момент точного контакта уточняется делением пополам — до секунды;
  · ТЖ стоит (градус по космограмме), а ДОМ под ней меняется — пишем по ходу;
  · режим главы: ☀ день (сознание) · ☾ ночь (подсознание) · ◇ мухурта (созерцание).

Ничего не выдумывается: все числа из Швейцарских эфемерид.
"""
from datetime import datetime, timedelta, timezone
import swisseph as swe

ЗНАКИ = ['Овен', 'Телец', 'Близнецы', 'Рак', 'Лев', 'Дева',
         'Весы', 'Скорпион', 'Стрелец', 'Козерог', 'Водолей', 'Рыбы']
ЗНАКИ_Р = ['Овна', 'Тельца', 'Близнецов', 'Рака', 'Льва', 'Девы',
           'Весов', 'Скорпиона', 'Стрельца', 'Козерога', 'Водолея', 'Рыб']

СЕПТЕНЕР = {'Солнце', 'Луна', 'Меркурий', 'Венера', 'Марс', 'Юпитер', 'Сатурн'}
ОРБИС_СЕПТЕНЕР = 2.0
ОРБИС_ПРОЧИЕ = 1.0

УГЛОВЫЕ = {0: 'Асцендент', 3: 'IC — Глубина неба', 6: 'Десцендент', 9: 'MC — Середина неба'}


# ─────────────────────────── мелочи ───────────────────────────

def jd(момент: datetime) -> float:
    м = момент.astimezone(timezone.utc)
    return swe.julday(м.year, м.month, м.day,
                      м.hour + м.minute / 60.0 + м.second / 3600.0)


def дмс(градус: float) -> str:
    г = ((градус % 360) + 360) % 360
    в = г % 30
    д = int(в); м = int((в - д) * 60); с = int(round((((в - д) * 60) - м) * 60))
    if с == 60: с = 0; м += 1
    return f"{д}°{м:02d}'{с:02d}\" {ЗНАКИ_Р[int(г // 30)]}"


def орбис(имя: str) -> float:
    return ОРБИС_СЕПТЕНЕР if имя in СЕПТЕНЕР else ОРБИС_ПРОЧИЕ


def _система(широта: float) -> bytes:
    # за полярным кругом Плацидуса нет — там Региомонтан, как и в движке
    return b'P' if abs(широта) <= 66.5 else b'R'


def куспиды_в(момент: datetime, широта: float, долгота: float) -> list:
    к, _ = swe.houses(jd(момент), широта, долгота, _система(широта))
    return [float(x) for x in к[:12]]


def асцендент_в(момент: datetime, широта: float, долгота: float) -> float:
    return куспиды_в(момент, широта, долгота)[0]


def дуга(а: float, б: float) -> float:
    """Кратчайшее расстояние между градусами, 0..180."""
    д = abs((а - б) % 360)
    return min(д, 360 - д)


# ────────────────────── начало круга ──────────────────────

def начало_круга(день: datetime, якорь: float, широта: float, долгота: float) -> datetime:
    """Момент выбранных суток, когда АС встал на якорный градус.
    Ищем по минутам, потом уточняем до секунды."""
    т = день.replace(hour=0, minute=0, second=0, microsecond=0)
    пред = дуга(асцендент_в(т, широта, долгота), якорь)
    шаг = timedelta(minutes=1)
    лучший, лучшая = т, пред
    for _ in range(1440):
        т2 = т + шаг
        d = дуга(асцендент_в(т2, широта, долгота), якорь)
        if d < лучшая:
            лучшая, лучший = d, т2
        т, пред = т2, d
    # уточняем в окне ±1 минута
    низ, верх = лучший - шаг, лучший + шаг
    for _ in range(20):
        сер = низ + (верх - низ) / 2
        if дуга(асцендент_в(сер - timedelta(seconds=1), широта, долгота), якорь) < \
           дуга(асцендент_в(сер + timedelta(seconds=1), широта, долгота), якорь):
            верх = сер
        else:
            низ = сер
    return (низ + (верх - низ) / 2).replace(microsecond=0)


# ────────────────────── прокрутка суток ──────────────────────

def точки_дня(момент: datetime, натал: dict) -> dict:
    """Все точки, по которым ищем узлы: натальные (стоят) и транзитные (на этот момент)."""
    точки = {}
    for имя, п in натал.get('planets', {}).items():
        точки[f"натальный {имя}"] = п['abs_degree']
    ids = [(swe.SUN, "Солнце"), (swe.MOON, "Луна"), (swe.MERCURY, "Меркурий"),
           (swe.VENUS, "Венера"), (swe.MARS, "Марс"), (swe.JUPITER, "Юпитер"),
           (swe.SATURN, "Сатурн"), (swe.URANUS, "Уран"), (swe.NEPTUNE, "Нептун"),
           (swe.PLUTO, "Плутон"), (swe.TRUE_NODE, "Сев.Узел"), (swe.MEAN_APOG, "Лилит"),
           (swe.CHIRON, "Хирон")]
    j = jd(момент)
    for pid, имя in ids:
        try:
            точки[f"транзитный {имя}"] = swe.calc_ut(j, pid)[0][0]
        except Exception:
            pass
    if "транзитный Сев.Узел" in точки:
        точки["транзитный Юж.Узел"] = (точки["транзитный Сев.Узел"] + 180) % 360
    # ⚠️ Белой Луны (Селены) нет в эфемеридах — она считается формулой,
    # тем же счётом, что и в натале, иначе транзитная Селена молча выпадает
    try:
        from engine.natal import _compute_selena
        точки["транзитный Селена"] = _compute_selena(j) % 360
    except Exception:
        pass
    # ⚠️ и выкидываем ТЖ из натального списка: движок кладёт туда Точку Жизни
    # на ТЕКУЩИЙ момент, и она ловит сама себя в узлы
    точки.pop("натальный ТЖ", None)
    # ⚠️ Фортуна и Вертекс считаются от асцендента, а времени рождения мы не спрашиваем —
    # без него они недостоверны (проверено: при сдвиге места на 80 км уезжают на 41′ и 82′).
    # Его решение 14.08: в космограмме прогноза они не нужны вовсе
    точки.pop("натальный Фортуна", None)
    точки.pop("натальный Вертекс", None)
    return точки


def _чистое_имя(ключ: str) -> str:
    return ключ.split(' ', 1)[1] if ' ' in ключ else ключ


# быстрые транзитные тела — их положение за сутки заметно меняется,
# потому в узлах они пересчитываются на каждом шаге, а не берутся застывшими
БЫСТРЫЕ = {"транзитный Луна": swe.MOON, "транзитный Солнце": swe.SUN,
           "транзитный Меркурий": swe.MERCURY, "транзитный Венера": swe.VENUS,
           "транзитный Марс": swe.MARS}


def узлы_круга(начало: datetime, натал: dict, широта: float, долгота: float,
               шаг_минут: int = 1) -> list:
    """Все контакты бегущего АС и угловых куспидов с точками за круг.
    Возвращает список: время точного контакта, что с чем, орбис, окно.

    ⚠️ Луна за сутки проходит 13°: если брать её застывшей, лунные узлы уезжают
    по времени на полчаса. Потому быстрые тела пересчитываются на каждом шаге.
    """
    точки = точки_дня(начало + timedelta(hours=12), натал)   # медленные — на середину суток
    конец = начало + timedelta(hours=24)
    шаг = timedelta(minutes=шаг_минут)

    def позиции(момент):
        к = куспиды_в(момент, широта, долгота)
        return {имя: к[i] for i, имя in УГЛОВЫЕ.items()}

    def точка_в(ключ, момент):
        """Градус точки на момент: быстрые считаем заново, остальные стоят."""
        pid = БЫСТРЫЕ.get(ключ)
        if pid is None:
            return точки[ключ]
        return swe.calc_ut(jd(момент), pid)[0][0]

    найдено = []
    т = начало
    пред = позиции(т)
    while т < конец:
        т2 = т + шаг
        тек = позиции(т2)
        for угол, гр2 in тек.items():
            гр1 = пред[угол]
            for ключ in точки:
                о = орбис(_чистое_имя(ключ))
                точка = точка_в(ключ, т2)
                d1, d2 = дуга(гр1, точка_в(ключ, т)), дуга(гр2, точка)
                # ищем ДНО: расстояние сближалось (d1 >= d2) и дальше начнёт расти.
                # ⚠️ раньше здесь стояло «if d1 > d2: continue» — оно отбрасывало
                # ровно случай сближения, потому узлов не находилось совсем.
                if d2 > о or d1 < d2:
                    continue
                d3 = дуга(позиции(т2 + шаг)[угол], точка_в(ключ, т2 + шаг))
                if d3 < d2:
                    continue
                if True:
                    # уточняем момент точного контакта — точка тоже едет, если быстрая
                    низ, верх = т, т2 + шаг
                    while (верх - низ).total_seconds() > 1:
                        a = низ + (верх - низ) / 3
                        b = верх - (верх - низ) / 3
                        if дуга(позиции(a)[угол], точка_в(ключ, a)) < дуга(позиции(b)[угол], точка_в(ключ, b)):
                            верх = b
                        else:
                            низ = a
                    точный = (низ + (верх - низ) / 2).replace(microsecond=0)
                    найдено.append({
                        "время": точный,
                        "угол": угол,
                        "точка": ключ,
                        "градус_точки": точка_в(ключ, точный),
                        "орбис": о,
                        "окно_минут": round(о * 2 * 4, 1),   # 1° = 4 минуты хода АС
                    })
        т, пред = т2, тек
    найдено.sort(key=lambda у: у["время"])
    return найдено


def главы_круга(начало: datetime, широта: float, долгота: float) -> list:
    """Границы глав — моменты, когда АС переходит в новый знак."""
    конец = начало + timedelta(hours=24)
    шаг = timedelta(minutes=1)
    главы = []
    т = начало
    текущий = int(асцендент_в(т, широта, долгота) // 30)
    старт = т
    while т < конец:
        т2 = т + шаг
        зн = int(асцендент_в(т2, широта, долгота) // 30)
        if зн != текущий:
            низ, верх = т, т2
            while (верх - низ).total_seconds() > 1:
                сер = низ + (верх - низ) / 2
                if int(асцендент_в(сер, широта, долгота) // 30) == текущий:
                    низ = сер
                else:
                    верх = сер
            главы.append({"знак": ЗНАКИ[текущий], "начало": старт,
                          "конец": верх.replace(microsecond=0)})
            текущий, старт = зн, верх.replace(microsecond=0)
        т = т2
    главы.append({"знак": ЗНАКИ[текущий], "начало": старт, "конец": конец})
    # пометки неполноты
    if главы:
        главы[0]["неполная"] = "хвост знака — круг начался с середины"
        главы[-1]["неполная"] = "начало того же знака — круг замкнулся"
    return главы


# ═══════════ МЕДЛЕННЫЕ: ДИРЕКЦИИ И ПРОГРЕССИИ ═══════════
# Причинный слой. За сутки не двигаются вовсе, потому живут в центре карты
# ровным светом, а событием становится проход бегущего АС по ним.
#   дирекции  — солнечная дуга: сколько прошло Солнце за столько ДНЕЙ,
#               сколько человеку ЛЕТ; эта дуга прибавляется ко всем точкам;
#   прогрессии — вторичные: положение планет на (рождение + возраст в днях).

МЕДЛЕННЫЕ_ТОЧКИ = [(swe.SUN,"Солнце"),(swe.MOON,"Луна"),(swe.MERCURY,"Меркурий"),
                   (swe.VENUS,"Венера"),(swe.MARS,"Марс"),(swe.JUPITER,"Юпитер"),
                   (swe.SATURN,"Сатурн")]
АСПЕКТЫ = [("соединение",0),("секстиль",60),("квадрат",90),("трин",120),("оппозиция",180)]
ОРБИС_МЕДЛЕННЫХ = 1.0


def медленные(рождение_utc, момент_utc, натал):
    """Дирекции и прогрессии на выбранный день."""
    прожито = jd(момент_utc) - jd(рождение_utc)
    лет = прожито / 365.25

    # солнечная дуга: Солнце за «лет» дней после рождения
    сол_рожд = swe.calc_ut(jd(рождение_utc), swe.SUN)[0][0]
    сол_дуга = swe.calc_ut(jd(рождение_utc) + лет, swe.SUN)[0][0]
    дуга = ((сол_дуга - сол_рожд) % 360)

    дир = {}
    for имя, п in натал.get("planets", {}).items():
        if имя in ("ТЖ", "Фортуна", "Вертекс"):
            continue
        дир[имя] = round((п["abs_degree"] + дуга) % 360, 4)

    прог = {}
    jd_прог = jd(рождение_utc) + лет          # день за год
    for pid, имя in МЕДЛЕННЫЕ_ТОЧКИ:
        try:
            прог[имя] = round(swe.calc_ut(jd_прог, pid)[0][0] % 360, 4)
        except Exception:
            pass

    return {"дуга": round(дуга, 4), "лет": round(лет, 3),
            "дирекции": дир, "прогрессии": прог}


def аспекты_медленных(мед, натал, транзит_точки):
    """Связи причинного слоя: к натальным точкам и к транзитным, орбис 1°."""
    цели = {}
    for имя, п in натал.get("planets", {}).items():
        if имя not in ("ТЖ", "Фортуна", "Вертекс"):
            цели[f"натальный {имя}"] = п["abs_degree"]
    for ключ, гр in (транзит_точки or {}).items():
        if ключ.startswith("транзитный"):
            цели[ключ] = гр

    найдено = []
    for слой, набор in (("дирекция", мед["дирекции"]), ("прогрессия", мед["прогрессии"])):
        for имя, гр in набор.items():
            for ключ, цель in цели.items():
                d = дуга(гр, цель)
                for ан, угол in АСПЕКТЫ:
                    о = abs(d - угол)
                    if о <= ОРБИС_МЕДЛЕННЫХ:
                        найдено.append({"слой": слой, "точка": имя, "градус": гр,
                                        "аспект": ан, "к": ключ, "градус_цели": round(цель, 4),
                                        "орбис": round(о, 3)})
                        break
    найдено.sort(key=lambda а: а["орбис"])
    return найдено


