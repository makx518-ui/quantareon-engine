# -*- coding: utf-8 -*-
"""
МУХУРТА — окно медитации (Брахма-мухурта).
Ядро: только восход и окно перед ним. Ничего лишнего.

Канон (источники сходятся): ведические сутки идут от восхода до восхода.
Брахма-мухурта — предпоследняя мухурта ночи: начинается за 1ч36м до восхода,
кончается за 48 минут до восхода. Привязка к ВОСХОДУ, не к часам.

Два счёта, оба честные:
  фикс  — мухурта ровно 48 минут (канон, устойчив на любой широте);
  проп  — ночь делится на 15 частей (мухурта плавает по сезону).
На равноденствии совпадают; к солнцестояниям расходятся.
"""
from datetime import datetime, timedelta, timezone
import swisseph as swe

МУХУРТА_МИН = 48.0


def _восход(jd_старт, широта, долгота):
    """Ближайший восход центра диска после момента jd_старт (UTC)."""
    флаг = swe.CALC_RISE
    рез, момент = swe.rise_trans(jd_старт, swe.SUN, флаг, (долгота, широта, 0))
    if рез < 0 or not момент or not момент[0]:
        return None
    return момент[0]


def _закат(jd_старт, широта, долгота):
    флаг = swe.CALC_SET
    рез, момент = swe.rise_trans(jd_старт, swe.SUN, флаг, (долгота, широта, 0))
    if рез < 0 or not момент or not момент[0]:
        return None
    return момент[0]


def _в_местное(jd, сдвиг_часов):
    """Юлианский день → местное время строкой ЧЧ:ММ и datetime."""
    y, m, d, ч = swe.revjul(jd + сдвиг_часов / 24.0)
    ч_ц = int(ч); мин = (ч - ч_ц) * 60
    return datetime(y, m, d, ч_ц, int(мин), int(round((мин - int(мин)) * 60)) % 60)


def _полярно(jd_полночь, широта, долгота, сдвиг_часов):
    """Различаем полярный день и полярную ночь по высоте солнца в местный полдень."""
    jd_полдень = jd_полночь + 0.5
    # ⚠️ calc_ut по умолчанию даёт ЭКЛИПТИЧЕСКИЕ координаты — значит и преобразование ECL2HOR,
    # иначе высота считается от неверных чисел (проверено: EQU2HOR на эклиптике врал)
    поз = swe.calc_ut(jd_полдень, swe.SUN)[0]
    высота = swe.azalt(jd_полдень, swe.ECL2HOR, (долгота, широта, 0), 0, 0,
                       (поз[0], поз[1], поз[2]))[1]
    if высота > 0:
        return "полярный день: солнце не заходит, восхода нет — окна медитации в этот день не существует"
    return "полярная ночь: солнце не восходит — окна медитации в этот день не существует"


def окно_медитации(год, месяц, день, широта, долгота, сдвиг_часов, путь_эфемерид=None):
    """Возвращает окно медитации на указанную дату в указанном месте.

    сдвиг_часов — смещение местного времени от UTC (Ижевск +4, Тбилиси +4, Москва +3).
    Всё время в ответе — МЕСТНОЕ.
    """
    if путь_эфемерид:
        swe.set_ephe_path(путь_эфемерид)

    # полночь местная → в UTC
    jd_полночь = swe.julday(год, месяц, день, 0.0) - сдвиг_часов / 24.0

    восход = _восход(jd_полночь, широта, долгота)
    if восход is None:
        return {"есть": False, "почему": _полярно(jd_полночь, широта, долгота, сдвиг_часов)}

    закат = _закат(восход, широта, долгота)
    восход2 = _восход(восход + 0.1, широта, долгота)
    if закат is None or восход2 is None:
        return {"есть": False, "почему": _полярно(jd_полночь, широта, долгота, сдвиг_часов)}

    ночь_часов = (восход2 - закат) * 24.0
    ночная_мухурта_мин = ночь_часов * 60.0 / 15.0

    # фиксированный счёт: 96 → 48 минут до восхода
    ф_нач = восход - (2 * МУХУРТА_МИН) / 1440.0
    ф_кон = восход - МУХУРТА_МИН / 1440.0
    # пропорциональный: две ночные мухурты → одна ночная мухурта до восхода
    п_нач = восход - (2 * ночная_мухурта_мин) / 1440.0
    п_кон = восход - ночная_мухурта_мин / 1440.0

    return {
        "есть": True,
        "дата": f"{день:02d}.{месяц:02d}.{год}",
        "восход": _в_местное(восход, сдвиг_часов),
        "закат": _в_местное(закат, сдвиг_часов),
        "окно": {  # главное: канонический счёт
            "начало": _в_местное(ф_нач, сдвиг_часов),
            "конец": _в_местное(ф_кон, сдвиг_часов),
            "длительность_мин": МУХУРТА_МИН,
        },
        "второй_счёт": {  # пропорциональный, для сверки
            "начало": _в_местное(п_нач, сдвиг_часов),
            "конец": _в_местное(п_кон, сдвиг_часов),
            "длительность_мин": round(ночная_мухурта_мин, 1),
        },
        "ночь_часов": round(ночь_часов, 2),
    }


def строкой(о):
    """Человеческая распечатка."""
    if not о.get("есть"):
        return f"Окна нет: {о['почему']}"
    ч = lambda d: d.strftime("%H:%M")
    return (f"{о['дата']} · восход {ч(о['восход'])} · закат {ч(о['закат'])}\n"
            f"  ОКНО МЕДИТАЦИИ  {ч(о['окно']['начало'])}–{ч(о['окно']['конец'])}  (48 мин до восхода)\n"
            f"  второй счёт     {ч(о['второй_счёт']['начало'])}–{ч(о['второй_счёт']['конец'])}"
            f"  (ночная мухурта {о['второй_счёт']['длительность_мин']:.0f} мин)")
