def факт(имя: str, знак: str, дом: int, суть_градуса: str = "") -> str:
    """Сухая запись для кухни. Наружу не идёт."""
    с = f" · {суть_градуса}" if суть_градуса else ""
    return f"{имя} · {знак} · {дом}-й дом ({ДОМ_СФЕРА[дом][0]}) · {РОЛЬ_ФАКТ.get(имя,'')}{с}"


def смысл(имя: str, знак: str, дом: int) -> str:
    """То, что пойдёт в трактовку. Без терминов."""
    return f"{РОЛЬ_СМЫСЛ.get(имя,'')}: {ДОМ_СФЕРА[дом][1]}, {ЗНАК_СПОСОБ[знак][1]}"


def вектор_фактом(юз: str, юд: int, сз: str, сд: int) -> str:
    return (f"Юж.Узел {юз} {юд}-й дом → Сев.Узел {сз} {сд}-й дом "
            f"({ДОМ_СФЕРА[юд][0]} → {ДОМ_СФЕРА[сд][0]})")


def вектор_смыслом(юз: str, юд: int, сз: str, сд: int) -> str:
    """Основа строки ядра: от чего к чему сегодня идти. Без терминов.

    Градус даёт тему суток — она одна для всех. Дом делает её личной.
    """
    return (f"уйти от того, что держит {ДОМ_СФЕРА[юд][1]} — "
            f"к тому, что можно реализовать {ДОМ_СФЕРА[сд][1]}, {ЗНАК_СПОСОБ[сз][1]}")


