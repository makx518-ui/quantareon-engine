# -*- coding: utf-8 -*-
"""
СБОРЩИК ЯДРА ДНЯ — кармический узор карты момента.

Что делает: читает четыре кармические точки по одной и той же классической
цепочке, считает их вес, выбирает ведущую и сводит вектор узлов с её окраской
в одну строку — ядро дня. Вся остальная карта потом разворачивает эту строку.

Цепочка чтения точки (её же порядок в выдаче):
    планета → достоинство и ход → знак → чем владеет → дом стояния →
    хозяин дома и где он стоит → градус и подградус → аспекты с орбисами →
    резюме

Аспект читается по закону двух концов: не названием, а тем, что несёт каждая
сторона и что даёт их встреча.

Машина ничего не сочиняет: слова берутся из Азбуки 360 и из малой библиотеки
кармики. Здесь только счёт, порядок и выбор.
"""
from __future__ import annotations

from engine import kosmogramma as K

# ─────────────────────────────────────────────────────────────────────────────
# Четыре показателя ядра. Порядок жёсткий — он же порядок веса при равенстве.
# ─────────────────────────────────────────────────────────────────────────────
ВЕКТОР = ("Юж.Узел", "Сев.Узел")   # откуда и куда держит путь день
БОЛЬ = "Хирон"                              # где зудит и что требует лечения
ОПОРА = "Селена"                            # благодать: где день держит
СОБЛАЗН = "Лилит"                           # искушение свернуть с вектора

КАРМИКА = (*ВЕКТОР, БОЛЬ, ОПОРА, СОБЛАЗН)

РОЛЬ = {
    "Юж.Узел":  "откуда день уходит: пройденное, что тянет назад",
    "Сев.Узел": "куда день держит путь за эти сутки",
    БОЛЬ:            "боль дня: где зудит сильнее всего и что требует лечения",
    ОПОРА:           "поддержка: где день держит и по какой заслуге",
    СОБЛАЗН:         "соблазн: чем день искушает свернуть с пути",
}

# Углы карты: индекс куспида → имя
УГЛЫ = {0: "Асцендент", 9: "MC", 6: "Десцендент", 3: "IC"}

ОРБ_УГЛА = 3.0        # стояние на угле — самый сильный признак
ОРБ_ТОЧНОГО = 0.5     # точная связь
УГЛОВЫЕ_ДОМА = (1, 4, 7, 10)


def _дуга(а: float, б: float) -> float:
    return abs((а - б + 180) % 360 - 180)


# ─────────────────────────────────────────────────────────────────────────────
# ЦЕПОЧКА ЧТЕНИЯ ОДНОЙ ТОЧКИ
# ─────────────────────────────────────────────────────────────────────────────
def прочесть_точку(имя: str, точки: dict, куспиды: list, аспекты: list) -> dict:
    """Одна точка по всей цепочке. Порядок звеньев не меняется никогда."""
    т = точки.get(имя)
    if not т:
        return {}

    знак = т["знак"]
    дом = K.дом_точки(т["градус"], куспиды)

    # 2. достоинство и ход — задают направление всей цепочки
    дост = K.достоинство(имя, знак)   # пара: звание и пояснение
    ретро = т.get("ретро", False)

    # 4. чем владеет — канал выхода в мир
    владеет = K.владеет(имя) or []
    дома_владения = [i + 1 for i in range(12)
                     if K.знак(куспиды[i]) in владеет] if куспиды else []

    # 6. хозяин дома стояния — режиссёр сцены
    хозяин = хозяин_где = None
    if дом and куспиды:
        хозяин = K.УПРАВИТЕЛЬ[K.знак(куспиды[дом - 1])][0]
        х = точки.get(хозяин)
        if х:
            хозяин_где = {
                "имя": хозяин, "знак": х["знак"],
                "градус": х["словами"], "текст": х["текст"],
                "дом": K.дом_точки(х["градус"], куспиды),
                "код": х["код"]["тег"], "суть": х["код"]["суть"],
            }

    # 8. аспекты — от самых тесных к широким, оба конца целиком
    связи = []
    for а in аспекты:
        if имя not in (а["а"], а["б"]):
            continue
        другой = а["б"] if а["а"] == имя else а["а"]
        д = точки.get(другой, {})
        связи.append({
            "аспект": а["аспект"], "орбис": а["орбис"],
            "точный": а["орбис"] <= ОРБ_ТОЧНОГО,
            # закон двух концов: второй конец несёт своё целиком
            "второй_конец": {
                "имя": другой, "знак": д.get("знак"),
                "градус": д.get("словами"), "дом": K.дом_точки(д["градус"], куспиды) if д else None,
                "код": d_код(д), "владеет": K.владеет(другой) or [],
            },
        })
    связи.sort(key=lambda с: с["орбис"])

    # близость к углам карты
    на_угле = None
    if куспиды:
        for i, имя_угла in УГЛЫ.items():
            о = _дуга(т["градус"], куспиды[i])
            if о <= ОРБ_УГЛА:
                на_угле = {"угол": имя_угла, "орбис": round(о, 2)}
                break

    return {
        "имя": имя,                      # 1. планета
        "роль": РОЛЬ.get(имя, ""),
        "достоинство": дост,             # 2. достоинство и ход
        "ретро": ретро,
        "знак": знак,                    # 3. знак
        "владеет_знаками": владеет,      # 4. чем владеет
        "владеет_домами": дома_владения,
        "дом": дом,                      # 5. дом стояния
        "хозяин_дома": хозяин_где,       # 6. хозяин дома и где он стоит
        "градус": т["словами"],          # 7. градус и подградус
        "градус_текст": т["текст"],
        "код": т["код"],
        "подградусы": т["подградусы"],
        "связи": связи,                  # 8. аспекты с орбисами
        "на_угле": на_угле,
        # 9. резюме собирается на слое слов, из малой библиотеки кармики
    }


def d_код(д: dict) -> str:
    return (д.get("код") or {}).get("тег", "") if д else ""


# ─────────────────────────────────────────────────────────────────────────────
# ВЕС: что звучит громче
# ─────────────────────────────────────────────────────────────────────────────
def вес(п: dict, оси: tuple) -> dict:
    """Вес точки по пяти признакам. Нужен, чтобы выбрать ведущую."""
    очки = 0
    почему = []

    if п.get("на_угле"):
        очки += 5
        почему.append(f"стоит на угле {п['на_угле']['угол']} ({п['на_угле']['орбис']}°)")

    точных = [с for с in п["связи"] if с["точный"]]
    if точных:
        очки += 3 * len(точных)
        почему.append(f"точных связей {len(точных)}")

    с_осью = [с for с in п["связи"] if с["второй_конец"]["имя"] in оси]
    if с_осью:
        очки += 3
        почему.append("связана с осью узлов")

    флаг = (п.get("код") or {}).get("флаг", "")
    if флаг and флаг.upper() != "НЕТ":
        очки += 2
        почему.append(f"особый градус: {флаг}")

    if п.get("дом") in УГЛОВЫЕ_ДОМА:
        очки += 2
        почему.append(f"угловой дом ({п['дом']}-й)")

    return {"очки": очки, "почему": почему}


# ─────────────────────────────────────────────────────────────────────────────
# ТЕНЬ НА ВЕКТОРЕ
# ─────────────────────────────────────────────────────────────────────────────
МЯГКИЕ = ("секстиль", "трин", "соединение")


def тень_на_векторе(соблазн: dict) -> dict | None:
    """Чёрная Луна в мягкой связи с осью узлов — соблазн идёт ПО линии пути.

    Такой соблазн не тормозит, он подменяет: дело подменяется позой, работа —
    видимостью. Потому он опаснее, чем соблазн поперёк пути.
    """
    if not соблазн:
        return None
    с_осью = [с for с in соблазн["связи"]
              if с["второй_конец"]["имя"] in ВЕКТОР and с["аспект"] in МЯГКИЕ]
    if not с_осью:
        return None
    бьёт = [с for с in соблазн["связи"] if с["аспект"] not in МЯГКИЕ][:3]
    return {
        "на_векторе": True,
        "связи_с_осью": с_осью,
        "бьёт_по": [{"имя": с["второй_конец"]["имя"], "дом": с["второй_конец"]["дом"],
                     "аспект": с["аспект"], "орбис": с["орбис"]} for с in бьёт],
    }


# ─────────────────────────────────────────────────────────────────────────────
# СХОЖДЕНИЕ ЦЕЛЕЙ
# ─────────────────────────────────────────────────────────────────────────────
def схождение_целей(точки: dict, куспиды: list) -> dict | None:
    """Внутренняя цель (приходящий узел) и внешняя (MC) — под одной планетой?

    Если да, это сильнейший признак дня: внутреннее и внешнее сошлись в одной
    точке, и признак выносится в текст отдельной строкой.
    """
    узел = точки.get(ВЕКТОР[1])
    if not узел or not куспиды:
        return None
    дом_узла = K.дом_точки(узел["градус"], куспиды)
    хозяин_узла = K.УПРАВИТЕЛЬ[K.знак(куспиды[дом_узла - 1])][0]
    хозяин_mc = K.УПРАВИТЕЛЬ[K.знак(куспиды[9])][0]
    знак_mc = K.знак(куспиды[9])

    х = точки.get(хозяин_узла)
    сошлись_знаком = bool(х and х["знак"] == знак_mc)
    сошлись_планетой = хозяин_узла == хозяин_mc
    if not (сошлись_знаком or сошлись_планетой):
        return None
    return {
        "хозяин_пути": хозяин_узла,
        "хозяин_цели": хозяин_mc,
        "знак_MC": знак_mc,
        "одной_планетой": сошлись_планетой,
        "в_одном_знаке": сошлись_знаком,
        "где_хозяин_пути": {
            "знак": х["знак"], "дом": K.дом_точки(х["градус"], куспиды),
            "градус": х["словами"], "код": х["код"]["тег"],
            "суть": х["код"]["суть"], "ретро": х.get("ретро", False),
        } if х else None,
    }


# ─────────────────────────────────────────────────────────────────────────────
# КАК ПОЙДЁТ РЕАЛИЗАЦИЯ
# ─────────────────────────────────────────────────────────────────────────────
def реализация(точки: dict, куспиды: list, аспекты: list, тень: dict | None) -> dict:
    """Сразу · с задержкой · не сейчас.

    Считается по трём вещам: свободен ли канал инструмента (хозяин асцендента),
    сходится ли связь с целью (хозяин 1-го и хозяин MC), лежит ли тень на векторе.
    """
    if not куспиды:
        return {}
    хоз1 = K.УПРАВИТЕЛЬ[K.знак(куспиды[0])][0]
    хозMC = K.УПРАВИТЕЛЬ[K.знак(куспиды[9])][0]
    т1 = точки.get(хоз1)

    канал_открыт = True
    почему_канал = []
    if т1:
        дост = K.достоинство(хоз1, т1["знак"])[0]   # достоинство() отдаёт пару (звание, пояснение)
        if дост in ("В ПАДЕНИИ", "В ИЗГНАНИИ"):
            канал_открыт = False
            почему_канал.append(f"хозяин асцендента {хоз1} {дост.lower()}")
        elif дост:
            почему_канал.append(f"хозяин асцендента {хоз1} {дост.lower()}")
        if т1.get("ретро"):
            почему_канал.append(f"{хоз1} ретрограден — сила идёт внутрь")
        дом1 = K.дом_точки(т1["градус"], куспиды)
        if дом1 in УГЛОВЫЕ_ДОМА:
            почему_канал.append(f"{хоз1} в угловом доме ({дом1}-й) — инструмент в руках")

    связь_с_целью = None
    if хоз1 != хозMC:
        for а in аспекты:
            if {а["а"], а["б"]} == {хоз1, хозMC}:
                связь_с_целью = {"аспект": а["аспект"], "орбис": а["орбис"]}
                break
    else:
        связь_с_целью = {"аспект": "одна планета ведёт и личность, и цель", "орбис": 0.0}

    если_тень = bool(тень and тень.get("на_векторе"))

    if канал_открыт and связь_с_целью and not если_тень:
        исход = "сразу"
    elif канал_открыт:
        исход = "с задержкой"
    else:
        исход = "не сейчас"

    return {
        "исход": исход,
        "хозяин_асцендента": хоз1,
        "хозяин_цели": хозMC,
        "канал_открыт": канал_открыт,
        "почему_канал": почему_канал,
        "связь_с_целью": связь_с_целью,
        "тень_на_векторе": если_тень,
    }


# ─────────────────────────────────────────────────────────────────────────────
# СБОРКА ЯДРА
# ─────────────────────────────────────────────────────────────────────────────
def собрать_ядро(точки: dict, куспиды: list, аспекты: list) -> dict:
    """Кармический узор → ядро дня.

    Веса не выбирают одну точку из четырёх: они показывают РАССТАНОВКУ СИЛ —
    где карт-бланш, где тень, что перевешивает. Основа строки — всегда вектор
    узлов; ведущая точка добавляет окраску.
    """
    прочтённые = {и: прочесть_точку(и, точки, куспиды, аспекты) for и in КАРМИКА}
    прочтённые = {и: п for и, п in прочтённые.items() if п}

    веса = {и: вес(п, ВЕКТОР) for и, п in прочтённые.items()}

    соблазн = прочтённые.get(СОБЛАЗН)
    тень = тень_на_векторе(соблазн)

    # ведущая — среди трёх окрашивающих: узлы основа, они не соперник
    окраска = [и for и in (БОЛЬ, ОПОРА, СОБЛАЗН) if и in прочтённые]
    ведущая = max(окраска, key=lambda и: веса[и]["очки"]) if окраска else None

    расстановка = []
    опора = прочтённые.get(ОПОРА)
    if опора and опора.get("на_угле"):
        расстановка.append({
            "что": "карт-бланш",
            "точка": ОПОРА,
            "почему": f"благодать на угле {опора['на_угле']['угол']} "
                      f"({опора['на_угле']['орбис']}°) — поддержка стоит на самой точке дня",
        })
    if тень:
        расстановка.append({
            "что": "тень на векторе",
            "точка": СОБЛАЗН,
            "почему": "соблазн идёт по самой линии пути: не тормозит, а подменяет",
        })
    боль = прочтённые.get(БОЛЬ)
    if боль:
        расстановка.append({
            "что": "цена движения",
            "точка": БОЛЬ,
            "почему": боль["код"]["суть"][:120],
        })

    return {
        "вектор": {
            "откуда": прочтённые.get(ВЕКТОР[0]),
            "куда": прочтённые.get(ВЕКТОР[1]),
        },
        "боль": боль,
        "опора": опора,
        "соблазн": соблазн,
        "веса": веса,
        "ведущая": ведущая,
        "почему_ведущая": веса[ведущая]["почему"] if ведущая else [],
        "расстановка_сил": расстановка,
        "тень_на_векторе": тень,
        "схождение_целей": схождение_целей(точки, куспиды),
        "реализация": реализация(точки, куспиды, аспекты, тень),
        # строка ядра собирается на слое слов: вектор узлов + окраска ведущей.
        # Строка называет ДВИЖЕНИЕ, а не состояние.
        "строка": None,
    }
