def _яз(lang):
    return ЯЗЫК.get((lang or "ru").lower()[:2], ЯЗЫК["ru"])


def время_суток(час: int) -> str:
    if час < 5:
        return "ночь"
    if час < 12:
        return "утро"
    if час < 17:
        return "день"
    if час < 22:
        return "вечер"
    return "ночь"


def часы_домов(куспиды, момент, широта, долгота, пояс):
    """Окно каждого дома: когда бегущий асцендент входит на его куспид и когда
    выходит на следующий. Начинается с дома 1 — он идёт прямо сейчас."""
    окна = {}
    т = момент
    for дом in range(1, 13):
        нач = момент if дом == 1 else Р.когда_градус_на_угле(
            куспиды[дом - 1], т, широта, долгота, "АС")
        if not нач:
            break
        кон = Р.когда_градус_на_угле(куспиды[дом % 12], нач + timedelta(minutes=3),
                                     широта, долгота, "АС")
        if not кон:
            break
        окна[дом] = (нач, кон)
        т = кон - timedelta(minutes=3)
    return окна


def _мест(т, пояс):
    return т + timedelta(hours=пояс)


def _окно_словами(о, пояс, сегодня, lang="ru"):
    я = _яз(lang)
    a, b = _мест(о[0], пояс), _мест(о[1], пояс)
    завтра = я["уже_завтра"] if a.date() > сегодня else ""
    return f"{a.strftime('%H:%M')}–{b.strftime('%H:%M')}{завтра} · {я['время_суток'][время_суток(a.hour)]}"


def _суть(к):
    с = (к or {}).get("суть", "")
    if "Суть:" in с:
        с = с.split("Суть:", 1)[1]
    return с.strip().rstrip(".")


