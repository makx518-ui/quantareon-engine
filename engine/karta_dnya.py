def собрать_карту(момент, широта, долгота, пояс, место="", мухурта="", ичзин="", имя="гость",
                  этап=None, lang="ru", режим="полный", контекст=None):
    """Читает карту дня и собирает готовый файл; кухня и карта ложатся в архив
    одной записью. Возвращает {"fayl": ключ, "html": ..., "tekst": ...}."""
    from engine import karta_html, arhiv
    я = _яз(lang)
    if имя == "гость":
        имя = я["гость"]
    д = прочитать_день(момент, широта, долгота, пояс, имя=имя, место=место, этап=этап, lang=lang, режим=режим,
                       контекст=контекст)
    (этап or (lambda т: None))("собираю карту")
    мест = д["местное"]
    разделы = [(я["слово"], я["шапка"].format(дата=мест.strftime("%d.%m.%Y")))]
    _рез = {"РЕЗЮМЕ": "РЕЗЮМЕ ДНЯ", "SUMMARY": "SUMMARY OF THE DAY"}   # 16.09 · полный разбор
    разделы += [(я["итог_дня"] if з.strip().upper() == я["заголовки"][3] else _рез.get(з.strip().upper(), з), т)
                for з, т in д["razdely"] if з != я["часы_дня"] and т.strip()]
    if мухурта:
        разделы.append((я["деньги"], мухурта))
    if ичзин:
        разделы.append((я["символ"], ичзин))
    html = karta_html.карта_клиенту(
        разделы, имя, заказ="karta_dnya",
        # его решение 14.09: город в подписи карты не показываем — «гость · дата, время»
        данные_рождения={"дата": мест.strftime("%d.%m.%Y"), "время": мест.strftime("%H:%M"),
                         "место": ""},
        момент=д["момент"], пояс_часов=пояс, lang=lang)
    # архив: кухня (полочка целиком) и карта — одним моментом, как у остальных заказов
    ключ_карты = ""
    try:
        arhiv.положить_кухню(
            имя_клиента=имя, заказ="karta_dnya",
            итог={"время_известно": True, "слой1": д["полка"],
                  "слой2": "мухурта: " + мухурта + "\nИ-Цзин: " + ичзин},
            данные_рождения={"дата": мест.strftime("%d.%m.%Y"), "время": мест.strftime("%H:%M:%S"),
                             "место": место, "гмт": пояс, "широта": широта, "долгота": долгота},
            пояс_часов=пояс, момент=д["момент"])
        ключ_карты = arhiv.положить_карту(имя, "karta_dnya", html, момент=д["момент"], пояс_часов=пояс)
    except Exception as e:
        print("карта дня: архив не лёг:", e)
    # 14.09 (вечер) · его решение: карта целиком встаёт под колесом на главной,
    # в своём оформлении. Шапка «Слово Квантареона» на странице уже стоит над
    # картой, поэтому карта для страницы идёт без неё — иначе дубль.
    # В архивной копии шапка остаётся: там страницы нет.
    html_stranicy = karta_html.карта_клиенту(
        разделы[1:], имя, заказ="karta_dnya",
        # его решение 14.09: город в подписи карты не показываем — «гость · дата, время»
        данные_рождения={"дата": мест.strftime("%d.%m.%Y"), "время": мест.strftime("%H:%M"),
                         "место": ""},
        момент=д["момент"], пояс_часов=пояс, lang=lang)
    return {"fayl": ключ_карты, "html": html, "html_stranicy": html_stranicy,
            "tekst": д["tekst"], "razdely": разделы[1:], "асц": асц_дня(д), "местное": мест,
            "imya_fayla": f"{я['имя_файла']} · {мест.strftime('%d.%m.%Y')}.html"}
