def _шапки(lang="ru"):
    """Регэкспы заголовков сценария и того, что идёт после него, — по языку."""
    import re
    з = _яз(lang)["заголовки"]
    заг = r"(?:#+\s*|\*\*\s*)?" + re.escape(з[1]) + r"(?:\s*\*\*)?\s*\n"
    конец = r"(?=\n(?:#+\s*|\*\*\s*)?(?:" + re.escape(з[2]) + "|" + re.escape(з[3]) + r")|\Z)"
    return заг, конец


def _коротко(текст, lang="ru"):
    """Признак сжатого ответа: мало знаков или сценарий не разбит на четыре абзаца.
    Заголовок может быть «## СЦЕНАРИЙ ДНЯ», «**СЦЕНАРИЙ ДНЯ**» или голой строкой;
    абзацы — через пустую строку или через один перенос."""
    import re
    if len(текст) < 3200:
        return True
    заг, конец = _шапки(lang)
    м = re.search(r"(?is)" + заг + r"(.*?)" + конец, текст)
    if not м:
        return len(текст) < 3500   # заголовка нет — судим только по объёму
    тело = м.group(1)
    абзацы = [а for а in re.split(r"\n\s*\n", тело) if len(а.strip()) > 80]
    if len(абзацы) < 4:   # разделили одним переносом
        абзацы = [а for а in тело.split("\n") if len(а.strip()) > 200]
    return len(абзацы) < 4


