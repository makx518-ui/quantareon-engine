def _мест(т, пояс):
    return т + timedelta(hours=пояс)


def _окно_словами(о, пояс, сегодня):
    a, b = _мест(о[0], пояс), _мест(о[1], пояс)
    завтра = " (уже завтра)" if a.date() > сегодня else ""
    return f"{a.strftime('%H:%M')}–{b.strftime('%H:%M')}{завтра} · {время_суток(a.hour)}"


def _суть(к):
    с = (к or {}).get("суть", "")
    if "Суть:" in с:
        с = с.split("Суть:", 1)[1]
    return с.strip().rstrip(".")


