def часы_текстом(окна, пояс, сегодня, lang="ru"):
    """Блок часов от машины: четыре угла и все двенадцать домов словами."""
    я = _яз(lang)
    сферы = я["сферы"] or СФЕРА_ДОМА
    строки = []
    for имя_у, дом, роль in УГЛЫ:
        о = окна.get(дом)
        if о:
            имя_я, роль_я = я["углы"][имя_у] if lang != "ru" else (имя_у, роль.split(':')[0])
            строки.append(f"{имя_я} — {роль_я}: {_окно_словами(о, пояс, сегодня, lang)}")
    строки.append("")
    for дом in range(1, 13):
        о = окна.get(дом)
        if о:
            строки.append(f"{_окно_словами(о, пояс, сегодня, lang)} — {сферы[дом]}")
    return "\n".join(строки)


