def фаза_по_углу(угол):
    """Имя фазы и её смысл по углу Луна–Солнце."""
    for i in range(len(ФАЗЫ) - 1, -1, -1):
        if угол >= ФАЗЫ[i][0]:
            return {"угол": round(угол, 2), "имя": ФАЗЫ[i][1], "смысл": ФАЗЫ[i][2]}
    return {"угол": round(угол, 2), "имя": ФАЗЫ[0][1], "смысл": ФАЗЫ[0][2]}


def _угол(jd):
    с = swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]
    л = swe.calc_ut(jd, swe.MOON, swe.FLG_SWIEPH | swe.FLG_SPEED)[0][0]
    return (л - с) % 360


def лунный_день(момент):
    """Сколько дней прошло от последнего новолуния — лунный день 1..30."""
    j = swe.julday(момент.year, момент.month, момент.day,
                   момент.hour + момент.minute / 60)
    # ищем последнее новолуние
    низ, верх = j - 30, j
    for _ in range(50):
        с = (низ + верх) / 2
        if _угол(с) > 180 or _угол(с) < 0.001:
            низ = с
        else:
            верх = с
    # уточняем поиском минимума угла
    т = j - 30
    последнее = None
    while т < j:
        if _угол(т) > _угол(т + 0.5) and _угол(т + 0.5) < 20:
            a, b = т, т + 1
            for _ in range(30):
                m1 = a + (b - a) / 3
                m2 = b - (b - a) / 3
                if _угол(m1) % 360 > _угол(m2) % 360:
                    a = m1
                else:
                    b = m2
            последнее = (a + b) / 2
        т += 0.5
    if последнее is None:
        return None
    дней = j - последнее
    return {"день": int(дней) + 1, "от_новолуния_суток": round(дней, 2)}


def лунации(с_даты, по_дату, космо=None, орбис=3.0):
    """Все новолуния и полнолуния за срок, с касаниями точек карты."""
    найдено = []
    j0 = swe.julday(с_даты.year, с_даты.month, с_даты.day, 0)
    j1 = swe.julday(по_дату.year, по_дату.month, по_дату.day, 0)
    j = j0
    пред = _угол(j)
    while j < j1:
        j2 = j + 0.5
        у = _угол(j2)
        for цель, вид in ((0, "НОВОЛУНИЕ"), (180, "ПОЛНОЛУНИЕ")):
            пересекли = (пред < цель <= у) or (цель == 0 and пред > 300 and у < 60)
            if пересекли:
                a, b = j, j2
                for _ in range(40):
                    m = (a + b) / 2
                    d = _угол(m)
                    если = (d - цель) % 360
                    if если > 180:
                        если -= 360
                    if если < 0:
                        a = m
                    else:
                        b = m
                jм = (a + b) / 2
                г, мес, дн, ч = swe.revjul(jм)
                когда = datetime(г, мес, дн) + timedelta(hours=ч)
                солнце = swe.calc_ut(jм, swe.SUN, swe.FLG_SWIEPH)[0][0]
                луна = swe.calc_ut(jм, swe.MOON, swe.FLG_SWIEPH)[0][0]
                запись = {
                    "вид": вид, "когда": когда.replace(tzinfo=timezone.utc),
                    "солнце": солнце, "луна": луна,
                    "код_солнца": kod360.code_by_abs(солнце),
                    "код_луны": kod360.code_by_abs(луна),
                    "касания": [],
                }
                if космо:
                    for имя, т in космо.items():
                        for точка, подпись in ((солнце, "Солнцем"), (луна, "Луной")):
                            d = K.дуга(точка, т["градус"])
                            if d <= орбис:
                                запись["касания"].append(
                                    {"точка": имя, "чем": подпись,
                                     "орбис": round(d, 2), "код": т["код"]["тег"]})
                    запись["касания"].sort(key=lambda x: x["орбис"])
                найдено.append(запись)
        пред = у
        j = j2
    return найдено


def затмения(с_даты, по_дату, космо=None, орбис=3.0):
    """Солнечные и лунные затмения за срок — движок находит их сам."""
    найдено = []
    j = swe.julday(с_даты.year, с_даты.month, с_даты.day, 0)
    предел = swe.julday(по_дату.year, по_дату.month, по_дату.day, 0)
    # солнечные
    т = j
    while т < предел:
        try:
            рез = swe.sol_eclipse_when_glob(т)
            jе = рез[1][0]
        except Exception:
            break
        if jе > предел:
            break
        найдено.append(_запись_затмения(jе, "СОЛНЕЧНОЕ", рез[0], космо, орбис))
        т = jе + 1
    # лунные
    т = j
    while т < предел:
        try:
            рез = swe.lun_eclipse_when(т)
            jе = рез[1][0]
        except Exception:
            break
        if jе > предел:
            break
        найдено.append(_запись_затмения(jе, "ЛУННОЕ", рез[0], космо, орбис))
        т = jе + 1
    найдено.sort(key=lambda x: x["когда"])
    return найдено


def _запись_затмения(jе, вид, флаги, космо, орбис):
    г, мес, дн, ч = swe.revjul(jе)
    когда = (datetime(г, мес, дн) + timedelta(hours=ч)).replace(tzinfo=timezone.utc)
    солнце = swe.calc_ut(jе, swe.SUN, swe.FLG_SWIEPH)[0][0]
    луна = swe.calc_ut(jе, swe.MOON, swe.FLG_SWIEPH)[0][0]
    полное = bool(флаги & (swe.ECL_TOTAL | swe.ECL_ANNULAR))
    запись = {"вид": вид, "полное": полное, "когда": когда,
              "солнце": солнце, "луна": луна,
              "код_солнца": kod360.code_by_abs(солнце),
              "код_луны": kod360.code_by_abs(луна), "касания": []}
    if космо:
        for имя, т in космо.items():
            for точка, подпись in ((солнце, "Солнцем"), (луна, "Луной")):
                d = K.дуга(точка, т["градус"])
                if d <= орбис:
                    запись["касания"].append(
                        {"точка": имя, "чем": подпись, "орбис": round(d, 2),
                         "код": т["код"]["тег"]})
        запись["касания"].sort(key=lambda x: x["орбис"])
    return запись


def лунарная_сетка_текстом(момент, космо, вперёд_дней=180, назад_дней=30):
    """Раскладка: лунный день, ближайшие лунации и затмения с касаниями."""
    с = момент - timedelta(days=назад_дней)
    по = момент + timedelta(days=вперёд_дней)
    л = ["", "╔══ ЛУНАРНАЯ СЕТКА ══",
         "  Новолуния, полнолуния и затмения — где они падают на карту.", ""]
    лд = лунный_день(момент)
    if лд:
        л.append(f"  лунный день сейчас: {лд['день']}-й "
                 f"(от новолуния {лд['от_новолуния_суток']} суток)")
    ф = фаза_по_углу(_угол(swe.julday(момент.year, момент.month, момент.day,
                                      момент.hour + момент.minute / 60)))
    л += [f"  фаза сейчас: {ф['имя']} (угол {ф['угол']}°) — {ф['смысл']}", ""]

    лун = лунации(с, по, космо)
    задели = [x for x in лун if x["касания"]]
    л.append(f"  ЛУНАЦИЙ за срок: {len(лун)}, из них задевают карту: {len(задели)}")
    for x in лун:
        метка = "  ⚑" if x["касания"] else "   "
        л.append(f"{метка} {x['когда'].strftime('%d.%m.%Y')} · {x['вид']} · "
                 f"{K.градус_словами(x['солнце'])} [{x['код_солнца']['tag']}]")
        for к in x["касания"][:3]:
            л.append(f"        задевает {K.имя_точки(к['точка'])} {к['чем']} "
                     f"({к['орбис']}°) [{к['код']}]")
    зат = затмения(с, по, космо)
    if зат:
        л += ["", f"  ЗАТМЕНИЙ за срок: {len(зат)}"]
        for x in зат:
            вид = f"{x['вид']}{' ПОЛНОЕ' if x['полное'] else ''}"
            л.append(f"     {x['когда'].strftime('%d.%m.%Y')} · {вид} · "
                     f"{K.градус_словами(x['солнце'])} [{x['код_солнца']['tag']}]")
            for к in x["касания"][:3]:
                л.append(f"        ⚑ задевает {K.имя_точки(к['точка'])} {к['чем']} "
                         f"({к['орбис']}°) [{к['код']}]")
    л += ["", "  ▸ РЕЗЮМЕ: затмение и лунация, попавшие на точку карты, "
          "открывают тему этой точки.", ""]
    return л
