def луна_не_в_том_доме(текст, р, с_порядком=False):
    """24.09 · его месяц: «8 октября. Луна проходит по девятому дому, затем переходит в двенадцатый» —
    а в тот день Луна шла по одиннадцатому. Проверка по абзацу дня («**8 октября.** …»): каждый дом,
    названный рядом с транзитной Луной, должен быть среди домов, по которым Луна идёт в это число.
    Не сошлось — подсказка: где Луна в этот день и с какого часа."""
    import re
    отрезки, пояс = р.get("луна_по_домам") or [], р["пояс"]
    if not отрезки:
        return []
    мест0 = _мест(р["момент"], пояс)
    все_имена = "|".join(_ДАТ.values())
    итог = []
    for а in текст.split("\n"):
        м = re.match(r"\s*\*\*(\d{1,2}) ([а-яё]+)\.\*\*", а)
        if not м or м.group(2) not in _МЕС:
            continue
        мес = _МЕС.index(м.group(2)) + 1
        год = мест0.year + (1 if мес < мест0.month else 0)
        try:
            нач = мест0.replace(year=год, month=мес, day=int(м.group(1)), hour=0, minute=0, second=0, microsecond=0)
        except ValueError:
            continue
        a = (нач - timedelta(hours=пояс)).replace(tzinfo=timezone.utc)
        b = a + timedelta(days=1)
        дни = [(дом, x, y) for дом, x, y in отрезки if x < b and y > a]
        верные = {дом for дом, _, _ in дни}
        if not верные:
            continue
        подсказка = "Луна в этот день — " + "; затем ".join(
            f"{в_доме(дом)}" + (f" с {_мест(x, пояс).strftime('%H:%M')}" if x > a else "") for дом, x, _ in дни)
        for предл in re.findall(r"[^.!?\n]*[.!?]", а):
            # только сама Луна («Луна», «Луны», «Луне»…), не «лунный день» и не «лунация»
            for мл in re.finditer(r"Лун(?:а|ы|е|у|ой|ою)\b", предл):
                до = предл[max(0, мл.start() - 25):мл.start()]
                после = предл[мл.end():мл.end() + 20]
                if (re.search(r"\b(?:к|ко|с|со)\s+(?:[а-яё]+\s+){0,2}$", до) or re.search(r"(?:Ч[её]рн|Бел)[а-яё]*\s+$", до)
                        or re.match(r"\s+(?:твоей\s+)?карты", после) or re.search(r"натальн[а-яё]*\s+$", до, re.I)):
                    continue   # Луна карты, Чёрная и Белая Луна — не транзитная Луна дня
                хвост = предл[мл.end():мл.end() + 140]
                стоп = re.search(r"(?:" + все_имена + r"|дн[оаеу] неба|десцендент)[а-яё]*", хвост)
                if стоп:
                    хвост = хвост[:стоп.start()]
                for д in re.finditer(r"([а-яё]+)\s+дом", хвост):
                    н = _номер_слова(д.group(1))
                    if н and 1 <= н <= 12 and н not in верные:
                        # «** » от жирной даты не отдаём в правку: иначе модель может сломать жирный
                        чистое = предл.strip().lstrip("*").strip()
                        итог.append((чистое, д.group(0), подсказка)
                                    + ((мл.end() - предл.find(чистое), [дом for дом, _, _ in дни], м.group(0).strip())
                                       if с_порядком else ()))
                        break
    return итог


def луна_дом_машиной(текст, р):
    """24.09 · его месяц после правки: «8 октября. До 19:29 Луна находится в девятом доме, … переходит
    в двенадцатый» и «14 октября. До 19:05 Луна идёт по третьему дому, … в четвёртый» — модель правку
    не приняла. Если в предложении названо ровно столько домов Луны, сколько она проходит в это число,
    машина ставит верные номера по порядку, в том же падеже. Иначе не трогает."""
    import re
    все_имена = "|".join(_ДАТ.values())
    падеж = {"дом": "им", "доме": "пр", "дому": "да", "домом": "тв", "дома": "род"}
    def _слово(н, п):
        if п == "род":
            return _ОСНОВЫ[н - 1] + ("ьего" if н == 3 else "ого")
        return дом_словом(н, п)
    правок = 0
    for предл, _, _, откуда, порядок, дата in луна_не_в_том_доме(текст, р, с_порядком=True):
        хвост = предл[откуда:откуда + 140]   # тот же хвост, что смотрит проверка
        стоп = re.search(r"(?:" + все_имена + r"|дн[оаеу] неба|десцендент)[а-яё]*", хвост)
        if стоп:
            хвост = хвост[:стоп.start()]
        # только дом, куда/по которому/в котором идёт Луна: «в девятом доме», «по третьему дому»,
        # «из третьего дома»; «тему пятого дома», «куспида пятого дома» — не её дом, не трогаем
        названы = [(м, _номер_слова(м.group(2))) for м in
                   re.finditer(r"\b(в|во|по|из)\s+([а-яё]+)\s+(дом(?:ом|е|у|а)?)\b", хвост, re.I)]
        названы = [(м, н) for м, н in названы if н and 1 <= н <= 12]
        if len(названы) != len(порядок) or [н for _, н in названы] == порядок:
            continue
        if any(м.group(1).lower() == "из" for м, _ in названы[1:]):
            continue   # «в одиннадцатый из девятого» — порядок слов обратный ходу Луны, не угадываем
        новый = хвост
        for (м, _), верный in reversed(list(zip(названы, порядок))):
            слово = _слово(верный, падеж[м.group(3).lower()])
            пред = м.group(1)
            if пред.lower() in ("в", "во"):   # «во втором», но «в одиннадцатом»
                пред = пред[0] + ("о" if слово.startswith("втор") else "")
            if м.group(2)[0].isupper():
                слово = слово.capitalize()
            новый = новый[:м.start()] + пред + " " + слово + " " + м.group(3) + новый[м.end():]
        стало = предл[:откуда] + новый + предл[откуда + len(хвост):]
        # правим в абзаце этого числа, а не первое такое же предложение в тексте
        строки = текст.split("\n")
        for i, стр in enumerate(строки):
            if стр.lstrip().startswith(дата) and предл in стр:
                строки[i] = стр.replace(предл, стало, 1)
                текст = "\n".join(строки)
                правок += 1
                print(f"срок: дом Луны поставлен машиной — {стало[:90]}")
                break
    return текст, правок


# 24.09 · его месяц: «асценденту месяца в двенадцатом градусе Льва» (асцендент в Весах), «к Марсу десятого
# дома в двадцать восьмом градусе Весов» (Марс карты в Раке). Модель приписала градус не той точке.
# Машина знает градус каждой точки: у точки карты он один, у транзитной — путь за день или за срок.
_ПОРЯДК_ОСН = ("перв", "втор", "трет", "четвёрт", "пят", "шест", "седьм", "восьм", "девят", "десят",
               "одиннадцат", "двенадцат", "тринадцат", "четырнадцат", "пятнадцат", "шестнадцат", "семнадцат",
               "восемнадцат", "девятнадцат", "двадцат")
_ПОРЯДК_ОК = {"им": ("ый", "ой", "ий"), "пр": ("ом", "ом", "ьем"), "род": ("ого", "ого", "ьего"),
              "да": ("ому", "ому", "ьему"), "тв": ("ым", "ым", "ьим")}
_ГРАДУС_ПАДЕЖ = {"градус": "им", "градусе": "пр", "градуса": "род", "градусу": "да", "градусом": "тв"}


def _порядковое(н, падеж):
    """12 → «двенадцатом» (пр), 28 → «двадцать восьмом», 30 → «тридцатом»."""
    if н == 30:
        return "тридцат" + _ПОРЯДК_ОК[падеж][0]
    if 20 < н < 30:
        return "двадцать " + _порядковое(н - 20, падеж)
    осн = _ПОРЯДК_ОСН[н - 1]
    вид = 1 if осн in ("втор", "шест", "седьм", "восьм") else 2 if осн == "трет" else 0
    ок = _ПОРЯДК_ОК[падеж][вид]
    if вид == 1 and падеж != "им":
        ок = _ПОРЯДК_ОК[падеж][0]
    return осн + ок


def _гр_знак(долгота):
    т = K.точка("x", долгота % 360)
    return т["номер_градуса"], _ЗНАК_РОД[т["знак"]]


_ВЛАДЕЛЬЦЫ = (   # (образец имени в тексте, точка)
    (r"Ч[её]рн\w* Лун\w*", "Лилит"), (r"Бел\w* Лун\w*", "Селена"),
    (r"Северн\w* узл?\w*", "Сев.Узел"), (r"Южн\w* узл?\w*", "Юж.Узел"),
    (r"\bСолнц\w*", "Солнце"), (r"\bЛун(?:а|ы|е|у|ой|ою)\b", "Луна"), (r"\bМеркури\w*", "Меркурий"),
    (r"\bВенер\w*", "Венера"), (r"\bМарс\w*", "Марс"), (r"\bЮпитер\w*", "Юпитер"), (r"\bСатурн\w*", "Сатурн"),
    (r"\bУран\w*", "Уран"), (r"\bНептун\w*", "Нептун"), (r"\bПлутон\w*", "Плутон"), (r"\bХирон\w*", "Хирон"),
    (r"[Аа]сцендент\w*(?:\s+(?:этого\s+|того\s+|же\s+)?дня)?", "Асцендент"), (r"[Сс]ередин\w* неба", "MC"),
    (r"[Дд]н[оаеу]м? неба", "IC"), (r"[Дд]есцендент\w*", "DSC"), (r"(?:[Пп]олнолуни|[Нн]оволуни|[Лл]унаци|[Зз]атмени)\w*", "лунация"),
    (r"(?:[Гг]раниц|[Кк]успид|[Нн]ачал)\w*\s+(?:[а-яё]+\s+)?дом\w*", "дом"))   # градус границы дома — не проверяем


def градус_не_той_точки(текст, р):
    """Каждый «N-й градус Знака» в тексте сверяется с точкой, названной перед ним в том же предложении.
    Возвращает (предложение, как было, как надо или None, подсказка, дата абзаца или "")."""
    import re
    точки, куспиды, пояс = р["точки"], р["куспиды"], р["пояс"]
    начало, конец = р["момент"], р["конец"]
    мест0 = _мест(р["момент"], пояс)

    def карта(имя):
        if имя == "Асцендент":
            return куспиды[0]
        if имя in ("MC", "IC"):
            return куспиды[9] + (180 if имя == "IC" else 0)
        if имя == "DSC":
            return куспиды[0] + 180
        return точки[имя]["градус"] if имя in точки else None

    def путь(имя, a, b, шаг=timedelta(hours=1)):
        if имя == "Юж.Узел":
            return {_гр_знак(_где("Сев.Узел", t) + 180) for t in _моменты(a, b, шаг)}
        if имя not in ПЛАНЕТЫ:
            return set()
        return {_гр_знак(_где(имя, t)) for t in _моменты(a, b, шаг)}

    def _моменты(a, b, шаг):
        t = a
        while t < b:
            yield t
            t += шаг
        yield b

    срок_пути = {}
    лунации = {вид: {_гр_знак(л["луна"]) for л in р.get("лунации", []) if л["вид"].lower().startswith(вид)}
               for вид in ("новолуни", "полнолуни")}
    лунации[""] = лунации["новолуни"] | лунации["полнолуни"]
    итог = []
    def _сутки(число, месяц):
        """Начало и конец этого числа в пределах срока; None — не число срока."""
        if месяц not in _МЕС:
            return None, None
        мес = _МЕС.index(месяц) + 1
        год = мест0.year + (1 if мес < мест0.month else 0)
        try:
            нач = мест0.replace(year=год, month=мес, day=int(число), hour=0, minute=0, second=0, microsecond=0)
        except ValueError:
            return None, None
        x = (нач - timedelta(hours=пояс)).replace(tzinfo=timezone.utc)
        x, y = max(x, начало), min(x + timedelta(days=1), конец)
        return (x, y) if x < y else (None, None)

    for а in текст.split("\n"):
        м = re.match(r"\s*\*\*(\d{1,2}) ([а-яё]+)\.\*\*", а)
        a0 = b0 = None
        дата = ""
        if м:
            a0, b0 = _сутки(м.group(1), м.group(2))
            if a0:
                дата = м.group(0).strip()
        for предл in re.findall(r"[^.!?\n]*[.!?]", а):
            for мг in re.finditer(_ГРАДУС_В_ТЕКСТЕ, предл):
                н, з = _номер_слова(мг.group(1)), мг.group(2)
                if н is None or not 1 <= н <= 30:
                    continue
                # «в тридцатых градусах Рака и Овна», «в первом градусе Скорпиона и Рыб» — два конца сразу, не трогаем
                if (not re.fullmatch(r"градус(?:е|а|у|ом)?", re.search(r"градус[а-яё]*", мг.group(0)).group(0).lower())
                        or re.match(r"\s+и\s+(?:" + _ЗНАКИ_Р + r")", предл[мг.end():])):
                    continue
                # число, названное в самом предложении («в 13:31 5 октября»), главнее числа абзаца
                a, b = a0, b0
                своё = list(re.finditer(r"\b(\d{1,2}) (" + "|".join(_МЕС) + r")\b", предл[:мг.start()]))
                if своё:
                    a, b = _сутки(своё[-1].group(1), своё[-1].group(2))
                до = предл[max(0, мг.start() - 120):мг.start()]
                последний = None
                for образец, имя in _ВЛАДЕЛЬЦЫ:
                    for мв in re.finditer(образец, до):
                        if not последний or мв.start() > последний[0].start() or (
                                мв.start() == последний[0].start() and мв.end() > последний[0].end()):
                            последний = (мв, имя)
                if not последний:
                    continue
                мв, имя = последний
                if имя == "дом":
                    continue
                if имя == "Луна" and re.search(r"(?:Ч[её]рн|Бел)\w*\s+$", до[:мв.start()]):
                    continue
                if имя == "лунация":   # новолуние — градус новолуния, полнолуние — полнолуния
                    вид = next((в for в in ("новолуни", "полнолуни") if мв.group(0).lower().startswith(в)), "")
                    верные = лунации[вид]
                    if a is not None:   # в абзаце дня — лунация этого числа
                        этого = {_гр_знак(л["луна"]) for л in р.get("лунации", []) if a <= л["когда"] < b
                                 and л["вид"].lower().startswith(вид)}
                        верные = этого or верные
                    if верные and (н, з) not in верные:
                        п_ = _правка(предл, мг, н, з, верные)
                        итог.append(п_[:4] + (дата, п_[4]))
                    continue
                перед = до[max(0, мв.start() - 25):мв.start()]
                после = до[мв.end():мв.end() + 25]
                if имя == "Асцендент" and "дня" in мв.group(0):
                    дни = [д for д in р["дни_асц"] if (a is None or a <= д["момент"] < b)] or р["дни_асц"]
                    верные = {(д["номер"], _ЗНАК_РОД[д["знак"]]) for д in дни}
                else:
                    карт = карта(имя)
                    верные = {_гр_знак(карт)} if карт is not None else set()
                    своя_карта = (имя in ("Асцендент", "MC", "IC", "DSC", "Лилит", "Селена")
                                  or re.search(r"\b(?:к|ко|с|со)\s+$", перед) or re.search(r"натальн\w*\s+$", перед, re.I)
                                  or re.match(r"\s+(?:твоей\s+)?(?:карты|корня)", после))
                    транзит = re.search(r"транзитн\w*\s+$", перед, re.I)
                    if not своя_карта or транзит:
                        if a is not None:
                            час = [ч for ч in re.finditer(r"\b(\d{1,2}):(\d{2})\b", предл[:мг.start()])
                                   if int(ч.group(1)) < 24 and int(ч.group(2)) < 60]
                            час = час[-1] if час else None
                            if час:
                                м_ = _мест(a, пояс).replace(hour=int(час.group(1)), minute=int(час.group(2)))
                                t = (м_ - timedelta(hours=пояс)).replace(tzinfo=timezone.utc)
                                путь_дня = путь(имя, t, t + timedelta(minutes=1))
                            else:
                                путь_дня = путь(имя, a, b)
                        elif имя == "Луна":
                            continue   # транзитная Луна вне абзаца дня — за срок обходит весь круг
                        else:
                            if имя not in срок_пути:
                                срок_пути[имя] = путь(имя, начало, конец, timedelta(hours=6))
                            путь_дня = срок_пути[имя]
                        if транзит:
                            верные = путь_дня
                        else:
                            верные = верные | путь_дня
                if not верные or (н, з) in верные:
                    continue
                п_ = _правка(предл, мг, н, з, верные)
                итог.append(п_[:4] + (дата, п_[4]))
    return итог


def _правка(предл, мг, н, з, верные):
    """(предложение, как было, как надо или None, подсказка): верный один — готовая замена в том же падеже."""
    import re
    чистое = предл.strip().lstrip("*").strip()
    сдвиг = предл.find(чистое)
    if len(верные) != 1:
        return (чистое, мг.group(0), None,
                "у этой точки здесь " + " или ".join(f"{x}-й градус {y}" for x, y in sorted(верные)[:4]), мг.start() - сдвиг)
    вн, вз = next(iter(верные))
    падеж = _ГРАДУС_ПАДЕЖ.get(re.search(r"градус[а-яё]*", мг.group(0)).group(0).lower(), "пр")
    число = мг.group(1)
    новое_ч = str(вн) if число.isdigit() else _порядковое(вн, падеж)
    if число[:1].isupper():
        новое_ч = новое_ч[:1].upper() + новое_ч[1:]
    стало = новое_ч + мг.group(0)[len(число):мг.group(0).rfind(з)] + вз
    return (чистое, мг.group(0), стало, f"{вн}-й градус {вз}", мг.start() - сдвиг)


def градус_машиной(текст, р):
    """Однозначный верный градус машина ставит сама; неоднозначный — остаётся подсказкой модели.
    Все правки одного предложения — разом, с конца, по месту в предложении."""
    правки = {}
    for предл, было, стало, _, дата, где in градус_не_той_точки(текст, р):
        if стало and предл[где:где + len(было)] == было:
            правки.setdefault((дата, предл), []).append((где, было, стало))
    правок = 0
    for (дата, предл), список in правки.items():
        новое = предл
        for где, было, стало in sorted(список, reverse=True):
            новое = новое[:где] + стало + новое[где + len(было):]
        строки = текст.split("\n")
        for i, стр in enumerate(строки):
            if (not дата or стр.lstrip().startswith(дата)) and предл in стр:
                строки[i] = стр.replace(предл, новое, 1)
                текст = "\n".join(строки)
                правок += len(список)
                print(f"срок: градус поставлен машиной — " + "; ".join(f"«{б}» → «{с}»" for _, б, с in список))
                break
    return текст, правок


def падеж_градуса(текст):
    """24.09 · его месяц: «во втором доме в седьмого градусе Скорпиона». После «в» и перед «градусе» —
    порядковое всегда в предложном: «в седьмом градусе», «в двадцать восьмом градусе»."""
    import re
    def _п(м):
        слово = м.group(2)
        н = _номер_слова(слово)
        if not н or not 1 <= н <= 30:
            return м.group(0)
        # только само порядковое: «пятидесятом», «первозданном» — не наши слова
        последнее = слово.lower().split()[-1]
