def _разн(x, цель):
    """Знаковое расстояние x от цели, −180…180."""
    return (x - цель + 180) % 360 - 180


def _уточнить(ф, a, b, раз=30):
    """Момент, где ф меняет знак между a и b — делением пополам (до секунд)."""
    фa = ф(a)
    for _ in range(раз):
        m = a + (b - a) / 2
        фm = ф(m)
        if (фa < 0) == (фm < 0):
            a, фa = m, фm
        else:
            b = m
    return a + (b - a) / 2


def _шаг(имя):
    return timedelta(hours=1) if имя == "Луна" else timedelta(hours=6) if имя in БЫСТРЫЕ else timedelta(days=1)


def _пересечения(имя, цель, начало, конец, от_корня=True):
    """Все моменты, когда планета проходит через градус цель (с учётом попятного хода)."""
    шаг = _шаг(имя)
    ф = lambda т: _разн(_где(имя, т), цель)
    итог, т, пред = [], начало, ф(начало)
    while т < конец:
        т2 = min(т + шаг, конец)
        сейчас = ф(т2)
        # смена знака у нуля, а не прыжок через 180° на другой стороне круга
        if (пред < 0) != (сейчас < 0) and abs(пред - сейчас) < 90:
            к = _уточнить(ф, т, т2)
            if not от_корня or (к - начало) > timedelta(hours=1):   # сама точка корня в первую секунду — не событие
                итог.append(к)
        т, пред = т2, сейчас
    return итог


def _цели_аспекта(гц, угол):
    """Градусы, проход через которые даёт аспект. Соединение и оппозиция — один градус:
    округляем, иначе +180 и −180 расходятся в дробях и событие пишется дважды."""
    return sorted({round((гц + угол) % 360, 6), round((гц - угол) % 360, 6)})


