def _входы_в_дома(ф_градус, куспиды, начало, конец, шаг):
    """Когда стрелка переходит куспиды корня: [(момент, из_дома, в_дом)]."""
    итог, т = [], начало
    дом_пред = _дом(ф_градус(т), куспиды)
    while т < конец:
        т2 = min(т + шаг, конец)
        дом = _дом(ф_градус(т2), куспиды)
        if дом != дом_пред:
            куспид = куспиды[(дом - 1) if (дом - дом_пред) % 12 == 1 else (дом_пред - 1)]
            к = _уточнить(lambda x: _разн(ф_градус(x), куспид), т, т2)
            итог.append((к, дом_пред, дом))
        т, дом_пред = т2, дом
    return итог


def _отрезки(входы, начало, конец, дом_в_начале):
    """Входы в дома → отрезки [(дом, с, по)] на весь срок."""
    отрезки, с, дом = [], начало, дом_в_начале
    for к, _, в in входы:
        отрезки.append((дом, с, к))
        с, дом = к, в
    отрезки.append((дом, с, конец))
    return отрезки


