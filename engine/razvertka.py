    в_корне = {(ц, асп) for ц, гц in цели.items() for асп, угол in АСПЕКТЫ
               if abs(abs(_разн(г0, гц)) - угол) <= ОРБ_АС_ДНЯ}
    for n in range(дней + 1):
        т = старт + timedelta(days=n)
        г = _асц(т, широта, долгота)
        т_ = K.точка("x", г)
        касания = []
        for цель, гц in цели.items():
            for асп, угол in АСПЕКТЫ:
                if (цель, асп) in в_корне:
                    continue
                о = abs(abs(_разн(г, гц)) - угол)
                if о <= ОРБ_АС_ДНЯ:
                    касания.append((f"{асп} {цель} корня (орб {о:.1f}°)", (цель, асп), о))
        дни_асц.append({"n": n + 1, "момент": т, "градус": г, "знак": т_["знак"],
                        "номер": т_["номер_градуса"], "дом": _дом(г, куспиды),
                        "тег": (т_["код"] or {}).get("тег", ""), "касания": касания})
    if мас not in ("неделя", "месяц"):
        # на длинном сроке касание держится 2–3 дня подряд — оставляем только самый точный день
        for i, д in enumerate(дни_асц):
            д["касания"] = [к for к in д["касания"] if all(
                not (j != i and 0 <= j < len(дни_асц) and any(к2[1] == к[1] and к2[2] < к[2] for к2 in дни_асц[j]["касания"]))
                for j in (i - 1, i + 1))]
    for д in дни_асц:
        д["касания"] = [к[0] for к in д["касания"]]
    if мас in ("неделя", "месяц"):
        for д in дни_асц[:-1]:
            с.append(f"  день {д['n']} · {_когда(д['момент'], пояс, False)} · {д['номер']}-й градус {_ЗНАК_РОД[д['знак']]} "
                     f"[{д['тег']}] · {дом_словом(д['дом'])} дом корня"
                     + (" · " + "; ".join(д["касания"]) if д["касания"] else ""))
    else:
        # на длинном сроке — только смены знака (главы) и домов корня, и касания точек
        пред = None
        for д in дни_асц:
            if пред is None or д["знак"] != пред["знак"] or д["дом"] != пред["дом"] or д["касания"]:
                что = []
                if пред is None:
                    что.append("начало")
                elif д["знак"] != пред["знак"]:
                    что.append(f"новая глава — асцендент дня в знаке {д['знак']}")
                if пред is not None and д["дом"] != пред["дом"]:
                    что.append(f"вход {'во' if д['дом'] == 2 else 'в'} {дом_словом(д['дом'])} дом корня ({СФЕРА_ДОМА[д['дом']]})")
                что += д["касания"]
                с.append(f"  {_когда(д['момент'], пояс, False)} · {д['номер']}-й градус {_ЗНАК_РОД[д['знак']]} [{д['тег']}] · "
                         + "; ".join(что))
                с += три_слоя(д["градус"])
            пред = д
    с.append("")

    # ── 4. Транзиты к точкам корня
    длинный = мас in ("полгода", "год")
    # на длинном сроке Меркурий и Венера — фон (обходят круг по нескольку раз), их нет;
    # Солнце бьёт только в углы, светила и управителя АС; Марс — только напряжённые
    двигатели = (["Солнце", "Марс"] + list(МЕДЛЕННЫЕ)) if длинный else list(БЫСТРЫЕ)
    цели_солнца = {"Асцендент", "MC", "Солнце", "Луна", управитель_асц}
    события = []
    for тр in двигатели:
        for цель, гц in цели.items():
            if длинный and тр == "Солнце" and цель not in цели_солнца:
                continue
            # медленная планета на своё же место в корне — не событие: корень и есть небо
            # срока, за год она лишь пятится и возвращается на тот же градус
            if тр in МЕДЛЕННЫЕ and (цель == тр or (тр == "Сев.Узел" and цель == "Юж.Узел")):
                continue
            for асп, угол in АСПЕКТЫ:
                if длинный and тр == "Марс" and асп in ("трин", "секстиль"):
                    continue
                # 23.09 · его разбор месяца: «Венера соединяется со своим положением» — пустое событие.
                # Быстрая планета возвращается на свой градус корня только петлёй ретро (или Солнце —
                # к концу года, это и есть точка выхода): то же небо, что в секунду входа, не событие
                if асп == "соединение" and цель == тр:
                    continue
                for L in _цели_аспекта(гц, угол):
                    for к in _пересечения(тр, L, старт, конец, с_корня):
                        события.append(_событие(тр, цель, асп, к, гц, точки, куспиды, управитель_асц))
    if мас in ("неделя", "месяц"):   # Луна — только к углам корня, иначе ~90 событий в месяц
        # 23.09 · его месяц: «в 11:30 Луна переходит в четвёртый дом… в 11:30 Луна встаёт в оппозицию к
        # середине неба» — одно и то же дважды: соединение и оппозиция к углам и есть вход Луны в 1, 4, 7, 10 дом
        # (куспиды Плацидуса). Эти входы уже в строке Луны дня с пометкой угла; здесь — только квадрат.
        for цель in ("Асцендент", "MC"):
            for асп, угол in АСПЕКТЫ[2:3]:
                for L in _цели_аспекта(цели[цель], угол):
                    for к in _пересечения("Луна", L, старт, конец, с_корня):
                        события.append(_событие("Луна", цель, асп, к, цели[цель], точки, куспиды, управитель_асц))
    события.sort(key=lambda е: е["момент"])
    # 23.09 · его разбор месяца: дни без событий выходили общими словами. Для таких дней машина
    # берёт напряжённые касания Луны к точкам карты (соединение, оппозиция, квадрат) — у каждого дня
    # своё событие. В узловые дни и в вес срока они не идут: это голос дня, а не стержень.
    луна_дня = []
    if мас in ("неделя", "месяц"):
        for цель in ("Солнце", "Луна", "Меркурий", "Венера", "Марс", "Юпитер", "Сатурн", "Уран", "Нептун",
                     "Плутон", "Хирон", "Сев.Узел", "Лилит"):
            if цель not in цели:
                continue
            for асп, угол in АСПЕКТЫ:
                if цель == "Луна" and асп == "соединение":
                    continue
                for L in _цели_аспекта(цели[цель], угол):
                    for к in _пересечения("Луна", L, старт, конец, с_корня):
                        е = _событие("Луна", цель, асп, к, цели[цель], точки, куспиды, управитель_асц)
                        е["звезда"] = "☽"
                        луна_дня.append(е)
        луна_дня.sort(key=lambda е: (е["момент"]))
    порог = 8
    for е in события:
        if длинный:   # на длинном сроке стержень — медленная планета; Солнце и Марс — рабочие
            е["звезда"] = "⭐" if (е["тр"] in МЕДЛЕННЫЕ and е["вес"] >= 7) else "•" if е["вес"] >= 6 else "·"
        else:
            е["звезда"] = "⭐" if е["вес"] >= порог else "•" if е["вес"] >= порог - 3 else "·"
    с.append("── 4. ТРАНЗИТЫ К ТОЧКАМ КОРНЯ (точный момент; ⭐ — стержень срока, • — рабочее, · — фон)")
    if not события:
        с.append("  (точных транзитов за срок нет)")
    for е in события:
        зв = е["звезда"]
        if длинный and зв == "·":
            continue   # на длинном сроке фон не выводим — только стержни и рабочие
        с.append(f"  {зв} {_когда(е['момент'], пояс)} · {е['тр']}{' ℞' if е['ретро'] else ''} {е['асп']} "
                 f"{е['цель']} корня · [{е['тег_тр']}] → [{е['тег_цели']}]")
        с.append(f"      ▸ {е['резюме']}")
        с.append(f"      ◆ СМЫСЛ ПО ГРАДУСАМ: {е['смысл']}")
        с += три_слоя(е["где_тр"], "      " + _транзитный(е["тр"]) + " " + е["тр"] + " · ")
        с.append(f"      цель — {е['цель']} корня [{е['тег_цели']}]: её три слоя в разделе 0")
    с.append("")

    # ── 5. Новолуния и полнолуния срока
    лун = Л.лунации(старт - timedelta(days=1), конец + timedelta(days=1), космо=точки)
    лун = [л for л in лун if старт <= л["когда"] <= конец]
    с.append("── 5. НОВОЛУНИЯ И ПОЛНОЛУНИЯ СРОКА")
    if not лун:
        с.append("  (в сроке нет)")
    for л in лун:
        гр = л["луна"]
        т_ = K.точка("x", гр)
        кас = ", ".join([f"{к['чем']} на {к['точка']} корня (орб {к['орбис']}°)"
                         for к in л["касания"] if к["точка"] in ЦЕЛИ][:3])
        с.append(f"  {_когда(л['когда'], пояс)} · {л['вид'].lower()} · Луна {т_['текст']} [{(т_['код'] or {}).get('тег', '')}] "
                 f"· {дом_словом(_дом(гр, куспиды))} дом корня ({СФЕРА_ДОМА[_дом(гр, куспиды)]})" + (f" · {кас}" if кас else ""))
        с += три_слоя(гр)
    с.append("")

    # ── 6. Узловые дни и резюме срока
    короткий = мас in ("неделя", "месяц")

    def _день_срока(м):
        """23.09 · его разбор месяца: день срока — календарное число (полночь–полночь) на любом сроке.
        Раньше неделя и месяц шли сутками от секунды входа, и «23 сентября, 01:51» читалось не той ночью."""
        return _мест(м, пояс).date()

    по_дням = {}
    for е in события:
        по_дням.setdefault(_день_срока(е["момент"]), []).append(е)
    for л in лун:
        по_дням.setdefault(_день_срока(л["когда"]), []).append({"вес": 4, "лунация": л["вид"]})
    сколько = {"неделя": 3, "месяц": 7, "полгода": 10, "год": 12}[мас]
    узловые = sorted(по_дням.items(), key=lambda кв: -sum(е["вес"] for е in кв[1]))[:сколько]
    узловые.sort(key=lambda кв: кв[0])
    с.append(f"── 6. УЗЛОВЫЕ ДНИ СРОКА (дни с наибольшим весом событий; всего {len(узловые)}"
             + ")")
    for день, ее in узловые:
        главное = sorted([е for е in ее if "тр" in е], key=lambda е: -е["вес"])[:2]
        с.append(f"  {день.strftime('%d.%m')} · вес {sum(е['вес'] for е in ее)} · "
                 + "; ".join(f"{е['тр']} {е['асп']} {е['цель']} корня" for е in главное)
                 + ("; " + "; ".join(е["лунация"].lower() for е in ее if "лунация" in е)
                    if any("лунация" in е for е in ее) else ""))
    с.append("")
    дома_срока = {}
    for е in события:
        дома_срока[е["дом_цели"]] = дома_срока.get(е["дом_цели"], 0) + е["вес"]
    главные_дома = sorted(дома_срока.items(), key=lambda кв: -кв[1])[:3]
    стержни = [е for е in события if е["звезда"] == "⭐"]
    # ── 6а. Нерв срока: машина сама выбирает два аспекта и кладёт их концы готовыми
    # 23.09 · в месяце модель собрала нерв из памяти: «квадрат Солнца первого дома 20 октября»,
    # а Солнце тогда во втором доме, и градус не тот. Теперь нерв — только отсюда.
    def _нерв(е, как):
        т_тр, т_ц = K.точка("x", е["где_тр"]), K.точка("x", точки[е["цель"]]["градус"] if е["цель"] in точки else цели[е["цель"]])
        дом_тр = _дом(е["где_тр"], куспиды)
        return [f"  {как}: {_когда(е['момент'], пояс)} · {е['тр']} {е['асп']} {е['цель']}",
                f"      один конец — {_транзитный(е['тр'])} {е['тр']}: {т_тр['номер_градуса']}-й градус {_ЗНАК_РОД[т_тр['знак']]}, "
                f"идёт по {дом_словом(дом_тр, 'да')} дому ({СФЕРА_ДОМА[дом_тр]}) — {связка_слоёв(е['где_тр'])}",
                f"      другой конец — {е['цель']} карты: {т_ц['номер_градуса']}-й градус {_ЗНАК_РОД[т_ц['знак']]}"
                + (f", {в_доме(е['дом_цели'])} ({СФЕРА_ДОМА[е['дом_цели']]})" if е["цель"] not in ("Асцендент", "MC") else "")
                + f" — {связка_слоёв(цели[е['цель']])}",
                f"      как встречаются: {е['тр']} {ПРИРОДА[е['асп']]} {е['цель']} — смысл встречи скажи своими словами, строки выше не цитируй"]
    # 23.09 · его месяц: нервом вышел «квадрат Луны к асценденту» — Луна проходит его за часы, это не нерв
    # срока. Нерв — только планеты от Солнца и дальше; Луна остаётся, лишь если других событий нет.
    кандидаты = [е for е in события if е["тр"] != "Луна"] or события
    тянет = max([е for е in кандидаты if е["асп"] in ("квадрат", "оппозиция")], key=lambda е: е["вес"], default=None)
    держит = max([е for е in кандидаты if е["асп"] in ("трин", "секстиль")], key=lambda е: е["вес"], default=None)
    с.append("── 6а. НЕРВ СРОКА (два аспекта для главы «Нерв»; градусы и дома концов — ТОЛЬКО отсюда)")
    if тянет:
        с += _нерв(тянет, "ЧТО ТЯНЕТ")
    if держит:
        с += _нерв(держит, "ЧТО ДЕРЖИТ")
    с.append("")
    # ── 7. Точка выхода: последняя секунда срока — куда сюжет приходит
    посл = дни_асц[-1]
    г_луны = _где("Луна", конец)
    г_солнца = _где("Солнце", конец)
    дом_юу, дом_су = _дом(точки["Юж.Узел"]["градус"], куспиды), _дом(точки["Сев.Узел"]["градус"], куспиды)
    с.append("── 7. ТОЧКА ВЫХОДА (последняя секунда срока — сюда приходит сквозной сценарий)")
    с.append(f'  <выход момент="{_когда(конец, пояс)}" дата_словами="{дата_словами(_мест(конец, пояс))}" />')
    с.append(f"  Асцендент дня в точке выхода: {посл['номер']}-й градус {_ЗНАК_РОД[посл['знак']]} [{посл['тег']}], "
             f"{дом_словом(посл['дом'])} дом корня ({СФЕРА_ДОМА[посл['дом']]}).")
    с += три_слоя(посл["градус"])
    с.append(f"  Луна в точке выхода: {в_доме(_дом(г_луны, куспиды))} корня "
             f"({СФЕРА_ДОМА[_дом(г_луны, куспиды)]}), в знаке {K.точка('x', г_луны)['знак']}.")
    с.append(f"  Солнце в точке выхода: {в_доме(_дом(г_солнца, куспиды))} корня "
             f"({СФЕРА_ДОМА[_дом(г_солнца, куспиды)]}).")
    if события:
        е = события[-1]
        с.append(f"  Последнее событие срока: {_когда(е['момент'], пояс)} · {е['тр']} {е['асп']} {е['цель']} корня.")
    с.append(f"  Кармический путь срока: от Южного узла ({дом_словом(дом_юу)} дом корня) к Северному узлу "
             f"({дом_словом(дом_су)} дом корня) — скажи, насколько срок продвигает личность по этому пути.")
    с.append("")
    # ── 8. Дни срока: готовая раскладка — всё, что читается в главе о днях, по суткам
    if короткий:
        узловые_даты = {д for д, _ in узловые}
        с.append("── 8. ДНИ СРОКА (готовая раскладка; день срока — число календаря, от полуночи до полуночи; "
                 "первый день — с секунды входа, последний — до секунды выхода)")
        # 23.09 · его разбор месяца: календарные дни. Границы: секунда входа, полночи, секунда выхода.
        # Дней с числами на один больше, чем суток срока (первый и последний — неполные); асцендент дня
        # стоит на ту же секунду каждого числа — дни_асц[n] ровно на n-е число.
        полночь0 = (_мест(старт, пояс) + timedelta(days=1)).replace(hour=0, minute=0, second=0, microsecond=0)
        полночь0 = (полночь0 - timedelta(hours=пояс)).replace(tzinfo=timezone.utc)
        границы = [старт] + [полночь0 + timedelta(days=i) for i in range(дней + 2)
                             if полночь0 + timedelta(days=i) < конец] + [конец]
        отрезки_дней = list(zip(границы[:-1], границы[1:]))
        # 23.09 · месяц — четыре недельных блока (7 + 7 + 7 + остаток), у каждого итог от машины
        луна_в_тексте = []
        всего = len(отрезки_дней)
        недели = ([(0, 7), (7, 14), (14, 21), (21, всего)] if мас == "месяц" and всего > 21 else [])

        def _часы(a, b):
            ча, чб = _мест(a, пояс).strftime("%H:%M"), _мест(b, пояс).strftime("%H:%M")
            return f"{ча}–{'24:00' if чб == '00:00' and b != конец else чб}"
        for n, (a, b) in enumerate(отрезки_дней):
            ключ = _мест(a, пояс).date()
            for k, (н0, н1) in enumerate(недели):
                if n == н0:
                    с.append(f"  ═══ НЕДЕЛЯ {k + 1} · {_когда(отрезки_дней[н0][0], пояс, False)} – "
                             f"{_когда(отрезки_дней[н1 - 1][0], пояс, False)} ═══")
            с.append(f"  ДЕНЬ {n + 1} · {дата_словами(_мест(a, пояс))} · {_часы(a, b)}"
                     + (" · первый день, с секунды входа" if n == 0 else "")
                     + (" · последний день, до секунды выхода" if n == всего - 1 else "")
                     + (" · УЗЛОВОЙ ДЕНЬ" if ключ in узловые_даты else ""))
            луна = [f"{в_доме(дом)} корня ({СФЕРА_ДОМА[дом]})" + (f" с {_мест(x, пояс).strftime('%H:%M')}" if x > a else "")
                    + (f" — в этот миг Луна {_УГОЛ_ДОМА[дом]}" if x > a and дом in _УГОЛ_ДОМА else "")
                    for дом, x, y in луна_по_домам if x < b and y > a]
            с.append("    Луна: " + "; затем ".join(луна))
