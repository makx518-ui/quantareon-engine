def дни_машиной(текст, р):
    """Ставит факты машины на место меток ⟦n⟧: «<фраза машины>: <смысл модели>». Дни собираются в порядке
    машины (по часам), абзац дня встаёт туда, где модель поставила первую метку этого дня, дата — в начале
    абзаца. Факт, который модель пропустила, машина ставит сама (без смысла, но на своём месте). День без
    единой метки, но с абзацем модели под его датой (модель писала по-старому) не дублируется."""
    import re
    факты, дни = р.get("факты") or {}, р.get("дни_фактов") or []
    if not факты:   # шапка, финал года: фактов дня нет — метки, если модель их переписала, просто снимаем
        return re.sub(_МЕТКА_ОСТАТОК, "", текст)
    текст = re.sub(_МЕТКА_ИНАЧЕ, lambda м: f"⟦{м.group(1)}⟧" if int(м.group(1)) in факты else м.group(0), текст)
    if not re.search(_МЕТКА, текст):
        return re.sub(_МЕТКА_ОСТАТОК, "", текст)
    день_факта = {н: i for i, (_, ид) in enumerate(дни) for н in ид}
    метка_даты = [f"**{д.day} {_МЕС[д.month - 1]}.**" for д, _ in дни]
    число_дня = {(д.day, д.month): i for i, (д, _) in enumerate(дни)}
    смыслы = {}             # номер факта → смысл модели
    место_дня = {}          # день → номер строки, где встала его первая метка
    строки = текст.split("\n")
    вывод = []              # [(день или None, текст)]
    прошлая = None          # последний факт предыдущей строки, если та была строкой с метками
    for строка in строки:
        if not re.search(_МЕТКА, строка):
            # строка сразу под строкой с метками, без пустой строки и не заголовок — продолжение смысла
            if прошлая is not None and строка.strip() and not строка.lstrip().startswith(("**", "#")):
                смыслы[прошлая] = (смыслы.get(прошлая, "") + " " + строка.strip()).strip()
                continue
            прошлая = None
            вывод.append((None, строка))
            continue
        куски = re.split(_МЕТКА, строка)
        перед = re.sub(_ДАТА_СТРОКИ, "", куски[0], count=1).strip()
        последний = None
        дни_строки = []
        for i in range(1, len(куски), 2):
            н, смысл = int(куски[i]), куски[i + 1].strip()
            if н not in факты:   # чужая метка — её смысл остаётся при соседнем
                if последний is not None:
                    смыслы[последний] = (смыслы.get(последний, "") + " " + смысл).strip()
                else:
                    перед = (перед + " " + смысл).strip()
                continue
            if н in смыслы:      # метка повторилась — дописываем к её смыслу новым предложением
                if смысл:
                    смыслы[н] = (смыслы[н] + " " + смысл[:1].upper() + смысл[1:]).strip()
            else:
                смыслы[н] = смысл
            последний = н
            д = день_факта[н]
            if д not in дни_строки:
                дни_строки.append(д)
        прошлая = последний
        итог_недели = перед.startswith("**Итог")
        if перед.endswith(":"):
            перед = перед[:-1].rstrip() + "."
        if перед and not итог_недели:
            вывод.append((None, перед))   # текст модели до меток (вход в неделю) остаётся на месте
        for д in дни_строки:
            if д not in место_дня:
                место_дня[д] = len(вывод)
                вывод.append((д, ""))     # место абзаца дня
        if перед and итог_недели:
            вывод.append((None, перед))   # итог недели — после дней
    # дни без единой метки: старый абзац модели под датой — оставляем, иначе — новое место по неделям
    def _старый_абзац(д):
        for дд, т in вывод:
            м = re.match(_ДАТА_ЖИРНАЯ, т) if дд is None else None
            if (м and т[м.end():].strip()
                    and число_дня.get((int(м.group(1)), _МЕС.index(м.group(2)) + 1)) == д):
                return True
        return False
    for д in range(len(дни)):
        if д in место_дня or not дни[д][1] or _старый_абзац(д):
            continue
        концы = sorted(р.get("концы_недель", ()))
        неделя = lambda x: sum(1 for к in концы if к < x)
        позиции = [i for i, (дд, _) in enumerate(вывод) if дд is not None]
        после = [i for i in позиции if вывод[i][0] < д]
        до = [i for i in позиции if вывод[i][0] > д]
        своя_после = [i for i in после if неделя(вывод[i][0]) == неделя(д)]
