def главы_как_надо(текст, главы):
    """23.09 · модель написала «## СЦЕНАРИИ ГОДА» — глава потеряла значок. Заголовок, похожий на
    главу из списка (опечатка, «ё», лишнее слово), машина ставит буква в букву."""
    import re, difflib
    def _п(м):
        сам = м.group(1).strip().rstrip(":").upper().replace("Ё", "Е")
        лучший = max(главы, key=lambda г: difflib.SequenceMatcher(None, сам, г.replace("Ё", "Е")).ratio())
        return "## " + лучший if difflib.SequenceMatcher(None, сам, лучший.replace("Ё", "Е")).ratio() >= 0.8 else м.group(0)
    return re.sub(r"(?m)^#{1,2} +(.+?)\s*$", _п, текст)


def служебное_прочь(текст, р):
    """23.09 · его год: в текст протекли метки раздачи «═══ НЕДЕЛЯ 1 · … ═══» и значки ⭐ ☽ ◆ ▸ ◉, а дни
    начинались с «В 13:53 Луна идёт…» — час начала суток срока, не событие. Всё это машина снимает."""
    import re
    текст = re.sub(r"(?m)^\s*═+[^\n]*═+\s*$\n?", "", текст)
    текст = re.sub(r"\s*[⭐☽◆▸◉]\s*(?=[:.,;])", "", текст)
    текст = re.sub(r" ?[⭐☽◆▸◉] ?", " ", текст)
    try:
        час = р["местное"].strftime("%H:%M")
        for ч in (час, "00:00"):   # 23.09 · дни теперь с полуночи: «в 00:00 Луна/Солнце…» — граница дня, не событие
            текст = re.sub(r"\b[Вв] " + ч + r",? ((?:Луна|Солнце)\b)", r"\1", текст)
    except Exception:
        pass
    # 23.09 · «во время Новолуния», «Асцендент дня встаёт» посреди фразы — строчными
    текст = re.sub(r"(?<=[а-яёa-z,;:—] )(Новолуни|Полнолуни|Асцендент дня)",
                   lambda м: м.group(1)[0].lower() + м.group(1)[1:], текст)
    return re.sub(r"[ \t]{2,}", " ", текст)


def часы_по_порядку(текст):
    """23.09 · его разбор месяца: в абзаце дня «в 20:57» шло после «в 21:49», «в 08:40» раньше «в 04:06».
    В абзаце дня (начинается с «**23 сентября.**») предложения, которые НАЧИНАЮТСЯ с часа
    («В 08:40 …», «Позже, в 19:14, …»), машина расставляет по часам; остальные стоят на своих местах."""
    import re
    час = re.compile(r"^(?:(?:Однако|Позже|Затем|Следом|Потом|Далее|А|И|Уже)\s*,?\s*)?[Вв] (\d{2}):(\d{2})\b")

    def _абзац(а):
        if not re.match(r"\s*\*\*\d{1,2} [а-яё]+\.\*\*", а):
            return а
        куски = re.split(r"(?<=[.!?])(\s+)", а)          # чётные — предложения, нечётные — пробелы между ними
        предл = куски[0::2]
        места = [(i, int(м.group(1)) * 60 + int(м.group(2))) for i, п in enumerate(предл) if i > 0
                 for м in [час.match(п)] if м]           # первое предложение — с датой, его не трогаем
        if len(места) < 2 or all(x[1] <= y[1] for x, y in zip(места, места[1:])):
            return а
        новые = list(предл)
        for (i, _), (j, _) in zip(места, sorted(места, key=lambda x: x[1])):
            новые[i] = предл[j]
        куски[0::2] = новые
        return "".join(куски)
    return "\n".join(_абзац(а) for а in текст.split("\n"))


