def _смысл(суть):
    """Короткий смысл из сути кода: «Изменившийся мир. Суть: реальность обновилась — …»
    → «реальность обновилась». Для связки дня — без образа, только смысл."""
    с = (суть or "").split("Суть:", 1)[-1].strip()
    for знак in (";", " — ", "."):
        с = с.split(знак)[0]
    return с.strip(" ,.")


