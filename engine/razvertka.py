def _без_повтора_факта(факт, т):
    """24.09 · его месяц: «В 02:42 Луна входит в пятый дом: Луна переходит в пятый дом, пробуждая…» — смысл
    повторил факт. Первое звено смысла, повторяющее факт (то же подлежащее и глагол факта), машина снимает:
    остаток с деепричастия пристёгивается запятой («…в пятый дом, пробуждая…»). То же подлежащее без
    повтора — заменяется местоимением («…: она погружается в тишину»). → (соединитель, смысл)."""
    import re
    # «Первый день срока…», «Последний день срока…», «Узловой день.» — вступления фразы машины, не подлежащее
    факт = re.sub(r"^(?:(?:Первый|Последний) день срока[^.]*\.\s*)?(?:Узловой день\.\s*)?", "", факт)
    м = re.match(r"(?:В \d{1,2}:\d{2} )?(?:ретроградн\w+ )?([А-ЯЁа-яё]+)", факт)
    подл = м.group(1) if м else ""
    if подл not in _ПОДЛЕЖАЩЕЕ:
        return ": ", т
    м2 = re.match(r"\s*" + подл + r"\b\s*", т, re.I)
    if not м2 or re.match(r"(?:твоей\s+)?карты\b", т[м2.end():]):
        return ": ", т   # «Луна твоей карты…» — это точка карты, не повтор транзитной Луны
    звено = re.match(r"[^,;:—]*", т[м2.end():]).group(0)
    if re.search(_ГЛАГОЛ_ФАКТА, звено):
        ост = т[м2.end() + len(звено):].lstrip(" ,;:—–-")
        if len(ост) < 12:
            return ": ", ""   # смысл целиком повторил факт — остаётся один факт
        # деепричастие, можно с наречием впереди: «пробуждая», «вновь обращая», «требуя»
        if re.match(r"(?:[а-яё]+\s+)?[а-яё]{3,}(?:ая|яя|уя|юя|ея|ия|дя|тя|зя|ся|ав|ив|ыв|ув|вшись|ясь|ась)\b", ост):
            return ", ", ост
        return ": ", ост
    return ": ", _ПОДЛЕЖАЩЕЕ[подл] + " " + т[м2.end():]


def _смысл_после_факта(т):
    """Смысл модели продолжает фразу машины после двоеточия: с маленькой буквы, с точкой в конце."""
    import re
    т = re.sub(r"^[\s:;,—–-]+", "", т.strip())
    if not т:
        return ""
    if т[:1].isupper() and not _собственное(т) and (len(т) < 2 or not т[1].isupper()):
        т = т[:1].lower() + т[1:]
    if т[-1] not in ".!?…":
        т += "."
    return т


