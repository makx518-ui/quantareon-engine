"""
sloy2.py — СЛОЙ 2 · СОЛЯР по скрипту машины от 07.09.2026 (семь частей Влада).

  1 Вводная
  2 Две карты: натал (слой 1) + КАРТА ГОДА той же машиной (kosmogramma.полочка)
    и НАКЛАДКА двух карт: углы года в натале, натальные углы в году,
    дом на дом, точки натала в домах года, точки года в домах натала, хозяева домов года
  3 Колесо жизни · кармика полностью (портреты, кармика на кармику, кармика на карту)
  4 Медленные (Плутон → Юпитер) · дирекции · прогрессии
  5 Планетарный расклад — все точки года на карту, обоими концами, ▸ РЕЗЮМЕ под каждым
  6 Динамика по году — лента, ключевые события выкладкой, месяцы
  7 Свод машины

Ничего не считает заново, кроме карты года и накладки: всё остальное —
готовые функции situacia.py, переставленные в его порядок. Под каждым
аспектом стоит строка ▸ РЕЗЮМЕ (situacia.резюме_связи).
"""
import re
from datetime import datetime, timezone, timedelta
