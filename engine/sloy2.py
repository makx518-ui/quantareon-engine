УГЛЫ_ИМЕНА = {"Асцендент": 0, "Вершина (MC)": 9, "Десцендент": 6, "Дно (IC)": 3}


def _дом(градус, куспиды):
    return K.дом_точки(градус, куспиды) if куспиды else None


def _куспиды(момент, широта, долгота):
    j = S.юлиан(момент)
    к = swe.houses(j, широта, долгота, b'P')[0]
    return [x % 360 for x in к]


def _псевдоточка(имя, градус):
    """Угол как точка с градусом Азбуки — для блока обоими концами."""
    try:
        т = K.точка("Асцендент" if "сцендент" in имя else "MC", градус)
    except Exception:
        т = {"градус": градус, "знак": K.знак(градус), "код": {"тег": "", "суть": ""}, "текст": K.дмс(градус)}
    т["словами"] = f"{имя}: {K.градус_словами(градус)}"
    т["имя"] = имя
    return т


def _блок(внешнее, т, натал_имя, н, аспект, орбис, космо, ядро, куспиды, подпись, чей, вес=None):
    угол = {"соединение": 0, "оппозиция": 180, "квадрат": 90, "трин": 120, "секстиль": 60}[аспект]
    св = {"транзит": внешнее, "натал": натал_имя, "аспект": аспект, "угол": угол, "орбис": round(орбис, 3),
          "вес": вес or ("ТОЧНЫЙ" if орбис <= 0.5 else "РАБОЧИЙ" if орбис <= 1.5 else "ФОНОВЫЙ"),
          "поясн_веса": {"ТОЧНЫЙ": "в полную силу", "РАБОЧИЙ": "в работе", "ФОНОВЫЙ": "тихо, окраской"}.get(вес or ("ТОЧНЫЙ" if орбис <= 0.5 else "РАБОЧИЙ" if орбис <= 1.5 else "ФОНОВЫЙ"), ""), "сходится": True, "т": т, "н": н}
    шап = f"  ▪ {подпись} {K.имя_точки(внешнее).upper()} {аспект.upper()} {угол}° {натал_имя.upper()}"
    return S.трактовка_связи(св, космо, ядро, куспиды, подпись=подпись, чей=чей, шапка=шап)


