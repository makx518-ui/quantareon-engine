def собрать_соляр(космо, рождение, год, широта, долгота, куспиды_натал=None,
                  углы_натал=None, имя_человека="человек", место="", время_известно=True,
                  заказ="соляр", момент=None):
    """заказ='соляр' — момент возвращения Солнца, развёртка на год;
    заказ='транзиты' — момент сейчас (или переданный), развёртка на три месяца."""
    ч = "═" * 74
    if заказ == "транзиты":
        м = (момент or datetime.now(timezone.utc))
        # единый вид времени — как у момента соляра (он aware UTC, если рождение aware)
        if рождение.tzinfo and not м.tzinfo: м = м.replace(tzinfo=timezone.utc)
        if not рождение.tzinfo and м.tzinfo: м = м.astimezone(timezone.utc).replace(tzinfo=None)
        св_ = {"момент": м, "расхождение_сек": None}
    else:
        св_ = S.момент_соляра(рождение, год, широта, долгота)
        м = св_["момент"]
    ядро = K.ядро_узора(космо)
    хозяева_натала = (ядро.get("хозяин") or {}).get("кто", [])

    # ── точки года (небо на момент) и дома года
    тр = S.небо(м)
    куспиды_года = _куспиды(м, широта, долгота)
    углы_года = {"Асцендент года": куспиды_года[0], "Вершина года": куспиды_года[9],
                 "Десцендент года": куспиды_года[6], "Дно года": куспиды_года[3]}

    л = []

    # ══ 1 · ВВОДНАЯ ═══════════════════════════════════════════════════
    транзит = (заказ == "транзиты")
    л += [ч, (f"СЛОЙ 2 · ТРАНЗИТЫ НА {м.strftime('%d.%m.%Y %H:%M')} UTC · КАРТА МОМЕНТА · скрипт машины 07.09" if транзит
              else f"СЛОЙ 2 · СОЛЯР {год}–{год + 1} · КАРТА ГОДА · скрипт машины 07.09"), ч,
          "╔══ 1 · ВВОДНАЯ ══",
          f"  {имя_человека}{' · ' + место if место else ''} · дома {'момента' if транзит else 'года'} на широте {широта:.4f}, долготе {долгота:.4f}"]
    if транзит:
        л += [f"  момент: {м.strftime('%d.%m.%Y %H:%M:%S')} UTC · развёртка на ближайшие три месяца"]
    else:
        л += [f"  возвращение Солнца: {м.strftime('%d.%m.%Y %H:%M:%S')} UTC · расхождение с натальным градусом {св_['расхождение_сек']}″",
              ("  ⚑ СОВЕРШЕННЫЙ СОЛЯР — Солнце вернулось точно: год идёт на полной мощности природы, без разбавления"
               if св_["расхождение_сек"] < 60 else "  соляр с расхождением — год идёт с поправкой"),
              f"  год от {м.strftime('%d.%m.%Y')} до {(м + timedelta(days=365)).strftime('%d.%m.%Y')}"]
    л += [
          f"  время рождения: {'известно — натал с домами, накладка дом на дом' if время_известно else 'НЕ известно — натал как космограмма от Солнца; дом на дом не делается, только планета на планету'}"]
    проф = S.профекция(рождение, м)
    л += [f"  тема года по счёту лет: {проф['возраст']} лет → сектор {проф['сектор']} — {проф['тема']}", ""]

    # ══ 2 · ДВЕ КАРТЫ ═══════════════════════════════════════════════
    л += ["╔══ 2 · ДВЕ КАРТЫ · НАТАЛ (слой 1, выше) + КАРТА ГОДА (ниже) ══",
          "  Карта года построена той же машиной, что натал: свой асцендент, свои дома, свой хозяин узора.",
          "  Ниже — её полный расклад по натальной схеме, потом накладка двух карт друг на друга.", ""]
    # 2.1 карта года — натальной машиной
    точки_года = {и: т for и, т in тр.items() if и != "ТЖ"}
    try:
        from engine import lunacii as Л
        лд = Л.лунный_день(м)
        лунный_день_г = лд["день"] if лд else None
    except Exception:
        лунный_день_г = None
    угол_фазы = (тр["Луна"]["градус"] - тр["Солнце"]["градус"]) % 360 if "Луна" in тр and "Солнце" in тр else None
    углы_для_полочки = swe.houses(S.юлиан(м), широта, долгота, b'P')[1]   # ascmc — тот же вид, что даёт натал
    карта_года = K.полочка(точки_года, имя_человека=f"КАРТА ГОДА {год} · {имя_человека}",
                           дата=м.strftime("%d.%m.%Y %H:%M UTC"),
                           лунные_данные={"угол_фазы": угол_фазы, "лунный_день": лунный_день_г},
                           куспиды=куспиды_года, углы=углы_для_полочки)
    карта_года = карта_года.replace("БЛОК I · КОСМОГРАММА — ПЕРВИЧНЫЙ УЗОР ЛИЧНОСТИ",
                                    f"КАРТА ГОДА {год} — УЗОР ГОДА, построен как натал")
    карта_года = карта_года.replace("Карта рождения без домов и асцендента: только знаки, градусы и связи.",
                                    "Карта момента возвращения Солнца, дома на место жительства.")
    л += ["  ── 2.1 · КАРТА ГОДА · полный расклад ──", карта_года, ""]
    ядро_года = K.ядро_узора(точки_года)
    хозяева_года = (ядро_года.get("хозяин") or {}).get("кто", [])

    # 2.2 накладка двух карт
    л += ["  ── 2.2 · НАКЛАДКА ДВУХ КАРТ ──", ""]
    # 2.2.1 углы года в натале
    л.append("  ▸ УГЛЫ ГОДА В НАТАЛЕ")
    for имя_у, г in углы_года.items():
        дн = _дом(г, куспиды_натал)
        к = K.точка("Асцендент" if "сцендент" in имя_у else "MC", г)["код"]
        л.append(f"     {имя_у}: {K.градус_словами(г)} [{к['тег']}]" + (f" · в {дн}-м натальном доме — {K.СФЕРА_ДОМА[дн]}" if дн else "")
                 + f" · {к['суть'][:120]}")
        # на натальной точке?
        for ки, кт in космо.items():
            if ки == "ТЖ":
                continue
            d = K.дуга(г, кт["градус"])
            for асп, у in (("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                о = abs(d - у)
                if о <= (2.0 if у in (0, 180, 90) else 1.5):
                    л += _блок(имя_у, _псевдоточка(имя_у, г), ки, кт, асп, о, космо, ядро, куспиды_натал,
                               "УГОЛ ГОДА", "В НЕБЕ ГОДА")
                    break
    л.append("")
    # 2.2.2 натальные углы в году
    if куспиды_натал:
        л.append("  ▸ НАТАЛЬНЫЕ УГЛЫ В ГОДУ")
        for имя_у, i in УГЛЫ_ИМЕНА.items():
            г = куспиды_натал[i]
            дг = _дом(г, куспиды_года)
            л.append(f"     натальный {имя_у}: {K.градус_словами(г)} · в {дг}-м доме года — {K.СФЕРА_ДОМА[дг]}")
            for ти, тт in точки_года.items():
                d = K.дуга(г, тт["градус"])
                for асп, у in (("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                    о = abs(d - у)
                    if о <= (2.0 if у in (0, 180, 90) else 1.5):
                        л += _блок(ти, тт, f"натальный {имя_у}", _псевдоточка(имя_у, г), асп, о, космо, ядро, куспиды_натал,
                                   "ТОЧКА ГОДА", "В НЕБЕ ГОДА")
                        break
        л.append("")
        # 2.2.3 дом на дом
        нн = S.дом_на_дом(куспиды_натал, куспиды_года)
        л += [S.дом_на_дом_текстом(нн, подпись="года"), ""]
        # 2.2.4 / 2.2.5 точки в сетках + хозяева домов года
        нд = S.дома_момента_и_натала(космо, точки_года, куспиды_года, куспиды_натал)
        л += [S.дома_текстом(нд, подпись_момента="года"), ""]
    л += [f"  ▸ РЕЗЮМЕ НАКЛАДКИ: хозяин узора года — {', '.join(K.имя_точки(x) for x in хозяева_года) or '—'};"
          f" хозяин натала — {', '.join(K.имя_точки(x) for x in хозяева_натала) or '—'}"
          + (" · СОВПАЛИ — год и жизнь ведёт одна сила" if set(хозяева_года) & set(хозяева_натала) else ""), ""]

    # ══ 3–6 · ГОТОВЫЕ РАЗДЕЛЫ СЛОЯ 2 В ЕГО ПОРЯДКЕ ═══════════════════
    if транзит:
        полный = S.полочка_ситуации(космо, рождение, м, место=место, имя_человека=имя_человека,
                                    широта=широта, долгота=долгота,
                                    углы=(S.углы_карты(рождение, широта, долгота) if куспиды_натал else None),
                                    куспиды_натал=куспиды_натал)
        # 08.09, его слово: транзиты — снимок момента, без развёртки вперёд; лента только в соляре
    else:
        полный = S.соляр(космо, рождение, год, широта, долгота, куспиды_натал=куспиды_натал,
                         имя_человека=имя_человека, место=место)
    секции = re.split(r"(?=^╔══ )", полный, flags=re.M)
    def найти(ключ):
        for с in секции:
            if с.startswith("╔══ ") and ключ in с.split("\n")[0]:
                # лента и ключевые события идут после последней ╔══-секции — отрезаем, они печатаются в части 6
                k = с.find("ГОД ПОМЕСЯЧНО · ДИНАМИКА")
                if k > 0:
                    k = с.rfind("\n", 0, k - 80)
                    с = с[:k]
                return с
        return ""
    def найти_все(ключи):
        return "\n".join(x for x in (найти(k) for k in ключи) if x)
    def кусок(старт, стоп=None):
        a = полный.find(старт)
        if a < 0: return ""
        b = полный.find(стоп, a + 10) if стоп else -1
        return полный[a:b] if b > 0 else полный[a:]

    from engine import koleso_god as KG
    try:
        колесо_год = KG.колесо_по_году(космо, рождение, м, куспиды_натал=куспиды_натал,
                                        углы_натал=({"ASC": куспиды_натал[0], "MC": куспиды_натал[9]} if куспиды_натал else None))
    except Exception as e:
        колесо_год = f"  ⚠️ КОЛЕСО ПО ГОДУ не построено: {e}"
    л += ["╔══ 3 · КОЛЕСО ЖИЗНИ И КАРМИКА ══", "",
          найти("СТЕРЖЕНЬ · КОЛЕСО ЖИЗНИ"), колесо_год, "", найти("КАРМИКА В ДВИЖЕНИИ")]
    # ── 3.2 · КАРМИКА ПОЛНОСТЬЮ — добавки к разделу выше (07.09, его слово:
    #    «без кармики нет смысла, куда движется судьба по году»)
    КАРМ = ("Сев.Узел", "Юж.Узел", "Лилит", "Селена", "Хирон", "Плутон")
    # 3.2.2 · Плутон года — портрет (в разделе выше его нет)
    if "Плутон" in тр:
        л += ["  ── 3.2.2 · ПЛУТОН ГОДА · портрет ──"]
        л += S.конец_связи("Плутон", тр["Плутон"], "В НЕБЕ ГОДА", космо, куспиды=куспиды_натал, все_точки=космо)
        if куспиды_года:
            дг = _дом(тр["Плутон"]["градус"], куспиды_года)
            л.append(f"        в {дг}-м доме года — {K.СФЕРА_ДОМА[дг]}")
        л.append("")
    # 3.2.3 · кармика на кармику: точки года из КАРМ → натальные точки из КАРМ (узлы — орбис 3°)
    л.append("  ── 3.2.3 · КАРМИКА НА КАРМИКУ · транзитная кармика ложится на натальную ──")
    нашлось = 0
    for а in КАРМ:
        if а not in тр: continue
        for б in КАРМ:
            if б not in космо: continue
            d = K.дуга(тр[а]["градус"], космо[б]["градус"])
            орб_ = 3.0 if ("Узел" in а or "Узел" in б) else 2.0
            for асп, у in (("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                о = abs(d - у)
                if о <= (орб_ if у in (0, 180, 90) else 1.5):
                    л += _блок(а, тр[а], б, космо[б], асп, о, космо, ядро, куспиды_натал, "КАРМИКА НА КАРМИКУ", "В НЕБЕ ГОДА")
                    нашлось += 1
                    break
    if not нашлось:
        л.append("     кармика года на натальную кармику в орбисе не легла")
    л.append("")
    # 3.2.4 · кармика года на натальные углы
    if куспиды_натал:
        л.append("  ── 3.2.4 · КАРМИКА ГОДА НА НАТАЛЬНЫЕ УГЛЫ ──")
        нашлось_у = 0
        for а in КАРМ:
            if а not in тр: continue
            for имя_у, i in УГЛЫ_ИМЕНА.items():
                г = куспиды_натал[i]
                d = K.дуга(тр[а]["градус"], г)
                for асп, у in (("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                    о = abs(d - у)
                    if о <= (2.0 if у in (0, 180, 90) else 1.5):
                        л += _блок(а, тр[а], f"натальный {имя_у}", _псевдоточка(имя_у, г), асп, о, космо, ядро, куспиды_натал, "КАРМИКА ГОДА", "В НЕБЕ ГОДА")
                        нашлось_у += 1
                        break
        if not нашлось_у:
            л.append("     на натальные углы кармика года в орбисе не легла")
        л.append("")
    # 3.2.5 · РЕЗЮМЕ КАРМИКИ ПО ГОДУ — машиной, по полочкам
    л.append("  ── 3.2.5 · РЕЗЮМЕ КАРМИКИ ПО ГОДУ · по полочкам, для читателя ──")
    def дом_(имя):
        if имя in тр and куспиды_натал:
            д = _дом(тр[имя]["градус"], куспиды_натал)
            return f"{д}-й дом ({K.СФЕРА_ДОМА[д].split(',')[0]})" if д else "—"
        return "—"
    if "Сев.Узел" in тр and "Сев.Узел" in космо:
        d = K.дуга(тр["Сев.Узел"]["градус"], космо["Сев.Узел"]["градус"])
        как = ("СОВПАЛИ с натальной осью — год повторяет задачу воплощения" if d <= 3 else
               "ОБРАТНО натальной оси — год предлагает пройти задачу с другого конца" if abs(d - 180) <= 3 else
               "под прямым углом к натальной оси — год ставит задачу поперёк" if abs(d - 90) <= 3 else
               f"под углом {d:.0f}° к натальной оси")
