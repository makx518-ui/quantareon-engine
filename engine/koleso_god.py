# -*- coding: utf-8 -*-
"""
koleso_god.py — КОЛЕСО ЖИЗНИ ПО ГОДУ · стержень карты года (07.09.2026).

Его слово: «КЖ отдавать с полным прочтением — знак, натальный дом, управители,
градус, подградус; с кем аспектирует с натальными точками — полное прочтение
с двух концов; и резюме по году. Это ключевая фаза, стержень карты года».

Что отдаёт машина:
  1) портрет Точки жизни по всем полям (как натальная точка): знак, натальный
     дом, хозяин знака и где он в натале, градус с сутью, подградусы;
  2) сезоны года — все градусы, которые Колесо проходит за год, с датами
     входа/выхода, сутью, действием, риском; дольки (подградусы) по неделям;
  3) дорожка — все касания натальных точек и углов за год (орбис 1°):
     даты входа, точного дня, выхода, и полный блок обоими концами;
  4) транзиты НА Колесо — планеты неба, Селена, Лилит, Хирон, узлы, вставшие на
     Точку жизни за год (орбис жёстко 1°), с датами;
  5) лунации и затмения на Колесе;
  6) резюме Колеса по году машиной.
"""
from datetime import timedelta
import swisseph as swe

from engine import kosmogramma as K
from engine import situacia as S
from engine import kod360
from engine import lunacii as Л

ХОД = S.ХОД_КОЛЕСА          # °/год
АСПЕКТЫ = [("соединение", 0), ("оппозиция", 180), ("квадрат", 90), ("трин", 120), ("секстиль", 60)]
ОРБИС_КОЛЕСА = 1.0          # его правило 14.08: жёстко 1°
МЕСЯЦЫ = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля",
          "августа", "сентября", "октября", "ноября", "декабря"]
ТРАНЗИТНЫЕ = [("Марс", swe.MARS), ("Юпитер", swe.JUPITER), ("Сатурн", swe.SATURN),
              ("Уран", swe.URANUS), ("Нептун", swe.NEPTUNE), ("Плутон", swe.PLUTO),
              ("Хирон", swe.CHIRON), ("Сев.Узел", swe.TRUE_NODE), ("Лилит", swe.MEAN_APOG)]


def _д(d):
    return f"{d.day} {МЕСЯЦЫ[d.month - 1]} {d.year}"


def _градус_на(рождение, момент):
    лет = (момент - рождение).total_seconds() / (365.25 * 86400)
    return (лет * ХОД) % 360


def _когда_градус(рождение, момент, цель):
    """Дата, когда Колесо придёт в градус `цель` (вперёд от момента)."""
    г = _градус_на(рождение, момент)
    дельта = (цель - г) % 360
    return момент + timedelta(days=дельта / ХОД * 365.25)


def колесо_по_году(космо, рождение, момент, куспиды_натал=None, углы_натал=None, тр_момента=None):
    ч = "═" * 74
    м = момент
    конец = м + timedelta(days=365)
    кол = S.колесо(рождение, м)
    г0 = кол["градус"]
    ядро = K.ядро_узора(космо)
    л = [ч, "КОЛЕСО ЖИЗНИ ПО ГОДУ · СТЕРЖЕНЬ КАРТЫ ГОДА", ч,
         "  Ключевая фаза: всё остальное в году читается на фоне того, где Колесо и что оно касается.",
         "  Орбис Колеса жёстко 1° (его правило 14.08); ход 4.29° в год — связь держится около пяти месяцев.", ""]

    # ── 1 · портрет Точки жизни по всем полям
    л.append("  ── 1 · ТОЧКА ЖИЗНИ В ДЕНЬ РОЖДЕНИЯ · портрет по всем полям ──")
    тж = K.точка("Колесо жизни", г0)
    л += S.конец_связи("Колесо жизни", тж, "СТЕРЖЕНЬ", космо, куспиды=куспиды_натал, все_точки=космо)
    э = кол["эпоха"]
    л.append(f"        эпоха {э['номер']}-я, знак {э['знак']}, годы {э['годы'][0]}–{э['годы'][1]} · прожито {кол['лет']:.2f} лет")
    if куспиды_натал:
        дн = K.дом_точки(г0, куспиды_натал)
        if дн:
            л.append(f"        ⚑ стержень года идёт по {дн}-му натальному дому — {K.СФЕРА_ДОМА[дн]}: вот сфера, где живёт этот год")
    упр = K.УПРАВИТЕЛЬ.get(э["знак"], [None])[0]
    if упр and упр in космо:
        х = космо[упр]
        л.append(f"        управитель эпохи {упр}: {х.get('словами','')} [{х['код']['тег']}]"
                 + (f", в {K.дом_точки(х['градус'], куспиды_натал)}-м доме" if куспиды_натал else "")
                 + f" — {х['код']['суть'][:110]}")
    л.append("")

    # ── 2 · сезоны года: градусы, которые Колесо пройдёт за год
    л.append("  ── 2 · СЕЗОНЫ ГОДА · градусы Колеса от дня рождения до дня рождения ──")
    тек = int(г0)
    старт = м
    while старт < конец:
        след = (тек + 1) % 360
        д_выхода = _когда_градус(рождение, старт, след)
        if д_выхода > конец + timedelta(days=30):
            д_выхода = конец
        к = kod360.code_by_abs(тек + 0.5) or {}
        л.append(f"  ◆ {K.градус_словами(тек + 0.5)} [{к.get('tag','')}] · с {_д(старт)} по {_д(д_выхода)}")
        л.append(f"       суть: {к.get('суть','')[:200]}")
        л.append(f"       делать: {к.get('действие','')} · остерегаться: {к.get('риск','')}")
        # дольки внутри градуса — по подградусу 2-го уровня, шаг ~7 дней
        дольки = []
        d = старт
        посл = None
        while d < д_выхода:
            гг = _градус_на(рождение, d)
            яд = K.точка("Колесо жизни", гг).get("подградусы") or []
            под = яд[0] if яд else None
            # долька = знак подградуса первого уровня (12 долек по ~7 дней на градус Колеса);
            # градус внутри дольки бежит по 6 часов — его берём только у входа в дольку
            if под and под.get("знак") != посл:
                дольки.append(f"{_д(d)}: долька {под.get('знак','')} — вход [{под.get('тег','')}] {под.get('суть','')[:70]}")
                посл = под.get("знак")
            d += timedelta(days=1)
        if дольки:
            л.append("       дольки: " + " | ".join(дольки[:14]))
        старт = д_выхода
        тек = след
        if тек == int(г0) and старт >= конец:
            break
    л.append("")

    # ── 3 · дорожка: касания натальных точек за год, обоими концами
    л.append("  ── 3 · ДОРОЖКА · касания натальных точек и углов за год · полной выкладкой ──")
    цели = {и: т for и, т in космо.items() if и != "ТЖ"}
    if углы_натал:
        for имя_у, г in (("Асцендент", углы_натал.get("ASC")), ("Вершина (MC)", углы_натал.get("MC"))):
            if г is not None:
                цели[имя_у] = K.точка("Асцендент" if "сцендент" in имя_у else "MC", г)
                цели[имя_у]["словами"] = f"{имя_у}: {K.градус_словами(г)}"
    нашлось = 0
    for имя, т in цели.items():
        гц = т["градус"]
        for асп, у in АСПЕКТЫ:
            # градус, где Колесо точно в аспекте: гц − у и гц + у
            for знак_ in (1, -1):
                точный_градус = (гц - знак_ * у) % 360
                дельта = (точный_градус - г0) % 360
                дней = дельта / ХОД * 365.25
                if -160 <= дней <= 365 + 160:   # в орбисе ±1° это ~±85 дней
                    д_точн = м + timedelta(days=дней)
                    д_вх = д_точн - timedelta(days=ОРБИС_КОЛЕСА / ХОД * 365.25)
                    д_вых = д_точн + timedelta(days=ОРБИС_КОЛЕСА / ХОД * 365.25)
                    if д_вых < м - timedelta(days=10) or д_вх > конец + timedelta(days=10):
                        continue
                    тж_т = K.точка("Колесо жизни", точный_градус)
                    св = {"транзит": "Колесо жизни", "натал": имя, "аспект": асп, "угол": у,
                          "орбис": 0.0, "вес": "ТОЧНЫЙ", "поясн_веса": "стержень касается точки",
                          "сходится": д_точн >= м, "т": тж_т, "н": т}
                    шап = (f"  ▪ КОЛЕСО {асп.upper()} {у}° {имя.upper()} · точно {_д(д_точн)}"
                           f" · в орбисе с {_д(д_вх)} по {_д(д_вых)}" + (" · уже прошло, ещё держится" if д_точн < м else ""))
                    л += S.трактовка_связи(св, космо, ядро, куспиды_натал, подпись="КОЛЕСО", чей="СТЕРЖЕНЬ НА ЭТОТ ДЕНЬ", шапка=шап)
                    нашлось += 1
                if у == 0:
                    break
    if not нашлось:
        л.append("     касаний в орбисе 1° за год нет")
    л.append("")

    # ── 4 · транзиты на Колесо (орбис 1°), день за днём
    л.append("  ── 4 · ТРАНЗИТЫ НА КОЛЕСО · планета неба на Точке жизни (орбис жёстко 1°) ──")
    лента = []
    d = м - timedelta(days=30)
    while d <= конец + timedelta(days=30):
        j = S.юлиан(d)
        гг = _градус_на(рождение, d)
        поз = {}
        for имя, pl in ТРАНЗИТНЫЕ:
            try:
                поз[имя] = swe.calc_ut(j, pl)[0][0] % 360
            except Exception:
                pass
        поз["Селена"] = (87.9580 + (j - 2447892.5) * 0.1408056) % 360
        if "Сев.Узел" in поз:
            поз["Юж.Узел"] = (поз["Сев.Узел"] + 180) % 360
        лента.append((d, гг, поз))
        d += timedelta(days=1)
    события = []
    for имя in list(dict(ТРАНЗИТНЫЕ).keys()) + ["Селена", "Юж.Узел"]:
        for асп, у in АСПЕКТЫ:
            ряд = [abs(K.дуга(п.get(имя, -999), гг) - у) if имя in п else None for _, гг, п in лента]
            i = 1
            while i < len(ряд) - 1:
                a, b, c = ряд[i - 1], ряд[i], ряд[i + 1]
                if a is not None and b is not None and c is not None and b <= ОРБИС_КОЛЕСА and b <= a and b <= c and (b < a or b < c):
                    j = i
                    while j > 0 and ряд[j - 1] is not None and ряд[j - 1] <= ОРБИС_КОЛЕСА: j -= 1
                    k = i
                    while k < len(ряд) - 1 and ряд[k + 1] is not None and ряд[k + 1] <= ОРБИС_КОЛЕСА: k += 1
                    события.append({"тр": имя, "асп": асп, "дата": лента[i][0], "орб": round(b, 2),
                                    "окно": (лента[j][0], лента[k][0]), "где": лента[i][2][имя], "тж": лента[i][1]})
                    i = k + 1
                    continue
                i += 1
    события.sort(key=lambda e: e["дата"])
    if not события:
        л.append("     за год ни одна планета не встаёт на Колесо в орбисе 1°")
    for е in события:
        if е["дата"] < м - timedelta(days=15) or е["дата"] > конец + timedelta(days=15):
            continue
        тт = K.точка(е["тр"], е["где"])
        тж_т = K.точка("Колесо жизни", е["тж"])
        св = {"транзит": е["тр"], "натал": "Колесо жизни", "аспект": е["асп"],
              "угол": dict(АСПЕКТЫ)[е["асп"]], "орбис": е["орб"], "вес": "ТОЧНЫЙ" if е["орб"] <= 0.5 else "РАБОЧИЙ",
              "поясн_веса": "планета на стержне — серьёзный момент (его решение 14.08)", "сходится": True, "т": тт, "н": тж_т}
        шап = (f"  ▪ {е['тр'].upper()} {е['асп'].upper()} КОЛЕСО ЖИЗНИ · точно {_д(е['дата'])}"
               f" · окно {_д(е['окно'][0])} – {_д(е['окно'][1])}")
        л += S.трактовка_связи(св, космо, ядро, куспиды_натал, подпись="ТРАНЗИТ", чей="В НЕБЕ НА ЭТУ ДАТУ", шапка=шап)
    л.append("")

    # ── 5 · лунации и затмения на Колесе
    л.append("  ── 5 · ЛУНАЦИИ И ЗАТМЕНИЯ НА КОЛЕСЕ ──")
    найдено = 0
    try:
        from datetime import timezone as _tz
        м_aw = м if м.tzinfo else м.replace(tzinfo=_tz.utc)
        конец_aw = конец if конец.tzinfo else конец.replace(tzinfo=_tz.utc)
        рождение_aw = рождение if рождение.tzinfo else рождение.replace(tzinfo=_tz.utc)
        for лн in Л.лунации(м_aw, конец_aw, None, орбис=3.0):
            дата = лн.get("когда")
            if дата is None:
                continue
            гг = _градус_на(рождение_aw, дата)
            for ключ, кого in (("луна", "Луна"), ("солнце", "Солнце")):
                гл = лн.get(ключ)
                if гл is not None and K.дуга(гл, гг) <= 1.5:
                    к = kod360.code_by_abs(гл) or {}
                    л.append(f"     {лн.get('вид','')} {_д(дата)}: {кого} на {K.градус_словами(гл)} [{к.get('tag','')}] — стержень освещён; {к.get('суть','')[:100]}")
                    найдено += 1
        for з in Л.затмения(м_aw, конец_aw, None, орбис=3.0):
            дата = з.get("когда")
            if дата is None:
                continue
            гг = _градус_на(рождение_aw, дата)
            for ключ in ("луна", "солнце"):
                гл = з.get(ключ)
                if гл is not None and K.дуга(гл, гг) <= 2.0:
                    л.append(f"     ЗАТМЕНИЕ {з.get('вид','')} {_д(дата)} на {K.градус_словами(гл)} — открывает тему стержня на год")
                    найдено += 1
    except Exception as e:
        л.append(f"     (лунации на Колесо не посчитались: {e})")
    if not найдено:
        л.append("     лунаций и затмений на Колесе за год нет")
    л.append("")

    # ── 6 · резюме
    касания = [x for x in л if x.startswith("  ▪ КОЛЕСО")]
    транз = [x for x in л if x.startswith("  ▪ ") and "КОЛЕСО ЖИЗНИ · точно" in x]
    л.append(f"  ▸ РЕЗЮМЕ КОЛЕСА ПО ГОДУ: стержень идёт по {э['знак']}у, эпоха {э['годы'][0]}–{э['годы'][1]}"
             + (f", в {K.дом_точки(г0, куспиды_натал)}-м натальном доме" if куспиды_натал and K.дом_точки(г0, куспиды_натал) else "")
             + f"; сезонов за год {sum(1 for x in л if x.startswith('  ◆ '))}; касаний натальных точек {len(касания)}; планет на стержне {len(транз)}; лунаций на стержне {найдено}.")
    for x in касания:
        л.append("     " + x.strip()[2:])
    for x in транз:
        л.append("     " + x.strip()[2:])
    return "\n".join(л)
