# 28.09 · ОРБИСЫ НАТАЛА (его слово, итог): «большие только у светил и угловых: Солнце 10° туда и 10°
# сюда, Луна по 7°; угловые 10° вперёд, 5° назад; у планет между собой 5°». Хирон, узлы, Чёрная и Белая
