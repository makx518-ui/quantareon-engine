def _знак(гр):
    return ЗНАКИ[int(гр % 360 // 30)]


def _градус(гр):
    """Как на полочке: номер градуса знака (10°30′ → 11°)."""
    return int(гр % 30) + 1


def _реал(гр):
    """28.09 · реальное положение с минутами: «10°30′ Водолея» (не номер градуса-символа)."""
    гр = float(гр) % 360
    г = int(гр % 30)
    return f"{г}°{int(((гр % 30) - г) * 60):02d}′ {ЗНАКИ_Р[ЗНАКИ.index(_знак(гр))]}"


def _где(м, имя):
    return _реал(м.flat[имя])


def _дома_управления(м):
    """Какими домами управляет каждая планета (по знакам на куспидах)."""
    упр = {}
    for н, к in enumerate(м.cusps[:12], 1):
        упр.setdefault(УПРАВИТЕЛЬ[_знак(к)], []).append(н)
    return упр


def _разн(a, b):
    d = abs(a - b) % 360
    return 360 - d if d > 180 else d


def _аспект(a, b, угол, орб):
    return abs(_разн(a, b) - угол) <= орб


# ── 1. ПЛАНЕТЫ В ДОМАХ ──
def планеты_в_домах(м):
    if len(м.cusps) < 12:
        return ""
    внутри = {н: [] for н in range(1, 13)}
    for имя in ПЛАНЕТЫ + ["Хирон", "Сев.Узел", "Юж.Узел", "Чёрная Луна", "Белая Луна"]:
        if имя in м.flat:
            внутри[м.house_of(м.flat[имя])].append(f"{имя} {_где(м, имя)}")
    л = ["╔══ ПЛАНЕТЫ В ДОМАХ (машина: кто стоит в каждом доме; дом читается куспидом, "
         "управителем и жильцами вместе) ══"]
    for н in range(1, 13):
        к = м.cusps[н - 1]
        упр = УПРАВИТЕЛЬ[_знак(к)]
        где_упр = f"{_где(м, упр)}, дом {м.house_of(м.flat[упр])}" if упр in м.flat else "—"
        жильцы = ", ".join(внутри[н]) if внутри[н] else "пуст — читается через управителя"
        куспид = _реал(к)
        л.append(f"  дом {н:>2} ({СФЕРА_ДОМА[н]}): куспид {куспид} · управитель {упр} ({где_упр}) · стоят: {жильцы}")
    return "\n".join(л)


# ── 2. БАЛАНС ──
def баланс(м):
    точки = [и for и in ПЛАНЕТЫ if и in м.flat] + [и for и in ("ASC", "MC") if и in м.flat]
    ст, кр = {}, {}
    for и in точки:
        з = _знак(м.flat[и])
        ст.setdefault(СТИХИЯ[з], []).append(и)
        кр.setdefault(КРЕСТ[з], []).append(и)
    л = [f"╔══ БАЛАНС (машина: {len(точки)} точек — 10 планет и углы) ══"]
    for с in ("огонь", "земля", "воздух", "вода"):
        сп = ст.get(с, [])
        л.append(f"  {с:<7} {len(сп):>2} · {СМЫСЛ_СТИХИИ[с]}: {', '.join(сп) if сп else 'нет — дефицит стихии'}")
    for к in ("кардинальный", "фиксированный", "мутабельный"):
        сп = кр.get(к, [])
        л.append(f"  {к:<13} {len(сп):>2} · {СМЫСЛ_КРЕСТА[к]}: {', '.join(сп) if сп else 'нет'}")
    мах_с = max(ст, key=lambda x: len(ст[x]))
    мах_к = max(кр, key=lambda x: len(кр[x]))
    нет = [с for с in ("огонь", "земля", "воздух", "вода") if not ст.get(с)]
    л.append(f"  ведущая стихия: {мах_с} ({len(ст[мах_с])}); ведущий крест: {мах_к} ({len(кр[мах_к])})"
             + (f"; нет стихии: {', '.join(нет)}" if нет else ""))
    return "\n".join(л)


# ── 3. ЦЕПИ ДИСПОЗИТОРОВ ──
def цепи_диспозиторов(м):
    дисп = {и: УПРАВИТЕЛЬ[_знак(м.flat[и])] for и in ПЛАНЕТЫ if и in м.flat}
    л = ["╔══ ЦЕПИ ДИСПОЗИТОРОВ (машина: от каждой точки к её хозяину и дальше, до вершины) ══"]
    вершины, петли = set(), set()
    for и in ПЛАНЕТЫ + ["Сев.Узел", "Юж.Узел", "Хирон", "Чёрная Луна", "Белая Луна", "ASC", "MC"]:
        if и not in м.flat:
            continue
        путь = [и]
        т = УПРАВИТЕЛЬ[_знак(м.flat[и])] if и not in ПЛАНЕТЫ else дисп[и]
        while т not in путь and т in дисп:
            путь.append(т)
            т = дисп[т]
        if т == путь[-1]:
            хвост = f"{т} — в своём знаке: ВЕРШИНА"
            вершины.add(т)
        elif т in путь:
            кольцо = путь[путь.index(т):]
            хвост = f"замыкается кольцом {' ⇄ '.join(кольцо)}"
            петли.add(" ⇄ ".join(sorted(кольцо)))
        else:
            хвост = т
        л.append(f"  {' → '.join(путь)} → {хвост}" if т != путь[-1] else f"  {' → '.join(путь)} ({хвост})")
    итог = []
    if вершины:
        итог.append("вершины (планета в своём знаке, сама себе хозяин): " + ", ".join(sorted(вершины)))
    if петли:
        итог.append("кольца (взаимная рецепция — хозяева друг друга): " + "; ".join(sorted(петли)))
    л.append("  ИТОГ: " + (" · ".join(итог) if итог else "единой вершины нет — власть рассеяна"))
    return "\n".join(л)


