# В аспекте со светилом решает орбис светила; с углом — нужны оба конца (Солнце трин МС: у Солнца 10°
# и у МС спереди 10°). Оппозиция — не больше 5°, кроме светил и углов. Один источник и для списка
# аспектов, и для фигур.
ОРБИС_ТОЧКИ = {"Солнце": 10, "Луна": 7}
ОРБИС_ОСТАЛЬНЫХ = 5
СВЕТИЛА = {"Солнце", "Луна"}
УЗЛЫ = {"Сев.Узел", "Юж.Узел"}
ПОТОЛОК_ОППОЗИЦИИ = 5


def орбис(a, b, вид):
    """Без учёта положения (углы — см. орбис_поз): светило решает, планеты между собой 5°."""
    о = max(ОРБИС_ТОЧКИ.get(a, ОРБИС_ОСТАЛЬНЫХ), ОРБИС_ТОЧКИ.get(b, ОРБИС_ОСТАЛЬНЫХ))
    if вид == "оппозиция" and not ({a, b} & СВЕТИЛА):
        о = min(о, ПОТОЛОК_ОППОЗИЦИИ)
    return о


# 28.09 · СВЯЗКИ (его слово): «Сев.Узел в точном практически соединении с Плутоном, у Плутона
# соединение с асцендентом — это связка, аспект к асценденту состоявшийся, сложившийся»; «Сатурн в
# оппозиции с Луной, а Луна в соединении с Чёрной Луной — эта связка должна читаться именно так».
#   1) связка — точки в почти точном соединении (≤ ТОЧНАЯ_СВЯЗКА°): стоят как одно целое;
#   2) аспект к одному участнику связки засчитывается и к остальным её участникам
#      (орбис растёт ровно на расстояние внутри связки: 4,92° + 1,89° = 6,81°);
#   3) ось узлов: соединение с одним узлом — оппозиция к другому (ASC ☌ Сев.Узел → ☍ Юж.Узел).
# Добавленные так аспекты помечаются «через связку (…)».
УГЛЫ_АСПЕКТОВ = {"соединение": 0, "оппозиция": 180, "трин": 120, "квадрат": 90, "секстиль": 60}
ТОЧНАЯ_СВЯЗКА = 2.0

# 28.09 · УГЛОВЫЕ ТОЧКИ (его слово): «у асцендента, МС — 5 сзади и 10 спереди: МС в девятом доме 5,
# в десятом 10; асцендент 5 в двенадцатом и 10 в первом; так же все угловые точки» (DSC, IC — это
# оппозиция к ASC и MC: 5 в шестом/третьем, 10 в седьмом/четвёртом). «Спереди» — точка стоит дальше
# точного аспекта по ходу знаков (внутри углового дома), «сзади» — не дошла. Потолок оппозиции 5° к
# углам не применяется: оппозиция к углу — соединение с противоположным углом.
УГЛОВЫЕ = {"ASC", "MC"}
УГОЛ_СПЕРЕДИ, УГОЛ_СЗАДИ = 10, 5


def орбис_поз(flat, a, b, вид):
    """Орбис с учётом положения: у угловых точек — 10° спереди, 5° сзади."""
    о = орбис(a, b, вид)
    for угол, точка in ((a, b), (b, a)):
        if угол in УГЛОВЫЕ and точка not in УГЛОВЫЕ and угол in flat and точка in flat:
            θ = УГЛЫ_АСПЕКТОВ[вид]
            точные = {(flat[угол] + θ) % 360, (flat[угол] - θ) % 360}
            знаковое = min(((((flat[точка] - т) + 540) % 360) - 180 for т in точные), key=abs)
            у = УГОЛ_СПЕРЕДИ if знаковое > 0 else УГОЛ_СЗАДИ
            if вид in ("соединение", "оппозиция"):
                # точка на угле (или на противоположном угле) — решает орбис угла
                о = у
            else:
                # трин, квадрат, секстиль к углу — нужны оба конца: у Солнца 10° и у МС спереди 10°
                о = min(у, ОРБИС_ТОЧКИ.get(точка, ОРБИС_ОСТАЛЬНЫХ))
    return о


def аспекты_классики(flat):
    """Список аспектов натала классики: орбисы Влада + сложившиеся через связки.
    [(вид, орб, a, b, пометка)] — как ждёт af_natal_scenario.render_natal(aspects=...)."""
    import os as _os, sys as _sys
    _п = _os.path.join(_os.path.dirname(__file__), "af")
    if _п not in _sys.path:
        _sys.path.insert(0, _п)
    import af_natal_scenario as _A
    прямые = [(в, о, a, b, "") for в, о, a, b in _A.natal_aspects(flat, lambda a, b, в: орбис_поз(flat, a, b, в))]
    есть = {frozenset((a, b)) for _, _, a, b, _ in прямые}
    итог = list(прямые)

    def разн(a, b):
        d = abs(flat[a] - flat[b]) % 360
        return min(d, 360 - d)

    def добавить(a, b, вид, предел, через):
        if a == b or frozenset((a, b)) in есть or {a, b} == УЗЛЫ or {a, b} == {"ASC", "MC"}:
            return
        откл = abs(разн(a, b) - УГЛЫ_АСПЕКТОВ[вид])
        if откл > предел + 1e-9:
            return
        есть.add(frozenset((a, b)))
        итог.append((вид, round(откл, 2), a, b, f"через связку ({через})"))

    # 1) связки: компоненты по почти точным соединениям
    сосед = {}
    for вид, о, a, b, _ in прямые:
        if вид == "соединение" and о <= ТОЧНАЯ_СВЯЗКА:
            сосед.setdefault(a, set()).add(b)
            сосед.setdefault(b, set()).add(a)
    связки, видел = [], set()
    for т in сосед:
        if т in видел:
            continue
        стек, группа = [т], set()
        while стек:
            x = стек.pop()
            if x not in группа:
                группа.add(x)
                стек += list(сосед.get(x, ()))
        видел |= группа
        связки.append(группа)
    # 2) аспект к участнику связки — и к остальным её участникам
    for вид, о, a, b, _ in прямые:
        for г in связки:
            for внутри, снаружи in ((a, b), (b, a)):
                if внутри in г and снаружи not in г:
                    for другой in sorted(г - {внутри}):
                        точно = abs(разн(a, b) - УГЛЫ_АСПЕКТОВ[вид])   # без округления
                        добавить(снаружи, другой, вид, точно + разн(внутри, другой),
                                 f"{внутри} ☌ {другой}")
    # 3) ось узлов
    for вид, о, a, b, _ in list(итог):
        if вид == "соединение" and (a in УЗЛЫ) != (b in УЗЛЫ):
            узел, точка = (a, b) if a in УЗЛЫ else (b, a)
            другой = (УЗЛЫ - {узел}).pop()
            if другой in flat:
                добавить(точка, другой, "оппозиция", abs(разн(точка, узел)) + 0.01, f"ось узлов: {точка} ☌ {узел}")
    return sorted(итог, key=lambda x: (x[4] != "", x[1]))


