def подсказка(а, б, аспект, тег_а="", тег_б="", орбис=None, точный=False):
    """Короткая машинная трактовка связи — для ИИ, а не вместо него."""
    роль_а = РОЛЬ.get(а, ("", ""))[0] or а
    роль_б = РОЛЬ.get(б, ("", ""))[0] or б
    вид, оговорка = ХАРАКТЕР.get(аспект, ("связь", ""))
    гл = ГЛАГОЛ.get(аспект, "связан с")
    # ⚠️ без склонений: русские падежи в машинной склейке ломаются
    # («воля и напор легко переходит в рана и мост»). Потому — через стрелку.
    стрелка = {"соединение": "⊕", "оппозиция": "↔", "трин": "→",
               "квадрат": "⊥", "секстиль": "⇢"}.get(аспект, "·")
    ф = f"{вид.upper()} · {роль_а} {стрелка} {роль_б}"
    if тег_а and тег_б:
        ф += f" · [{тег_а}] {стрелка} [{тег_б}]"
    сила = ""
    if точный:
        сила = " · СТОИТ В ТОЧКУ: звучит громче остальных"
    elif орбис is not None and орбис > 4:
        сила = " · широкий, фоном"
    return {"фраза": ф, "вид": вид, "оговорка": оговорка, "сила": сила.strip(" ·")}


