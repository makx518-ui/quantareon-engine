def дмс(градус):
    г = ((градус % 360) + 360) % 360
    в = г % 30
    d = int(в); m = int((в - d) * 60); s = int(round((((в - d) * 60) - m) * 60))
    if s == 60: s = 0; m += 1
    if m == 60: m = 0; d += 1
    return f"{d}°{m:02d}'{s:02d}\" {ЗНАКИ_Р[int(г // 30)]}"


def номер_градуса(градус):
    """Градусы считаются с ЕДИНИЦЫ: 10°53′ — это ОДИННАДЦАТЫЙ градус знака.
    Его поправка 16.08 — иначе трактовка называет градус не своим именем."""
    return int((((градус % 360) + 360) % 360) % 30) + 1


def градус_словами(градус):
    """«11-й градус Козерога (10°53′41″)» — как надо называть в тексте."""
    return f"{номер_градуса(градус)}-й градус {ЗНАКИ_Р[int((((градус % 360) + 360) % 360) // 30)]} ({дмс(градус)})"


def знак(градус):
    return ЗНАКИ[int((((градус % 360) + 360) % 360) // 30)]


def дуга(а, б):
    d = abs((а - б) % 360)
    return min(d, 360 - d)


def ядро(градус, уровней=2):
    """Подградус: внутри градуса лежит весь зодиак. Отдаём не только знак,
    но и КОД подградуса — его смысл «здесь и сейчас» (его требование 16.08)."""
    try:
        к = cascade_from_absolute(градус, levels=уровней)
        сл = к.get("cascade") or []
        итог = []
        for у in сл[:уровней]:
            абс = у["sign_index"] * 30 + у["degree"]
            код = kod360.code_by_abs(абс)
            итог.append({
                "уровень": у["level"],
                "текст": f"{у['degree_int']}°{у.get('degree_min',0):02d}' {ЗНАКИ_Р[у['sign_index']]}",
                "номер": у['degree_int'] + 1,
                "словами": f"{у['degree_int']+1}-й градус {ЗНАКИ_Р[у['sign_index']]}",
                "знак": ЗНАКИ[у["sign_index"]],
                "градус": round(абс, 4),
                "тег": код.get("tag", ""),
                "суть": код.get("суть", ""),
                "действие": код.get("действие", ""),
                "флаг": код.get("flag", ""),
            })
        return итог
    except Exception:
        return []


def ядро_строкой(я):
    """Короткая запись подградусов для беглого взгляда."""
    if not я:
        return ""
    return " · ".join(f"{у['текст']} [{у['тег']}]" for у in я)


