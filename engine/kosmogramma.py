#  Как в синастрии: две карты кладутся друг на друга и читаются связи
#  между ними. Орбис жёстко 1° — его правило для всего движущегося.

def накладка(космо, тр, орбис=ОРБИС_НАКЛАДКИ):
    """Связи транзит → космограмма: кто из неба задевает какую точку личности."""
    найдено = []
    for ти, тт in тр.items():
        for ки, кт in космо.items():
            d = дуга(тт["градус"], кт["градус"])
            for ан, угол in [("соединение", 0), ("секстиль", 60), ("квадрат", 90),
                             ("трин", 120), ("оппозиция", 180)]:
                о = abs(d - угол)
                if о <= орбис:
                    найдено.append({
                        "транзит": ти, "космограмма": ки, "аспект": ан,
                        "орбис": round(о, 3), "точный": о <= 0.5,
                        "сходится": (тт.get("скорость", 0) or 0) != 0,
                        "т_градус": тт["текст"], "к_градус": кт["текст"],
                        "т_тег": тт["код"]["тег"], "к_тег": кт["код"]["тег"],
                    })
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


