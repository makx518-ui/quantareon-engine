def диспозитор(имя, точки):
    """Где стоит управитель знака этой точки — и в каком он знаке."""
    з = точки.get(имя, {}).get("знак")
    if not з:
        return None
    упр = УПРАВИТЕЛЬ[з][0]
    if упр == имя or упр not in точки:
        return None
    return {"кто": упр, "в_знаке": точки[упр]["знак"], "градус": точки[упр]["текст"]}


def цепь_диспозиторов(имя, точки, глубина=8):
    """Куда ведёт корень: точка → её управитель → его управитель … до вершины или круга."""
    путь = [имя]
    текущий = имя
    for _ in range(глубина):
        д = диспозитор(текущий, точки)
        if not д:
            break
        если_круг = д["кто"] in путь
        путь.append(д["кто"])
        if если_круг:
            break
        текущий = д["кто"]
    if len(путь) < 2:
        return None
    замкнулась = путь[-1] in путь[:-1]
    return {"путь": путь, "вершина": путь[-1], "замкнулась": замкнулась}


