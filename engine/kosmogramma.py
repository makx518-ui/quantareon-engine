def сторона(имя, точки, свои=None):
    """Одна сторона аспекта целиком: знак, управитель и где он стоит, градус, код, роль."""
    т = свои if свои else точки.get(имя)
    if not т:
        return []
    з = т["знак"]
    упр = УПРАВИТЕЛЬ[з][0]
    где = ""
    if упр in точки:
        у = точки[упр]
        свой = " — в своём чертоге" if УПРАВИТЕЛЬ[у["знак"]][0] == упр else ""
        где = f", стоит {у['текст']}{свой}"
    роль, пояснение = РОЛЬ.get(имя, ("", ""))
    к = т.get("код", {})
    стр = [f"     ── {имя_точки(имя).upper()}: {т.get('словами') or т['текст']}",
           f"        знак {з} · управитель знака {упр}{где}"]
    if к.get("тег"):
        стр += [f"        градус [{к['тег']}] {к.get('вектор','')}"
                + (f" · флаг {к['флаг']}" if к.get("флаг") and к["флаг"] != "НЕТ" else ""),
                f"        суть градуса: {к.get('суть','')}"]
    for у in (т.get("подградусы") or [])[:2]:
        стр += [f"        подградус {у['уровень']}: {у.get('словами', у['текст'])} — {у['текст']} [{у['тег']}]"
                + (f" · {у['флаг']}" if у.get("флаг") and у["флаг"] != "НЕТ" else ""),
                f"           здесь и сейчас: {у['суть']}"]
    if роль:
        стр += [f"        роль в карте: {роль} — {пояснение}"]
    return стр


def выкладка_аспекта(а, б, аспект, орбис, точки, свой_а=None, свой_б=None):
    """Полная двусторонняя выкладка + сплав: что это даёт личности."""
    та = свой_а or точки.get(а, {})
    тб = свой_б or точки.get(б, {})
