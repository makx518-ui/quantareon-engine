    шапка = шапка_захода(точки, я)
    порции = []

    # ── порция A: кармика и связки ──
    л = [ч, "ЗАХОД 2 · ПОРЦИЯ A — ПРОГРАММА И СПЛАВЫ", ч, шапка, ""]
    if лунные:
        л += лунный_блок(точки, **лунные) + [""]
    л += ["╔══ I. КАРМИКА — откуда пришёл и куда идёт ══", ""]
    for и in СЛОИ[0][1]:
        if и in точки:
            л += портрет_планеты(и, точки, асп)
            if и in КАРМИЧЕСКИЙ_СМЫСЛ:
                л += [f"     РОЛЬ В СУДЬБЕ: {КАРМИЧЕСКИЙ_СМЫСЛ[и]}"]
            л += [""]
    л += резюме_кармики(точки) + [""]
    л += блок_связок_текстом(точки)
    л += ["", "  ▸ ЗАДАЧА ПОРЦИИ: выписать для себя 3–5 заметок — что здесь главное,",
          "     что противоречит, что подтверждает точку сборки.", ч]
    порции.append("\n".join(л))

    # ── порция B: планеты ──
    л = [ч, "ЗАХОД 2 · ПОРЦИЯ B — ИНСТРУМЕНТЫ", ч, шапка, ""]
    for заголовок, набор in СЛОИ[1:]:
        есть = [и for и in набор if и in точки]
        if not есть:
            continue
        л += [f"╔══ {заголовок} ══", ""]
        for и in есть:
            л += портрет_планеты(и, точки, асп) + [""]
        подпись = "ЧЕМ ЖИВЁТ" if "ВНУТРЕННИЕ" in заголовок else "ЧЕМ СТРОИТ"
        л += резюме_точек(есть, точки, подпись) + [""]
    л += ["  ▸ ЗАДАЧА ПОРЦИИ: по каждой точке — одна строка заметки:",
          "     чем она служит пути, названному в шапке.", ч]
    порции.append("\n".join(л))

    # ── порция C: связи ──
    л = [ч, "ЗАХОД 2 · ПОРЦИЯ C — УЗОР СВЯЗЕЙ", ч, шапка, ""]
    точные = [а for а in асп if а["вес"] == "ТОЧНЫЙ"]
    рабочие = [а for а in асп if а["вес"] == "РАБОЧИЙ"]
    фон = [а for а in асп if а["вес"] == "ФОНОВЫЙ"]
    if точные:
        л += ["  ── ТОЧНЫЕ СВЯЗИ — полной выкладкой ──"]
        for а in точные:
            л += [""] + аспект_полностью(а["а"], а["б"], точки, я, куспиды=куспиды)
    if рабочие:
        л += ["", "  ── РАБОЧИЕ СВЯЗИ ──"]
        for а in рабочие:
            л += [""] + аспект_полностью(а["а"], а["б"], точки, я, кратко=True, куспиды=куспиды)
    if фон:
        л += ["", "  ── ФОНОВЫЕ СВЯЗИ — окраска ──"]
        for а in фон:
            п = а.get("подсказка", {})
            л += [f"     {имя_точки(а['а'])} {а['аспект']} {имя_точки(а['б'])} · "
                  f"орб {а['орбис']:.2f}° · {п.get('фраза','')}"]
    л += резюме_аспектов(асп, точки)
    л += ["", "  ▸ ЗАДАЧА ПОРЦИИ: выписать узлы напряжения и дары —",
          "     что тянет врозь, что держит вместе.", ч]
    порции.append("\n".join(л))
    return порции


