def стеллиумы(точки, порог=3):
    """Скопления в одном знаке. Диспозитор скопления получает вес."""
    по_знакам = {}
    for и, т in точки.items():
        по_знакам.setdefault(т["знак"], []).append(и)
    найдено = []
    for з, состав in по_знакам.items():
        if len(состав) >= порог:
            упр = УПРАВИТЕЛЬ[з][0]
            найдено.append({"знак": з, "состав": состав, "сколько": len(состав),
                            "диспозитор": упр,
                            "смысл": f"{len(состав)} точки собраны в {з} — "
                                     f"через дела {statyi.ЗНАК_КАК_ОБЛАСТЬ.get(з,'')} "
                                     f"проходит непропорционально много жизни; "
                                     f"вся группа работает через {упр}"})
    найдено.sort(key=lambda x: -x["сколько"])
    return найдено


def точка_сборки(точки, я=None):
    """Вокруг чего держится вся карта — первое, что читает ИИ."""
    я = я or ядро_узора(точки)
    итог = {"судьбоносные": [], "ось": None, "хозяин": я.get("хозяин"),
            "перевес": я.get("перевес_стихии"), "нехватка": я.get("нехватка_стихии")}
    суд = [с for с in судьбоносные(точки) if с["аспект"] == "соединение"]
    итог["судьбоносные"] = суд
    ю, с_ = точки.get("Юж.Узел"), точки.get("Сев.Узел")
    if ю and с_:
        итог["ось"] = {"откуда": {"знак": ю["знак"], "градус": ю.get("словами", ""),
                                  "тег": ю["код"]["тег"], "суть": ю["код"]["суть"]},
                       "куда": {"знак": с_["знак"], "градус": с_.get("словами", ""),
                                "тег": с_["код"]["тег"], "суть": с_["код"]["суть"]}}
    return итог


def признаки_регистра(точки, я=None):
    """Машина считает признаки, НЕ оценивая человека: устройство карты."""
    я = я or ядро_узора(точки)
    высшие = {"Уран", "Нептун", "Плутон"}
    признаки = {}

    суд = судьбоносные(точки)
    тесные = [с for с in суд if с["аспект"] == "соединение" and с["орбис"] <= 3]
    признаки["кармический_слой"] = {
        "есть": bool(тесные),
        "что": [f"{имя_точки(с['узел'])} ☌ {имя_точки(с['планета'])} ({с['орбис']:.2f}°)"
                for с in тесные],
        "высшая_на_узле": [с["планета"] for с in тесные if с["планета"] in высшие],
    }
    хозяева = (я.get("хозяин") or {}).get("кто", [])
    признаки["хозяин_узора"] = {"кто": хозяева,
                                "высшая": bool(set(хозяева) & высшие)}
    асп = я.get("аспекты", [])
    счёт = {}
    for а in асп:
        for к in (а["а"], а["б"]):
            if к in высшие:
                счёт[к] = счёт.get(к, 0) + 1
    признаки["связность_высших"] = счёт
    особые = []
    for и, т in точки.items():
        ф = т["код"].get("флаг", "")
        if ф and ф not in ("НЕТ", ""):
            особые.append(f"{имя_точки(и)}: {ф}")
    признаки["особые_градусы"] = особые
    опп = [а for а in асп if а["аспект"] in ("оппозиция", "квадрат") and а.get("вес") != "ФОНОВЫЙ"]
    признаки["напряжений"] = len(опп)
    признаки["перевес_стихии"] = я.get("перевес_стихии")

    # свод по признакам
    очки = 0
    if признаки["кармический_слой"]["есть"]:
        очки += 2
    if признаки["кармический_слой"]["высшая_на_узле"]:
        очки += 2
    if признаки["хозяин_узора"]["высшая"]:
        очки += 2
    if len(особые) >= 5:
        очки += 1
    if признаки["напряжений"] >= 5:
        очки += 1
    if признаки["перевес_стихии"] in ("вода", "огонь"):
        очки += 1
    признаки["очки"] = очки
    признаки["регистр"] = ("ВЫСОКИЙ — карта задаёт путь внутренней работы и переплавки"
                           if очки >= 6 else
                           "СРЕДНИЙ — есть и глубина, и земные задачи"
                           if очки >= 3 else
                           "БЫТОВОЙ — карта про дела, семью, ремесло и достаток")
    признаки["оговорка"] = ("это оценка УСТРОЙСТВА КАРТЫ, а не человека: "
                            "карта показывает задачу и потенциал, а не то, взялся ли он за неё")
    return признаки


