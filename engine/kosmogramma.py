def завязки(имя, точки, орб=3.0):
    """Натальные связи этой точки теснее заданного орбиса — её ближний круг."""
    если = []
    if имя not in точки:
        return если
    for другой, т in точки.items():
        if другой == имя:
            continue
        d = дуга(точки[имя]["градус"], т["градус"])
        for ан, угол in АСПЕКТЫ:
            о = abs(d - угол)
            if о <= орб:
                если.append({"с": другой, "аспект": ан, "орбис": round(о, 2)})
                break
    если.sort(key=lambda x: x["орбис"])
    return если


