def дом_точки(градус, куспиды):
    """В каком доме стоит точка."""
    if not куспиды:
        return None
    for i in range(12):
        а, б = куспиды[i], куспиды[(i + 1) % 12]
        ш = ((б - а) % 360) or 360
        if ((градус - а) % 360) < ш:
            return i + 1
    return 12


def управитель_дома(номер, куспиды, точки):
    """Знак на куспиде даёт планету — она и есть хозяин дома.

    Это то, чем читалась чужая карта: «управитель пятого дома заперт
    в двенадцатом» — ключ от творчества в комнате забвения.
    """
    if not куспиды or not (1 <= номер <= 12):
        return None
    куспид = куспиды[номер - 1]
    зн = знак(куспид)
    хозяин = УПРАВИТЕЛЬ[зн][0]
    где = точки.get(хозяин)
    return {
        "дом": номер,
        "сфера": СФЕРА_ДОМА[номер],
        "знак_куспида": зн,
        "градус_куспида": куспид,
        "код_куспида": kod360.code_by_abs(куспид),
        "хозяин": хозяин,
        "хозяин_в_знаке": где["знак"] if где else None,
        "хозяин_в_доме": дом_точки(где["градус"], куспиды) if где else None,
        "хозяин_градус": где.get("словами") if где else None,
        "хозяин_код": где["код"]["тег"] if где else None,
    }


def все_управители(куспиды, точки):
    """Двенадцать хозяев и где каждый стоит."""
    return [управитель_дома(н, куспиды, точки) for н in range(1, 13)]


def дом_текстом(у):
    """Строка про один дом: чей он и где хозяин."""
    if not у:
        return []
    л = [f"  {у['дом']:2}-й дом · {у['сфера']}",
         f"      на куспиде {знак_словами(у['градус_куспида'])} "
         f"[{у['код_куспида']['tag']}]",
         f"      хозяин {у['хозяин']}"]
    if у["хозяин_в_доме"]:
        л.append(f"         стоит {у['хозяин_градус']} [{у['хозяин_код']}] "
                 f"→ в {у['хозяин_в_доме']}-м доме")
        л.append(f"         ▸ дела {у['сфера'].split(',')[0]} идут через сферу: "
                 f"{СФЕРА_ДОМА[у['хозяин_в_доме']]}")
    return л


def знак_словами(градус):
    """Градус в человеческом виде, для куспидов."""
    return градус_словами(градус)


def дневная_карта(солнце_градус, ас_градус):
    """Солнце над горизонтом или под ним. Влияет на достоинства."""
    д = (солнце_градус - ас_градус) % 360
    if 0 <= д < 180:
        return {"вид": "НОЧНАЯ", "поясн": "Солнце под горизонтом — "
                "сила идёт от Луны, ночная секта"}
    return {"вид": "ДНЕВНАЯ", "поясн": "Солнце над горизонтом — "
            "сила идёт от Солнца, дневная секта"}


def чем_владеет_в_домах(имя, куспиды, точки):
    """Какими ДОМАМИ владеет эта планета — то есть какие сферы жизни
    она за собой тянет.

    ⚠️ Его поправка 04.09: мало сказать «хозяин первого дома — Меркурий».
    Надо у каждой планеты писать, чем она владеет: Марс управитель
    восьмого, Уран шестого, Плутон третьего. Без этого карта читается
    неверно.
    """
    if not куспиды:
        return []
    свои = []
    for н in range(1, 13):
        зн = знак(куспиды[н - 1])
        if УПРАВИТЕЛЬ[зн][0] == имя:
            свои.append(н)
    return свои


def владение_домами_текстом(имя, куспиды, точки):
    """Строки для портрета: чем владеет и куда это приводит."""
    свои = чем_владеет_в_домах(имя, куспиды, точки)
    if not свои or not куспиды:
        return []
    т = точки.get(имя)
    где = дом_точки(т["градус"], куспиды) if т else None
    л = []
    номера = ", ".join(f"{н}-м" for н in свои)
    л.append(f"     ВЛАДЕЕТ ДОМАМИ: {номера}")
    for н in свои:
        л.append(f"        {н}-й дом — {СФЕРА_ДОМА[н]}")
    if где:
        л.append(f"     А САМА СТОИТ В {где}-м доме ({СФЕРА_ДОМА[где]})")
        for н in свои:
            если_то = ("дела этого дома человек ведёт сам, изнутри"
                       if н == где else
                       f"дела {н}-го дома идут через сферу {СФЕРА_ДОМА[где].split(',')[0]}")
            л.append(f"        ▸ {н}-й → {где}-й: {если_то}")
    return л
