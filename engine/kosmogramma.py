# правило сожжённости — классическое, вынесено в настройку, а не спрятано в коде
СЕРДЦЕ_СОЛНЦА = 0.2833      # 17 угловых минут
СОЖЖЕНА = 8.0
ПОД_ЛУЧАМИ = 17.0


def сожжённость(имя, точки):
    """Близость к Солнцу по классическому правилу (настройка выше)."""
    if имя == "Солнце" or "Солнце" not in точки or имя in ("Сев.Узел", "Юж.Узел"):
        return None
    d = дуга(точки[имя]["градус"], точки["Солнце"]["градус"])
    if d <= СЕРДЦЕ_СОЛНЦА:
        return ("В СЕРДЦЕ СОЛНЦА", f"{d*60:.0f}′ от Солнца — редчайшее положение: "
                "сила не гаснет, а наоборот получает высшее полномочие")
    if d <= СОЖЖЕНА:
        return ("СОЖЖЕНА", f"{d:.2f}° от Солнца — действует в тени духа: "
                "своей воли почти нет, всё подчинено замыслу Солнца, со стороны не видна")
    if d <= ПОД_ЛУЧАМИ:
        return ("под лучами", f"{d:.2f}° от Солнца — свет Солнца ещё слепит её, "
                "проявляется приглушённо")
    return None


