def ядро_узора(точки):
    """Кто в карте хозяин, куда сходятся цепи, что держит узор."""
    итог = {}

    # 1. цепи всех точек и куда они втекают
    вершины = {}
    цепи = {}
    for имя in точки:
        ц = цепь_диспозиторов(имя, точки)
        if not ц:
            continue
        цепи[имя] = ц
        в = ц["вершина"]
        вершины[в] = вершины.get(в, 0) + 1
    итог["цепи"] = цепи
    итог["счёт_вершин"] = dict(sorted(вершины.items(), key=lambda x: -x[1]))

    # 2. хозяин узора — куда сходится больше всего цепей
    if вершины:
        макс = max(вершины.values())
        хозяева = [и for и, н in вершины.items() if н == макс]
        итог["хозяин"] = {"кто": хозяева, "сколько_цепей": макс,
                          "всего_точек": len(точки)}

    # 3. сам себе хозяин — точка, чей управитель она сама
    сами = []
    for имя, т in точки.items():
        if УПРАВИТЕЛЬ.get(т["знак"], (None,))[0] == имя:
            сами.append({"кто": имя, "знак": т["знак"], "градус": т["текст"]})
    итог["в_своём_чертоге"] = сами

    # 4. рецепции
    итог["рецепции"] = рецепции(точки)

    # 5. склад
    ст, кр = стихии_кресты(точки)
    итог["стихии"] = ст
    итог["кресты"] = кр
    итог["перевес_стихии"] = max(ст, key=lambda к: len(ст[к])) if ст else None
    итог["нехватка_стихии"] = min(ст, key=lambda к: len(ст[к])) if ст else None
    итог["перевес_креста"] = max(кр, key=lambda к: len(кр[к])) if кр else None

    # 6. связи и конфигурации
    асп = аспекты_космограммы(точки)
    итог["аспекты"] = асп
    итог["точные"] = [а for а in асп if а["точный"]]
    итог["конфигурации"] = конфигурации(асп)

    # 7. самые связанные точки — узлы напряжения узора
    счёт = {}
    for а in асп:
        счёт[а["а"]] = счёт.get(а["а"], 0) + 1
        счёт[а["б"]] = счёт.get(а["б"], 0) + 1
    итог["связность"] = dict(sorted(счёт.items(), key=lambda x: -x[1]))
    return итог


def судьбоносные(точки, орб=3.0):
    """Связи узлов судьбы с планетами.

    ⚠️ Его поправка 20.08: соединение Северного узла с Плутоном (орб 1.14°)
    выпало у меня из показа, потому что порог «точных» стоял на 1°.
    Такие связи режут по-другому: ось «откуда-куда» проходит ЧЕРЕЗ эту планету,
    и это судьба, а не оттенок. Потому — отдельный блок и свой орбис.
    """
    найдено = []
    for узел in ("Сев.Узел", "Юж.Узел"):
        if узел not in точки:
            continue
        for имя, т in точки.items():
            if имя in ("Сев.Узел", "Юж.Узел"):
                continue
            d = дуга(точки[узел]["градус"], т["градус"])
            for ан, угол in (("соединение", 0), ("оппозиция", 180),
                             ("квадрат", 90), ("трин", 120), ("секстиль", 60)):
                о = abs(d - угол)
                if о <= орб:
                    роль = РОЛЬ.get(имя, ("", ""))[0]
                    если = ("путь вперёд проходит ЧЕРЕЗ эту силу — она и есть дорога"
                            if узел == "Сев.Узел" and ан == "соединение" else
                            "багаж прошлого держится ЭТОЙ силой — она и есть привычка"
                            if узел == "Юж.Узел" and ан == "соединение" else
                            f"дорога судьбы связана с тем, что отвечает за {роль}")
                    найдено.append({"узел": узел, "планета": имя, "аспект": ан,
                                    "орбис": round(о, 2), "смысл": если})
                    break
    найдено.sort(key=lambda x: x["орбис"])
    return найдено


