    точный = орбис <= 1.0
    стр = [f"  {имя_точки(а)}  {аспект} {угол}°  {имя_точки(б)}  ·  орбис {орбис:.2f}°"
           + ("  ← ТОЧНЫЙ" if точный else "")]
    стр += сторона(а, точки, та)
    стр += сторона(б, точки, тб)
    роль_а = РОЛЬ.get(а, ("", ""))[0] or а
    роль_б = РОЛЬ.get(б, ("", ""))[0] or б
    знак_б = тб.get("знак", "")
    тег_а = (та.get("код") or {}).get("тег", "")
    тег_б = (тб.get("код") or {}).get("тег", "")
    па = (та.get("подградусы") or [{}])[0]
    пб = (тб.get("подградусы") or [{}])[0]
    стр += ["     ── ЧТО ДАЁТ ЭТО СОЧЕТАНИЕ",
            f"        {ЧТО_ДАЁТ.get(аспект,'')}",
            f"        {роль_а} и {роль_б} сходятся по знаку {знак_б}"
            + (f" — сфера {знак_б}" if знак_б else ""),
            f"        общая тема (градусы): [{тег_а}] и [{тег_б}]"]
