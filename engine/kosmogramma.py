def шапка_захода(точки, я=None):
    """Идёт с КАЖДОЙ порцией: читатель ни на шаг не теряет, кого читает."""
    я = я or ядро_узора(точки)
    тс = точка_сборки(точки, я)
    рег = признаки_регистра(точки, я)
    л = ["┌─ КОГО ЧИТАЕМ (эта шапка идёт с каждой порцией) ─"]
    for с_ in тс["судьбоносные"]:
        л += [f"│  точка сборки: {имя_точки(с_['узел'])} ☌ {имя_точки(с_['планета'])} "
              f"({с_['орбис']:.2f}°) — {с_['смысл']}"]
    if тс["ось"]:
        о = тс["ось"]
        л += [f"│  путь: из [{о['откуда']['тег']}] ({о['откуда']['знак']}) "
              f"в [{о['куда']['тег']}] ({о['куда']['знак']})"]
    х = тс["хозяин"]
    if х:
        л += [f"│  хозяин узора: {', '.join(имя_точки(к) for к in х['кто'])} "
              f"— {х['сколько_цепей']} цепей из {х['всего_точек']}"]
    л += [f"│  склад: перевес {тс['перевес']}, нехватка {тс['нехватка']}",
          f"│  РЕГИСТР: {рег['регистр']}",
          "└─"]
    return "\n".join(л)


