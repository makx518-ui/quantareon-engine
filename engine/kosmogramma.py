def конфигурации(асп):
    """Тау-квадраты и большие трины — по уже найденным аспектам."""
    найдено = []
    квадраты = [(a["а"], a["б"]) for a in асп if a["аспект"] == "квадрат"]
    оппозиции = [(a["а"], a["б"]) for a in асп if a["аспект"] == "оппозиция"]
    трины = [(a["а"], a["б"]) for a in асп if a["аспект"] == "трин"]
    for х, у in оппозиции:
        for к in set([n for пара in квадраты for n in пара]):
            if (min(х, к), max(х, к)) in [(min(a, b), max(a, b)) for a, b in квадраты] and \
               (min(у, к), max(у, к)) in [(min(a, b), max(a, b)) for a, b in квадраты]:
                найдено.append({"вид": "тау-квадрат", "участники": [х, у, к],
                                "смысл": f"ось {х}–{у} упирается в {к} — там выход и там же давление"})
    for i, (а, б) in enumerate(трины):
        for в, г in трины[i + 1:]:
            общие = {а, б} & {в, г}
            if len(общие) == 1:
                третий = ({а, б} | {в, г}) - общие
                if len(третий) == 2:
                    п = sorted({а, б} | {в, г})
                    if any(x["аспект"] == "трин" and {x["а"], x["б"]} == set(третий)
                           for x in асп):
                        запись = {"вид": "большой трин", "участники": п,
                                  "смысл": "замкнутое течение — дар, который работает сам"}
                        if запись not in найдено:
                            найдено.append(запись)
    return найдено


