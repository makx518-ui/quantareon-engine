    текст = _re.sub(r"(?m)^[^\n]{0,40}в полочке нет строки[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^\s*\*{1,3}\s*$", "", текст)
    # 10.09 · служебное ловим ПО ПРИЗНАКУ, а не по списку слов: модель пишет
    # печать каждый раз по-новому («Точек в блоке:», «Ядра: у всех семи — 7/7 ✓»,
    # «Слоты зачина: из ПАСПОРТА»). Признак печати — счёт вида N/N или галочка
    # в короткой строке, либо ссылка на ПАСПОРТ и полочку.
    текст = _re.sub(r"(?m)^[^\n]{0,120}\b\d{1,3}\s*/\s*\d{1,3}\b[^\n]{0,120}$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,140}[✓✔][^\n]{0,60}$", "", текст)
    текст = _re.sub(r"(?m)^\s*Слоты зачина[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^\s*\([^)\n]{0,200}(полочк|аспектных строк|строк[аи]?\b)[^)\n]{0,200}\)\s*$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,80}(в полочке|по закону: не выдумываю|не выдумываю)[^\n]{0,120}$", "", текст)

    # заголовок вида «ИНСТРУМЕНТЫ · ВЛАД-СТОРОЖ» или «АСПЕКТНЫЙ КАРКАС · имя»
    текст = _re.sub(r"(?m)^\s*#*\s*[✦🌟🌙⬆🪐💫🏠🎯🔮📅]?\s*(?:ИНСТРУМЕНТЫ|КАРМИКА|КАРКАС|АСПЕКТНЫЙ КАРКАС)\s*·[^\n]*$", "", текст)

    вон_начало = (
        "Точек:", "Точек ", "Аспектных строк", "Аспектов:", "Строк-родителей",
        "Строк аспектов", "Управителей домов", "Фракталов:", "Синтез-строк",
        "Чек-лист", "ЧЕК-ЛИСТ", "Печать поставлена", "Начинаю",
        "Светила (Солнце", "Блок «", "блок «",
    )
