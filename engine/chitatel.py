def _файл(имя):
    п = ПОЛКА / имя
    return п.read_text(encoding="utf-8") if п.exists() else ""


def _спросить(система, сообщения, максимум=25000, температура=ТЕМПЕРАТУРА):
    """Один вызов модели через OpenRouter. Ключ — из окружения, не из кода."""
    ключ = os.environ.get("OPENROUTER_API_KEY", "")
    if not ключ:
        raise RuntimeError("нет OPENROUTER_API_KEY в окружении — пропиши на Render")
    тело = json.dumps({
        "model": МОДЕЛЬ,
        "max_tokens": максимум,
        "temperature": температура,
        "messages": [{"role": "system", "content": система}] + сообщения,
    }, ensure_ascii=False).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело, headers={
        "Content-Type": "application/json",
        "Authorization": f"Bearer {ключ}",
        "HTTP-Referer": "https://quantareon.com",
        "X-Title": "QUANTAREON Chitatel",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=900) as о:
            ответ = json.loads(о.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробно = e.read().decode("utf-8", "ignore")[:400]
        raise RuntimeError(f"OpenRouter {e.code}: {подробно}")
    выбор = (ответ.get("choices") or [{}])[0]
    текст = ((выбор.get("message") or {}).get("content") or "").strip()
    if not текст:
        raise RuntimeError(f"модель вернула пусто: {str(ответ)[:300]}")
    return текст


def _без_служебного(текст):
    """Чек-лист печатью нужен для дисциплины читателя (METODOLOGIYA_II),
    но клиенту не показывается. Режем строки счёта, оставляя разбор."""
    # 09.09: служебное иногда приходит склеенным в одну строку без переносов —
    # «ЧЕК-ЛИСТ ПЕЧАТЬЮ:Аспектов: 25/25 ✓Синтез-полочка: ✓». Такие куски режем
    # выражением, а не построчно.
    import re as _re
    # 11.09 · его правка: всё служебное читатель кладёт между метками
    # <служебное>…</служебное>. Режем по метке — неважно, какими словами
    # он там писал. Прежние фильтры ниже остаются вторым слоем.
    текст = _re.sub(r"(?is)<\s*служебное\s*>.*?<\s*/\s*служебное\s*>", "", текст)
    текст = _re.sub(r"(?is)<\s*/?\s*служебное\s*>", "", текст)
    # формы признаний о нехватке данных — вылезли в карте 10.09
    текст = _re.sub(r"(?m)^[^\n]{0,70}[Чч]естная граница[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,90}(без выдумывания данных|обозначен как отсутствующ|машиной не дан|машиной не выдан)[^\n]*$", "", текст)
    текст = _re.sub(r"ЧЕК-ЛИСТ[^\n]{0,400}", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,80}ПРОХОД\s*[12][^\n]{0,120}$", "", текст)
    текст = _re.sub(r"(?m)^\s*#+\s*[^\n]*ПРОХОД\s*[12][^\n]*$", "", текст)
    текст = _re.sub(r"[^\n]{0,60}(Блок|блок)\s*«[^»]+»\s*(завершён|прочитан|закончен)[^\n]{0,160}", "", текст)
    текст = _re.sub(r"Готов к следующему блоку[^\n]{0,160}", "", текст)
    текст = _re.sub(r"(?:Аспектов|Точек|Строк|Управителей|Фракталов|Синтез-строк|Синтез-полочка)[^\n]{0,10}:\s*[^\n]{0,60}[✓✔][^\n]{0,120}", "", текст)
    # 10.09: формы, что проскочили в прогоне 12:48
    текст = _re.sub(r"(?m)^\s*Строк\s+\w+:\s*\d+/\d+[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,40}в полочке нет строки[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^\s*\*{1,3}\s*$", "", текст)
    # 10.09 · служебное ловим ПО ПРИЗНАКУ, а не по списку слов: модель пишет
    # печать каждый раз по-новому («Точек в блоке:», «Ядра: у всех семи — 7/7 ✓»,
    # «Слоты зачина: из ПАСПОРТА»). Признак печати — счёт вида N/N или галочка
    # в короткой строке, либо ссылка на ПАСПОРТ и полочку.
    текст = _re.sub(r"(?m)^[^\n]{0,120}\b\d{1,3}\s*/\s*\d{1,3}\b[^\n]{0,120}$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,140}[✓✔][^\n]{0,60}$", "", текст)
    текст = _re.sub(r"(?m)^\s*Слоты зачина[^\n]*$", "", текст)
    текст = _re.sub(r"(?m)^\s*\([^)\n]{0,200}(полочк|аспектных строк|строк[аи]?\b)[^)\n]{0,200}\)\s*$", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,80}(в полочке|по закону: не выдумываю|не выдумываю)[^\n]{0,120}$", "", текст)

    # заголовок вида «ИНСТРУМЕНТЫ · ВЛАД-СТОРОЖ» или «АСПЕКТНЫЙ КАРКАС · имя»
    текст = _re.sub(r"(?m)^\s*#*\s*[✦🌟🌙⬆🪐💫🏠🎯🔮📅]?\s*(?:ИНСТРУМЕНТЫ|КАРМИКА|КАРКАС|АСПЕКТНЫЙ КАРКАС)\s*·[^\n]*$", "", текст)

    вон_начало = (
        "Точек:", "Точек ", "Аспектных строк", "Аспектов:", "Строк-родителей",
        "Строк аспектов", "Управителей домов", "Фракталов:", "Синтез-строк",
        "Чек-лист", "ЧЕК-ЛИСТ", "Печать поставлена", "Начинаю",
        "Светила (Солнце", "Блок «", "блок «",
    )
    вон_внутри = (
        "по закону атома. Все", "прочитан. Все", "Печать поставлена",
        "точек N/N", "строк M/M", "— в предыдущем блоке",
    )
    строки = []
    for л in текст.split("\n"):
        г = л.strip()
        if not г:
            строки.append(л)
            continue
        if any(г.startswith(в) for в in вон_начало):
            continue
        if any(в in г for в in вон_внутри) and len(г) < 220:
            continue
        # строка вида «✦Вступление», за которой шёл только счёт
        if г in ("Вступление", "✦Вступление", "## Вступление"):
            continue
        строки.append(л)
    т = "\n".join(строки).strip()
    import re as _re
    т = _re.sub(r"\n{3,}", "\n\n", т)
    return т


def _разделы_из_текста(текст, первый=True):
    """Markdown читателя → [(заголовок, текст), ...] для karta_html."""
    текст = текст.strip()
    # выкидываем возможную обёртку кода
    текст = re.sub(r"^```(?:markdown)?\s*|\s*```$", "", текст)
    части = re.split(r"\n#{1,3} ", "\n" + текст)
    разделы = []
    вступление = части[0].strip().lstrip("#").strip()
    if вступление and первый:
        # первая строка может быть общим заголовком — выбрасываем её
        строки = [с for с in вступление.split("\n") if с.strip() and not с.strip().startswith("---")]
        if строки and len(строки[0]) < 80 and строки[0].isupper():
            строки = строки[1:]
        if строки:
            разделы.append(("Вступление", "\n".join(строки).strip()))
    служебные = ("проход 1", "проход 2", "чек-лист", "печать", "вступление")
    for ч in части[1:]:
        стр = ч.split("\n", 1)
        заг = стр[0].strip().rstrip(":")
        тело = стр[1].strip() if len(стр) > 1 else ""
        # служебный заголовок («ПРОХОД 2 · БЛОК …») не создаёт раздела:
        # его содержимое присоединяется к предыдущему
        низ = заг.lower().lstrip("✦🌟🌙⬆🪐💫🏠🎯🔮📅# ")
        if any(низ.startswith(с) for с in служебные) or "блок «" in низ:
            if тело and разделы:
                разделы[-1] = (разделы[-1][0], разделы[-1][1] + "\n\n" + тело)
            elif тело:
                разделы.append(("", тело))
            continue
        if тело:
            разделы.append((заг, тело))
    return разделы


def _система(доп=""):
    """Ядро читателя + полный закон. Оба файла Оракула, дословно."""
    я = _файл(ЯДРО)
    м = _файл(МЕТОДОЛОГИЯ)
    if not я:
        raise RuntimeError("на полке нет PROMPT_CORE.md")
    сис = я + "\n\n═══ ПОЛНАЯ МЕТОДОЛОГИЯ ═══\n" + м
    if доп:
        сис += "\n\n" + доп
    return сис


