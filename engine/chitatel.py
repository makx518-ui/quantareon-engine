    if ЧИТАТЕЛЬ == "gemini":
        return _спросить_gemini(система, сообщения, максимум, бесплатно=бесплатно, timeout=timeout)
    ключ = os.environ.get("OPENROUTER_API_KEY", "")
    if not ключ:
        raise RuntimeError("нет OPENROUTER_API_KEY в окружении — пропиши на Render")
    тело = json.dumps({
        "model": МОДЕЛЬ,
        "max_tokens": максимум,
        "temperature": температура,
        "messages": [{"role": "system", "content": система}] + сообщения,
    }, ensure_ascii=False).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело, headers={
        "Content-Type": "application/json",
        "Authorization": f"Bearer {ключ}",
        "HTTP-Referer": "https://quantareon.com",
        "X-Title": "QUANTAREON Chitatel",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=timeout) as о:
            ответ = json.loads(о.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробно = e.read().decode("utf-8", "ignore")[:400]
        raise RuntimeError(f"OpenRouter {e.code}: {подробно}")
    выбор = (ответ.get("choices") or [{}])[0]
    _ОБРЫВ["было"] = выбор.get("finish_reason") == "length"
    текст = ((выбор.get("message") or {}).get("content") or "").strip()
    if not текст:
        raise RuntimeError(f"модель вернула пусто: {str(ответ)[:300]}")
    return текст


