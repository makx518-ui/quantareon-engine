def _файл(имя):
    п = ПОЛКА / имя
    return п.read_text(encoding="utf-8") if п.exists() else ""


def _спросить(система, сообщения, максимум=25000, температура=ТЕМПЕРАТУРА):
    """Один вызов модели через OpenRouter. Ключ — из окружения, не из кода."""
    ключ = os.environ.get("OPENROUTER_API_KEY", "")
    if not ключ:
        raise RuntimeError("нет OPENROUTER_API_KEY в окружении — пропиши на Render")
    тело = json.dumps({
        "model": МОДЕЛЬ,
        "max_tokens": максимум,
        "temperature": температура,
        "messages": [{"role": "system", "content": система}] + сообщения,
    }, ensure_ascii=False).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело, headers={
        "Content-Type": "application/json",
        "Authorization": f"Bearer {ключ}",
        "HTTP-Referer": "https://quantareon.com",
        "X-Title": "QUANTAREON Chitatel",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=900) as о:
            ответ = json.loads(о.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробно = e.read().decode("utf-8", "ignore")[:400]
        raise RuntimeError(f"OpenRouter {e.code}: {подробно}")
    выбор = (ответ.get("choices") or [{}])[0]
    текст = ((выбор.get("message") or {}).get("content") or "").strip()
    if not текст:
        raise RuntimeError(f"модель вернула пусто: {str(ответ)[:300]}")
    return текст


def _без_служебного(текст):
    """Чек-лист печатью нужен для дисциплины читателя (METODOLOGIYA_II),
    но клиенту не показывается. Режем строки счёта, оставляя разбор."""
    # 09.09: служебное иногда приходит склеенным в одну строку без переносов —
    # «ЧЕК-ЛИСТ ПЕЧАТЬЮ:Аспектов: 25/25 ✓Синтез-полочка: ✓». Такие куски режем
    # выражением, а не построчно.
    import re as _re
    текст = _re.sub(r"ЧЕК-ЛИСТ[^\n]{0,400}", "", текст)
    текст = _re.sub(r"(?m)^[^\n]{0,80}ПРОХОД\s*[12][^\n]{0,120}$", "", текст)
    текст = _re.sub(r"(?m)^\s*#+\s*[^\n]*ПРОХОД\s*[12][^\n]*$", "", текст)
    текст = _re.sub(r"[^\n]{0,60}(Блок|блок)\s*«[^»]+»\s*(завершён|прочитан|закончен)[^\n]{0,160}", "", текст)
    текст = _re.sub(r"Готов к следующему блоку[^\n]{0,160}", "", текст)
    текст = _re.sub(r"(?:Аспектов|Точек|Строк|Управителей|Фракталов|Синтез-строк|Синтез-полочка)[^\n]{0,10}:\s*[^\n]{0,60}[✓✔][^\n]{0,120}", "", текст)

    вон_начало = (
        "Точек:", "Точек ", "Аспектных строк", "Аспектов:", "Строк-родителей",
        "Строк аспектов", "Управителей домов", "Фракталов:", "Синтез-строк",
        "Чек-лист", "ЧЕК-ЛИСТ", "Печать поставлена", "Начинаю",
        "Светила (Солнце", "Блок «", "блок «",
    )
    вон_внутри = (
        "по закону атома. Все", "прочитан. Все", "Печать поставлена",
        "точек N/N", "строк M/M", "— в предыдущем блоке",
    )
    строки = []
    for л in текст.split("\n"):
        г = л.strip()
        if not г:
            строки.append(л)
            continue
        if any(г.startswith(в) for в in вон_начало):
            continue
        if any(в in г for в in вон_внутри) and len(г) < 220:
            continue
        # строка вида «✦Вступление», за которой шёл только счёт
        if г in ("Вступление", "✦Вступление", "## Вступление"):
            continue
        строки.append(л)
    т = "\n".join(строки).strip()
    import re as _re
    т = _re.sub(r"\n{3,}", "\n\n", т)
    return т


def _разделы_из_текста(текст, первый=True):
    """Markdown читателя → [(заголовок, текст), ...] для karta_html."""
    текст = текст.strip()
    # выкидываем возможную обёртку кода
    текст = re.sub(r"^```(?:markdown)?\s*|\s*```$", "", текст)
    части = re.split(r"\n#{1,3} ", "\n" + текст)
    разделы = []
    вступление = части[0].strip().lstrip("#").strip()
    if вступление and первый:
        # первая строка может быть общим заголовком — выбрасываем её
        строки = [с for с in вступление.split("\n") if с.strip() and not с.strip().startswith("---")]
        if строки and len(строки[0]) < 80 and строки[0].isupper():
            строки = строки[1:]
        if строки:
            разделы.append(("Вступление", "\n".join(строки).strip()))
    служебные = ("проход 1", "проход 2", "чек-лист", "печать", "вступление")
    for ч in части[1:]:
        стр = ч.split("\n", 1)
        заг = стр[0].strip().rstrip(":")
        тело = стр[1].strip() if len(стр) > 1 else ""
        # служебный заголовок («ПРОХОД 2 · БЛОК …») не создаёт раздела:
        # его содержимое присоединяется к предыдущему
        низ = заг.lower().lstrip("✦🌟🌙⬆🪐💫🏠🎯🔮📅# ")
        if any(низ.startswith(с) for с in служебные) or "блок «" in низ:
            if тело and разделы:
                разделы[-1] = (разделы[-1][0], разделы[-1][1] + "\n\n" + тело)
            elif тело:
                разделы.append(("", тело))
            continue
        if тело:
            разделы.append((заг, тело))
    return разделы


def _система(доп=""):
    """Ядро читателя + полный закон. Оба файла Оракула, дословно."""
    я = _файл(ЯДРО)
    м = _файл(МЕТОДОЛОГИЯ)
    if not я:
        raise RuntimeError("на полке нет PROMPT_CORE.md")
    сис = я + "\n\n═══ ПОЛНАЯ МЕТОДОЛОГИЯ ═══\n" + м
    if доп:
        сис += "\n\n" + доп
    return сис


def прочитать(слой1, слой2=None, заказ="natal", имя="человек",
              данные_рождения=None, полочка=None, точки=None, куспиды=None, углы=None,
              рождение=None, местное=None, место="", пояс=None):
    """Натал по схеме Оракула: проход-1 молча → блоки по одному.

    Возвращает {'razdely': [...], 'tekst': '...', 'gologramma': '...'}.
    Полочку собирает engine/most.py их же сценарием.
    """
    кто = имя
    if данные_рождения:
        д = данные_рождения
        кто = f"{имя} · {д.get('дата','')}" + (f", {д.get('время')}" if д.get("время") else "") \
              + (f" · {д.get('место')}" if д.get("место") else "")

    # ── полочка: их сценарий на наших расчётах
    from engine import most as _мост
    полка = ""
    if точки and куспиды and len(куспиды) >= 12:
        полка = _мост.полочка_натала(точки, куспиды, углы, имя=имя, рождение=рождение,
                                     место=место, пояс=пояс, местное=местное)
    if not полка:
        # космограмма (времени рождения нет) — домов нет, их сценарий не применим
        полка = полочка or слой1 or ""
    паттерны = _файл(ПАТТЕРНЫ)
    мини = _файл(МИНИ_ЭТАЛОНЫ)
    эталон = _файл(ЭТАЛОН_КАРМИКИ)

    # ── ПРОХОД 1 · чтение молча, наружу ни слова
    голограмма = _спросить(
        _система("═══ БИБЛИОТЕКА ПАТТЕРНОВ ГРАДУСОВ ═══\n" + паттерны),
        [{"role": "user", "content":
            f"Карта: {кто}.\n\nПОЛНАЯ ПОЛОЧКА МАШИНЫ:\n\n{полка}\n\n"
            "ЭТО ПРОХОД 1 по методологии. Прочти ВСЮ полочку молча, полочка за полочкой, "
            "с первой строки до последней: полный обход с чек-листом покрытия; узор целиком "
            "(стихии, оси, конфигурации, диспозиторные цепи до вершины); главный узел карты — "
            "корень и его господин. Итог — ГОЛОГРАММА: объёмное ядро гороскопа, понимание "
            "«кто эта личность и что за судьба». Наружу трактовку не пиши: только голограмму "
            "для себя, сжато."}],
        максимум=6000)

    # ── ПРОХОД 2 · блоками, один блок за вызов
    разделы, куски = [], []
    for блок, о_чём in БЛОКИ_НАТАЛА:
        полка_блока = _мост.кусок(полка, блок) or полка
        задание = (f"ЭТО ПРОХОД 2, блок «{блок}» ({о_чём}).\n\n"
                   f"[ГОЛОГРАММА прохода-1]\n{голограмма}\n\n"
                   f"[ПОЛОЧКА БЛОКА — только он]\n{полка_блока}\n\n"
                   f"[МИНИ-ЭТАЛОН — образец звучания]\n{мини}\n\n")
        if блок == "кармика":
            задание += ("[ЭТАЛОН ПРОЧТЕНИЯ — живой образец исполнения]\n"
                        + эталон[:20000] + "\n\n")
            задание += ("Начни с канона зачина (МИНИ-0) — слоты бери из ПАСПОРТА полочки. "
                        "Затем кармика пятью вопросами: ЮУ откуда → СУ куда (и инструмент "
                        "при цели) → ЧЛ что искушает → БЛ что спасает → Хирон: рана и её "
                        "причина по диспозитору. Затем СВЕТИЛА — Солнце и Луна, каждое по "
                        "закону атома; и ОСИ — асцендент и MC. Их строки в этой полочке.")
        elif блок == "инструменты":
            задание += ("Изнутри наружу, начиная С МЕРКУРИЯ: Меркурий, Венера, Марс → "
                        "Юпитер, Сатурн → Уран, Нептун, Плутон. Затем управители двенадцати "
                        "домов. Каждая точка — по закону атома, без пропусков.\n"
                        "Светила и оси уже разобраны в предыдущем блоке — не повторяй их. "
                        "Чёрная и Белая Луна тоже разобраны в кармике: здесь их не трогай.")
        else:
            задание += ("Аспектный каркас: конфигурации целиком, дары и задачи, высшие не "
                        "глушатся; каждый аспект с обоих концов. Затем синтез: главный узел, "
                        "причинная цепь, исход. И прощание.")
        задание += ("\n\nПеред блоком предъяви чек-лист печатью («точек N/N, строк M/M»). "
                    "Работай только с этой полочкой; ни одной фразы без строки-родителя.\n"
                    "ГРАДУС И КОД берутся ТОЛЬКО из строки той самой точки, которую "
                    "разбираешь. Не бери у соседней строки: точки идут подряд и легко "
                    "спутать. Если строки точки в этой полочке нет — не пиши «градус из "
                    "полочки такой-то» и не выдумывай: просто не называй градус.\n"
                    "СЛОВА ПРО РАССТОЯНИЕ: «вплотную», «впритык», «рядом» — только при "
                    "СОЕДИНЕНИИ. При ОППОЗИЦИИ говори «напротив, через всю карту»; "
                    "при квадрате — «под прямым углом»; при трине и секстиле — «в ладу», "
                    "«протягивает руку». Не путай концы оси: если точка соединена с одним "
                    "узлом, то второму она СМОТРИТ НАПРОТИВ, а не стоит вплотную.")
        текст = _спросить(_система(), [{"role": "user", "content": задание}],
                          максимум=ПРЕДЕЛ_ОТВЕТА.get(заказ, 25000) // 2)
        текст = _без_служебного(текст)
        # 09.09 · СТОРОЖ: числа и коды сверяются с расчётом машины.
        # Случай, ради которого он поставлен: читатель написал Солнцу градус
        # Меркурия — соседнюю строку полочки. Правило «не выдумывай» этого не
        # остановило; сторож правит на машинное, ложь до клиента не доходит.
        if точки:
            try:
                from engine import storozh as _стор
                текст, _правки = _стор.выправить(текст, точки, куспиды)
                if _правки:
                    print("СТОРОЖ выправил:", "; ".join(_правки[:6]))
            except Exception as _e:
                print("СТОРОЖ не сработал:", _e)
        куски.append(текст)
        разделы += _разделы_из_текста(текст, первый=(блок == "кармика"))

    return {"razdely": разделы, "tekst": "\n\n".join(куски), "gologramma": голограмма,
            "razbor": голограмма}
