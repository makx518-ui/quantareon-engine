def _градусы_один_раз(текст):
    """30.09 · каркас читался справочником: «секстиль к Асценденту в 6°22′ Козерога, к Луне в
    5°50′ Козерога…» — один и тот же градус по пять раз. Градус точки называется при первой
    встрече в главе, дальше — только имя. Заголовки не трогаем."""
    было = set()
    def зам(м):
        ключ = re.sub(r"\s+", " ", м.group(2))
        if ключ in было:
            return ""
        было.add(ключ)
        return м.group(0)
    строки = []
    for с in текст.split("\n"):
        if re.match(r"\s*#", с):
            строки.append(с)
            continue
        с = re.sub(r"(,?\s(?:на|в)\s)(\d{1,2}°\d{2}′\s+[А-ЯЁ][а-яё]+)", зам, с)
        строки.append(re.sub(r"\s+([,.;:])", r"\1", с))
    return "\n".join(строки)


