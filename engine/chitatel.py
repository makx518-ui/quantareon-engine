# -*- coding: utf-8 -*-
"""
chitatel.py — ЧИТАТЕЛЬ · 08.09.2026.

Его закон: машина считает и раскладывает всё, читатель ничего не считает —
только оживляет. Здесь тот кусок, что зовёт модель: берёт полочку слоя,
берёт промпт с полки (data/chitatel/) и возвращает готовые разделы для карты.

Модель зовётся через OpenRouter — тем же ключом, что и аудит: OPENROUTER_API_KEY
(он уже стоит на Render). Модель по умолчанию — Opus 4.8, строка взята из его
проекта аудита, где она проверена в бою; сменить можно переменной READER_MODEL.

Полочка соляра большая (≈150 тыс. знаков), поэтому чтение идёт в два хода:
  1) ЧТЕНИЕ МОЛЧА — модель получает полочку и отвечает коротким разбором:
     суть года, ядро, нить, приоритеты (шаг 2 промпта);
  2) РАССКАЗ — модель получает тот же разбор и пишет текст по разделам.
Так ни один заход не превышает того, что читается целиком, и ничего не выпадает.
"""
import os
import json
import re
from pathlib import Path

import urllib.request
import urllib.error

ПОЛКА = Path(__file__).resolve().parent.parent / "data" / "chitatel"
ПРОМПТЫ = {
    "natal": "PROMPT_1_NATAL.md",
    "kosmogramma": "PROMPT_1_NATAL.md",
    "solyar": "PROMPT_2_SOLYAR.md",
    "tranzity": "PROMPT_2_SOLYAR.md",
}
ОБРАЗЦЫ = "OBRAZCY_CHTENIYA.md"
ЭТАЛОНЫ = {"natal": "ETALON_NATAL_Vlad.md", "kosmogramma": "ETALON_NATAL_Vlad.md",
           "solyar": "ETALON_SOLYAR_Vlad_2026.md", "tranzity": "ETALON_SOLYAR_Vlad_2026.md"}

МОДЕЛЬ = os.environ.get("READER_MODEL", "anthropic/claude-opus-4.8")
API = "https://openrouter.ai/api/v1/chat/completions"


def _файл(имя):
    п = ПОЛКА / имя
    return п.read_text(encoding="utf-8") if п.exists() else ""


def _спросить(система, сообщения, максимум=16000, температура=1.0):
    """Один вызов модели через OpenRouter. Ключ — из окружения, не из кода."""
    ключ = os.environ.get("OPENROUTER_API_KEY", "")
    if not ключ:
        raise RuntimeError("нет OPENROUTER_API_KEY в окружении — пропиши на Render")
    тело = json.dumps({
        "model": МОДЕЛЬ,
        "max_tokens": максимум,
        "temperature": температура,
        "messages": [{"role": "system", "content": система}] + сообщения,
    }, ensure_ascii=False).encode("utf-8")
    запрос = urllib.request.Request(API, data=тело, headers={
        "Content-Type": "application/json",
        "Authorization": f"Bearer {ключ}",
        "HTTP-Referer": "https://quantareon.com",
        "X-Title": "QUANTAREON Chitatel",
    })
    try:
        with urllib.request.urlopen(запрос, timeout=900) as о:
            ответ = json.loads(о.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробно = e.read().decode("utf-8", "ignore")[:400]
        raise RuntimeError(f"OpenRouter {e.code}: {подробно}")
    выбор = (ответ.get("choices") or [{}])[0]
    текст = ((выбор.get("message") or {}).get("content") or "").strip()
    if not текст:
        raise RuntimeError(f"модель вернула пусто: {str(ответ)[:300]}")
    return текст


def _разделы_из_текста(текст):
    """Markdown читателя → [(заголовок, текст), ...] для karta_html."""
    текст = текст.strip()
    # выкидываем возможную обёртку кода
    текст = re.sub(r"^```(?:markdown)?\s*|\s*```$", "", текст)
    части = re.split(r"\n#{1,3} ", "\n" + текст)
    разделы = []
    вступление = части[0].strip().lstrip("#").strip()
    if вступление:
        # первая строка может быть общим заголовком — выбрасываем её
        строки = [с for с in вступление.split("\n") if с.strip() and not с.strip().startswith("---")]
        if строки and len(строки[0]) < 80 and строки[0].isupper():
            строки = строки[1:]
        if строки:
            разделы.append(("Вступление", "\n".join(строки).strip()))
    for ч in части[1:]:
        стр = ч.split("\n", 1)
        заг = стр[0].strip().rstrip(":")
        тело = стр[1].strip() if len(стр) > 1 else ""
        if тело:
            разделы.append((заг, тело))
    return разделы


def прочитать(слой1, слой2=None, заказ="natal", имя="человек",
              данные_рождения=None, полочка=None):
    """Возвращает {'razdely': [...], 'tekst': '...', 'razbor': '...'}.

    слой1     — кухня натала (нужна всегда: соляр без натала не читается);
    слой2     — полочка второго слоя (для соляра и транзитов);
    полочка   — сжатая редакция слоя 2, если она уже посчитана.
    """
    промпт = _файл(ПРОМПТЫ.get(заказ, "PROMPT_1_NATAL.md"))
    if not промпт:
        raise RuntimeError(f"на полке нет промпта для заказа «{заказ}»")
    образцы = _файл(ОБРАЗЦЫ)
    эталон = _файл(ЭТАЛОНЫ.get(заказ, ""))

    система = (промпт
               + "\n\n═══ ОБРАЗЦЫ ЧТЕНИЯ ═══\n" + образцы
               + ("\n\n═══ ЭТАЛОН ТОНА (принят Владом; сверяйся с ним) ═══\n" + эталон[:24000]
                  if эталон else ""))

    кто = имя
    if данные_рождения:
        д = данные_рождения
        кто = f"{имя} · {д.get('дата','')}" + (f", {д.get('время')}" if д.get("время") else "") \
              + (f" · {д.get('место')}" if д.get("место") else "")

    материал = слой1 if заказ in ("natal", "kosmogramma") else (полочка or слой2 or "")
    вступ = ("Первый слой (натал) — ниже отдельно, он основание.\n\n" + слой1[:120000] + "\n\n"
             if заказ not in ("natal", "kosmogramma") and слой1 else "")

    # ── ход 1 · чтение молча
    разбор = _спросить(система, [{"role": "user", "content":
        f"Полочка машины для «{кто}», заказ: {заказ}.\n\n{вступ}{материал}\n\n"
        "═══ ЗАДАНИЕ · ШАГ ПЕРВЫЙ ═══\n"
        "Прочитай полочку целиком и ответь коротко, только для себя, не для клиента:\n"
        "1. СУТЬ — что это за карта (для года: чем год является по существу, из трёх мест полочки).\n"
        "2. ЯДРО — точка, к которой сходится больше всего; почему именно она.\n"
        "3. НИТЬ — одной фразой.\n"
        "4. ПРИОРИТЕТЫ — что в полный голос, что фразой, что молчит (списком).\n"
        "5. ЧТО НЕЛЬЗЯ ПОТЕРЯТЬ — перечисли строки полочки, которые обязаны прозвучать.\n"
        "Не пиши сам текст — только этот разбор."}],
        максимум=4000)

    # ── ход 2 · рассказ
    текст = _спросить(система, [
        {"role": "user", "content":
            f"Полочка машины для «{кто}», заказ: {заказ}.\n\n{вступ}{материал}"},
        {"role": "assistant", "content": разбор},
        {"role": "user", "content":
            "═══ ЗАДАНИЕ · ШАГ ВТОРОЙ ═══\n"
            "Теперь напиши текст клиенту по своему разбору — единым сквозным рассказом, "
            "по строению из промпта. Разделы обозначай строками вида «## Название раздела». "
            "Ни одного термина, ни градуса, ни орбиса; даты живут внутри живых фраз. "
            "Держи закон полноты и связности: ничего не потерять, ничего не выдумать, "
            "вести одну линию с причинами и следствиями. Пиши сразу текст, без предисловий о себе."}],
        максимум=16000)

    return {"razdely": _разделы_из_текста(текст), "tekst": текст, "razbor": разбор}
