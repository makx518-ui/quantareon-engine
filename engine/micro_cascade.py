"""Микрокаскад: внутри градуса лежит весь зодиак."""
ЗНАКИ = ['Овен','Телец','Близнецы','Рак','Лев','Дева','Весы','Скорпион','Стрелец','Козерог','Водолей','Рыбы']
СТИХИИ = ['Огонь','Земля','Воздух','Вода']

def cascade_from_absolute(abs_degree, levels=6):
    а = abs_degree % 360
    зн = int(а // 30)
    гр = а % 30
    сл = []
    доля = гр % 1
    шаг = 300.0
    for ур in range(1, levels+1):
        ч = доля * 12
        и = int(ч) % 12
        вн = (ч - int(ч)) * 30
        сл.append({"level": ур, "sign_index": и, "sign_name": ЗНАКИ[и],
                   "element": СТИХИИ[и % 4], "degree": вн,
                   "degree_int": int(вн), "degree_min": int((вн % 1) * 60),
                   "sabian": int(вн) + 1, "segment_size_arcsec": шаг})
        доля = вн % 1
        шаг = шаг / 12
    return {"abs_degree": а, "sign_index": зн, "sign_name": ЗНАКИ[зн],
            "degree": гр, "degree_int": int(гр), "cascade": сл}


