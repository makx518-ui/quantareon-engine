def _время_суток(час):
    """Как в паспорте расчёта (engine/most.паспорт): ночь до 4, раннее утро до 6, утро, день, вечер."""
    if час < 4:
        return "Была ночь"
    if час < 6:
        return "Было раннее утро"
    if час < 12:
        return "Было утро"
    if час < 18:
        return "Был день"
    return "Был вечер"


_морф = None


def _творительный(место):
    """«Петропавловск» → «Петропавловском»; не склоняется — None."""
    global _морф
    try:
        if _морф is None:
            import pymorphy3
            _морф = pymorphy3.MorphAnalyzer()
        def _сл(ч):
            разборы = _морф.parse(ч)
            гео = [р for р in разборы if "Geox" in р.tag] or [р for р in разборы if "NOUN" in р.tag] or разборы
            ф = гео[0].inflect({"ablt"})
            return ф.word if ф else None
        слова = []
        for сл in место.split():
            целиком = _сл(сл) if "-" in сл else None      # «Санкт-Петербург» склоняется целиком
            if целиком:
                слова.append("-".join(х[:1].upper() + х[1:] if о[:1].isupper() else х
                                      for х, о in zip(целиком.split("-"), сл.split("-")))
                             if целиком.count("-") == сл.count("-") else целиком)
                continue
            части = []
            for ч in сл.split("-"):
                разборы = _морф.parse(ч)
                гео = [р for р in разборы if "Geox" in р.tag] or [р for р in разборы if "NOUN" in р.tag] or разборы
                ф = гео[0].inflect({"ablt"})
                if not ф:
                    return None
                н = ф.word
                части.append(н[:1].upper() + н[1:] if ч[:1].isupper() else н)
            слова.append("-".join(части))
        return " ".join(слова)
    except Exception:
        return None


def _город(место):
    """«Советское / район … / область / Казахстан», «Петропавловск, Северо-Казахстанская область» → первое имя."""
    return re.split(r"\s*[/,]\s*", (место or "").strip())[0].strip()


def зачин(местное, место, знак_асц, знак_солнца):
    """Готовый зачин или "" (если чего-то нет — тогда остаётся зачин ИИ)."""
    if not местное or знак_асц not in _ЗНАК_РОД or знак_солнца not in _ЗНАК_РОД:
        return ""
    время = _время_суток(местное.hour)
    первая = ("И " + время[0].lower() + время[1:] + f" {_СЕЗОН[местное.month]}, "
              f"{_ДНИ[местное.day - 1]} день {_МЕСЯЦ[местное.month - 1]} {местное.year} года, "
              f"когда душа вошла в этот мир.")
    город = _город(место)
    над = _творительный(город) if город else None
    if над:
        где = f"В это время над {над} — над восточным горизонтом восходил"
    elif город:
        где = f"В это время там, где лежит {город}, — над восточным горизонтом восходил"
    else:
        где = "В это время над восточным горизонтом восходил"
    вторая = (f"{где} знак {_ЗНАК_РОД[знак_асц]}, {ВОСХОД[знак_асц]}, а Солнце стояло в знаке "
              f"{_ЗНАК_РОД[знак_солнца]}, {СОЛНЦЕ[знак_солнца]}.")
    return (первая + " " + вторая + "\n"
            "А читать эту Книгу надлежит с того узора, что был запечатлён с первым вздохом.")


