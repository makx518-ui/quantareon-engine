"""
РЕНДЕР ДНЯ — сборка текста суток из ядра.

Машина не сочиняет: берёт готовое ядро (yadro_dnya), одевает его словами из
малой библиотеки кармики и Азбуки 360 и выстраивает сквозной текст.

Наружу не идут названия планет, знаков, градусов и символов. Человек читает
про свой день.
"""
from __future__ import annotations

from engine import kosmogramma as K
from engine import biblioteka_karmiki as Б
from engine import slova_karmiki as С
from engine import yadro_dnya as Я

СФЕРА = {i: Б.ДОМ_СФЕРА[i][1] for i in range(1, 13)}


def _суть(п) -> str:
    """Суть градуса из Азбуки — без тега и без символики, только смысл.

    Принимает и точку целиком, и готовую строку сути.
    """
    if isinstance(п, str):
        с = п
    elif isinstance(п.get("код"), str):      # у схождения целей код уже строкой
        с = п.get("суть", "")
    else:
        с = (п.get("код") or {}).get("суть", "")
    if "Суть:" in с:
        с = с.split("Суть:", 1)[1]
    return с.strip().rstrip(".").split(";")[0].strip()


def ядро_абзацем(я: dict) -> str:
    """О чём день — живыми словами: строка + раскрытие + куда ведёт дальше."""
    о, к = я["вектор"]["откуда"], я["вектор"]["куда"]
    if not (о and к):
        return ""
    return С.ядро_абзацем(о["дом"], к["дом"], к["знак"])


def расстановка_живыми(я: dict) -> str:
    """Опора, цена, тень — живыми словами, без образов из Азбуки."""
    оп, бл, сб = я["опора"], я["боль"], я["соблазн"]
    т = я.get("тень_на_векторе")
    бьёт = tuple(b["дом"] for b in (т or {}).get("бьёт_по", []) if b.get("дом"))
    return С.расстановка_абзацем(
        оп["дом"] if оп else 0, бл["дом"] if бл else 0, сб["дом"] if сб else 0,
        тень_на_векторе=bool(т), бьёт_по=бьёт)


def расстановка_текстом(я: dict) -> list:
    строки = []
    оп, бл, сб = я["опора"], я["боль"], я["соблазн"]
    if оп:
        где = СФЕРА[оп["дом"]]
        угол = " и стоит прямо на точке дня" if оп.get("на_угле") else ""
        строки.append(f"Держит день то, что уже сделано честно: опора приходит {где}{угол}. "
                      f"{_суть(оп).capitalize()}.")
    if бл:
        строки.append(f"Цена движения известна: {_суть(бл)}. Сфера — {СФЕРА[бл['дом']]}.")
    if сб:
        т = я.get("тень_на_векторе")
        куда = СФЕРА[сб["дом"]]
        если_на_пути = (" Соблазн идёт по самой линии пути: он не останавливает, "
                        "он подменяет — работу видимостью, дело позой.") if т else ""
        бьёт = ""
        if т and т.get("бьёт_по"):
            дома = {b["дом"] for b in т["бьёт_по"] if b["дом"]}
            if дома:
                бьёт = " Бьёт туда, где сегодня сила: " + ", ".join(СФЕРА[d] for d in sorted(дома)) + "."
        строки.append(f"Уводит {куда}: {_суть(сб)}.{если_на_пути}{бьёт}")
    return строки


def наружу_текстом(я: dict, точки: dict, куспиды: list) -> list:
    """Как ядро проступает: личность, цель, схождение целей."""
    строки = []
    асц = K.точка("Асцендент", куспиды[0])
    мс = K.точка("MC", куспиды[9])
    хоз1 = K.УПРАВИТЕЛЬ[K.знак(куспиды[0])][0]
    т1 = точки.get(хоз1)
    дом1 = K.дом_точки(т1["градус"], куспиды) if т1 else None

    строки.append(f"День начинается с того, что {_суть(асц)}.")
    if дом1:
        строки.append(f"Делается он {СФЕРА[дом1]}: оттуда сегодня идёт всё остальное.")
    строки.append(f"Цель на виду: {_суть(мс)}.")

    сц = я.get("схождение_целей")
    if сц and сц.get("где_хозяин_пути"):
        г = сц["где_хозяин_пути"]
        строки.append(
            f"Внутренняя цель и цель на виду сошлись в одном: {_суть(г)}. "
            f"Сфера — {СФЕРА[г['дом']]}"
            + (", и делается это возвратом к уже накопленному." if г.get("ретро") else ".")
        )
    return строки


def реализация_текстом(я: dict) -> str:
    р = я.get("реализация") or {}
    исход = р.get("исход")
    if исход == "сразу":
        return ("Начатое сегодня сегодня и сложится: всё нужное под рукой, "
                "помех нет.")
    if исход == "с задержкой":
        return ("Начинать сегодня можно и нужно — всё нужное под рукой. "
                "Но часть дела зависит от других: от партнёров, друзей, "
                "работодателей. Завершение придёт позже.")
    return ("Для решающего шага день не годится: слишком многое связывает руки. "
            "Лучше подготовить и вернуться к этому позже.")


def собрать(я: dict, точки: dict, куспиды: list) -> str:
    ч = [ядро_абзацем(я), "", расстановка_живыми(я), "", реализация_текстом(я)]
    return "\n".join(ч)


