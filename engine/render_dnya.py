from datetime import timedelta

from engine.day_engine import асцендент_в, куспиды_в


def _чч(т, пояс_часов: int) -> str:
    return (т + timedelta(hours=пояс_часов)).strftime("%H:%M")


def когда_градус_на_угле(цель: float, момент, широта: float, долгота: float,
                         какой: str = "АС", предел_часов: int = 25) -> object:
    """Когда бегущий угол встанет на заданный градус. Поиск по минуте, уточнение делением."""
    шаг = timedelta(minutes=2)
    т = момент
    предел = момент + timedelta(hours=предел_часов)

    def угол(t):
        return асцендент_в(t, широта, долгота) if какой == "АС" else куспиды_в(t, широта, долгота)[9]

    пред = (угол(т) - цель) % 360
    while т < предел:
        т2 = т + шаг
        тек = (угол(т2) - цель) % 360
        if тек < пред:                       # перешли через цель
            низ, верх = т, т2
            while (верх - низ).total_seconds() > 20:
                сер = низ + (верх - низ) / 2
                if ((угол(сер) - цель) % 360) > 180:
                    низ = сер
                else:
                    верх = сер
            return верх.replace(microsecond=0)
        пред, т = тек, т2
    return None


def часы_дня(я: dict, точки: dict, куспиды: list, момент, широта: float,
             долгота: float, пояс_часов: int) -> dict:
    """Когда тема выходит наружу, когда возвращается и где сильный отрезок.

    Считается по одной опоре: якорный градус — сам асцендент момента.
    Он приходит на вершину карты — тема выходит на виду; возвращается на
    восход — круг замкнулся и тема стала понятной.
    """
    якорь = куспиды[0]
    наружу = когда_градус_на_угле(якорь, момент, широта, долгота, "MC")
    замок = когда_градус_на_угле(якорь, момент + timedelta(minutes=5),
                                 широта, долгота, "АС")

    # сильный отрезок — пока восходящий градус идёт по дому, где стоит опора;
    # слабый — где стоит тень
    def окно(дом: int):
        """Начало окна — ближайший приход АС на куспид дома; конец ищется ПОСЛЕ
        начала, иначе граница может попасть в другие сутки и окно вывернется."""
        if not дом:
            return None
        нач = когда_градус_на_угле(куспиды[дом - 1], момент, широта, долгота, "АС")
        if not нач:
            return None
        кон = когда_градус_на_угле(куспиды[дом % 12], нач + timedelta(minutes=3),
                                   широта, долгота, "АС")
        return (нач, кон) if кон else None

    оп, сб = я.get("опора"), я.get("соблазн")
    сильный = окно(оп["дом"]) if оп else None
    слабый = окно(сб["дом"]) if сб else None

    # ⚠️ бегущий угол приходит на градус раз в сутки, поэтому сутки отсчитываются
    # от самого момента вопроса, и часть окон попадает уже на следующий день.
    # Помечаем их, чтобы человек не искал их сегодня.
    def когда(т):
        if not т:
            return None
        мест = т + timedelta(hours=пояс_часов)
        сейчас_мест = момент + timedelta(hours=пояс_часов)
        ночью = мест.date() > сейчас_мест.date()
        return {"час": мест.strftime("%H:%M"), "за_полночь": ночью}

    def окно_чч(о):
        return (когда(о[0]), когда(о[1])) if о else None

    return {
        "наружу": когда(наружу),
        "замок": когда(замок),
        "сильный": окно_чч(сильный),
        "слабый": окно_чч(слабый),
    }


def _час(к) -> str:
    if not к:
        return ""
    return ("завтра в " if к["за_полночь"] else "в ") + к["час"]


def _окно(о) -> str:
    """«с 15:25 до 17:33» или «ночью, с 04:16 до 06:37»."""
    if not о:
        return ""
    a, b = о
    завтра = a["за_полночь"] and b["за_полночь"]
    начало = "завтра, с " if завтра else "с "
    return f"{начало}{a['час']} до {b['час']}"


def часы_текстом(ч: dict) -> str:
    строки = []
    if ч.get("наружу"):
        строки.append(f"Главное в дне проявится {_час(ч['наружу'])} — в этот час "
                      f"станет понятнее всего, о чём он.")
    if ч.get("сильный"):
        строки.append(f"Лучшее время: {_окно(ч['сильный'])} — дело идёт легче всего.")
    if ч.get("слабый"):
        строки.append(f"Трудное время: {_окно(ч['слабый'])} — легче всего "
                      f"отвлечься и потерять день.")
    if ч.get("замок"):
        строки.append(f"Круг замкнётся {_час(ч['замок'])}: то, с чего день начался, "
                      f"вернётся уже понятым.")
    return "\n".join(строки)
