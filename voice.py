def _вcё_вместо_все(текст: str) -> str:
    """«Все отлично» → «Всё отлично»."""
    def _r(m):
        слово, хвост = m.group(1), m.group(2)
        замена = "Всё" if слово[0].isupper() else "всё"
        return f"{замена} {хвост}"

    шаблон = r"\b(Все|все)\s+(" + "|".join(re.escape(с) for с in _ВСЁ_ПЕРЕД) + r")\b"
    return re.sub(шаблон, _r, текст)


_UDAR_SUBSTR = [
    ("кундалини", "кундалинии"),
    ("самому",    "самомуу"),
    ("среду",     "сридуу"),
]

_UDAR_ABBR = [
    ("ДНК", "дэ-эн-каа"),
    ("РНК", "эр-эн-каа"),
    ("ИИ",  "И-И"),
]


def _udar_to(text: str) -> str:
    """«-то» после дефиса → «-та»: разговорное безударное окончание.

    Движок читает «какая-ТО», «где-ТО» с ударением на конце, а в живой речи
    это «какая-та», «где-та». Правило узкое: трогаем ТОЛЬКО «то» после дефиса,
    поэтому отдельное «то» в «то есть», «то же самое», «в то время»
    остаётся нетронутым — там ударение законное.
    """
    def _r(m):
        w = m.group(0)
        # сохраняем тот же дефис, что был, меняем только гласную
        дефис = w[0]
        return дефис + ("Та" if w[1:2].isupper() else "та")

    # ⚠️ ДЕФИСЫ БЫВАЮТ РАЗНЫЕ. Модель ставит типографские: неразрывный
    # ‑ (U+2011), короткое тире – (U+2013), длинное — (U+2014). Правило
    # знало только обычный «-», поэтому в живой речи он продолжал говорить
    # «где-тО». Он это и услышал 08.08. Теперь ловим все виды.
    text = re.sub(r"(?<=[А-Яа-яЁё])[-\u2010\u2011\u2012\u2013\u2014]то\b",
                  _r, text)

    # и раздельное написание: модель иногда пишет «где то», «какая то»
    text = re.sub(r"\b(где|как|какая|какой|какое|какие|что|чего|чему|чем|"
                  r"кто|кого|кому|кем|когда|куда|откуда|почему|зачем|"
                  r"сколько|чей|чья|чьё|чьи)\s+то\b",
                  lambda m: f"{m.group(1)}-та", text, flags=re.IGNORECASE)
    return text


def _udar_godu(text: str) -> str:
    """«году» → «годду», но не после предлога «в».

    Движок читает «году́», а в живой речи помощника нужно «го́ду»:
    «каждый градус отвечает своему го́ду». ОДНАКО после предлога «в»
    ударение и правда падает на конец («в этом году́», «в следующем году́»),
    и там движок прав — эти места не трогаем. Смотрим одно-два слова слева.
    """
    def _r(m):
        # смотрим только текущий кусок предложения — до ближайшего знака слева,
        # иначе предлог из соседней фразы сбил бы решение
        отрезок = re.split(r"[.,;:!?—–()]", text[:m.start()])[-1]
        слова = [сл.lower() for сл in re.findall(r"[А-Яа-яЁё]+", отрезок)]
        # «в году», «в этом году», «в тысяча девятьсот девяносто третьем году»
        if "в" in слова:
            return m.group(0)
        w = m.group(0)
        return "Годду" if w[:1].isupper() else "годду"

    return re.sub(r"\bгоду\b", _r, text, flags=re.IGNORECASE)


def _apply_udar(text: str) -> str:
    """Подставить произносимые формы вместо капризных слов."""
    t = text

    def _keep_case(good):
        def _r(m):
            w = m.group(0)
            return good[0].upper() + good[1:] if w[:1].isupper() else good
        return _r

    for bad, good in _UDAR_SUBSTR:
        t = re.sub(re.escape(bad), _keep_case(good), t, flags=re.IGNORECASE)
    for bad, good in _UDAR_ABBR:
        t = t.replace(bad, good)

    def _wrepl(m):
        w = m.group(0)
        rep = _UDAR_WORDS[w.lower()]
        return rep[0].upper() + rep[1:] if w[0].isupper() else rep

    pattern = r"\b(" + "|".join(re.escape(k) for k in _UDAR_WORDS) + r")\b"
    t = re.sub(pattern, _wrepl, t, flags=re.IGNORECASE)

    t = _udar_godu(t)
    t = _вcё_вместо_все(t)
    t = _udar_to(t)
    return t


def _mnogotochiya(текст: str) -> str:
    """Точка между предложениями → многоточие. ТОЛЬКО на выходе в озвучку.

    Его выбор 11.08: с многоточиями речь ложится на слух чище. Правка живёт
    здесь, в _tts_clean, и никуда больше не попадает: в окне разговора текст
    остаётся с обычными точками, а запрет на многоточия в системном промпте
    (чтобы модель не обрывала мысль) НЕ ТРОГАЕМ — он про другое.

    ⚠️ Замер 11.08: длительность от этого НЕ растёт — меняется интонация,
    а не паузы. Если понадобятся настоящие паузы — делать тишиной при склейке.
    """
    т = текст or ""
    # только точка МЕЖДУ предложениями: слева конец слова, справа — начало
    # нового предложения с большой буквы. «?» и «!» не трогаем — там своя
    # интонация. Последнюю точку в реплике оставляем как есть.
    т = re.sub(r"(?<=[А-Яа-яЁёA-Za-z0-9»”)\]])\.\s+(?=[А-ЯЁA-Z«“\"])", "... ", т)
    # если точек подряд стало больше трёх — свести к трём
    т = re.sub(r"\.{4,}", "...", т)
    return т


def _tts_clean(text: str, language: str = "ru") -> str:
    """Готовим текст к озвучке: убираем то, что голос прочитал бы как мусор."""
    t = text or ""
    t = re.sub(r"\[sticker:[^\]]*\]", "", t, flags=re.IGNORECASE)      # служебные метки
    t = re.sub(r"[\U0001F000-\U0001FAFF\u2600-\u27BF\uFE0F]", "", t)   # эмодзи
    t = re.sub(r"\*{1,3}", "", t)                                       # **жирный**
    t = re.sub(r"#{1,6}\s*", "", t)                                      # ## заголовки
    t = re.sub(r"`+", "", t)                                             # `код`
    t = re.sub(r"\s+", " ", t).strip()

    # ≈ и прочие значки голос читает невнятно или пропускает
    t = t.replace("≈", " about ").replace("~", " about ") if not str(language).lower().startswith("ru") \
        else t.replace("≈", " примерно ").replace("~", " примерно ")

    if not str(language).lower().startswith("ru"):
        # 🔢 АНГЛИЙСКИЕ ЧИСЛА. Раньше их не трогали вовсе, и голос читал
        # «81.29 rubles» как «восемьдесят один точка двадцать девять».
        # Округляем так же, как в русской ветке: погода и крупные суммы —
        # до целых, курс валют — до сотых.
        def _окр_en(м):
            try:
                ч = float(м.group(1))
            except Exception:
                return м.group(0)
            return f"{round(ч)} {м.group(2).strip()}"

        t = re.sub(r"(-?\d+\.\d+)\s*(°\s?[CF]\b|degrees?\b)", _окр_en, t)
        t = re.sub(r"(\d+\.\d+)\s*(km/h|mph|m/s)", _окр_en, t)

        def _деньги_en(м):
            """Крупные суммы — без копеек, мелкие — не длиннее двух знаков.

            ⚠️ Раньше правило ловило только дроби в ТРИ знака и длиннее, а
            «64 852.49» проскакивало — голос читал «64 852 точка 49» с
            паузой посреди числа. Он это и услышал 07.08.
            """
            цел, дроб = м.group(1).strip(), м.group(2)
            голая = цел.replace(",", "").replace("\u00a0", "").replace(" ", "")
            try:
                крупное = int(голая) >= 1000
            except Exception:
                крупное = False
            if крупное:
                return цел            # 64 852.49 → «64 852»
            return f"{цел}.{дроб[:2]}"

        t = re.sub(r"(\d[\d,\u00a0 ]*)\.(\d+)", _деньги_en, t)
        t = re.sub(r"\babout\s+about\b", "about", t, flags=re.IGNORECASE)
        t = re.sub(r"(\d)\s?%", r"\1 percent", t)
        t = re.sub(r"\s?°\s?C\b", " degrees Celsius", t)
        t = re.sub(r"\bkm/h\b", "kilometers per hour", t)
        t = re.sub(r"\s+", " ", t).strip()

    if str(language).lower().startswith("ru"):
        # 🔢 ЧИСЛА С ЗАПЯТОЙ голос читает слитно: «32,2» звучит как
        # «триста двадцать два». Он это и поймал 07.08. Готовим числа
        # так, как их произнёс бы человек.

        def _окр(м, знаков=0):
            try:
                ч = float(м.group(1).replace(",", "."))
            except Exception:
                return м.group(0)
            ц = round(ч) if знаков == 0 else round(ч, знаков)
            return f"{ц} {м.group(2).strip()}"

        def _скл(число: int, одна: str, две: str, много: str) -> str:
            """градус / градуса / градусов — по числу."""
            о, д = число % 10, число % 100
            if 11 <= д <= 14:
                return много
            if о == 1:
                return одна
            if 2 <= о <= 4:
                return две
            return много

        # ⚠️ ПАДЕЖ ПОСЛЕ ПРЕДЛОГА. «около 21 градус» — ошибка, нужно
        # «около 21 градусА»: после «около», «примерно», «до», «свыше»
        # идёт родительный падеж. Он это услышал 08.08 про Ижевск.
        _РОДИТЕЛЬНЫЙ = ("около", "примерно", "порядка", "свыше", "более",
                        "менее", "выше", "ниже", "до", "почти", "чуть")

        def _падеж_нужен_родительный(текст: str, позиция: int) -> bool:
            перед = текст[:позиция].rstrip().lower()
            хвост = перед.split()[-1] if перед.split() else ""
            return хвост in _РОДИТЕЛЬНЫЙ

        # температура: 32,2 °C → «32 градуса» (десятые в разговоре не нужны)
        def _темп(м):
            try:
                ц = round(float(м.group(1).replace(",", ".")))
            except Exception:
                return м.group(0)
            если_род = _падеж_нужен_родительный(t, м.start())
            if если_род:
                слово = "градуса" if abs(ц) % 10 == 1 and abs(ц) % 100 != 11 else "градусов"
                return f"{_число_родительный(ц)} {слово}"
            return f"{ц} {_скл(abs(ц), 'градус', 'градуса', 'градусов')}"

        t = re.sub(r"(-?\d+(?:[.,]\d+)?)\s*(?:°\s?[CСc]\b|градус\w*)", _темп, t)

        # скорость ветра: 14,8 км/ч → «15 километров в час»
        def _ветер(м):
            try:
                ц = round(float(м.group(1).replace(",", ".")))
            except Exception:
                return м.group(0)
            если_род = _падеж_нужен_родительный(t, м.start())
            if если_род:
                слово = "километра" if ц % 10 == 1 and ц % 100 != 11 else "километров"
                return f"{_число_родительный(ц)} {слово} в час"
            return f"{ц} {_скл(ц, 'километр', 'километра', 'километров')} в час"

        t = re.sub(r"(\d+(?:[.,]\d+)?)\s*км/ч", _ветер, t)
        t = re.sub(r"(\d+(?:[.,]\d+)?)\s*м/с",
                   lambda м: f"{round(float(м.group(1).replace(',', '.')))} "
                             f"{_скл(round(float(м.group(1).replace(',', '.'))), 'метр', 'метра', 'метров')} в секунду", t)

        # 💰 ДЕНЬГИ И ПРОЧИЕ ДРОБИ.
        # Крупные суммы вслух округляем: «64 348,07 доллара» → «64 348».
        # Мелкие (курс валют) оставляем две цифры и читаем по-русски:
        # «2,6191» → «2 целых 62 сотых».
        def _дробь(м):
            цел, дроб = м.group(1), м.group(2)
            try:
                если_крупное = int(цел.replace(" ", "").replace("\u00a0", "")) >= 1000
            except Exception:
                если_крупное = False
            if если_крупное:
                return цел                       # десятые не нужны
            дроб = дроб[:2]
            слово = "десятых" if len(дроб) == 1 else "сотых"
            return f"{цел} целых {int(дроб)} {слово}"

        t = re.sub(r"(\d[\d \u00a0]*)[.,](\d+)", _дробь, t)
        # хвост вида «64 852 .49» после округления — убрать
        t = re.sub(r"\s+\.\d+", "", t)

        # проценты — со склонением: 53 % → «53 процента»
        def _проц(м):
            ц = int(м.group(1))
            если_род = _падеж_нужен_родительный(t, м.start())
            if если_род:
                слово = "процента" if ц % 10 == 1 and ц % 100 != 11 else "процентов"
                return f"{_число_родительный(ц)} {слово}"
            return f"{ц} {_скл(ц, 'процент', 'процента', 'процентов')}"

        t = re.sub(r"(\d+)\s?%", _проц, t)
        t = re.sub(r"\s+", " ", t).strip()
        t = _apply_udar(t)
        t = _mnogotochiya(t)
    return t



