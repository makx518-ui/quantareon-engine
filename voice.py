class VoiceSessionTurbo:
    """
    TURBO Voice session with optimized latency.
    
    Optimizations:
    1. Faster LLM chunking
    2. Streaming TTS
    3. Parallel processing where possible
    """
    
    def __init__(self, websocket: WebSocket, session_id: str, client_ip: str = ""):
        self.websocket = websocket
        self.session_id = session_id
        self.client_ip = client_ip
        
        # Components
        self.stt: Optional[DeepgramSTT] = None
        self.llm = GroqLLM()
        self.tts = EdgeTTSTurbo()
        self.geo = GeoLocation()
        
        # State
        self.is_active = False
        self.is_processing = False
        self._processing_since = 0     # когда началась обработка (для сторожа)
        self._flush_task = None        # 🛟 задача автообработки
        self._browser_speech_at = 0.0  # 🛡 когда браузер подтвердил живую речь
        self.is_speaking = False
        self.barge_in_requested = False
        self.first_message = True
        
        self.lang: str = "ru"          # 🌐 язык страницы, с которой пришли
        self._last_topic = None        # 📚 раздел сайта, о котором сейчас речь
        self.user_tz: str = ""         # 🕐 часовой пояс браузера (точнее, чем по IP)
        self.cached_filler_audio: bytes = b""
        self.cached_filler_text: str = ""
        self.filler_ready = asyncio.Event()
        
        # 🧠 Memory
        self.user_id: int = 0
        self.memory_cache: str = ""
        self._chat_name: str = ""  # имя из chat_history для инжекта в память
        self._memory_task: Optional[asyncio.Task] = None
        
        # Transcript buffer
        self.transcript_buffer = ""
        
        logger.info(f"[{session_id}] TURBO Session created (IP: {client_ip})")
    
    async def start(self):
        """Start session - connect STT (PARALLEL INIT)."""
        self.is_active = True
        
        # 🚀 PARALLEL INIT: Запускаем одновременно для ускорения старта
        async def init_deepgram():
            """Инициализация Deepgram."""
            # 🧠 Сначала пробуем Flux — он сам понимает конец реплики.
            # Не вышло (сеть, тариф, что угодно) — молча возвращаемся
            # на Nova-3, чтобы голос работал в любом случае.
            # 🎙️ NOVA-3 ОСНОВНОЙ. У него Flux появился позже, а прежний
            # реалтайм был именно на Nova-3 — с быстрыми числами ниже.
            # Flux включается только явно: USE_FLUX=1
            if os.getenv("USE_FLUX", "0") == "1":
                flux = FluxSTT(
                    on_transcript=self._on_flux_interim,
                    on_turn_end=self._on_flux_turn_end,
                    on_error=self._on_stt_error,
                    lang=self.lang,
                )
                flux.session_id = self.session_id
                if await flux.connect():
                    self.stt = flux
                    self.using_flux = True
                    note(self.session_id, "распознавание", "Flux — конец реплики по смыслу")
                    return True
                logger.warning("FLUX не поднялся — возвращаюсь на Nova-3")
                note(self.session_id, "откат на Nova-3", "Flux не подключился")

            self.using_flux = False
            self.stt = DeepgramSTT(
                on_transcript=self._on_transcript,
                on_error=self._on_stt_error,
                lang=self.lang
            )
            return await self.stt.connect()
        
        async def init_geolocation():
            """Определение геолокации."""
            await self.geo.detect_location(self.client_ip)
            return True
        
        async def init_memory():
            """🧠 Фоновая подгрузка памяти."""
            try:
                # ⚡ Глубокая память отключена на голосе (грузила апр-паттерны + задержку/DNS).
                # Оставляем только имя пользователя из истории чата — для обращения.
                if hasattr(self, '_chat_name') and self._chat_name:
                    self.memory_cache = f"name={self._chat_name}"
                    logger.info(f"[{self.session_id}] 🔗 Name only (deep memory off): {self._chat_name}")
            except Exception as e:
                logger.warning(f"[{self.session_id}] ⚠️ Memory preload failed: {e}")
            return True
        
        # 🚀 Запускаем параллельно (экономия ~200-300ms)
        try:
            stt_ok, geo_ok = await asyncio.gather(
                init_deepgram(),
                init_geolocation(),
                return_exceptions=False
            )
        except Exception as e:
            logger.error(f"[{self.session_id}] Parallel init error: {e}")
            await self._send_json({
                "type": "error",
                "message": "Initialization failed"
            })
            return False
        
        # 🧠 Память загружаем отдельно — не блокируем старт если упала
        asyncio.create_task(init_memory())

        # 🔥 ПРОГРЕВ ГОЛОСА — ПРОБОВАЛ, НЕ ГОДИТСЯ.
        # Замер 08.08: первый синтез стоит ~1.5 сек против ~0.5 у следующих,
        # и казалось, что прогрев в фоне это снимет. На деле стало ХУЖЕ:
        # прогревочный синтез занимает то же соединение, что и присказка,
        # и первый настоящий ответ ждёт дольше. Не возвращать.
        
        if not stt_ok:
            await self._send_json({
                "type": "error",
                "message": "STT connection failed"
            })
            return False
        
        # Кешируем филлер в фоне (уже было)
        asyncio.create_task(self._cache_filler())
        
        await self._send_json({
            "type": "stt_ready"
        })
        
        await self._send_json({
            "type": "status",
            "status": "ready",
            "message": "🎤 Нажми на микрофон"
        })
        
        logger.info(f"[{self.session_id}] ⚡ TURBO Session started (parallel init)")
        return True
    
    async def _cache_filler(self):
        """Кешируем филлер в фоне — готов к мгновенной отправке."""
        try:
            self.cached_filler_text = self.geo.generate_filler(self.lang)
            
            audio_buffer = io.BytesIO()
            
            communicate = edge_tts.Communicate(
                _tts_clean(self.cached_filler_text, self.lang),
                self.tts.voice,
                rate=self.tts.rate,
                pitch=self.tts.pitch,
                volume=self.tts.volume
            )
            
            async for chunk in communicate.stream():
                if chunk["type"] == "audio":
                    audio_buffer.write(chunk["data"])
            
            self.cached_filler_audio = audio_buffer.getvalue()
            logger.info(f"[{self.session_id}] ✅ Filler cached: {len(self.cached_filler_audio)} bytes")
            
        except Exception as e:
            logger.error(f"[{self.session_id}] Filler cache error: {e}")
            self.cached_filler_text = "Hello!" if self.lang == "en" else "Привет!"
            self.cached_filler_audio = b""
        finally:
            self.filler_ready.set()
    
    async def handle_audio(self, audio_data: bytes):
        """Forward audio to STT."""
        if self.stt and self.stt.is_connected:
            await self.stt.send_audio(audio_data)
    
    def _schedule_autoflush(self):
        """🛟 СТРАХОВКА: если браузер не пришлёт «я договорил» (детектор речи
        иногда не срабатывает на коротких фразах), сами обработаем накопленное
        через полторы секунды тишины. Иначе реплика пропадает молча."""
        try:
            if getattr(self, "_flush_task", None):
                self._flush_task.cancel()
        except Exception:
            pass

        async def _later():
            try:
                await asyncio.sleep(2.8)   # ждём дольше: вдруг человек ещё говорит
                if self.transcript_buffer.strip() and not self.is_processing:
                    logger.info(f"[{self.session_id}] 🛟 Браузер молчит — обрабатываю сам")
                    await self.on_speech_end()
            except asyncio.CancelledError:
                pass
            except Exception as e:
                logger.warning(f"[{self.session_id}] автообработка не вышла: {e}")

        try:
            self._flush_task = asyncio.create_task(_later())
        except Exception:
            self._flush_task = None

    def _on_transcript(self, text: str):
        """Buffer transcripts."""
        if not self.is_active:
            return
        
        if self.transcript_buffer:
            self.transcript_buffer += " " + text
        else:
            self.transcript_buffer = text
        
        logger.info(f"[{self.session_id}] 📝 Buffer: '{self.transcript_buffer}'")
        note(self.session_id, "услышал", self.transcript_buffer)
        
        asyncio.create_task(self._send_json({
            "type": "transcript_interim",
            "content": self.transcript_buffer
        }))
        self._schedule_autoflush()   # 🛟 на случай, если браузер промолчит
    
    def _on_stt_error(self, error):
        logger.error(f"[{self.session_id}] STT error: {error}")
    

    def _on_flux_interim(self, text: str, is_final: bool = False):
        """Промежуточный текст от Flux — только показать в окне разговора."""
        try:
            asyncio.create_task(self._send_json({
                "type": "transcript_interim",
                "content": text,
            }))
        except Exception:
            pass

    def _on_flux_speech_start(self):
        """Flux услышал начало речи.

        ПЕРЕБИВАТЬ ЗДЕСЬ НЕЛЬЗЯ. Начало речи ловится и тогда, когда микрофон
        слышит голос самого помощника из динамика — и ответ глохнет, не успев
        начаться. Обрыв делаем только по ЗАКОНЧЕННОЙ реплике (EndOfTurn):
        там уже есть текст, значит человек правда сказал что-то осмысленное.
        """
        note(self.session_id, "заговорил", "")

    async def _on_flux_turn_end(self, text: str):
        """Flux сказал: человек договорил. Обрабатываем сразу.

        Здесь не нужны ни таймеры тишины, ни сигнал «я закончил» от браузера —
        модель уже решила это по смыслу и интонации.
        """
        # 🛡 СТОРОЖ ОТ ЭХА — тот самый, что работал при Nova-3.
        # Пока помощник ГОВОРИТ, микрофон слышит его же голос из колонок,
        # и Flux принимает это за речь человека: он слушает сырой поток.
        # Браузер слушает поток УЖЕ ОЧИЩЕННЫЙ от эха — если речь настоящая,
        # он присылает подтверждение. Нет подтверждения — значит эхо.
        # Когда помощник молчит, сторож не вмешивается: Flux работает как обычно.
        if self.is_speaking or self.is_processing:
            since = time.time() - getattr(self, "_browser_speech_at", 0.0)
            if since > 6.0:
                note(self.session_id, "ЭХО — пропускаю", text)
                logger.info(f"[{self.session_id}] 🛡 Эхо из колонок, пропускаю: '{text[:60]}'")
                return

        note(self.session_id, "КОНЕЦ РЕПЛИКИ (Flux)", text)
        self.transcript_buffer = text
        await self.on_speech_end()

    async def on_speech_end(self, from_browser: bool = False):
        """Реплика закончена — обрабатываем.

        При Flux решение принимает модель, поэтому сигнал от браузера
        («детектор речи услышал тишину») игнорируем — иначе одна реплика
        обработается дважды.
        """
        if from_browser and getattr(self, "using_flux", False):
            return

        """TURBO processing with streaming TTS."""
        # 🔧 FIX: Проверяем активность сессии СРАЗУ
        if not self.is_active:
            logger.info(f"[{self.session_id}] Session inactive, skipping")
            return
        
        self.barge_in_requested = False

        # 🫱 КОРОТКАЯ ПЕРЕДЫШКА ПЕРЕД ОБРАБОТКОЙ.
        # Детектор в браузере объявляет «договорил» уже через полсекунды
        # тишины — это его число, оно даёт реалтайм. Но живая речь с паузой
        # посреди мысли из-за этого рвётся надвое: «найди большой кусок
        # текста» уходит отдельно, «я попробую прерывание» отдельно. Он это
        # и поймал 08.08.
        # Лечение мягкое: ждём совсем чуть-чуть и смотрим, не продолжил ли
        # человек. Продолжил — копим дальше и молчим, эту реплику обработает
        # следующий сигнал. Не продолжил — идём как обычно.
        # Задержка платится ТОЛЬКО этой долей секунды и не трогает числа
        # реалтайма. Крутится переменной SPEECH_GRACE_SEC, 0 — выключить.
        # ⚡ ЖДЁМ ТОЛЬКО ЕСЛИ МЫСЛЬ ОБОРВАНА. Замер 08.08: ожидание на
        # КАЖДОЙ реплике стоило почти секунду (0.80 → 1.70 с) — слишком
        # дорого. Законченную фразу обрабатываем сразу, как и раньше, а
        # ждём лишь когда человек оборвался на предлоге, союзе или запятой.
        # Тогда цена платится только там, где она оправдана.
        срок = float(os.getenv("SPEECH_GRACE_LONG_SEC", "1.4"))
        if from_browser and срок > 0 and _мысль_не_закончена(self.transcript_buffer):
            logger.info(f"[{self.session_id}] 🫱 мысль не закончена — жду продолжения")
            было = self.transcript_buffer
            ждали = 0.0
            while ждали < срок:
                await asyncio.sleep(0.05)
                ждали += 0.05
                if self.transcript_buffer != было:
                    logger.info(f"[{self.session_id}] 🫱 человек продолжает — не перебиваю")
                    return

        transcript = self.transcript_buffer.strip()
        self.transcript_buffer = ""
        
        if not transcript:
            note(self.session_id, "ПУСТО — нечего обрабатывать", "браузер сказал «договорил», а текста нет")
            logger.info(f"[{self.session_id}] Empty transcript, skipping")
            return
        
        # 🛡 СТОРОЖ: если прошлая обработка висит слишком долго — она застряла,
        # снимаем флаг, иначе помощник замолчит навсегда
        stuck_for = time.time() - getattr(self, "_processing_since", 0)
        if self.is_processing and getattr(self, "_processing_since", 0) and stuck_for > 45:
            logger.warning(f"[{self.session_id}] ⚠️ Обработка висит {stuck_for:.0f}с — снимаю флаг")
            self.is_processing = False

        if self.is_processing:
            # РАНЬШЕ реплику молча выбрасывали — отсюда «отвечает через раз».
            # Теперь: обрываем предыдущий ответ и берём новый вопрос.
            note(self.session_id, "ОБРЫВ прошлого ответа", "пришла новая реплика")
            logger.info(f"[{self.session_id}] 🔁 Пришла новая реплика — обрываю прошлый ответ")
            self.barge_in_requested = True
            try:
                stopPlayback = getattr(self, "_stop_playback", None)
                if callable(stopPlayback):
                    stopPlayback()
            except Exception:
                pass
            self.is_processing = False
            await asyncio.sleep(0.15)

        # 🔻 ОБЯЗАТЕЛЬНО опустить флаг перебивания перед новым ответом.
        # Раньше он оставался поднятым после обрыва старого — и новый ответ
        # обрывался тем же флагом, не успев начаться. Отсюда было молчание.
        self.barge_in_requested = False

        note(self.session_id, "обрабатываю", transcript)
        logger.info(f"[{self.session_id}] ⚡ TURBO Processing: '{transcript}'")
        if self.user_id:
            logger.info(f"🎤 [{self.user_id}]: \"{transcript[:120]}\"")
        
        self.is_processing = True
        self._processing_since = time.time()
        
        try:
            await self._send_json({
                "type": "transcript_final",
                "content": transcript
            })

            # 🎨 РЕЖИМ КАРТИНКИ: хозяин включил кнопку — рисуем и выходим,
            # реплику в разговор НЕ пускаем. Работает и с голоса, и с текста.
            if _image_mode and self.user_id == 803501001:
                await self._generate_image(transcript, _image_mode)
                self.is_processing = False
                return

            # 🌐 ИНТЕРНЕТ. Решение принимаем МГНОВЕННО (просто разбор слов),
            # и только если правда идём в сеть — показываем человеку «Ищу…»,
            # чтобы пауза не выглядела зависанием.
            # 🌐 РЕШЕНИЕ ПРИНИМАЕТ САМА МОДЕЛЬ, а не код.
            # Ей дано описание инструмента поиска (см. ИНСТРУМЕНТЫ выше) —
            # она вызывает его, когда считает нужным, и сама пишет запрос.
            # Раньше здесь стояли словари слов-приманок и отдельный «судья»
            # на второй модели: они угадывали намерение по буквам, и каждое
            # новое слово требовало заплатки. Всё это убрано.
            # Значок «Ищу…» зажигается по сигналу от модели — колбэк ниже.
            web_ctx = ""

            await self._send_json({
                "type": "status",
                "status": "thinking",
                "message": "⚡ Думаю..."
            })

            # ⏱️ METRIC: LLM начал работу
            await self._send_json({"type": "metric_llm_start"})

            # 🌐 Значок «Ищу…»: зажигается, когда модель ПОПРОСИЛА поиск,
            # и горит до первого слова настоящего ответа.
            _значок_горит = False
            _значок_зажжён_в = [0.0]

            async def _зажечь_значок():
                nonlocal _значок_горит
                _значок_горит = True
                _значок_зажжён_в[0] = time.time()
                try:
                    await self._send_json({"type": "status",
                                           "status": "searching",
                                           "message": "🌐 Ищу"})
                except Exception:
                    pass

            async def _снять_значок():
                """Гасим значок — но не раньше, чем человек успеет его увидеть.

                Он жаловался 07.08: значок мелькнул, потом пауза, и только
                потом голос. Причина в том, что текст ответа приходит РАНЬШЕ
                звука: пока кусок синтезируется, экран уже пуст. Поэтому
                держим значок не меньше МИН_ЗНАЧОК секунд и гасим его на
                первом настоящем ЗВУКЕ, а не на первой букве.
                """
                nonlocal _значок_горит
                if not _значок_горит:
                    return
                прошло = time.time() - (_значок_зажжён_в[0] or time.time())
                мин = float(os.getenv("МИН_ЗНАЧОК", os.getenv("MIN_BADGE_SEC", "1.2")))
                if прошло < мин:
                    await asyncio.sleep(мин - прошло)
                _значок_горит = False
                try:
                    await self._send_json({"type": "status",
                                           "status": "search_done"})
                except Exception:
                    pass
            
            await self._send_json({"type": "audio_start"})
            self.is_speaking = True
            
            start_time = time.time()
            first_audio_time = None
            chunk_count = 0
            response_main_lang = None  # 🛡️ Основной язык ответа (определяем по первому чанку)
            
            if self.first_message:
                self.first_message = False
                
                # ⏳ СКОЛЬКО ЖДЁМ ПРИСКАЗКУ ПРО ДАТУ. В оригинале платформы
                # стоит 2.0 — и это ПРАВИЛЬНО. Присказка заранее озвучена и
                # играет сразу, закрывая собой те секунды, пока модель думает.
                # 08.08 я укоротил ожидание до 0.7, думая что ускоряю: на деле
                # присказка не успевала, её выбрасывали, и человек ждал ещё
                # дольше — пока досинтезируется настоящий ответ. НЕ УКОРАЧИВАТЬ.
                try:
                    await asyncio.wait_for(
                        self.filler_ready.wait(),
                        timeout=float(os.getenv("FILLER_WAIT_SEC", "2.0")))
                except asyncio.TimeoutError:
                    logger.warning(f"[{self.session_id}] присказка не готова — отвечаю сразу")
                
                if self.cached_filler_audio and not self.barge_in_requested:
                    first_audio_time = time.time()
                    latency = first_audio_time - start_time
                    logger.info(f"[{self.session_id}] ⚡ INSTANT Filler: {latency:.3f}s ({len(self.cached_filler_audio)} bytes)")
                    
                    await self.websocket.send_bytes(self.cached_filler_audio)

                    # ⚠️ ЗНАЧОК ЗДЕСЬ НЕ ГАСИМ. Филлер — присказка про дату,
                    # она звучит СРАЗУ, ещё до поиска. Если погасить на ней,
                    # человек видит, как значок мелькнул и пропал, а ответ
                    # приходит заметно позже — ровно на это он и пожаловался
                    # 07.08. Значок держится до первого слова НАСТОЯЩЕГО
                    # ответа, ниже по циклу.
                    await self._send_json({
                        "type": "response_text",
                        "content": self.cached_filler_text
                    })
                    
                    chunk_count += 1
                else:
                    logger.warning(f"[{self.session_id}] Filler not cached, skipping")
            
            # 📌 Копим то, что успели сказать вслух. Нужно на случай обрыва:
            # без этого прерванный ответ нигде не сохраняется, и на «продолжай»
            # помощник честно отвечает, что не помнит, о чём говорил.
            сказано = []
            оборвали = False

            async for text_chunk in self.llm.generate_stream_turbo(
                    transcript, self.memory_cache, web_ctx,
                    на_поиск=_зажечь_значок,
                    lang=getattr(self, "lang", "ru")):
                if not self.is_active or self.barge_in_requested:
                    self.barge_in_requested = False
                    оборвали = True
                    break
                
                # 🛡️ Фильтр дублирования языка (внутри чанка)
                text_chunk = GroqLLM.filter_language_duplicates(text_chunk)
                if not text_chunk:
                    continue

                # 🇷🇺 Второй рубеж: на русской версии ответ жёстко русифицируем
                # (промпт — просьба, этот фильтр — замок). Ловит украинский,
                # белорусский и прочих родственников по чужим буквам.
                if getattr(self, "lang", "ru") != "en":
                    text_chunk = GroqLLM.только_русский(text_chunk)
                    if not text_chunk:
                        continue
                
                # 🛡️ Удаляем эмодзи (TTS читает их как текст)
                text_chunk_tts = GroqLLM.strip_emoji(text_chunk)
                # 🛡️ Удаляем стикеры [sticker:xxx] и markdown **bold**
                text_chunk_tts = re.sub(r'\[sticker:[^\]]*\]', '', text_chunk_tts)
                text_chunk_tts = re.sub(r'\*{1,3}', '', text_chunk_tts)
                text_chunk_tts = re.sub(r'#{1,3}\s*', '', text_chunk_tts)
                text_chunk_tts = text_chunk_tts.strip()
                # 🔊 Убираем паузы только в первом чанке (быстрый старт речи)
                if chunk_count == 0:
                    text_chunk_tts = re.sub(r'[,;:\-—–]', '', text_chunk_tts)
                    text_chunk_tts = text_chunk_tts.strip()
                if not text_chunk_tts:
                    continue
                
                # 🛡️ Межчанковая защита: определяем основной язык по первому чанку
                has_cyr = bool(re.search(r'[а-яёА-ЯЁ]', text_chunk))
                has_lat = bool(re.search(r'[a-zA-Z]{2,}', text_chunk))
                
                if response_main_lang is None and (has_cyr or has_lat):
                    response_main_lang = 'cyr' if has_cyr else 'lat'
                
                # Если чанк ЦЕЛИКОМ на другом языке — пропускаем (это дубль)
                if response_main_lang == 'cyr' and has_lat and not has_cyr:
                    logger.info(f"[{self.session_id}] 🛡️ Filtered cross-chunk duplicate: '{text_chunk[:30]}'")
                    continue
                if response_main_lang == 'lat' and has_cyr and not has_lat:
                    logger.info(f"[{self.session_id}] 🛡️ Filtered cross-chunk duplicate: '{text_chunk[:30]}'")
                    continue
                
                chunk_count += 1
                logger.info(f"[{self.session_id}] 💬 [{chunk_count}] '{text_chunk[:40]}...'")
                
                # ⏱️ METRIC: TTS начал работу (отправляем только один раз для первого чанка)
                if chunk_count == 1 and not self.first_message:
                    await self._send_json({"type": "metric_tts_start"})
                
                async def send_audio(audio_bytes):
                    nonlocal first_audio_time
                    if first_audio_time is None:
                        first_audio_time = time.time()
                        # 🌐 Человек слышит ответ — значку пора гаснуть.
                        # ⚠️ НО СНИМАЕМ ЕГО В ФОНЕ, не дожидаясь. Внутри
                        # _снять_значок есть выдержка (чтобы не мелькал), и
                        # если ждать её здесь, то ЗВУК встанет в очередь за
                        # ней — голос молчит, пока досиживает значок. Он
                        # это и услышал 08.08: «пауза, потом текст, потом
                        # говорит». Звук важнее значка.
                        asyncio.create_task(_снять_значок())
                        latency = first_audio_time - start_time
                        logger.info(f"[{self.session_id}] ⚡ First audio: {latency:.2f}s")
                    
                    if not self.barge_in_requested:
                        await self.websocket.send_bytes(audio_bytes)
                
                # ⚡ СНАЧАЛА текст на экран (мгновенно, не ждёт озвучку)
                if not self.barge_in_requested:
                    сказано.append(text_chunk)
                    await self._send_json({
                        "type": "response_text",
                        "content": text_chunk
                    })
                # 🔊 ПОТОМ озвучка (идёт следом, текст уже виден)
                await self.tts.synthesize_streaming(text_chunk_tts, send_audio)
            
            # 🇷🇺 Если фильтр языка вычистил ВЕСЬ ответ (модель ушла в чужой
            # язык целиком) — помощник не должен молчать. Говорим по-русски.
            if not оборвали and not сказано and getattr(self, "lang", "ru") != "en":
                запасная = "Извини, я отвлёкся. Повтори, пожалуйста, вопрос."
                logger.warning(f"[{self.session_id}] 🚨 ЯЗЫК: весь ответ вычищен, отдаю запасную фразу")

                async def send_audio_fallback(audio_bytes):
                    if not self.barge_in_requested:
                        await self.websocket.send_bytes(audio_bytes)

                сказано.append(запасная)
                await self._send_json({"type": "response_text", "content": запасная})
                try:
                    await self.tts.synthesize_streaming(запасная, send_audio_fallback)
                except Exception as e:
                    logger.warning(f"[{self.session_id}] запасная фраза не озвучилась: {e}")

            # 📌 ОБОРВАЛИ — сохраняем недоговорённое, чтобы можно было продолжить.
            # Обычный путь пишет ответ в память только после последнего куска,
            # а при обрыве до него дело не доходит — вот и провал.
            if оборвали and сказано:
                кусок = " ".join(сказано).strip()
                if кусок:
                    self.llm.history.append({"role": "user", "content": transcript})
                    self.llm.history.append({
                        "role": "assistant",
                        "content": кусок + " …(здесь меня перебили — если попросят продолжить, продолжай с этого места)"
                    })
                    note(self.session_id, "сохранил недоговорённое", кусок[-70:])

            # страховка: ответ кончился, а значок мог не погаснуть
            asyncio.create_task(_снять_значок())
            await self._send_json({"type": "audio_end"})
            
            total = time.time() - start_time
            first_latency = (first_audio_time - start_time) if first_audio_time else total
            
            logger.info(f"[{self.session_id}] ✅ TURBO Done: {total:.1f}s total, {first_latency:.2f}s first audio, {chunk_count} chunks")
            
            # 🧠 Фоновое сохранение в память + обновление кеша
            if self.user_id:
                full_response = self.llm.history[-1]["content"] if self.llm.history else ""
                # 📊 Итоговый лог голосового ответа (симметрия с чатом)
                _vname_match = re.search(r'name=([^\s;,\]\n]+)', self.memory_cache or "")
                _vname = f" ({_vname_match.group(1)})" if _vname_match else ""
                logger.info(f"📊 ГОЛОС [{self.user_id}{_vname}]: {total:.1f}с | Groq | {len(full_response)} chars | first={first_latency:.2f}s")
                pass  # память платформы не используется — голос живёт на Render
                async def _delayed_refresh():
                    await asyncio.sleep(3.0)
                    await self._refresh_memory_cache()
                asyncio.create_task(_delayed_refresh())
            
            await self._send_json({
                "type": "status",
                "status": "ready",
                "message": f"⚡ Готов ({first_latency:.1f}s)"
            })
            
        except Exception as e:
            logger.error(f"[{self.session_id}] Error: {e}")
            try:
                await self._send_json({"type": "status", "status": "search_done"})
            except Exception:
                pass
            await self._send_json({"type": "error", "message": str(e)})
        finally:
            note(self.session_id, "ответ завершён", "")
            self.is_processing = False
            self.is_speaking = False
            self._processing_since = 0
    
    async def _refresh_memory_cache(self):
        """🧠 Обновление глубокой памяти отключено на голосе (только сессионная история)."""
        # ⚡ recall убран — не грузим старые паттерны, не долбим мёртвый сервис.
        return
    
    async def stop(self):
        """Stop session."""
        self.is_active = False
        
        if self.stt:
            await self.stt.close()
        
        await self.llm.close()
        await self.geo.close()
        
        logger.info(f"[{self.session_id}] TURBO Stopped")
    
    async def _send_json(self, data: dict):
        try:
            # 🛡️ Проверяем что WebSocket всё ещё подключен
            if self.websocket.client_state.name == "CONNECTED":
                await self.websocket.send_json(data)
        except Exception as e:
            # Игнорируем ошибки отправки после закрытия соединения
            if "close message has been sent" not in str(e):
                logger.error(f"[{self.session_id}] Send error: {e}")

    async def _generate_image(self, prompt: str, режим: str = "lite"):
        """🎨 Нарисовать картинку по промпту (только хозяин, режим картинки).

        Ключ Gemini берём из окружения — в коде его нет. Готовую картинку
        шлём клиенту одним сообщением type=image; окно всплывает поверх сайта.
        """
        prompt = (prompt or "").strip()
        if not prompt:
            return

        # Убираем обращение-команду в начале: рисовать надо то, что ПОСЛЕ неё.
        # «Сделай картинку, кот на окне» → «кот на окне».
        _мусор = [
            "сделай картинку", "сделай изображение", "сделай рисунок", "сделай фото",
            "нарисуй картинку", "нарисуй изображение", "нарисуй мне", "нарисуй",
            "покажи картинку", "создай картинку", "создай изображение", "сгенерируй картинку",
            "сгенерируй изображение", "картинка", "картинку",
            "draw me", "draw a", "draw", "generate an image of", "generate image",
            "make an image of", "make a picture of", "create an image of", "picture of",
        ]
        _низ = prompt.lower()
        for _ф in sorted(_мусор, key=len, reverse=True):
            if _низ.startswith(_ф):
                prompt = prompt[len(_ф):].lstrip(" ,.:;—-").strip()
                break
        if not prompt:
            await self._send_json({"type": "error",
                "message": "🎨 Скажи, что именно нарисовать"})
            return
        key = os.getenv("GEMINI_API_KEY", "").strip()
        if not key:
            await self._send_json({"type": "error",
                "message": "🎨 Картинки не настроены: нет ключа GEMINI_API_KEY"})
            return

        подпись = "🎨 Рисую в PRO (это дольше)" if режим == "pro" else "🎨 Рисую"
        await self._send_json({"type": "status", "status": "drawing",
                               "message": подпись})
        logger.info(f"[{self.session_id}] 🎨 Рисую [{режим}]: \"{prompt[:100]}\"")

        # 🛡 ПУЛЬС ВО ВРЕМЯ РИСОВАНИЯ.
        # В браузере сторож рвёт связь, если 30 секунд от сервера тишина
        # (CONFIG.WATCHDOG_MS). PRO рисует 30+ секунд — и картинка прилетала
        # уже в оборванное соединение, окно висело на «Рисую». Поэтому пока
        # рисуем, каждые 5 секунд подаём признак жизни: сторож видит, что
        # связь живая, и не трогает её. Сам сторож не меняем — он нужен для
        # настоящих зависаний.
        _пульс_жив = True

        async def _пульс():
            секунд = 0
            while _пульс_жив:
                await asyncio.sleep(5)
                if not _пульс_жив:
                    break
                секунд += 5
                try:
                    await self._send_json({
                        "type": "status", "status": "drawing",
                        "message": подпись + f" · {секунд}с",
                    })
                except Exception:
                    break

        задача_пульса = asyncio.create_task(_пульс())

        выбор = IMAGE_MODELS.get(режим) or IMAGE_MODELS["lite"]
        gen_cfg = {"responseModalities": ["IMAGE"]}
        img_cfg = {}
        if выбор.get("size"):
            img_cfg["imageSize"] = выбор["size"]
        if выбор.get("ratio"):
            img_cfg["aspectRatio"] = выбор["ratio"]
        if img_cfg:
            gen_cfg["imageConfig"] = img_cfg

        url = IMAGE_API_BASE + выбор["id"] + ":generateContent?key=" + key
        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": gen_cfg,
        }
        try:
            # Pro думает дольше и рисует 4K — даём ему запас времени
            timeout = aiohttp.ClientTimeout(total=300 if режим == "pro" else 120)
            async with aiohttp.ClientSession(timeout=timeout) as sess:
                async with sess.post(url, json=payload) as resp:
                    status = resp.status
                    data = await resp.json()

            if status != 200:
                msg = ((data or {}).get("error", {}) or {}).get("message", "ошибка генерации")
                await self._send_json({"type": "error",
                    "message": "🎨 " + str(msg)[:300]})
                return

            b64, mime = None, "image/png"
            for cand in (data.get("candidates", []) or []):
                for part in cand.get("content", {}).get("parts", []) or []:
                    inline = part.get("inlineData") or part.get("inline_data")
                    if inline and inline.get("data"):
                        b64 = inline["data"]
                        mime = inline.get("mimeType") or inline.get("mime_type") or "image/png"
                        break
                if b64:
                    break

            # Модель может ответить без картинки. Причину она пишет в
            # finishReason — говорим человеку прямо, а не молчим:
            #   PROHIBITED_CONTENT / SAFETY — фильтр Google не пропустил
            #     (часто это сказочные и киногерои: права на образ);
            #   NO_IMAGE — просто не нарисовала, второй заход обычно берёт.
            if not b64:
                причина = ""
                for cand in (data.get("candidates", []) or []):
                    причина = str(cand.get("finishReason") or "")
                    break

                if причина in ("NO_IMAGE", "PROHIBITED_CONTENT", "SAFETY", "IMAGE_SAFETY"):
                    # Модель отвечает неровно: тот же запрос то проходит, то
                    # режется фильтром. Поэтому пробуем ещё раз ею же, а если
                    # снова пусто — запасной моделью. Молчать нельзя.
                    попытки = [(url, payload)]
                    зап_url = IMAGE_API_BASE + IMAGE_FALLBACK + ":generateContent?key=" + key
                    попытки.append((зап_url, {
                        "contents": [{"parts": [{"text": prompt}]}],
                        "generationConfig": {"responseModalities": ["IMAGE"]},
                    }))
                    for _u, _p in попытки:
                        try:
                            async with aiohttp.ClientSession(timeout=timeout) as sess:
                                async with sess.post(_u, json=_p) as resp2:
                                    data2 = await resp2.json()
                            for cand in (data2.get("candidates", []) or []):
                                for part in cand.get("content", {}).get("parts", []) or []:
                                    inline = part.get("inlineData") or part.get("inline_data")
                                    if inline and inline.get("data"):
                                        b64 = inline["data"]
                                        mime = inline.get("mimeType") or inline.get("mime_type") or "image/png"
                                        break
                                if b64:
                                    break
                        except Exception:
                            pass
                        if b64:
                            break
                if not b64:
                    if причина in ("PROHIBITED_CONTENT", "SAFETY", "IMAGE_SAFETY"):
                        текст = ("🎨 Гугл не пропустил этот запрос — так бывает с "
                                 "known-персонажами и брендами. Опиши своими словами: "
                                 "например «кот в высоких кожаных сапогах и шляпе с пером»")
                    elif причина == "RECITATION":
                        текст = "🎨 Запрос отклонён из-за авторских прав — опиши образ своими словами"
                    else:
                        текст = "🎨 Не нарисовалось — попробуй описать подробнее"
                    logger.info(f"[{self.session_id}] 🎨 без картинки, finishReason={причина}")
                    await self._send_json({"type": "error", "message": текст})
                    return

            # 🎨 Нарисовали — режим сам выключается, чтобы следующая фраза
            # снова шла в разговор. Иначе кнопка горит, про неё забываешь,
            # и обычное «привет» уходит в рисовалку. Он поймал это 10.08.
            # При НЕудаче режим оставляем: значит он будет переформулировать.
            global _image_mode
            _image_mode = ""
            _save_image_mode("")

            await self._send_json({
                "type": "image",
                "mime": mime,
                "data": b64,
                "prompt": prompt[:200],
                "mode_off": True,
            })
            logger.info(f"[{self.session_id}] 🎨 Готово ({len(b64)//1024} KB base64), режим выключен")
        except Exception as e:
            logger.error(f"[{self.session_id}] 🎨 Ошибка генерации: {e}")
            await self._send_json({"type": "error", "message": "🎨 " + str(e)[:200]})
        finally:
            # пульс глушим при любом исходе — и на удаче, и на ошибке
            _пульс_жив = False
            задача_пульса.cancel()


