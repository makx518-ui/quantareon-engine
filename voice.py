    _ЧУЖИЕ_СЛОВА = re.compile(
        r'\b(що|цього|цьому|якщо|дуже|цікав\w*|помічник\w*|'
        r'ёсць|сайце|табе|вельмі|можа|трэба|дзякуй\w*|дзень|добры\s+дзень|'
        r'съм|това|който|няма|защото|здравей|аз\s+съм|'
        r'сакам|треба|многу|јас|сум|'
        r'jestem|jesteś|jest|dzień|dziękuję|strony|asystent\w*|'
        r'dobrý|děkuji|ďakujem|prosím|jsem|hlasov\w*|'
        r'sam|ovog|stranice|pomo\w*nik)\b', re.IGNORECASE)

    # Названия и сокращения, которые ОБЯЗАНЫ проходить: это вещи с его же
    # страниц, помощник должен уметь их называть.
    _ЛАТИНИЦА_РАЗРЕШЕНА = re.compile(
        r'\b(the\s+code\s+of\s+the\s+soul|sacred\s+rhythm|search|kundalini|'
        r'quantareon|quantarion|dream\s+oracle|luck\s+forecast|youtube|'
        r'telegram|github|cloudflare|render|ai|tts|stt|api|url|http[s]?)\b',
        re.IGNORECASE)

    @staticmethod
    def только_русский(text: str) -> str:
        """Приводит ответ к русскому. Порядок важен:
        1) СНАЧАЛА опознаём чужие предложения — по буквам, которых в русском
           нет, и по словам-приметам, — и выбрасываем их целиком;
        2) ПОТОМ в оставшемся заменяем чужие буквы русскими (вдруг проскочило
           одно слово — пусть звучит по-русски);
        3) вырезаем длинные куски латиницей, КРОМЕ названий с его страниц.
        Пусто на выходе — значит кусок был чужим целиком: вслух он не идёт.
        """
        if not text:
            return text

        было = text

        # ── шаг 1: чужие предложения — целиком вон (ДО всякой замены букв,
        #    иначе замена сотрёт те самые приметы, по которым их узнаём)
        предложения = re.split(r'(?<=[.!?…])\s+', text)
        оставили = []
        for п in предложения:
            разрешено = GroqLLM._ЛАТИНИЦА_РАЗРЕШЕНА.search(п)
            чужая_латиница = any(б in GroqLLM._ЧУЖАЯ_ЛАТИНИЦА for б in п)
            чужая_кириллица = any(б in GroqLLM._ЧУЖИЕ_БУКВЫ for б in п)
            чужие_слова = bool(GroqLLM._ЧУЖИЕ_СЛОВА.search(п))
            if (чужая_латиница or чужая_кириллица or чужие_слова) and not разрешено:
                logger.warning(f"🚨 ЯЗЫК: выброшено чужое предложение — '{п[:50]}'")
                continue
            оставили.append(п)
        text = ' '.join(оставили)

        # ── шаг 2: одиночные чужие буквы в уцелевшем тексте
        for чужая, наша in GroqLLM._ЧУЖИЕ_БУКВЫ.items():
            if чужая in text:
                text = text.replace(чужая, наша)
        text = re.sub(r"(?<=[а-яёА-ЯЁ])['’ʼ](?=[а-яёА-ЯЁ])", '', text)

        # ── шаг 3: длинные латинские куски (шесть слов и больше)
        def _проверить(m):
            кусок = m.group(0)
            if GroqLLM._ЛАТИНИЦА_РАЗРЕШЕНА.search(кусок):
                return кусок
            logger.info(f"🇷🇺 Вырезан латинский кусок '{кусок[:40]}'")
            return ' '
        text = re.sub(r'\b(?:[A-Za-z][A-Za-z\'-]*\s+){5,}[A-Za-z][A-Za-z\'-]*\b',
                      _проверить, text)

        # осиротевшие знаки после вырезания
        text = re.sub(r'\s+([.,!?;:])', r'\1', text)
        text = re.sub(r'([.!?])\s*[.,!?;:]+', r'\1', text)
        text = re.sub(r'\s+', ' ', text).strip()

        if not text:
            logger.warning(f"🚨 ЯЗЫК: кусок отброшен целиком — '{было[:50]}'")
            return ''
        return text

    @staticmethod
    def strip_emoji(text: str) -> str:
        """Удаляет все эмодзи из текста."""
        cleaned = GroqLLM.EMOJI_PATTERN.sub('', text)
        return re.sub(r'\s+', ' ', cleaned).strip()
    
    @staticmethod
    def filter_language_duplicates(text: str) -> str:
        """Удаляет дублирование на другом языке из ответа.
        Определяет основной язык по первым символам и вырезает хвост на другом."""
        if not text:
            return text
        
        has_cyrillic = bool(re.search(r'[а-яёА-ЯЁ]', text))
        has_latin = bool(re.search(r'[a-zA-Z]{2,}', text))
        
        # Если только один алфавит — чисто, не трогаем
        if not (has_cyrillic and has_latin):
            return text
        
        # Определяем основной язык по первому слову (>1 буквы)
        first_word = re.search(r'[а-яёА-ЯЁa-zA-Z]{2,}', text)
        if not first_word:
            return text
        
        main_is_cyrillic = bool(re.search(r'[а-яёА-ЯЁ]', first_word.group()))
        
        if main_is_cyrillic:
            # Основной — кириллица: вырезаем латинские фразы (3+ символов подряд)
            # Но сохраняем: аббревиатуры (AI, TTS), имена (QUANTARION), стикеры
            cleaned = re.sub(r'(?<=[.!?])\s*[A-Z][a-zA-Z0-9\s,!?\'-]{3,}[.!?]?\s*', ' ', text)
            cleaned = re.sub(r'\s*\([A-Za-z\s,!?\'-]+\)', '', cleaned)
        else:
            # Основной — латиница: вырезаем кириллические фразы
            cleaned = re.sub(r'(?<=[.!?])\s*[А-ЯЁ][а-яёА-ЯЁ0-9\s,!?\'-]{3,}[.!?]?\s*', ' ', text)
            cleaned = re.sub(r'\s*\([а-яёА-ЯЁ\s,!?\'-]+\)', '', cleaned)
        
        cleaned = re.sub(r'\s+', ' ', cleaned).strip()
        return cleaned if cleaned else text
    
    def _get_optimal_chunk_size(self, chunk_count: int, total_chars: int) -> int:
        """
        Минимальная длина куска перед отправкой на озвучку.

        🗣 ГЛАВНОЕ ДЛЯ ГЛАДКОЙ РЕЧИ: каждый кусок озвучивается ОТДЕЛЬНО,
        поэтому короткие куски = рваная речь. Обрывок вроде «Сейчас разберёмся,»
        движок читает как законченное предложение — с падением голоса, — а на
        каждом стыке добавляется тишина. Поэтому куски крупные и режутся
        ТОЛЬКО по концу предложения (запятые — аварийный случай, см. ниже).

        Первый кусок поменьше — чтобы ответ начинался без ощутимой задержки.
        """
        if chunk_count == 0:
            # первый кусок — быстрый старт, но не обрывок
            return 40
        elif chunk_count == 1:
            return 90
        elif total_chars < 300:
            return 120
        else:
            # дальше — крупно, речь льётся ровно
            return 150
    
    def __init__(self):
        self.history: List[Dict] = []
        self._session: Optional[aiohttp.ClientSession] = None
        self.user_id: int = 0
        self.lang: str = "ru"          # 🌐 язык страницы, с которой пришли
    
    async def _get_session(self):
        if not self._session or self._session.closed:
            self._session = aiohttp.ClientSession()
        return self._session
    
    async def close(self):
        if self._session and not self._session.closed:
            await self._session.close()
    
    def _build_messages(self, user_input: str, memory_ctx: str = "", web_ctx: str = ""):
        # Серверный промпт (orchestrator) или статичный (fallback)
        # ⚡ Голос: чистый голосовой промпт (3К) вместо раздутого оркестратором (13К) → быстрее отклик
        system = config.SYSTEM_PROMPT
        # 👑 Создатель или гость — это решает, как к человеку обращаться
        system += config.OWNER_BLOCK if self.user_id == 803501001 else config.GUEST_BLOCK

        # 🌐 СВЕЖЕЕ ИЗ СЕТИ — если сборщик что-то принёс.
        # Ставим ВЫШЕ знаний о сайте: свежий факт важнее справки.
        if web_ctx:
            system += "\n\n" + web_ctx

        # 📚 ЗНАНИЯ О САЙТЕ: карта разделов всегда, а знание нужного раздела —
        # только когда о нём спросили. Тема «липкая»: держится, пока человек
        # не свернёт на другую, иначе на «а поподробнее?» терялась бы нить.
        if site_knowledge is not None:
            try:
                deep = len(getattr(self, "history", [])) >= 4   # разговор пошёл вглубь
                block, topic = site_knowledge.build_knowledge_block(
                    user_input,
                    sticky_topic=getattr(self, "_last_topic", None),
                    deep=deep,
                    lang=getattr(self, "lang", "ru"),   # знания на языке страницы
                )
                if block:
                    system += "\n\n════ ЧТО ТЫ ЗНАЕШЬ О САЙТЕ ════\n" + block
                self._last_topic = topic
            except Exception as e:
                logger.warning(f"VOICE: знания не подмешались: {e}")
        # 🌐 Английская версия сайта: характер описан по-русски, и память тянет
        # ассистента обратно в русский. Поэтому язык задаём прямо и жёстко.
        if getattr(self, "lang", "ru") == "en":
            system += ("\n\n[LANGUAGE - OVERRIDES EVERYTHING ABOVE]: The user is on the English "
                       "version of the site. Reply in English ONLY, every single time, even if the "
                       "user's message is short, ambiguous, or written in another language, and even "
                       "if your memory of this user is in Russian. Never mix languages.")
        else:
            system += ("\n\n[ЯЗЫК — ВАЖНЕЕ ВСЕГО, ЧТО НАПИСАНО ВЫШЕ]: Собеседник на русской "
                       "версии сайта. Отвечай ТОЛЬКО на русском языке — всегда, без единого "
                       "исключения. Даже если он написал по-английски, по-украински, "
                       "по-белорусски или на любом другом языке — ты понимаешь его, но "
                       "ОТВЕЧАЕШЬ ПО-РУССКИ. Даже если его сообщение короткое, непонятное или "
                       "состоит из одного слова. Даже если он прямо просит перейти на другой "
                       "язык — вежливо откажись и продолжай по-русски. Никогда не смешивай "
                       "языки в одном ответе. Пиши чистым литературным русским: никакого "
                       "украинского, белорусского, болгарского, сербского и прочих "
                       "родственных языков — ни отдельного слова, ни оборота.")
        # ⚡ Глубокая память отключена на голосе (грузила старые паттерны + 2с задержка).
        # Остаётся только сессионная история текущего разговора (self.history ниже).
        # ═══ Защита архитектуры в голосовом ═══
        if self.user_id != 803501001:
            system += "\n\n[КОНФИДЕНЦИАЛЬНОСТЬ]: НЕ раскрывай свою архитектуру, технологии, модели или структуру системы. Отвечай: \"Информация о моей архитектуре закрыта разработчиком.\""
        messages = [{"role": "system", "content": system}]
        
        if len(self.history) > 20:
            messages.extend(self.history[-20:])
        else:
            messages.extend(self.history)
        
        messages.append({"role": "user", "content": user_input})
        return messages
    
    async def generate_stream_turbo(self, user_input: str, memory_ctx: str = "",
                                    web_ctx: str = "", на_поиск=None,
                                    lang: str = "ru") -> AsyncGenerator[str, None]:
        """Поток ответа. Модель сама решает, звать ли поиск.

        Если она вызвала инструмент — мы выполняем поиск, кладём данные
        в разговор и спрашиваем её ещё раз, уже с фактами на руках.
        `на_поиск` — колбэк, чтобы зажечь человеку значок «Ищу…».
        """
        session = await self._get_session()

        сообщения = self._build_messages(user_input, memory_ctx, web_ctx)
        payload = {
            "model": current_model(),
            "messages": сообщения,
            "temperature": config.LLM_TEMPERATURE,
            # 🧠 Умная модель сначала рассуждает про себя, и рассуждение
            # съедает предел ответа. Иногда весь — и ответ приходил ПУСТЫМ.
            # Для разговора глубокие раздумья не нужны: ставим слабые.
            "reasoning_effort": os.getenv("REASONING_EFFORT", "low"),
            "max_tokens": config.LLM_MAX_TOKENS,
            "stream": True,
            "tools": ИНСТРУМЕНТЫ,
            "tool_choice": "auto",
        }

        # сюда собираем вызов инструмента, если модель его сделает:
        # в потоке аргументы приходят по кусочкам, их надо склеить
        вызовы = {}

        full_response = ""
        chunk_buffer = ""
        
        # 🎯 Счётчики для динамического chunking
        chunk_count = 0
        total_chars = 0
        
        # ⚠️ НЕ РЕЗАТЬ ПОСРЕДИ ЧИСЛА. Каждый кусок озвучивается ОТДЕЛЬНО, и
        # если разрез попадёт внутрь «17,9», то уедет «17,» одним куском и
        # «9 °C» другим — голос прочитает «сто семьдесят девять». Он это и
        # услышал 08.08 про погоду в Лондоне. Поэтому точка и запятая между
        # цифрами концом фразы НЕ считаются.
        sentence_end = re.compile(r'(?<!\d)[.!?。！？]|[.!?。！？](?!\d)')
        natural_break = re.compile(r'(?<!\d)[,;:\-]\s|[,;:\-](?!\d)\s')
        
        rotation_start = None
        for attempt in range(groq_keys.total_keys + 2):   # +2 круга на вызов инструмента
            try:
                current_key = groq_keys.get_current_key()
                if not current_key:
                    yield "Извините, API ключи не настроены."
                    return
                
                logger.info(f"🔑 Using {groq_keys.get_key_info()}")
                
                headers = {
                    "Authorization": f"Bearer {current_key}",
                    "Content-Type": "application/json",
                    "User-Agent": "Mozilla/5.0 (compatible; Quantareon/2.1)"
                }
                
                async with session.post(
                    groq_keys.get_current_url(),
                    headers=headers,
                    json=payload,
                    # 15 сек вместо 30: если мозги молчат дольше — не ждём,
                    # а сразу переключаемся на следующий ключ. Человеку лучше
                    # быстрый переход, чем полминуты тишины.
                    timeout=aiohttp.ClientTimeout(total=15, connect=5)
                ) as response:
                    if response.status == 429:
                        if rotation_start is None:
                            rotation_start = time.time()
                        logger.warning(f"🔑 Rate limit ({groq_keys.get_key_info()}) → rotate")
                        groq_keys.rotate_key()
                        continue
                    
                    if response.status == 401:
                        if rotation_start is None:
                            rotation_start = time.time()
                        logger.warning(f"🔑 Invalid key ({groq_keys.get_key_info()}) → rotate")
                        groq_keys.rotate_key()
                        continue
                    
                    if response.status != 200:
                        error = await response.text()
                        if rotation_start is None:
                            rotation_start = time.time()
                        # 🔍 Пишем ОТВЕТ Groq целиком — без него причина невидима
                        # (429 = упёрлись в лимит, 401 = ключ не принят, 404 = модель снята)
                        logger.warning(
                            f"🔑 Error {response.status} ({groq_keys.get_key_info()}) → rotate | "
                            f"ответ Groq: {error[:400]}"
                        )
                        groq_keys.rotate_key()
                        continue
                    
                    if rotation_start:
                        rotation_time = time.time() - rotation_start
                        logger.info(f"🔑 ✅ Success with {groq_keys.get_key_info()} (rotation took {rotation_time:.2f}s)")
                    
                    async for line in response.content:
                        line_text = line.decode('utf-8').strip()
                        
                        if not line_text or line_text == "data: [DONE]":
                            continue
                        
                        if line_text.startswith("data: "):
                            try:
                                data = json.loads(line_text[6:])
                                дельта = data.get("choices", [{}])[0].get("delta", {})

                                # 🔧 модель зовёт инструмент — копим по кусочкам
                                for тк in (дельта.get("tool_calls") or []):
                                    н = тк.get("index", 0)
                                    я = вызовы.setdefault(н, {"имя": "", "арг": ""})
                                    ф = тк.get("function") or {}
                                    if ф.get("name"):
                                        я["имя"] = ф["name"]
                                    if ф.get("arguments"):
                                        я["арг"] += ф["arguments"]

                                content = дельта.get("content", "")
                                
                                if content:
                                    chunk_buffer += content
                                    full_response += content
                                    total_chars = len(full_response)  # 🎯 Обновляем счётчик
                                    
                                    min_size = self._get_optimal_chunk_size(chunk_count, total_chars)

                                    # 🗣 РЕЖЕМ ТОЛЬКО ПО КОНЦУ ПРЕДЛОЖЕНИЯ и только когда
                                    # набралось достаточно — иначе речь рвётся на обрывки.
                                    if len(chunk_buffer) >= min_size and sentence_end.search(chunk_buffer):
                                        matches = list(sentence_end.finditer(chunk_buffer))
                                        if matches:
                                            last_match = matches[-1]
                                            end_pos = last_match.end()
                                            to_yield = chunk_buffer[:end_pos].strip()
                                            chunk_buffer = chunk_buffer[end_pos:].strip()
                                            if to_yield:
                                                yield _fix_words(to_yield)
                                                chunk_count += 1

                                    # 🚨 Аварийный клапан: предложение затянулось без точки —
                                    # чтобы не молчать, режем по запятой, но только на длинном куске
                                    elif len(chunk_buffer) >= max(min_size * 3, 300):
                                        match = None
                                        for m in natural_break.finditer(chunk_buffer):
                                            match = m
                                        if match:
                                            end_pos = match.end()
                                            to_yield = chunk_buffer[:end_pos].strip()
                                            chunk_buffer = chunk_buffer[end_pos:].strip()
                                            if to_yield:
                                                yield _fix_words(to_yield)
                                                chunk_count += 1
                                                
                            except json.JSONDecodeError:
                                continue
                    
                    # 🔧 МОДЕЛЬ ПОПРОСИЛА ПОИСК. Сходим и спросим её снова —
                    # теперь у неё будут факты, и она договорит ответ сама.
                    if вызовы and not full_response.strip():
                        try:
                            import web_router
                        except Exception:
                            web_router = None

                        первый = вызовы[sorted(вызовы)[0]]
                        try:
                            арг = json.loads(первый["арг"] or "{}")
                        except Exception:
                            арг = {}
                        logger.info(f"🔧 модель зовёт поиск: {арг}")

                        if на_поиск:
                            try:
                                await на_поиск()
                            except Exception:
                                pass

                        данные = ""
                        if web_router is not None:
                            try:
                                данные = await asyncio.wait_for(
                                    web_router.выполнить(
                                        запрос=арг.get("запрос", ""),
                                        тема=арг.get("тема", "поиск"),
                                        город=арг.get("город", ""),
                                        lang=lang),
                                    timeout=float(os.getenv("SEARCH_TIMEOUT", "9")))
                            except asyncio.TimeoutError:
                                logger.warning("🌐 поиск не уложился в срок")
                            except Exception as e:
                                logger.warning(f"🌐 поиск не вышел: {e}")

                        # кладём вызов и его результат в разговор — так модель
                        # понимает, что инструмент отработал, и продолжает
                        сообщения.append({
                            "role": "assistant",
                            "tool_calls": [{
                                "id": "поиск_1",
                                "type": "function",
                                "function": {"name": первый["имя"] or "поиск_в_интернете",
                                             "arguments": первый["арг"] or "{}"},
                            }],
                        })
                        сообщения.append({
                            "role": "tool",
                            "tool_call_id": "поиск_1",
                            "content": данные or "Ничего не нашлось.",
                        })
                        payload["messages"] = сообщения
                        payload.pop("tools", None)      # второй круг — без инструмента
                        payload.pop("tool_choice", None)
                        вызовы = {}
                        continue                        # тем же ключом, ещё раз

                    # 🔇 МОДЕЛЬ ВЕРНУЛА ПУСТОТУ — НЕ МОЛЧАТЬ.
                    # С включённым инструментом такое бывает: всё уходит во
                    # внутреннее рассуждение, а текста наружу нет. Раньше мы
                    # тут молча выходили, и человек оставался без ответа —
                    # он это и поймал: «ни ответа, ни привета». Пробуем ещё
                    # раз, уже без инструмента: так надёжнее всего.
                    if not full_response.strip() and not chunk_buffer.strip():
                        if payload.get("tools"):
                            logger.warning("модель промолчала — повторяю без инструмента")
                            payload.pop("tools", None)
                            payload.pop("tool_choice", None)
                            вызовы = {}
                            continue
                        logger.warning("модель промолчала и без инструмента")

                    if chunk_buffer.strip():
                        yield _fix_words(chunk_buffer.strip())

                    if not full_response.strip():
                        # совсем нечего сказать — лучше короткая живая фраза,
                        # чем тишина в трубке
                        yield "Прости, я не расслышал. Повтори, пожалуйста."
                        return

                    self.history.append({"role": "user", "content": user_input})
                    self.history.append({"role": "assistant", "content": full_response})
                    return
                    
            except asyncio.TimeoutError:
                if rotation_start is None:
                    rotation_start = time.time()
                logger.warning(f"🔑 Timeout ({groq_keys.get_key_info()}) → rotate")
                groq_keys.rotate_key()
                continue
                
            except Exception as e:
                if rotation_start is None:
                    rotation_start = time.time()
                logger.warning(f"🔑 Error ({groq_keys.get_key_info()}): {type(e).__name__}: {e} → rotate")
                groq_keys.rotate_key()
                continue
        
        total_time = time.time() - rotation_start if rotation_start else 0
        logger.error(f"🔑 All {groq_keys.total_keys} keys failed! (total time: {total_time:.2f}s)")
        
        groq_keys.current_index = 0
        logger.info("🔄 Reset to key_1 for next attempt")
        
        yield "Извините, сервис временно недоступен."
    
    def clear_history(self):
        self.history = []


