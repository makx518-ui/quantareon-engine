def _time_ru(hhmm: str) -> str:
    """«07:37» → «семь тридцать семь» (без «ноль семь двоеточие»)."""
    try:
        h, m = hhmm.split(":")
        h, m = int(h), int(m)
        return f"{h}:{m:02d}" if m else f"{h} часов"
    except Exception:
        return hhmm


