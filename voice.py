def _какой_раздел_наверняка(текст: str) -> str:
    """Вопрос однозначен — возвращаем ИМЯ РАЗДЕЛА, который обязан отработать.

    Инструментов теперь несколько, и принуждать надо конкретный: обязать
    «поиск_в_интернете» на вопрос о погоде — значит получить общий поиск
    вместо погодной службы.
    """
    т = (текст or "").strip()
    if not т or len(т) < 4:
        return ""
    if _ЯВНО_ПОГОДА.search(т):
        return "weather"
    if _ЯВНО_КУРС.search(т):
        return "rates"
    if _ЯВНО_НОВОСТИ.search(т):
        return "news"
    return ""


def _нужен_интернет_наверняка(текст: str) -> bool:
    """Вопрос однозначно про живые данные — значит инструмент обязателен.

    Ловим только явное. «Расскажи про Азбуку 360», «что ты умеешь»,
    «который час» сюда не попадают — там интернет не нужен.
    """
    т = (текст or "").strip()
    if not т or len(т) < 4:
        return False
    return bool(_ЯВНО_В_ИНТЕРНЕТ.search(т))


