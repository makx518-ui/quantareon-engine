def _fix_words(text: str) -> str:
    """Заменить неверные слова на верные — и в окне разговора, и в звуке."""
    if not text:
        return text

    # 🔤 ВОЗВРАЩАЕМ БУКВУ Ё. Модель пишет «Все отлично» без точек над е —
    # и человек это ВИДИТ на экране, а голос ещё и читает как «всЕ», будто
    # про людей. Правим в самом тексте, поэтому исправление попадает разом
    # и в окно разговора, и в озвучку.
    text = _вcё_вместо_все(text)
    for bad, good in _WORD_FIXES:
        if bad in text:
            text = text.replace(bad, good)
    return text



