class EdgeTTSTurbo:
    """Edge TTS with streaming output for lower latency."""
    
    def __init__(self, lang: str = "ru"):
        en = str(lang).lower().startswith("en")
        self.voice = config.TTS_VOICE_EN if en else config.TTS_VOICE
        self.rate = config.TTS_RATE_EN if en else config.TTS_RATE
        self.pitch = config.TTS_PITCH_EN if en else config.TTS_PITCH
        self.volume = config.TTS_VOLUME_EN if en else config.TTS_VOLUME
        self.lang = "en" if en else "ru"
        # 🗣️ 24.08 Яндекс — основной, Дмитрий (Edge) — запасной.
        # ⚠️ ТОЛЬКО РУССКИЙ. Английскую сторону он трогать запретил:
        # там Эндрю его устраивает, а английский голос у Яндекса один
        # и незнакомый. Ставим — не рискуем тем, что уже работает.
        self.ya_voice = config.YANDEX_VOICE
        self.ya_on = (not en) and bool(config.YANDEX_API_KEY
                                       and config.YANDEX_FOLDER_ID)

    @staticmethod
    def _ya_text(text: str, lang: str) -> str:
        """Текст в записи Яндекса: ударения плюсом перед гласной."""
        return _apply_udar_ya(text) if lang == "ru" else text

    async def _yandex(self, text: str) -> bytes:
        """Озвучить у Яндекса. Пусто — значит не вышло.

        🗣️ 25.08 РЕЖЕМ ПО ТОЧКАМ И КЛЕИМ С ПАУЗОЙ. Его находка на слух:
        разметка SSML (<break/>) ЛОМАЕТ речь — Яндекс перестаёт вести
        интонацию сам и рубит фразу везде, даже там, где знаков нет
        («чувствуется прерывание везде, а надо только после знаков»).
        Поэтому каждое предложение просим ОБЫЧНЫМ текстом — внутри него
        Яндекс сам расставит дыхание на запятых и тире, как умеет, — а
        паузу добавляем только МЕЖДУ предложениями, склейкой.
        Замер на его отрывке: 3 предложения, пауза 0.7 с → 27.2 с речи;
        без пауз 26.3 с. Он выбрал этот способ, послушав пять других.
        """
        if not self.ya_on:
            return b""

        куски = [к.strip() for к in re.split(r"(?<=[.!?])\s+", text) if к.strip()]
        if not куски:
            return b""

        собранное = []
        тишина = _КАДР_ТИШИНЫ * max(1, round(config.YANDEX_PAUSE_MS / _КАДР_МС))
        for i, кусок in enumerate(куски):
            звук = await self._ya_один(кусок)
            if not звук:          # не отдали хоть одно предложение — уходим целиком
                return b""
            собранное.append(звук)
            if i < len(куски) - 1:
                собранное.append(тишина)
        return b"".join(собранное)

    async def _ya_один(self, text: str) -> bytes:
        """Одно предложение у Яндекса, сырым звуком (без сжатия)."""
        if not self.ya_on:
            return b""
        данные = urllib.parse.urlencode({
            "text": self._ya_text(text, self.lang),
            "lang": "ru-RU" if self.lang == "ru" else "en-US",
            "voice": self.ya_voice,
            "speed": config.YANDEX_SPEED,
            "emotion": config.YANDEX_EMOTION,
            "folderId": config.YANDEX_FOLDER_ID,
            # mp3: куски склеиваются встык, паузу берём готовым кусочком
            # (_КАДР_ТИШИНЫ) — так не нужен ffmpeg на сервере.
            "format": "mp3",
        }).encode()

        def _сходить() -> bytes:
            зпр = urllib.request.Request(
                "https://tts.api.cloud.yandex.net/speech/v1/tts:synthesize",
                data=данные,
                headers={"Authorization": f"Api-Key {config.YANDEX_API_KEY}",
                         "Content-Type": "application/x-www-form-urlencoded"})
            with urllib.request.urlopen(зпр, timeout=config.YANDEX_TIMEOUT) as о:
                return о.read()

        try:
            звук = await asyncio.wait_for(
                asyncio.get_event_loop().run_in_executor(None, _сходить),
                timeout=config.YANDEX_TIMEOUT)
        except Exception as e:
            logger.warning(f"🗣️ Яндекс не отдал звук ({type(e).__name__})")
            return b""

        # 🔇 СРЕЗАЕМ СЛУЖЕБНЫЙ ЗАГОЛОВОК ID3 (45 байт, подпись кодировщика).
        # Яндекс кладёт его в КАЖДОЕ предложение, а Edge отдаёт чистый звук.
        # Куски идут в браузер один за другим, и заголовок посреди потока
        # читается как мусор — щелчки на стыках.
        # ⚠️ Проверка длины обязательна: на обрывке ответа обращение к
        # звук[9] уронило бы озвучку.
        if len(звук) > 10 and звук[:3] == b"ID3":
            n = (звук[6] << 21) | (звук[7] << 14) | (звук[8] << 7) | звук[9]
            звук = звук[10 + n:]
        return звук
    @staticmethod
    async def _collect(communicate) -> bytes:
        """Собрать весь звук от Edge. Вынесено отдельно, чтобы обернуть
        сторожем: asyncio.wait_for не умеет обрывать `async for` на месте."""
        buf = io.BytesIO()
        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                buf.write(chunk["data"])
        return buf.getvalue()

    async def synthesize(self, text: str) -> bytes:
        """Озвучить текст целиком."""
        # 🔀 24.08 ДВЕ РАЗДЕЛЬНЫЕ ДОРОЖКИ — его требование, дословно:
        # «это экспериментальный вариант, внутренняя кухня, я экспериментирую;
        # не работает — не работает, никто этого не видит».
        #
        #   БЫСТРАЯ модель (все гости, по умолчанию) → только Дмитрий,
        #       со всеми его настройками. Яндекса тут нет вовсе.
        #   УМНАЯ модель (его админская кнопка)      → только Яндекс.
        #       Не ответил — молчим, к Дмитрию НЕ бежим.
        #
        # Так каждая дорожка настраивается сама по себе, и правки на одной
        # не задевают другую. Худший случай молчания на быстрой остаётся
        # прежним (22 с), потому что Яндекс её не касается.
        сырой = text
        на_умной = current_model() == MODELS["big"]["id"]

        if на_умной and self.ya_on:
            # ── дорожка Ермила: Яндекс и точка
            return await self._yandex(_tts_clean(сырой, self.lang, udar=False))

        # ── дорожка Дмитрия: как было до 24.08
        text = _tts_clean(text, self.lang)   # словарь произношения + чистка
        if not text or not text.strip():
            return b""

        try:
            communicate = edge_tts.Communicate(
                text=text,
                voice=self.voice,
                rate=self.rate,
                pitch=self.pitch,
                volume=self.volume
            )
            
            # 🛡️ сторож: попытка не длится дольше config.TTS_TIMEOUT
            return await asyncio.wait_for(
                self._collect(communicate), timeout=config.TTS_TIMEOUT
            )

        except asyncio.TimeoutError:
            logger.error(f"❌ TTS: Edge молчал дольше {config.TTS_TIMEOUT} с — обрываю")
            return b""
        except Exception as e:
            logger.error(f"TTS error: {e}")
            return b""
    
    async def synthesize_streaming(self, text: str, send_callback) -> None:
        """
        Synthesize and send audio for a text chunk.
        Собираем весь аудио для текста, потом отправляем — без щелчков между кусками.
        🛡️ С RETRY логикой при сбоях.
        """
        # 🔀 24.08 ДВЕ РАЗДЕЛЬНЫЕ ДОРОЖКИ (см. пояснение в synthesize).
        сырой = text
        if current_model() == MODELS["big"]["id"] and self.ya_on:
            звук_я = await self._yandex(_tts_clean(сырой, self.lang, udar=False))
            if звук_я:
                try:
                    await send_callback(звук_я)
                except Exception as e:
                    logger.warning(f"⚠️ отправка звука не прошла: {e}")
            else:
                logger.warning("🗣️ Яндекс молчит, а мы на умной модели — "
                               "звука не будет (так задумано, это проба)")
            return

        text = _tts_clean(text, self.lang)   # словарь произношения + чистка
        if not text or not text.strip():
            return

        # 🛡️ RETRY до 3 попыток — ТОЛЬКО ДЛЯ СИНТЕЗА.
        # Отправку готового звука повторами не лечат: если она упала, значит
        # соединение с браузером закрылось или нас перебили — синтезировать
        # заново бессмысленно, слать некому. (12.08 на живом сбое движок
        # пересинтезировал кусок и трижды долбил закрытую дверь.)
        max_retries = 3
        for attempt in range(max_retries):
            try:
                communicate = edge_tts.Communicate(
                    text=text,
                    voice=self.voice,
                    rate=self.rate,
                    pitch=self.pitch,
                    volume=self.volume
                )
                
                # Собираем ВСЁ аудио для этого текстового чанка.
                # 🛡️ сторож: попытка не длится дольше config.TTS_TIMEOUT
                звук = await asyncio.wait_for(
                    self._collect(communicate), timeout=config.TTS_TIMEOUT
                )

            except asyncio.TimeoutError:
                if attempt < max_retries - 1:
                    logger.warning(f"⚠️ TTS timeout, retry {attempt + 1}/{max_retries}")
                    await asyncio.sleep(0.5)  # Пауза перед повтором
                    continue
                logger.error(f"❌ TTS failed after {max_retries} attempts (timeout)")
                return
                
            except Exception as e:
                if attempt < max_retries - 1:
                    logger.warning(f"⚠️ TTS error: {e}, retry {attempt + 1}/{max_retries}")
                    await asyncio.sleep(0.5)
                    continue
                logger.error(f"❌ TTS failed after {max_retries} attempts: {e}")
                return

            # Синтез удался. Пустой звук — тоже беда Edge, идём на новую
            # попытку (как и раньше). Непустой отправляем ОДИН раз и выходим:
            # без разрывов = без щелчков, а сбой отправки не повторяем.
            if звук:
                try:
                    await send_callback(звук)
                except Exception as e:
                    logger.warning(f"⚠️ TTS: звук готов, но отправить не вышло (соединение закрыто или перебили): {e}")
                return  # ✅ синтез своё дело сделал — повторов не будет


