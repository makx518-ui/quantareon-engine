def _мысль_не_закончена(текст: str) -> bool:
    """Похоже ли, что человек оборвался на полуслове."""
    т = (текст or "").strip()
    if not т:
        return False

    # слова-паузы сильнее точки: «Подожди.» — это не конец мысли
    хвост = re.findall(r"[\w'-]+", т.lower())
    if хвост and хвост[-1] in _СЛОВА_ПАУЗЫ:
        return True

    # оборвался на запятой, тире, двоеточии — точно продолжает
    if т[-1] in ",-—–:;":
        return True
    # закончил точкой, восклицанием, вопросом — мысль целая
    if т[-1] in ".!?…":
        return False
    слова = re.findall(r"[\w'-]+", т.lower())
    if not слова:
        return False
    # последнее слово — предлог или союз: продолжение неизбежно
    if слова[-1] in _ХВОСТЫ_НЕЗАКОНЧЕННОСТИ:
        return True
    # одно слово без знака конца — вероятно, только начал говорить
    # («Расскажи анекдот» — это уже законченная просьба, её не ждём)
    if len(слова) <= 1:
        return True
    return False


